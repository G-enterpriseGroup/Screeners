from __future__ import annotations

import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import urllib.request

from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.support.ui import WebDriverWait

ROOT = Path(__file__).resolve().parents[1]
PORT = 18682
BASE = f"http://127.0.0.1:{PORT}"

FIXTURE = '''
import pandas as pd
import streamlit as st
from src.protective_puts_portfolio_ui import _chain_row_colors

st.set_page_config(page_title="Hedge chain contrast fixture", layout="wide")
with st.container(key="pp_portfolio_hedge"):
    sample = pd.DataFrame([
        {"BUY": False, "Proxy":"SPY", "Expiration":"10-12-26", "DTE":1,
         "Strike":715.0, "Bid":0.02, "Ask":0.02, "Cost":2.0,
         "Loss":6358.0, "Scenario":0.0, "Contracts":1, "OI":1270},
        {"BUY": False, "Proxy":"SPY", "Expiration":"10-12-26", "DTE":1,
         "Strike":714.0, "Bid":0.03, "Ask":0.04, "Cost":4.0,
         "Loss":6458.0, "Scenario":3.0, "Contracts":1, "OI":1200},
        {"BUY": False, "Proxy":"QQQ", "Expiration":"11-20-26", "DTE":40,
         "Strike":650.0, "Bid":2.50, "Ask":2.70, "Cost":270.0,
         "Loss":1180.0, "Scenario":81.0, "Contracts":1, "OI":532},
    ])
    def style(row):
        return _chain_row_colors(row.name, row.name == 0, row.name == 1, len(row))
    st.data_editor(
        sample.style.apply(style, axis=1),
        hide_index=True, width="stretch", height=415, row_height=32,
        disabled=[c for c in sample if c != "BUY"],
        key="pp_hedge_contract_editor_visual",
        column_config={
            "BUY": st.column_config.CheckboxColumn("BUY",width="small"),
            "Proxy": st.column_config.TextColumn("ETF",width="small"),
            "Expiration": st.column_config.TextColumn("EXP",width="small"),
            "Strike": st.column_config.NumberColumn("STRIKE",format="$%.2f",width="small"),
        },
    )
'''

JS_PIXELS = """
const grids=[...document.querySelectorAll('[data-testid="stDataFrame"]')];
if (!grids.length) return {error:"missing dataframe"};
const results=[];
for (const grid of grids) {
  for (const canvas of grid.querySelectorAll('canvas')) {
    try {
      if (canvas.width<450 || canvas.height<100) continue;
      const ctx=canvas.getContext('2d', {willReadFrequently:true});
      if (!ctx) continue;
      const sample=ctx.getImageData(0,0,canvas.width,canvas.height);
      let amber=0, green=0, orange=0;
      const p=sample.data;
      for (let i=0;i<p.length;i+=4) {
        const r=p[i],g=p[i+1],b=p[i+2],a=p[i+3];
        if (a<200) continue;
        // Distinguish ordinary-row amber from the orange highlighted fill.
        if (Math.abs(r-246)<21 && Math.abs(g-181)<21 && Math.abs(b-106)<21) amber++;
        if (Math.abs(r-74)<23 && Math.abs(g-246)<23 && Math.abs(b-195)<23) green++;
        if (Math.abs(r-251)<17 && Math.abs(g-139)<17 && Math.abs(b-30)<17) orange++;
      }
      results.push({width:canvas.width,height:canvas.height,amber,green,orange});
    } catch (e) {
      results.push({error:String(e)});
    }
  }
}
return {grids:grids.length,results};
"""


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="pp_chain_visual_") as tmp:
        script = Path(tmp) / "app.py"
        script.write_text(FIXTURE, encoding="utf-8")
        env = os.environ.copy()
        env["PYTHONPATH"] = str(ROOT) + os.pathsep + env.get("PYTHONPATH", "")
        server = subprocess.Popen(
            [sys.executable, "-m", "streamlit", "run", str(script),
             "--server.port", str(PORT), "--server.headless", "true",
             "--browser.gatherUsageStats", "false"],
            cwd=ROOT, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT,
        )
        driver = None
        try:
            deadline = time.monotonic() + 45
            while time.monotonic() < deadline:
                if server.poll() is not None:
                    raise AssertionError(f"Fixture exited: {server.returncode}")
                try:
                    with urllib.request.urlopen(BASE + "/_stcore/health", timeout=2) as response:
                        if response.status == 200:
                            break
                except Exception:
                    time.sleep(0.4)
            else:
                raise AssertionError("Visual test fixture never started")
            opts = Options()
            opts.add_argument("--headless=new")
            opts.add_argument("--no-sandbox")
            opts.add_argument("--disable-dev-shm-usage")
            opts.add_argument("--force-device-scale-factor=1")
            opts.add_argument("--window-size=1440,900")
            driver = webdriver.Chrome(options=opts)
            driver.get(BASE)
            wait = WebDriverWait(driver, 70)
            def visual_ready(_):
                report=driver.execute_script(JS_PIXELS)
                return report if (
                    report.get("grids", 0) > 0 and
                    any(x.get("amber",0)>18 and x.get("green",0)>18
                        and x.get("orange",0)>100 for x in report.get("results",[]))
                ) else False
            result=wait.until(visual_ready)
            assert result["grids"] == 1, result
            print("PROTECTIVE PUTS CHAIN CANVAS CONTRAST: PASS", result)
        finally:
            if driver is not None:
                driver.quit()
            server.terminate()
            try:
                server.wait(timeout=8)
            except subprocess.TimeoutExpired:
                server.kill()
                server.wait(timeout=5)


if __name__ == "__main__":
    main()
