def _money(value: Any) -> str:
    try:
        return "$" + f"{float(value):,.2f}"
    except (TypeError, ValueError):
        return "—"


def _normalize_symbol() -> None:
    value = str(st.session_state.get("pp_symbol") or "").strip().upper()
    st.session_state["pp_symbol"] = value or "SPY"


def _company_markup(name: str) -> str:
    safe = html.escape(str(name or "—"))
    return (
        '<div class="pp-company-field"><div class="pp-company-label">Company / ETF</div>'
        f'<div class="pp-company-box" title="{safe}">{safe}</div></div>'
    )


def _metric_markup(items: list[tuple[str, str, str]]) -> str:
    cells = "".join(
        '<div class="pp-card pp-' + html.escape(tone) + '"><div class="pp-label">'
        + html.escape(label) + '</div><div class="pp-value">' + html.escape(value) + "</div></div>"
        for label, value, tone in items
    )
    return '<div class="pp-grid">' + cells + "</div>"


def _live_etrade(client) -> bool:
    return client is not None and not bool(getattr(client, "is_offline", False))


def _expirations(client, symbol: str, touch_session) -> tuple[list[date], str]:
    now = time.time()
    source_key = "ETRADE" if _live_etrade(client) else "PUBLIC"
    cache = st.session_state.setdefault("_pp_expiration_cache", {})
    cache_key = f"{source_key}:{symbol}"
    cached = cache.get(cache_key)
    if cached and now - float(cached.get("loaded_at", 0.0)) < _EXPIRATION_CACHE_SECONDS:
        return list(cached.get("dates") or []), str(cached.get("source") or source_key)

    if _live_etrade(client):
        payload = client.get_option_expirations(symbol)
        touch_session()
        dates: list[date] = []
        for year, month, day in option_expiration_dates(payload):
            try:
                dates.append(date(year, month, day))
            except ValueError:
                continue
        dates = sorted(set(dates))
        source = "E*TRADE"
    else:
        dates, source = public_expirations(symbol)

    cache[cache_key] = {"loaded_at": now, "dates": dates, "source": source}
    return dates, source


def _put_chain(
    client, symbol: str, expiry: date, touch_session
) -> tuple[list[dict[str, Any]], bool, str]:
    source_key = "ETRADE" if _live_etrade(client) else "PUBLIC"
    cache = st.session_state.setdefault("_pp_chain_cache", {})
    key = f"{source_key}:{symbol}:{expiry.isoformat()}"
    now = time.time()
    cached = cache.get(key)
    if cached and now - float(cached.get("loaded_at", 0.0)) < _CHAIN_CACHE_SECONDS:
        return (
            list(cached.get("rows") or []),
            True,
            str(cached.get("source") or source_key),
        )

    if _live_etrade(client):
        payload = client.get_option_chain(
            symbol, expiry.year, expiry.month, expiry.day, no_of_strikes=None, chain_type="PUT"
        )
        touch_session()
        rows = [
            row for row in extract_option_rows(payload, expiry)
            if str(row.get("call_put") or "").upper() == "PUT"
        ]
        source = "E*TRADE"
    else:
        rows, source = public_put_chain(symbol, expiry)

    cache[key] = {"loaded_at": now, "rows": rows, "source": source}
    return rows, False, source


def _market_today() -> date:
    return datetime.now(ZoneInfo("America/New_York")).date()


def _default_expiry(expirations: list[date]) -> date:
    today = _market_today()
    return next((item for item in expirations if (item - today).days >= 30), expirations[0])


def _render_scan_result(result: dict[str, Any]) -> None:
    """One ASK-priced matched put per listed expiration; near-zero floor first."""
    frame = result.get("frame")
    if not isinstance(frame, pd.DataFrame) or frame.empty:
        st.info("No usable listed put contracts were returned for the expiration scan.")
        return

    target_dte = int(result.get("target_dte") or 60)
    candidates = cheapest_near_zero_put_by_expiration(frame, target_dte=target_dte)
    if candidates.empty:
        st.warning(
            "NO VALID PUT ASK QUOTES // Cannot establish a stock + put loss floor "
            "from these expirations. Try another ticker or expiration."
        )
        return
    selected = result.get("chosen_expiry")
    if isinstance(selected, date):
        candidates["Priority Expiration"] = (
            candidates["Expiration"] == selected.strftime("%m-%d-%y")
        )
    if not candidates["Priority Expiration"].any():
        candidates.loc[
            (candidates["DTE"] - target_dte).abs().idxmin(),
            "Priority Expiration",
        ] = True
    recommended = candidates.loc[candidates["Priority Expiration"]].iloc[0]
    stock_price = float(result.get("stock_price") or 0.0)
    shares = int(result.get("shares") or 0)
    matched_zero = bool(recommended["Target Met"])
    st.html('<div class="pp-section">SHARES + MATCHED PUT // EXPIRATION LOSS FLOOR</div>')
    st.html(_metric_markup([
        ("Ticker", str(result.get("symbol") or ""), "orange"),
        ("Stock Basis / Share", _money(stock_price), "blue"),
        ("Protected Shares", f"{shares:,}", "orange"),
        ("Put Contracts", f"{shares // 100:,}", "orange"),
        ("ASK Put Premium", _money(recommended["Put Cost (Ask)"]), "red"),
        ("Worst Loss At Expiry", _money(recommended["Max Loss (Ask)"]),
         "green" if matched_zero else "red"),
    ]))
    if matched_zero:
        st.success(
            "ZERO DOWNSIDE FLOOR AT EXPIRATION (modeled) // "
            "The selected put's strike covers stock cost plus ASK premium. "
            "Transaction costs and slippage are excluded."
        )
    else:
        st.warning(
            "A $0 MAXIMUM LOSS WAS NOT AVAILABLE FOR THE SELECTED EXPIRATION. "
            f"The highlighted put has the lowest quoted worst-case loss: "
            f"{_money(recommended['Max Loss (Ask)'])}. "
            "The scan will not falsely label a losing stock + put position as risk-free."
        )

    st.html('<div class="pp-section">LISTED EXPIRATIONS // LOWEST-COST ZERO-LOSS PUT OR CLOSEST FLOOR</div>')
    table = candidates[[
        "Priority Expiration", "Expiration", "DTE", "Strike", "Ask",
        "Contracts", "Put Cost (Ask)", "Max Loss (Ask)", "Status",
    ]].copy()
    table = table.rename(columns={
        "Priority Expiration": "Selected",
        "Put Cost (Ask)": "Total Put Premium",
        "Max Loss (Ask)": "Shares + Put Max Loss",
    })
    table["Selected"] = table["Selected"].map({True: "★", False: ""})
    def _highlight_floor(row):
        primary = row["Selected"] == "★"
        zero = row["Status"] == "ZERO-LOSS FLOOR"
        if primary:
            return [
                "background-color:#fb8b1e;color:#000;font-weight:900"
                for _ in row
            ]
        return [
            "color:#4af6c3;font-weight:800" if zero else ""
            for _ in row
        ]
    st.dataframe(
        table.style.apply(_highlight_floor, axis=1),
        hide_index=True, width="stretch",
        height=min(560, max(138, len(table) * 35 + 44)),
        column_config={
            "Strike": st.column_config.NumberColumn(format="$%.2f"),
            "Ask": st.column_config.NumberColumn(format="$%.2f"),
            "Total Put Premium": st.column_config.NumberColumn(format="$%.2f"),
            "Shares + Put Max Loss": st.column_config.NumberColumn(format="$%.2f"),
        },
    )
    st.caption(
        "ONE PUT PER 100 SHARES // ASK IS THE PURCHASE PRICE. "
        "PER EXPIRATION: PICK CHEAPEST PUT WITH $0 MAX LOSS; IF NONE, "
        "HIGHLIGHT THE PUT WITH THE LOWEST REAL MAX LOSS. "
        "MAX LOSS = MAX(0, SHARES × (COST BASIS + ASK − STRIKE)). "
        "This assumes direct puts on the SAME ticker held through expiry; "
        "it excludes trading fees, execution slippage, dividends and early exercise."
    )
    with st.expander(f"ALL PUT STRIKES // {len(frame):,}"):
        st.dataframe(
            frame[[
                "Expiration", "DTE", "Strike", "Bid", "Ask",
                "Put Cost (Ask)", "Max Loss (Ask)", "Max Loss % (Ask)",
                "Volume", "Open Interest",
            ]], hide_index=True, width="stretch",
        )
    st.download_button(
        "EXPORT PROTECTIVE PUT SCAN CSV", data=frame.to_csv(index=False),
        file_name=f"{result['symbol']}_protective_puts.csv",
        mime="text/csv", width="stretch", key="pp_download_csv",
    )
    if result.get("chain_sources"):
        st.caption("OPTIONS DATA // " + " + ".join(result["chain_sources"]))
    if result.get("errors"):
        with st.expander("CHAIN FETCH WARNINGS"):
            for msg in result["errors"]:
                st.warning(str(msg))


@st.fragment
def _render_protective_puts_fragment(client, touch_session) -> None:
    with st.container(key="protective_puts_workspace"):
        st.html(_PROTECTIVE_PUTS_CSS)
        st.markdown(
            '<div class="pp-note">READ-ONLY PROTECTIVE PUT ANALYTICS // '
            '<span class="muted">LEGACY MARRIED-PUT ENGINE ADAPTED TO LIVE E*TRADE QUOTES + CHAINS</span></div>',
            unsafe_allow_html=True,
        )
        using_etrade = _live_etrade(client)
        if not using_etrade:
            st.caption(
                "DATA FALLBACK ACTIVE // E*TRADE is not live // Protective Puts uses "
                "yfinance first, then Yahoo Finance HTML scraping if yfinance fails."
            )

        mode = st.radio(
            "Protection Mode", ("SINGLE HOLDING", "PORTFOLIO HEDGE"),
            horizontal=True, key="pp_protection_mode",
        )
        if mode == "PORTFOLIO HEDGE":
            render_portfolio_hedge(
                client, touch_session, get_expirations=_expirations,
                get_chain=_put_chain, market_today=_market_today,
                live_etrade=_live_etrade, money=_money,
                metric_markup=_metric_markup,
            )
            return

        top_ratios = [1.05, 2.25, 0.90, 1.05, 0.90]
        top = st.columns(top_ratios, gap="small")
        with top[0]:
            if "pp_symbol" not in st.session_state:
                st.session_state["pp_symbol"] = "SPY"
            symbol = str(
                st.text_input(
                    "Ticker",
                    key="pp_symbol",
                    placeholder="SPY",
                    on_change=_normalize_symbol,
                    help="Enter the ticker symbol only. Company / ETF name resolves automatically.",
                )
                or "SPY"
            ).strip().upper()

        try:
            if using_etrade:
                quote = quote_summary(client.get_quote(symbol))
                touch_session()
                quote_source = "E*TRADE"
            else:
                quote = public_quote(symbol)
                quote_source = str(quote.get("source") or "PUBLIC")
            last = float(quote.get("last") or 0.0)
            resolved_name = str(quote.get("description") or company_name(symbol) or "").strip()
            record_lookup(symbol, resolved_name)
        except Exception as exc:
            with top[1]:
                st.html(_company_markup(company_name(symbol)))
            st.error(f"Quote unavailable for {symbol}: {exc}")
            return

        with top[1]:
            st.html(_company_markup(resolved_name))
        with top[2]:
            st.text_input("Last", value=_money(last), disabled=True, key="pp_last_display")

        source_row = st.columns(top_ratios, gap="small")
        with source_row[2]:
            st.markdown(
                f'<div class="pp-note">QUOTE SOURCE // {html.escape(quote_source)}</div>',
                unsafe_allow_html=True,
            )

        if st.session_state.get("_pp_price_seed_symbol") != symbol:
            st.session_state["pp_purchase_price"] = round(last, 2)
            st.session_state["_pp_price_seed_symbol"] = symbol
        with top[3]:
            stock_price = float(
                st.number_input(
                    "Purchase Price", min_value=0.01, step=0.01, format="%.2f",
                    key="pp_purchase_price",
                    help="Your stock cost basis per share. New tickers seed from the E*TRADE last price.",
                )
            )
        with top[4]:
            if "pp_shares" not in st.session_state:
                st.session_state["pp_shares"] = 100
            shares = int(
                st.number_input(
                    "Shares", min_value=100, step=100, key="pp_shares",
                    help="Full protection uses one listed put contract per 100 shares.",
                )
            )
        try:
            validate_share_quantity(shares)
        except ValueError as exc:
            st.error(str(exc))
            return

        try:
            expirations, expiration_source = _expirations(client, symbol, touch_session)
        except Exception as exc:
            st.error(f"Option expirations unavailable for {symbol}: {exc}")
            return
        if not expirations:
            st.info("No listed put expirations are available for this symbol.")
            return

        st.html('<div class="pp-section">EXPIRATION PRIORITY // NEAR-ZERO SHARES + PUT LOSS</div>')
        today = _market_today()
        expirations = sorted(item for item in expirations if item >= today)
        if not expirations:
            st.info("There are no future listed put expiration dates for this ticker.")
            return
        expiry_columns = st.columns([0.82, 1.24, 3.2], gap="small",
                                    vertical_alignment="bottom")
        with expiry_columns[0]:
            target_dte = int(st.number_input(
                "HOW MANY DAYS OUT?", min_value=1, max_value=730,
                value=60, step=1, key="pp_target_dte",
                help="Automatically select the closest listed expiration.",
            ))
        closest = min(
            expirations, key=lambda item: (abs((item - today).days - target_dte), item),
        )
        if (
            st.session_state.get("_pp_last_target_dte") != target_dte
            or st.session_state.get("_pp_last_expiry_symbol") != symbol
            or st.session_state.get("pp_expiry") not in expirations
        ):
            st.session_state["pp_expiry"] = closest
        st.session_state["_pp_last_target_dte"] = target_dte
        st.session_state["_pp_last_expiry_symbol"] = symbol
        with expiry_columns[1]:
            chosen_expiry = st.selectbox(
                "LISTED EXPIRATION DATES", expirations, key="pp_expiry",
                format_func=lambda item: (
                    f"{item:%m-%d-%y} // {(item - today).days} DTE"
                ),
                help="Choose any listed date; the highlighted hedge uses this expiry.",
            )
        with expiry_columns[2]:
            st.caption(
                f"{len(expirations)} LISTED EXPIRATIONS // "
                f"SELECTED {(chosen_expiry - today).days} DAYS OUT // "
                "LOSS TARGET $0 // SAME-TICKER PUTS ONLY"
            )

        # Limit broker/public chain fetches to the 10 closest expirations;
        # always include the user-selected date, regardless of target days.
        nearby = sorted(
            expirations,
            key=lambda item: (
                abs((item - chosen_expiry).days), item
            ),
        )[:10]
        scan_dates = sorted(set([chosen_expiry, *nearby]))
        current_fingerprint = (
            symbol, round(stock_price, 4), shares,
            target_dte, chosen_expiry.isoformat(),
            expiration_source, tuple(scan_dates),
        )
        if st.button(
            "FIND LOWEST-LOSS PROTECTIVE PUTS BY EXPIRATION",
            type="primary", width="stretch", key="pp_scan",
        ):
            progress = st.progress(0.0, text="Comparing listed expiration puts...")
            frames: list[pd.DataFrame] = []
            errors: list[str] = []
            chain_sources: set[str] = set()
            for index, expiry in enumerate(scan_dates, start=1):
                try:
                    rows, _, chain_source = _put_chain(client, symbol, expiry, touch_session)
                    chain_sources.add(chain_source)
                    frame = build_put_analysis(
                        rows, expiry=expiry, stock_price=stock_price,
                        shares=shares, today=today,
                    )
                    if not frame.empty:
                        frames.append(frame)
                except Exception as exc:
                    errors.append(f"{expiry.isoformat()}: {exc}")
                progress.progress(
                    index / len(scan_dates),
                    text=f"Comparing {expiry:%m-%d-%y} // {index}/{len(scan_dates)}",
                )
            progress.empty()
            st.session_state["pp_scan_result"] = {
                "fingerprint": current_fingerprint,
                "symbol": symbol, "stock_price": stock_price,
                "shares": shares, "target_dte": target_dte,
                "chosen_expiry": chosen_expiry,
                "frame": pd.concat(frames, ignore_index=True) if frames else pd.DataFrame(),
                "errors": errors, "chain_sources": sorted(chain_sources),
            }

        result = st.session_state.get("pp_scan_result")
        if isinstance(result, dict):
            if result.get("fingerprint") == current_fingerprint:
                _render_scan_result(result)
            else:
                st.caption("INPUTS CHANGED // run the Protective Put scan again to refresh the table.")


def render_protective_puts(client, touch_session) -> None:
    """Render the production Protective Puts read-only analytics workspace."""
    _render_protective_puts_fragment(client, touch_session)


