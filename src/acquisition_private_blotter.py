"""Readable Acquisition trade blotter in a verified PRIVATE GitHub repository.

OWNERSHIP / EDITING NOTES
EDIT THIS FILE FOR: Private readable historical stock/ETF blotter and history backups.
DO NOT EDIT THIS FILE FOR: Public GEX export, broker orders, OAuth, UI/theme,
                           or the legacy encrypted recovery archive.

Never publish readable brokerage history to G-enterpriseGroup/Screeners.
The selected repository MUST be private at each actual publish.
"""

