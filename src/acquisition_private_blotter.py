from src.acquisition_history_github import ArchiveConfig, ArchiveError


PRIVATE_REPO = "G-enterpriseGroup/Portfolio"
BRANCH = "acquisition-history-data"
PREFIX = "acquisition/history/"
_MAX_RESPONSE_BYTES = 18_000_000
_VERTICAL_COLUMNS = (
    "ticker", "type", "expiry", "long", "short", "qty", "status", "opened", "closed",
    "open_net", "close_net", "fees", "pnl", "currency", "match", "basis", "open_ids", "close_ids",
)


def _json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)


def _number(value: float) -> str:
    return f"{value:.8f}".rstrip("0").rstrip(".")


def share_blotter(
    rows: list[dict[str, Any]],
    parse_trade: Callable[[dict[str, Any]], dict[str, Any] | None],
) -> str:
    """Full known buy/sell history, not only the currently open FIFO lots.

    Keep exactly five space-separated Pine fields per line. No CSV headers,
    lot numbers, or comments are added to the ready-to-copy text.
    """
    events = []
    for raw in rows:
        if not isinstance(raw, dict):
            continue
        trade = parse_trade(raw)
        if not trade or trade.get("action") not in ("BUY", "SELL"):
            continue
        try:
            price, quantity = float(trade["price"]), float(trade["quantity"])
            when = trade["when"]
            ticker = str(trade["symbol"]).upper().strip()
            if (not ticker or any(x.isspace() for x in ticker) or
                    not math.isfinite(price) or not math.isfinite(quantity) or
                    price <= 0 or quantity <= 0):
                continue
            action = "B" if trade["action"] == "BUY" else "S"
            events.append((when, str(trade["id"]), ticker, price, quantity, action))
        except (KeyError, TypeError, ValueError, OverflowError):
            continue
    events.sort(key=lambda event: (event[0], event[1]))
    return "\n".join(
        f"{ticker} {when:%m.%d.%Y} {_number(price)} {_number(qty)} {action}"
        for when, _, ticker, price, qty, action in events
    ) + ("\n" if events else "")


class PrivateTradeBlotter:
    """Per-account plaintext historical broker ledger and readable Pine .txt.

    All data, including the raw-source JSON, lives in a *separate* private
    GitHub repository. The legacy public-repo backups remain encrypted.
    """

    def __init__(self, config: ArchiveConfig, repo: str = PRIVATE_REPO):
        if repo != PRIVATE_REPO:
            raise ArchiveError("Readable blotter target is not the approved private repository.")
        self.repo = repo
        # Fine-grained PAT may be scoped to the private Portfolio repository,
        # independently from the existing public Screeners/GEX GitHub PAT.
        try:
            import streamlit as st
            section = st.secrets.get("acquisition", {})
            dedicated = section.get("blotter_token", "") if isinstance(section, Mapping) else ""
        except Exception:
            dedicated = ""
        # An explicitly saved Streamlit [acquisition] blotter_token MUST win
        # over old environment variables and the public-repo GEX token.
        # A stale ACQUISITION_BLOTTER_TOKEN environment setting previously
        # shadowed a newly saved Streamlit Secrets value.
        env_token = str(os.environ.get("ACQUISITION_BLOTTER_TOKEN") or "").strip()
        if str(dedicated).strip():
            self.token = str(dedicated).strip()
            self.token_source = "Streamlit [acquisition] blotter_token"
        elif env_token:
            self.token = env_token
            self.token_source = "ACQUISITION_BLOTTER_TOKEN environment"
        else:
            self.token = config.token
            self.token_source = "fallback GitHub/GEX token"
        # Existing encrypted-archive/GEX credential may independently have
        # private Portfolio access even when the dedicated token does not.
        self._fallback_token = config.token if config.token != self.token else ""
        self._secret = base64.urlsafe_b64decode(config.fernet_key)

    def _stem(self, account_key: str) -> str:
        if not account_key:
            raise ArchiveError("Missing account key.")
        return hmac.new(
            self._secret,
            b"acquisition-readable-history:" + str(account_key).encode("utf-8"),
            hashlib.sha256,
        ).hexdigest()

    def _legacy_paths(self, account_key: str) -> tuple[str, str]:
        stem = self._stem(account_key)
        return PREFIX + stem + ".json", PREFIX + stem + ".txt"

    def paths(self, account_key: str) -> tuple[str, str]:
        # Account-scoped folders; preserve the stable keyed hash across syncs.
        folder = PREFIX + "accounts/" + self._stem(account_key) + "/"
        return folder + "history.json", folder + "trades.txt"

    def named_paths(self, account_key: str, account_name: str, last_four: str = "") -> tuple[str, str]:
        """Human-readable private mirrors; keyed primary history never moves."""
        clean = unicodedata.normalize("NFKC", str(account_name or "E*TRADE Account"))
        clean = re.sub(r"[^\w .&()'-]+", "-", clean, flags=re.UNICODE)
        clean = re.sub(r"\s+", " ", clean).strip(" .-_")
        clean = clean[:64].rstrip(" .-_") or "E*TRADE Account"
        suffix = re.sub(r"\D", "", str(last_four or ""))[-4:]
        label = clean + (f" - {suffix}" if suffix else "")
        # Suffix avoids collisions between equal names, joint accounts and
        # changed broker nicknames; it never exposes the full broker key.
        folder = PREFIX + "by-account/" + label + " -- " + self._stem(account_key)[:16] + "/"
        return folder + "history.json", folder + "trades.txt"

    def vertical_paths(self, account: str, account_name: str = "", last_four: str = "") -> tuple[str, str]:
        history, _ = (self.named_paths(account, account_name, last_four) if account_name
                      else self.paths(account))
        folder = history.rsplit("/", 1)[0] + "/"
        return folder + "vertical_blotter.json", folder + "vertical_blotter.csv"

    def page_url(self, account_key: str, account_name: str = "", last_four: str = "") -> str:
        _, txt = (self.named_paths(account_key, account_name, last_four) if account_name
                  else self.paths(account_key))
        return f"https://github.com/{self.repo}/blob/{BRANCH}/{urllib.parse.quote(txt, safe='/')}"

    def _request(self, path: str, *, payload: dict[str, Any] | None = None,
                 ref: str = BRANCH) -> dict[str, Any] | None:
        endpoint = f"https://api.github.com/repos/{self.repo}"
        url = endpoint + ("/contents/" + urllib.parse.quote(path, safe="/") if path else "")
        if payload is None and path:
            url += "?ref=" + urllib.parse.quote(ref, safe="")
        headers = {
            "Authorization": "Bearer " + self.token,
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "raj-terminal-private-trade-blotter",
            "Cache-Control": "no-cache",
        }
        req = urllib.request.Request(
            url, method="GET" if payload is None else "PUT",
            headers=headers if payload is None else {**headers, "Content-Type": "application/json"},
            data=None if payload is None else _json(payload).encode("utf-8"),
        )
        try:
            with urllib.request.urlopen(req, timeout=20) as response:
                content = response.read(_MAX_RESPONSE_BYTES + 1)
            if len(content) > _MAX_RESPONSE_BYTES:
                raise ArchiveError("GitHub blotter archive response is too large.")
            return json.loads(content.decode("utf-8"))
        except urllib.error.HTTPError as exc:
            if exc.code == 404 and payload is None and path:
                return None
            if exc.code in (409, 422) and payload is not None:
                raise _Conflict() from exc
            if not path and exc.code in (401, 403, 404):
                raise ArchiveError(
                    "STREAMLIT GITHUB TOKEN CANNOT ACCESS PRIVATE PORTFOLIO "
                    f"(HTTP {exc.code}) // Credential source: {self.token_source}. "
                    "If this is your [acquisition] blotter_token, GitHub is rejecting "
                    "that token for the private Portfolio repository; verify its "
                    "resource owner, selected repository, authorization and "
                    "Contents: Read and write permission. No key changes are needed."
                ) from exc
            raise ArchiveError(f"Private GitHub blotter access failed (HTTP {exc.code}).") from exc
        except (urllib.error.URLError, OSError, TimeoutError, ValueError) as exc:
            raise ArchiveError("Private GitHub blotter could not be reached.") from exc

    def _token_identity_diagnostic(self) -> str:
        """Probe auth only after repo denial; never log or display credential data."""
        headers = {
            "Authorization": "Bearer " + self.token,
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "raj-terminal-private-trade-blotter",
        }
        request = urllib.request.Request("https://api.github.com/user", headers=headers)
        try:
            with urllib.request.urlopen(request, timeout=8) as response:
                data = json.loads(response.read(32768).decode("utf-8"))
        except urllib.error.HTTPError as exc:
            if exc.code == 401:
                return "TOKEN CHECK: GitHub rejected this token (401: expired, revoked or invalid)."
            if exc.code == 403:
                return "TOKEN CHECK: GitHub blocked identity verification (403)."
            return f"TOKEN CHECK: GitHub identity endpoint returned HTTP {exc.code}."
        except (urllib.error.URLError, OSError, TimeoutError, ValueError):
            return "TOKEN CHECK: GitHub identity could not be verified."
        login = str(data.get("login") or "") if isinstance(data, dict) else ""
        if not login:
            return "TOKEN CHECK: GitHub returned no authenticated user."
        if login.casefold() != "g-enterprisegroup":
            return (
                f"TOKEN CHECK: Authenticated GitHub account is @{login}, not "
                "@G-enterpriseGroup (owner of PRIVATE Portfolio). Review the "
                "existing token's resource owner and selected repositories."
            )
        return (
            "TOKEN CHECK: Token authenticates as @G-enterpriseGroup, but Portfolio "
            "is not accessible through this credential. Edit the existing fine-grained "
            "token's Selected repositories to include Portfolio, then set "
            "Contents: Read and write. No encryption-key change is needed."
        )

    def _verify_private(self) -> None:
        try:
            response = self._request("")
        except ArchiveError as error:
            # Only retry a known private-repository credential denial; never
            # retry failures from unrelated GitHub transport/JSON operations.
            if "STREAMLIT GITHUB TOKEN CANNOT ACCESS PRIVATE PORTFOLIO" not in str(error):
                raise
            if self._fallback_token:
                selected, original_source = self.token, self.token_source
                self.token = self._fallback_token
                try:
                    candidate = self._request("")
                    if (isinstance(candidate, dict) and
                            candidate.get("full_name") == self.repo and
                            candidate.get("private") is True and
                            candidate.get("archived") is not True):
                        self.token_source = "existing GitHub encrypted-archive credential (verified private)"
                        return
                except ArchiveError:
                    pass
                self.token, self.token_source = selected, original_source
            raise ArchiveError(str(error) + " // " + self._token_identity_diagnostic()) from error
        if (not isinstance(response, dict) or
                response.get("full_name") != self.repo or
                response.get("private") is not True or
                response.get("archived") is True):
            raise ArchiveError(
                "READABLE BLOTTER BLOCKED // The destination must remain a private, writable GitHub repository."
            )

    @staticmethod
    def _unpack(result: dict[str, Any] | None) -> tuple[str, str | None]:
        if result is None:
            return "", None
        if not isinstance(result, dict) or not isinstance(result.get("content"), str):
            raise ArchiveError("GitHub blotter file has no readable content; refusing overwrite.")
        try:
            encoded = result["content"].replace("\n", "")
            raw = base64.b64decode(encoded, validate=True).decode("utf-8")
        except (ValueError, UnicodeError, binascii.Error) as exc:
            raise ArchiveError("GitHub blotter content is corrupted; refusing overwrite.") from exc
        return str(result.get("sha") or ""), raw

    def _read_history(self, result: dict[str, Any] | None, account: str) -> tuple[str, dict[str, Any] | None]:
        sha, raw = self._unpack(result)
        if raw is None:
            return sha, None
        try:
            decoded = json.loads(raw)
            if (decoded["version"] != 1 or decoded["account"] != account or
                    not isinstance(decoded["rows"], list) or
                    not all(isinstance(tx, dict) for tx in decoded["rows"])):
                raise ValueError("Different account or invalid rows")
            from datetime import date
            date.fromisoformat(decoded["covered_from"])
            date.fromisoformat(decoded["covered_through"])
            if decoded["covered_from"] > decoded["covered_through"]:
                raise ValueError("Invalid history cursor")
            return sha, decoded
        except (ValueError, KeyError, TypeError) as exc:
            raise ArchiveError("Private GitHub history is invalid; refusing overwrite.") from exc

    def read_snapshot(self, account: str, *, preverified: bool = False) -> dict[str, Any] | None:
        """Restore persisted trades; block corruption or cross-account records.

        preverified=True is used only after the caller has authenticated and
        confirmed PRIVATE repository visibility for this account batch.
        """
        if not preverified:
            self._verify_private()
        history_path, _ = self.paths(account)
        _, snapshot = self._read_history(self._request(history_path), account)
        if snapshot is None:
            # Pre-folder archives remain readable after a restart/redeploy.
            legacy_path, _ = self._legacy_paths(account)
            _, snapshot = self._read_history(self._request(legacy_path), account)
        if snapshot is None:
            return None
        return {
            "rows": list(snapshot["rows"]),
            "covered_from": snapshot["covered_from"],
            "covered_through": snapshot["covered_through"],
            "synced_at": float(snapshot.get("synced_at") or 0),
        }

    @staticmethod
    def _validate_vertical_cache(payload: Any, account: str) -> dict[str, Any]:
        try:
            from datetime import date
            if (not isinstance(payload, dict) or payload["account"] != account or
                    type(payload["schema_version"]) is not int or payload["schema_version"] != 1 or
                    type(payload["algorithm_version"]) is not int or payload["algorithm_version"] < 1 or
                    not isinstance(payload["source_fingerprint"], str) or
                    not re.fullmatch(r"[0-9a-fA-F]{64}", payload["source_fingerprint"]) or
                    not all(isinstance(payload[key], list) and all(isinstance(row, dict) for row in payload[key])
                            for key in ("events", "review", "blotter"))):
                raise ValueError("Invalid vertical cache envelope")
            if "result_fingerprint" in payload and (
                    not isinstance(payload["result_fingerprint"], str) or
                    not re.fullmatch(r"[0-9a-fA-F]{64}", payload["result_fingerprint"])):
                raise ValueError("Invalid result fingerprint")
            date.fromisoformat(payload["covered_from"])
            date.fromisoformat(payload["covered_through"])
            if payload["covered_from"] > payload["covered_through"]:
                raise ValueError("Invalid coverage")
            # Do not silently turn dates, tuples, non-string keys or NaN into
            # a different persisted cache than the builder actually produced.
            encoded = json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)
            if json.loads(encoded) != payload:
                raise ValueError("Non-native JSON cache")
            if "result_fingerprint" in payload:
                result = {key: payload[key] for key in ("events", "review", "blotter")}
                digest = hashlib.sha256(json.dumps(result, sort_keys=True, separators=(",", ":"),
                                                   allow_nan=False).encode()).hexdigest()
                if payload["result_fingerprint"] != digest:
                    raise ValueError("Vertical results changed without a matching fingerprint")
            return payload
        except (ValueError, KeyError, TypeError, OverflowError) as exc:
            raise ArchiveError("Private GitHub vertical cache is invalid; rebuild it from source history.") from exc

    def read_vertical_cache(self, account: str, *, preverified: bool = False) -> dict[str, Any] | None:
        """Read a derived cache only; raw history is always restored separately."""
        if not preverified:
            self._verify_private()
        path, _ = self.vertical_paths(account)
        _, raw = self._unpack(self._request(path))
        if raw is None:
            return None
        try:
            payload = json.loads(raw)
        except (ValueError, TypeError) as exc:
            raise ArchiveError("Private GitHub vertical cache is invalid; rebuild it from source history.") from exc
        return self._validate_vertical_cache(payload, account)

    def save_vertical_cache(
        self, account: str, payload: dict[str, Any], *, covered_from: str, covered_through: str,
        account_name: str = "", last_four: str = "", preverified: bool = False,
    ) -> dict[str, Any]:
        """Publish a rebuildable report without changing the source history."""
        self.vertical_error = ""
        self.vertical_payload = None
        if not preverified:
            self._verify_private()
        if not isinstance(payload, dict) or payload.get("account", account) != account:
            raise ArchiveError("Private GitHub vertical cache belongs to a different account.")
        envelope = self._validate_vertical_cache({
            **payload, "account": account, "covered_from": covered_from, "covered_through": covered_through,
        }, account)
        canonical = json.dumps(envelope, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n"
        output = io.StringIO(newline="")
        writer = csv.writer(output, lineterminator="\n")
        writer.writerow(_VERTICAL_COLUMNS)
        for row in envelope["blotter"]:
            writer.writerow(
                json.dumps(row[key], separators=(",", ":"), allow_nan=False)
                if isinstance(row.get(key), (list, dict)) else row.get(key)
                for key in _VERTICAL_COLUMNS
            )
        readable = output.getvalue()
        paths = [self.vertical_paths(account)]
        if account_name:
            paths.append(self.vertical_paths(account, account_name, last_four))
        for json_path, csv_path in paths:
            self._write_text(json_path, canonical)
            self._write_text(csv_path, readable)
        self.vertical_payload = envelope
        return envelope

    def _write_text(self, path: str, content: str) -> None:
        for attempt in range(3):
            existing_sha, previous = self._unpack(self._request(path))
            if previous == content:
                return
            payload: dict[str, Any] = {
                "message": "Update Acquisition readable trade blotter",
                "branch": BRANCH,
                "content": base64.b64encode(content.encode("utf-8")).decode("ascii"),
            }
            if existing_sha:
                payload["sha"] = existing_sha
            try:
                response = self._request(path, payload=payload)
                commit = (response or {}).get("commit", {}).get("sha")
                if not commit:
                    raise ArchiveError("GitHub did not confirm blotter upload.")
                _, readback = self._unpack(self._request(path, ref=commit))
                if readback != content:
                    raise ArchiveError("Blotter commit verification failed.")
                return
            except _Conflict:
                if attempt == 2:
                    raise ArchiveError("Concurrent GitHub blotter updates conflicted.")
                time.sleep((attempt + 1) * .2)

    def save(
        self, account: str, snapshot: dict[str, Any],
        merge: Callable[[list[dict[str, Any]], list[dict[str, Any]]], list[dict[str, Any]]],
        parse_trade: Callable[[dict[str, Any]], dict[str, Any] | None],
        *, build_verticals: Callable[[list[dict[str, Any]]], dict[str, Any]] | None = None,
    ) -> str:
        """Save a canonical plaintext full ledger, then a human-readable blotter.

        Never discard old trades when the local worker has stale/partial history.
        Keep the canonical JSON as the durable source for future correction merges.
        """
        self.vertical_error = ""
        self.vertical_payload = None
        self.canonical_snapshot = None
        self._verify_private()  # Mandatory; no plaintext write to public repos.
        json_path, text_path = self.paths(account)
        for attempt in range(4):
            sha, previous = self._read_history(self._request(json_path), account)
            if previous is None:
                # Never bootstrap a shorter history over a legacy ledger.
                old_json, _ = self._legacy_paths(account)
                _, previous = self._read_history(self._request(old_json), account)
            joined = {
                "version": 1, "account": account,
                "rows": merge((previous or {}).get("rows", []), snapshot["rows"]),
                "covered_from": min((previous or {}).get("covered_from", snapshot["covered_from"]),
                                    snapshot["covered_from"]),
                "covered_through": max((previous or {}).get("covered_through", snapshot["covered_through"]),
                                      snapshot["covered_through"]),
                "synced_at": max(float((previous or {}).get("synced_at") or 0),
                                 float(snapshot.get("synced_at") or 0)),
            }
            canonical = _json(joined) + "\n"
            if previous is None or _json(previous) != _json(joined):
                payload: dict[str, Any] = {
                    "message": "Preserve Acquisition canonical plaintext trade history",
                    "branch": BRANCH,
                    "content": base64.b64encode(canonical.encode("utf-8")).decode("ascii"),
                }
                if sha:
                    payload["sha"] = sha
                try:
                    result = self._request(json_path, payload=payload)
                    commit = (result or {}).get("commit", {}).get("sha")
                    if not commit:
                        raise ArchiveError("Historical ledger commit not confirmed.")
                    _, verification = self._read_history(
                        self._request(json_path, ref=commit), account,
                    )
                    if verification != joined:
                        raise ArchiveError("Historical ledger read-back mismatch.")
                except _Conflict:
                    if attempt == 3:
                        raise ArchiveError("Concurrent GitHub history updates conflicted.")
                    time.sleep((attempt + 1) * .2)
                    continue
            readable = share_blotter(joined["rows"], parse_trade)
            self._write_text(text_path, readable)
            name = str(snapshot.get("account_name") or "").strip()
            if name:
                # Only mirror the verified canonical ledger. Named folders are
                # navigable copies; never restore from a nickname-based path.
                named_json, named_txt = self.named_paths(
                    account, name, str(snapshot.get("account_last_four") or ""),
                )
                self._write_text(named_json, canonical)
                self._write_text(named_txt, readable)
            url = self.page_url(account, name, str(snapshot.get("account_last_four") or ""))
            self.canonical_snapshot = joined
            if build_verticals is not None:
                # Build from the verified canonical merge, including older or
                # corrected rows another worker preserved remotely.
                try:
                    self.save_vertical_cache(
                        account, build_verticals(joined["rows"]),
                        covered_from=joined["covered_from"], covered_through=joined["covered_through"],
                        account_name=name, last_four=str(snapshot.get("account_last_four") or ""),
                        preverified=True,
                    )
                except Exception:
                    self.vertical_error = "VERTICAL BLOTTER BACKUP FAILED // source history remains saved; retry later."
            return url
        raise ArchiveError("Private GitHub trade history was not saved.")


class _Conflict(Exception):
    pass
