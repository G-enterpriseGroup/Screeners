"""Private encrypted Acquisition trade-history snapshots on GitHub data branch.

OWNERSHIP / EDITING NOTES
EDIT THIS FILE FOR: Acquisition GitHub read/write/restore, encryption and conflict handling.
DO NOT EDIT THIS FILE FOR: GEX publishing, trading orders, OAuth, shared UI or Risk Sizing.

This repository is public. NEVER upload plaintext trade or account data.
Every payload, including account identity, remains inside Fernet ciphertext.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import time
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass
from typing import Any, Callable

from cryptography.fernet import Fernet, InvalidToken


REPO = "G-enterpriseGroup/Screeners"
BRANCH = "gex-bridge-data"  # Existing data-only branch: never write to main.
PREFIX = "bridge/acquisition/v1/"
_MAX_BYTES = 12_000_000


class ArchiveError(RuntimeError):
    """A failed/unsafe archive operation; the previous remote file is untouched."""


@dataclass(frozen=True)
class ArchiveConfig:
    token: str
    fernet_key: str

    @classmethod
    def from_runtime(cls) -> "ArchiveConfig | None":
        """Use separately configured archive key; optionally reuse GEX GitHub PAT."""
        secrets: dict[str, Any] = {}
        try:
            import streamlit as st
            secrets = dict(st.secrets)
        except (FileNotFoundError, OSError, RuntimeError, Exception):
            secrets = {}

        def group_value(group: str, field: str) -> str:
            value = secrets.get(group, {})
            return str(value.get(field, "") if isinstance(value, dict) else "").strip()

        key = str(os.environ.get("ACQUISITION_ARCHIVE_KEY") or
                  secrets.get("ACQUISITION_ARCHIVE_KEY") or
                  group_value("acquisition", "archive_key") or "").strip()
        token = str(os.environ.get("ACQUISITION_GITHUB_TOKEN") or
                    secrets.get("ACQUISITION_GITHUB_TOKEN") or
                    group_value("acquisition", "github_token") or
                    group_value("github", "bridge_token") or
                    os.environ.get("GEX_GITHUB_TOKEN") or "").strip()
        if not key or not token:
            return None
        try:
            Fernet(key.encode("ascii"))
        except (ValueError, TypeError, UnicodeError) as exc:
            raise ArchiveError("Acquisition archive encryption key is invalid.") from exc
        return cls(token=token, fernet_key=key)


def _canonical(snapshot: dict[str, Any]) -> bytes:
    return json.dumps(snapshot, sort_keys=True, separators=(",", ":"), default=str).encode("utf-8")


class GitHubAcquisitionArchive:
    """Encrypted per-account snapshot with optimistic locking and read-back verification."""

    def __init__(self, config: ArchiveConfig):
        self.token = config.token
        self._key = base64.urlsafe_b64decode(config.fernet_key)
        self._cipher = Fernet(config.fernet_key.encode("ascii"))

    def path(self, account_key: str) -> str:
        key = str(account_key or "").strip()
        if not key:
            raise ArchiveError("Cannot archive a missing account key.")
        identifier = hmac.new(self._key, b"acquisition-account-v1:" + key.encode(), hashlib.sha256).hexdigest()
        return PREFIX + identifier + ".txt"

    def _request(self, path: str, *, ref: str = BRANCH,
                 payload: dict[str, Any] | None = None) -> dict[str, Any] | None:
        encoded_path = urllib.parse.quote(path, safe="/")
        url = f"https://api.github.com/repos/{REPO}/contents/{encoded_path}"
        if payload is None:
            url += "?ref=" + urllib.parse.quote(ref, safe="")
        headers = {
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "Authorization": "Bearer " + self.token,
            "User-Agent": "raj-terminal-acquisition-archive",
            "Cache-Control": "no-cache",
        }
        request = urllib.request.Request(
            url, method="GET" if payload is None else "PUT",
            data=None if payload is None else json.dumps(payload).encode("utf-8"),
            headers=headers if payload is None else {**headers, "Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=18) as response:
                raw = response.read(_MAX_BYTES + 1)
            if len(raw) > _MAX_BYTES:
                raise ArchiveError("Encrypted Acquisition file exceeds configured safety limit.")
            result = json.loads(raw.decode("utf-8"))
            if not isinstance(result, dict):
                raise ArchiveError("GitHub returned an unexpected archive response.")
            return result
        except urllib.error.HTTPError as exc:
            if payload is None and exc.code == 404:
                return None
            if payload is not None and exc.code in (409, 422):
                raise _Conflict() from exc
            raise ArchiveError(f"GitHub Acquisition archive request failed (HTTP {exc.code}).") from exc
        except (urllib.error.URLError, TimeoutError, OSError, ValueError) as exc:
            raise ArchiveError("GitHub Acquisition archive is unreachable or invalid.") from exc

    def _decode(self, result: dict[str, Any] | None, account_key: str) -> tuple[str, dict[str, Any] | None]:
        if result is None:
            return "", None
        content = result.get("content")
        if not isinstance(content, str):
            raise ArchiveError("GitHub archive has no encrypted content; refusing overwrite.")
        try:
            cipherbytes = base64.b64decode(content.replace("\n", ""), validate=True)
            doc = json.loads(self._cipher.decrypt(cipherbytes))
            if (not isinstance(doc, dict) or doc.get("version") != 1 or
                    not hmac.compare_digest(str(doc.get("account") or ""), str(account_key))):
                raise ValueError("Invalid encrypted archive scope")
            snapshot = doc.get("snapshot")
            if not isinstance(snapshot, dict) or not isinstance(snapshot.get("rows"), list):
                raise ValueError("Invalid archive history")
            if not isinstance(snapshot.get("covered_from"), str) or not isinstance(snapshot.get("covered_through"), str):
                raise ValueError("Invalid archive checkpoint")
            from datetime import date
            date.fromisoformat(snapshot["covered_from"])
            date.fromisoformat(snapshot["covered_through"])
            if snapshot["covered_from"] > snapshot["covered_through"]:
                raise ValueError("Invalid archive coverage")
            if not all(isinstance(tx, dict) for tx in snapshot["rows"]):
                raise ValueError("Invalid historical trade")
            return str(result.get("sha") or ""), snapshot
        except (InvalidToken, ValueError, TypeError, KeyError, json.JSONDecodeError) as exc:
            raise ArchiveError("Encrypted Acquisition archive cannot be verified; refusing overwrite.") from exc

    def read(self, account_key: str) -> dict[str, Any] | None:
        _, snapshot = self._decode(self._request(self.path(account_key)), account_key)
        return snapshot

    @staticmethod
    def _merged(base: dict[str, Any] | None, local: dict[str, Any],
                merge_transactions: Callable[[list[dict[str, Any]], list[dict[str, Any]]], list[dict[str, Any]]]) -> dict[str, Any]:
        if base is None:
            return dict(local)
        return {
            "rows": merge_transactions(base["rows"], local["rows"]),
            "covered_from": min(base["covered_from"], local["covered_from"]),
            "covered_through": max(base["covered_through"], local["covered_through"]),
            "synced_at": max(float(base.get("synced_at") or 0), float(local.get("synced_at") or 0)),
        }

    def save(self, account_key: str, local: dict[str, Any],
             merge_transactions: Callable[[list[dict[str, Any]], list[dict[str, Any]]], list[dict[str, Any]]]) -> dict[str, Any]:
        """Re-read latest remote, merge history and preserve previous snapshot on error.

        Concurrent writers may race. SHA CAS prevents silent overwrite; retry merges
        the winner into the next attempt. Verified commit is immutable in GitHub.
        """
        if (not isinstance(local.get("rows"), list) or
                not all(isinstance(tx, dict) for tx in local["rows"])):
            raise ArchiveError("Refusing to archive invalid transaction history.")
        path = self.path(account_key)
        last: Exception | None = None
        for attempt in range(4):
            try:
                sha, remote = self._decode(self._request(path), account_key)
                merged = self._merged(remote, local, merge_transactions)
                # Avoid an unnecessary commit for the exact same transactions/date
                # window (synced_at is in-memory freshness, not a durable change).
                comparable = lambda snap: {
                    "rows": snap["rows"], "covered_from": snap["covered_from"],
                    "covered_through": snap["covered_through"],
                }
                if remote is not None and _canonical(comparable(remote)) == _canonical(comparable(merged)):
                    return merged
                data = self._cipher.encrypt(_canonical({
                    "version": 1, "account": account_key, "snapshot": merged,
                })).decode("ascii")
                body: dict[str, Any] = {
                    "message": "Update encrypted Acquisition history snapshot",
                    "branch": BRANCH,
                    "content": base64.b64encode((data + "\n").encode("utf-8")).decode("ascii"),
                }
                if sha:
                    body["sha"] = sha
                response = self._request(path, payload=body)
                commit = str((response or {}).get("commit", {}).get("sha") or "")
                if not commit:
                    raise ArchiveError("GitHub did not confirm an Acquisition archive commit.")
                # Verify the exact committed object, not an eventually cached branch.
                _, verified = self._decode(self._request(path, ref=commit), account_key)
                if verified is None or _canonical(verified) != _canonical(merged):
                    raise ArchiveError("Committed Acquisition history failed read-back verification.")
                return merged
            except _Conflict as exc:
                last = exc
                if attempt < 3:
                    time.sleep(0.25 * (attempt + 1))
                    continue
            except ArchiveError:
                raise
        raise ArchiveError("Concurrent GitHub updates prevented safe Acquisition history saving.") from last


class _Conflict(Exception):
    pass
