from __future__ import annotations

import secrets
from datetime import date
from typing import Any


def _as_list(value: Any) -> list[Any]:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def _find_key(value: Any, wanted: str) -> Any:
    wanted = str(wanted).casefold()
    if isinstance(value, dict):
        for key, child in value.items():
            if str(key).casefold() == wanted:
                return child
        for child in value.values():
            found = _find_key(child, wanted)
            if found is not None:
                return found
    elif isinstance(value, list):
        for child in value:
            found = _find_key(child, wanted)
            if found is not None:
                return found
    return None


def new_vertical_client_order_id(prefix: str = "VO") -> str:
    """Return a unique E*TRADE-safe <=20-character client order id."""
    clean = "".join(ch for ch in str(prefix).upper() if ch.isalnum())[:3] or "VO"
    return clean + secrets.token_hex(8).upper()


def validate_vertical(
    *,
    call_put: str,
    buy_strike: float,
    sell_strike: float,
    quantity: int,
) -> None:
    """Validate the canonical debit vertical structure requested by Raj."""
    side = str(call_put or "").strip().upper()
    if side not in {"CALL", "PUT"}:
        raise ValueError("Vertical type must be CALL or PUT.")
    try:
        buy = float(buy_strike)
        sell = float(sell_strike)
        qty = int(quantity)
    except (TypeError, ValueError) as exc:
        raise ValueError("Strikes and quantity must be valid numbers.") from exc
    if buy <= 0 or sell <= 0:
        raise ValueError("Both strikes must be positive.")
    if qty <= 0:
        raise ValueError("Quantity must be at least 1.")
    if side == "CALL" and not buy < sell:
        raise ValueError("Call debit vertical requires BUY strike below SELL strike.")
    if side == "PUT" and not buy > sell:
        raise ValueError("Put debit vertical requires BUY strike above SELL strike.")


def build_vertical_preview_payload(
    *,
    symbol: str,
    call_put: str,
    expiry: date,
    buy_strike: float,
    sell_strike: float,
    quantity: int,
    limit_price: float,
    order_term: str = "GOOD_FOR_DAY",
    client_order_id: str | None = None,
) -> dict[str, Any]:
    """Build a two-leg E*TRADE NET_DEBIT vertical spread preview request."""
    symbol = str(symbol or "").strip().upper()
    if not symbol:
        raise ValueError("A ticker is required.")
    if not isinstance(expiry, date):
        raise ValueError("A valid expiration date is required.")
    validate_vertical(
        call_put=call_put,
        buy_strike=buy_strike,
        sell_strike=sell_strike,
        quantity=quantity,
    )
    term = str(order_term or "").strip().upper()
    if term not in {"GOOD_FOR_DAY", "GOOD_UNTIL_CANCEL"}:
        raise ValueError("Duration must be DAY or GTC.")
    try:
        debit = float(limit_price)
    except (TypeError, ValueError) as exc:
        raise ValueError("Enter a valid debit limit.") from exc
    if debit <= 0:
        raise ValueError("Debit limit must be positive.")

    client_id = str(client_order_id or new_vertical_client_order_id()).strip()
    if not client_id.isalnum() or len(client_id) > 20:
        raise ValueError("Client order id must be <=20 alphanumeric characters.")

    side = str(call_put).upper()
    qty = int(quantity)
    instruments = []
    for action, strike in (("BUY_OPEN", float(buy_strike)), ("SELL_OPEN", float(sell_strike))):
        instruments.append(
            {
                "Product": {
                    "symbol": symbol,
                    "securityType": "OPTN",
                    "callPut": side,
                    "expiryYear": int(expiry.year),
                    "expiryMonth": int(expiry.month),
                    "expiryDay": int(expiry.day),
                    "strikePrice": strike,
                },
                "orderAction": action,
                "orderedQuantity": qty,
                "quantity": qty,
            }
        )

    return {
        "PreviewOrderRequest": {
            "orderType": "SPREADS",
            "clientOrderId": client_id,
            "Order": [
                {
                    "allOrNone": False,
                    "priceType": "NET_DEBIT",
                    "limitPrice": round(debit, 4),
                    "stopPrice": 0.0,
                    "orderTerm": term,
                    "marketSession": "REGULAR",
                    "Instrument": instruments,
                }
            ],
        }
    }


def build_place_payload(preview_payload: dict[str, Any], preview_id: Any) -> dict[str, Any]:
    """Convert one successful preview into the exact E*TRADE place request."""
    request = preview_payload.get("PreviewOrderRequest")
    if not isinstance(request, dict) or preview_id in (None, ""):
        raise ValueError("A successful E*TRADE preview is required before placement.")
    return {
        "PlaceOrderRequest": {
            "orderType": request.get("orderType"),
            "clientOrderId": request.get("clientOrderId"),
            "PreviewIds": [{"previewId": preview_id}],
            "Order": request.get("Order") or [],
        }
    }


def preview_details(payload: dict[str, Any]) -> dict[str, Any]:
    """Normalize the fields needed for the Vertical Options review panel."""
    response = _find_key(payload, "PreviewOrderResponse")
    response = response if isinstance(response, dict) else payload
    preview_id = _find_key(response, "previewId")
    messages: list[str] = []
    for item in _as_list(_find_key(response, "Message")):
        if isinstance(item, dict):
            parts = [
                str(part)
                for part in (
                    item.get("type"),
                    item.get("code"),
                    item.get("description") or item.get("message"),
                )
                if part not in (None, "")
            ]
            if parts:
                messages.append(" // ".join(parts))
        elif item not in (None, ""):
            messages.append(str(item))

    def number(*keys: str) -> float | None:
        for key in keys:
            raw = _find_key(response, key)
            try:
                return float(raw)
            except (TypeError, ValueError):
                continue
        return None

    return {
        "preview_id": preview_id,
        "messages": messages,
        "total_order_value": number("totalOrderValue"),
        "estimated_commission": number("estimatedCommission"),
    }


def extract_order_id(payload: dict[str, Any]) -> Any:
    """Return the first E*TRADE order id from a place response."""
    order_ids = _find_key(payload, "OrderIds")
    for item in _as_list(order_ids):
        if isinstance(item, dict):
            order_id = _find_key(item, "orderId")
        else:
            order_id = item
        if order_id not in (None, ""):
            return order_id
    return _find_key(payload, "orderId")
