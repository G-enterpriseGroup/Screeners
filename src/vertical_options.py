def _as_list(value: Any) -> list[Any]:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def _find_key(value: Any, wanted: str) -> Any:
    wanted = str(wanted).casefold()
    if isinstance(value, dict):
        for key, child in value.items():
            if str(key).casefold() == wanted:
                return child
        for child in value.values():
            found = _find_key(child, wanted)
            if found is not None:
                return found
    elif isinstance(value, list):
        for child in value:
            found = _find_key(child, wanted)
            if found is not None:
                return found
    return None


def new_vertical_client_order_id(prefix: str = "VO") -> str:
    """Return a unique E*TRADE-safe <=20-character client order id."""
    clean = "".join(ch for ch in str(prefix).upper() if ch.isalnum())[:3] or "VO"
    return clean + secrets.token_hex(8).upper()


def validate_vertical(
    *,
    call_put: str,
    buy_strike: float,
    sell_strike: float,
    quantity: int,
) -> None:
    """Validate the canonical debit vertical structure requested by Raj."""
    side = str(call_put or "").strip().upper()
    if side not in {"CALL", "PUT"}:
        raise ValueError("Vertical type must be CALL or PUT.")
    try:
        buy = float(buy_strike)
        sell = float(sell_strike)
        qty = int(quantity)
    except (TypeError, ValueError) as exc:
        raise ValueError("Strikes and quantity must be valid numbers.") from exc
    if buy <= 0 or sell <= 0:
        raise ValueError("Both strikes must be positive.")
    if qty <= 0:
        raise ValueError("Quantity must be at least 1.")
    if side == "CALL" and not buy < sell:
        raise ValueError("Call debit vertical requires BUY strike below SELL strike.")
    if side == "PUT" and not buy > sell:
        raise ValueError("Put debit vertical requires BUY strike above SELL strike.")


# ==============================
# FULL-CHAIN DEBIT-VERTICAL SCAN
# ==============================

_MIN_REWARD_RISK = 2.0


def _finite_number(value: Any, *, positive: bool = False) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError):
        return None
    if not math.isfinite(number) or (number <= 0 if positive else number < 0):
        return None
    return number


def scan_vertical_candidates(
    *,
    symbol: str,
    spot_last: float,
    option_rows: Iterable[dict[str, Any]],
    target_breakeven: float,
    max_cost: float,
    max_per_expiration: int = 20,
) -> tuple[list[dict[str, Any]], set[str]]:
    """Rank one-contract debit spreads across every supplied expiration.

    Prices use each option leg's E*TRADE Last, never bid/ask or midpoint.
    Both canonical directions are scanned: CALL buys the lower strike and
    PUT buys the higher strike. Keep only the top ``max_per_expiration``
    matches per expiration for the table, while finding each calendar year's
    winner from the complete qualifying pair set before that cap is applied.
    The fixed 1:2 ratio is an eligibility gate; qualifying rows rank by
    breakeven distance, then cost, then higher reward:risk.
    """
    ticker = str(symbol or "").strip().upper()
    spot = _finite_number(spot_last, positive=True)
    target = _finite_number(target_breakeven, positive=True)
    budget = _finite_number(max_cost)
    if not ticker or spot is None or target is None or budget is None:
        raise ValueError("Ticker, underlying Last, breakeven, and cost must be valid.")
    if type(max_per_expiration) is not int or max_per_expiration < 1:
        raise ValueError("max_per_expiration must be a positive integer.")

    # One normalized chain row per exact contract. This bounds memory by the
    # input chain size, rather than the quadratic number of possible spreads.
    groups: dict[tuple[date, str], dict[tuple[float, str], dict[str, Any]]] = {}
    for raw in option_rows:
        if not isinstance(raw, dict):
            continue
        expiry = raw.get("expiry")
        if isinstance(expiry, datetime):
            expiry = expiry.date()
        side = str(raw.get("call_put") or "").strip().upper()
        strike = _finite_number(raw.get("strike"), positive=True)
        last = _finite_number(raw.get("last"), positive=True)
        if not isinstance(expiry, date) or side not in {"CALL", "PUT"}:
            continue
        if strike is None or last is None:
            continue
        contract = {
            "strike": strike,
            "last": last,
            "bid": _finite_number(raw.get("bid")),
            "ask": _finite_number(raw.get("ask")),
            "osi": str(raw.get("osi") or "").strip(),
        }
        group = groups.setdefault((expiry, side), {})
        key = (strike, contract["osi"])
        prior = group.get(key)
        # Duplicate transport rows for one contract must not create duplicate
        # spread IDs. Use a quote-value tie break independent of input order.
        quote_key = lambda row: (
            row["last"],
            row["bid"] if row["bid"] is not None else math.inf,
            row["ask"] if row["ask"] is not None else math.inf,
        )
        if prior is None or quote_key(contract) < quote_key(prior):
            group[key] = contract

    retained: dict[date, list[tuple[tuple[Any, ...], dict[str, Any]]]] = {}
    annual_best: dict[int, tuple[tuple[Any, ...], str]] = {}
    for (expiry, side), group in sorted(groups.items()):
        legs = sorted(group.values(), key=lambda row: (row["strike"], row["osi"]))
        top = retained.setdefault(expiry, [])
        for lower_index, lower in enumerate(legs):
            for higher in legs[lower_index + 1:]:
                if lower["strike"] == higher["strike"]:
                    continue
                buy, sell = (lower, higher) if side == "CALL" else (higher, lower)
                debit = round(buy["last"] - sell["last"], 6)
                width = round(higher["strike"] - lower["strike"], 6)
                if not 0 < debit < width:
                    continue
                cost = round(100.0 * debit, 4)
                profit = round(100.0 * (width - debit), 4)
                if not math.isfinite(cost) or not math.isfinite(profit):
                    continue
                if cost > budget or profit < _MIN_REWARD_RISK * cost:
                    continue
                breakeven = round(
                    buy["strike"] + debit if side == "CALL" else buy["strike"] - debit,
                    6,
                )
                ratio = profit / cost
                if not math.isfinite(breakeven) or not math.isfinite(ratio):
                    continue
                identity = "|".join((
                    ticker, expiry.isoformat(), side,
                    f'{buy["strike"]:.6f}', f'{sell["strike"]:.6f}',
                    buy["osi"], sell["osi"],
                ))
                rank = (
                    abs(breakeven - target), cost, -ratio, expiry,
                    side, buy["strike"], sell["strike"],
                    buy["osi"], sell["osi"],
                )
                yearly = annual_best.get(expiry.year)
                if yearly is None or rank < yearly[0]:
                    annual_best[expiry.year] = (rank, identity)
                if len(top) == max_per_expiration and rank >= top[-1][0]:
                    continue
                candidate = {
                    "id": identity, "symbol": ticker, "spot_last": spot,
                    "expiry": expiry, "year": expiry.year, "call_put": side,
                    "buy_strike": buy["strike"], "sell_strike": sell["strike"],
                    "buy_osi": buy["osi"], "sell_osi": sell["osi"],
                    "buy_last": buy["last"], "buy_bid": buy["bid"], "buy_ask": buy["ask"],
                    "sell_last": sell["last"], "sell_bid": sell["bid"], "sell_ask": sell["ask"],
                    "debit": debit, "width": width, "cost": cost,
                    "max_profit": profit, "max_loss": cost,
                    "breakeven": breakeven, "reward_risk": ratio,
                }
                insert_at = next(
                    (index for index, (saved_rank, _) in enumerate(top)
                     if rank < saved_rank), len(top),
                )
                top.insert(insert_at, (rank, candidate))
                if len(top) > max_per_expiration:
                    top.pop()

    ranked = sorted(
        (item for top in retained.values() for item in top),
        key=lambda item: item[0],
    )
    return [candidate for _, candidate in ranked], {
        identity for _, identity in annual_best.values()
    }


def build_vertical_preview_payload(
    *,
    symbol: str,
    call_put: str,
    expiry: date,
    buy_strike: float,
    sell_strike: float,
    quantity: int,
    limit_price: float,
    order_term: str = "GOOD_FOR_DAY",
    client_order_id: str | None = None,
) -> dict[str, Any]:
    """Build a two-leg E*TRADE NET_DEBIT vertical spread preview request."""
    symbol = str(symbol or "").strip().upper()
    if not symbol:
        raise ValueError("A ticker is required.")
    if not isinstance(expiry, date):
        raise ValueError("A valid expiration date is required.")
    validate_vertical(
        call_put=call_put,
        buy_strike=buy_strike,
        sell_strike=sell_strike,
        quantity=quantity,
    )
    term = str(order_term or "").strip().upper()
    if term not in {"GOOD_FOR_DAY", "GOOD_UNTIL_CANCEL"}:
        raise ValueError("Duration must be DAY or GTC.")
    try:
        debit = float(limit_price)
    except (TypeError, ValueError) as exc:
        raise ValueError("Enter a valid debit limit.") from exc
    if debit <= 0:
        raise ValueError("Debit limit must be positive.")

    client_id = str(client_order_id or new_vertical_client_order_id()).strip()
    if not client_id.isalnum() or len(client_id) > 20:
        raise ValueError("Client order id must be <=20 alphanumeric characters.")

    side = str(call_put).upper()
    qty = int(quantity)
    instruments = []
    for action, strike in (("BUY_OPEN", float(buy_strike)), ("SELL_OPEN", float(sell_strike))):
        instruments.append(
            {
                "Product": {
                    "symbol": symbol,
                    "securityType": "OPTN",
                    "callPut": side,
                    "expiryYear": int(expiry.year),
                    "expiryMonth": int(expiry.month),
                    "expiryDay": int(expiry.day),
                    "strikePrice": strike,
                },
                "orderAction": action,
                "orderedQuantity": qty,
                "quantity": qty,
            }
        )

    return {
        "PreviewOrderRequest": {
            "orderType": "SPREADS",
            "clientOrderId": client_id,
            "Order": [
                {
                    "allOrNone": False,
                    "priceType": "NET_DEBIT",
                    "limitPrice": round(debit, 4),
                    "stopPrice": 0.0,
                    "orderTerm": term,
                    "marketSession": "REGULAR",
                    "Instrument": instruments,
                }
            ],
        }
    }


def build_place_payload(preview_payload: dict[str, Any], preview_id: Any) -> dict[str, Any]:
    """Convert one successful preview into the exact E*TRADE place request."""
    request = preview_payload.get("PreviewOrderRequest")
    if not isinstance(request, dict) or preview_id in (None, ""):
        raise ValueError("A successful E*TRADE preview is required before placement.")
    return {
        "PlaceOrderRequest": {
            "orderType": request.get("orderType"),
            "clientOrderId": request.get("clientOrderId"),
            "PreviewIds": [{"previewId": preview_id}],
            "Order": request.get("Order") or [],
        }
    }


def preview_details(payload: dict[str, Any]) -> dict[str, Any]:
    """Normalize the fields needed for the Vertical Options review panel."""
    response = _find_key(payload, "PreviewOrderResponse")
    response = response if isinstance(response, dict) else payload
    preview_id = _find_key(response, "previewId")
    messages: list[str] = []
    for item in _as_list(_find_key(response, "Message")):
        if isinstance(item, dict):
            parts = [
                str(part)
                for part in (
                    item.get("type"),
                    item.get("code"),
                    item.get("description") or item.get("message"),
                )
                if part not in (None, "")
            ]
            if parts:
                messages.append(" // ".join(parts))
        elif item not in (None, ""):
            messages.append(str(item))

    def number(*keys: str) -> float | None:
        for key in keys:
            raw = _find_key(response, key)
            try:
                return float(raw)
            except (TypeError, ValueError):
                continue
        return None

    return {
        "preview_id": preview_id,
        "messages": messages,
        "total_order_value": number("totalOrderValue"),
        "estimated_commission": number("estimatedCommission"),
    }


def extract_order_id(payload: dict[str, Any]) -> Any:
    """Return the first E*TRADE order id from a place response."""
    order_ids = _find_key(payload, "OrderIds")
    for item in _as_list(order_ids):
        if isinstance(item, dict):
            order_id = _find_key(item, "orderId")
        else:
            order_id = item
        if order_id not in (None, ""):
            return order_id
    return _find_key(payload, "orderId")
