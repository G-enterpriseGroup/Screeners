_MIN_REWARD_RISK = 2.0


def _finite_number(value: Any, *, positive: bool = False) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError):
        return None
    if not math.isfinite(number) or (number <= 0 if positive else number < 0):
        return None
    return number


def _reward_risk_floor(value: Any) -> float:
    minimum = _finite_number(value, positive=True)
    if minimum is None:
        raise ValueError("Minimum reward-to-risk ratio must be positive and finite.")
    return minimum


def price_vertical_quote(
    *,
    buy_last: float | None,
    sell_last: float | None,
    buy_bid: float | None,
    buy_ask: float | None,
    sell_bid: float | None,
    sell_ask: float | None,
    width: float,
    max_cost: float | None,
    pricing_mode: str = "NORMAL",
    min_reward_risk: float = _MIN_REWARD_RISK,
    buy_volume: float | None = None,
    sell_volume: float | None = None,
    buy_open_interest: float | None = None,
    sell_open_interest: float | None = None,
) -> dict[str, Any] | None:
    """Choose a debit under the selected NORMAL or SMART FILL execution policy.

    ASK is the two-leg natural debit (BUY ask - SELL bid), not one option's
    ask. LAST is eligible only if it is within the current spread market
    at or above its midpoint; an old Last below MID is not a likely fill.
    Missing bid/ask yields a visible LAST* estimate only, never an order.
    SMART FILL offers a conservative, liquidity-aware *indicative* price
    between MID and natural ASK, capped by the minimum reward/risk and max cost.
    It is not a calibrated fill probability and cannot place orders.
    No quote basis is a guarantee of execution or liquidity.
    """
    if pricing_mode not in {"NORMAL", "SMART FILL"}:
        raise ValueError("Invalid Vertical Options pricing mode.")
    minimum = _reward_risk_floor(min_reward_risk)
    spread_width = _finite_number(width, positive=True)
    budget = None if max_cost is None else _finite_number(max_cost, positive=True)
    if spread_width is None or (max_cost is not None and budget is None):
        return None
    last_buy = _finite_number(buy_last, positive=True)
    last_sell = _finite_number(sell_last, positive=True)
    last_debit = (last_buy - last_sell
                  if last_buy is not None and last_sell is not None else None)
    bb, ba = _finite_number(buy_bid), _finite_number(buy_ask, positive=True)
    sb, sa = _finite_number(sell_bid), _finite_number(sell_ask, positive=True)
    quoted = all(value is not None for value in (bb, ba, sb, sa))
    choices: list[tuple[str, float, int, bool]] = []
    quote_bid = quote_mid = quote_ask = None
    liquidity = "UNVERIFIED"
    if quoted:
        if bb > ba or sb > sa:
            return None  # Inverted/stale single-leg markets must not be trusted.
        quote_bid = round(bb - sa, 4)
        quote_ask = round(ba - sb, 4)
        quote_mid = round((quote_bid + quote_ask) / 2, 4)
        if pricing_mode == "SMART FILL":
            # Volume/OI describe the individual legs, not executable spread
            # depth. No bid/ask size, quote timestamp, or fill history is
            # available through the existing normalized chain.
            volumes = [_finite_number(v) for v in (buy_volume, sell_volume)]
            interests = [_finite_number(v) for v in (buy_open_interest, sell_open_interest)]
            if all(v is not None for v in volumes + interests):
                if min(volumes) >= 20 and min(interests) >= 100:
                    liquidity = "ACTIVE LEGS"
                elif min(volumes) < 5 or min(interests) < 20:
                    liquidity = "THIN LEGS"
                else:
                    liquidity = "MODERATE LEGS"
            half_gap = max(0.0, quote_ask - quote_mid)
            fraction = 0.50 if half_gap <= .05 else (0.35 if half_gap <= .20 else 0.25)
            if liquidity == "ACTIVE LEGS":
                fraction = min(fraction, .25)
            elif liquidity == "THIN LEGS":
                fraction = min(fraction, .20)  # Do not chase thin markets.
            # Round *up* to the next cent rather than guessing sub-cent limit
            # precision. Cap the order against both independent risk limits.
            target_cents = math.ceil((quote_mid + fraction * half_gap) * 100 - 1e-8)
            max_debit = min(spread_width / (1 + minimum),
                            budget / 100 if budget is not None else math.inf,
                            quote_ask)
            capped_cents = min(target_cents, math.floor(max_debit * 100 + 1e-8))
            if (quote_mid > 0 and capped_cents >= math.ceil(quote_mid * 100 - 1e-8)
                    and capped_cents >= 1):
                choices.append(("SMART", capped_cents / 100, 0, True))
            else:
                choices.append(("MID", quote_mid, 2, True))
        else:
            choices.append(("ASK", quote_ask, 0, True))
            if (last_debit is not None
                    and quote_mid - .005 <= last_debit <= quote_ask + .005):
                choices.append(("LAST", last_debit, 1, True))
            choices.append(("MID", quote_mid, 2, True))
    elif last_debit is not None:
        choices.append(("LAST*", last_debit, 3, False))

    for basis, raw_debit, grade, orderable in choices:
        debit = round(raw_debit, 2)  # E*TRADE orderable two-decimal limit.
        cost = round(100 * debit, 2)
        if (not math.isfinite(debit) or not .01 <= debit < spread_width
                or (budget is not None and cost > budget + 1e-8)
                or spread_width - debit + 1e-8 < minimum * debit):
            continue
        return {
            "debit": debit, "cost": cost, "basis": basis,
            "grade": grade, "orderable": orderable,
            "spread_bid": quote_bid, "spread_mid": quote_mid,
            "spread_ask": quote_ask, "last_debit": last_debit,
            "liquidity_signal": liquidity if pricing_mode == "SMART FILL" else "",
        }
    return None


def smart_fill_ladder(
    candidate: dict[str, Any], max_cost: float | None, *, levels: int = 4,
    min_reward_risk: float = _MIN_REWARD_RISK,
) -> list[float]:
    """Manual, risk-capped limit choices for one SMART-quoted candidate.

    Selecting a rung never changes or submits a broker order by itself.
    """
    minimum = _reward_risk_floor(min_reward_risk)
    if candidate.get("basis") != "SMART":
        return []
    start = _finite_number(candidate.get("debit"), positive=True)
    natural = _finite_number(candidate.get("spread_ask"), positive=True)
    midpoint = _finite_number(candidate.get("spread_mid"))
    width = _finite_number(candidate.get("width"), positive=True)
    if None in (start, natural, midpoint, width):
        return []
    budget = None if max_cost is None else _finite_number(max_cost, positive=True)
    if max_cost is not None and budget is None:
        return []
    limit = min(natural, width / (1 + minimum),
                budget / 100 if budget is not None else math.inf)
    ceiling_cents = math.floor(limit * 100 + 1e-8)
    current = math.ceil(start * 100 - 1e-8)
    if current > ceiling_cents:
        return []
    gap = natural - midpoint
    step = 1 if gap <= .20 else (5 if gap <= 1 else 10)
    ladder = [round(current / 100, 2)]
    for _ in range(max(0, min(int(levels), 8) - 1)):
        current += step
        if current > ceiling_cents:
            break
        ladder.append(round(current / 100, 2))
    return ladder


def scan_vertical_candidates(
    *,
    symbol: str,
    spot_last: float,
    option_rows: Iterable[dict[str, Any]],
    target_breakeven: float | None,
    max_cost: float | None,
    max_per_expiration: int | None = 20,
    pricing_mode: str = "NORMAL",
    min_reward_risk: float = _MIN_REWARD_RISK,
    candidate_sink: Callable[[dict[str, Any]], None] | None = None,
    progress: Callable[[int], None] | None = None,
) -> tuple[list[dict[str, Any]], set[str]]:
    """Rank one-contract debit spreads across every supplied expiration.

    Per spread, attempt the natural ASK debit first, then a current-market
    LAST (only if >= MID), then MID, then unquoted LAST* (display-only).
    Each candidate's risk/reward, breakeven, cost, and live order price use
    the SAME selected debit. Prefer execution grades before breakeven and cost.
    Both canonical CALL and PUT directions are scanned. Annual winners are
    selected from the complete pair set, before any optional display cap.
    Pass max_per_expiration=None for exhaustive, untruncated enumeration of
    every canonical pair satisfying the minimum reward/risk and cost rules.
    Reversing the legs creates a credit spread, not a second debit spread.
    """
    ticker = str(symbol or "").strip().upper()
    spot = _finite_number(spot_last, positive=True)
    target = (_finite_number(target_breakeven, positive=True)
              if target_breakeven is not None else None)
    budget = None if max_cost is None else _finite_number(max_cost)
    if pricing_mode not in {"NORMAL", "SMART FILL"}:
        raise ValueError("Invalid Vertical Options pricing mode.")
    minimum = _reward_risk_floor(min_reward_risk)
    if (not ticker or spot is None or (target_breakeven is not None and target is None)
            or (max_cost is not None and budget is None)):
        raise ValueError("Ticker and underlying Last must be valid; supplied breakeven and cost must be positive.")
    if max_per_expiration is not None and (type(max_per_expiration) is not int or max_per_expiration < 1):
        raise ValueError("max_per_expiration must be a positive integer or None for exhaustive scanning.")
    if candidate_sink is not None and max_per_expiration is not None:
        raise ValueError("Streaming requires exhaustive scanning without a retention limit.")

    # One normalized chain row per exact contract. This bounds memory by the
    # input chain size, rather than the quadratic number of possible spreads.
    groups: dict[tuple[date, str], dict[tuple[float, str], dict[str, Any]]] = {}
    for raw in option_rows:
        if not isinstance(raw, dict):
            continue
        expiry = raw.get("expiry")
        if isinstance(expiry, datetime):
            expiry = expiry.date()
        side = str(raw.get("call_put") or "").strip().upper()
        strike = _finite_number(raw.get("strike"), positive=True)
        last = _finite_number(raw.get("last"), positive=True)
        if not isinstance(expiry, date) or side not in {"CALL", "PUT"}:
            continue
        if strike is None:
            continue
        # A live bid/ask pair can be usable even when Last is missing.
        if last is None and not all(
            _finite_number(raw.get(key)) is not None for key in ("bid", "ask")
        ):
            continue
        contract = {
            "strike": strike,
            "last": last,
            "bid": _finite_number(raw.get("bid")),
            "ask": _finite_number(raw.get("ask")),
            "osi": str(raw.get("osi") or "").strip(),
            "volume": _finite_number(raw.get("volume")),
            "open_interest": _finite_number(raw.get("open_interest")),
        }
        group = groups.setdefault((expiry, side), {})
        key = (strike, contract["osi"])
        prior = group.get(key)
        # Duplicate transport rows for one contract must not create duplicate
        # spread IDs. Use a quote-value tie break independent of input order.
        quote_key = lambda row: (
            row["last"] if row["last"] is not None else math.inf,
            row["bid"] if row["bid"] is not None else math.inf,
            row["ask"] if row["ask"] is not None else math.inf,
        )
        if prior is None or quote_key(contract) < quote_key(prior):
            group[key] = contract

    retained: dict[date, list[tuple[tuple[Any, ...], dict[str, Any]]]] = {}
    annual_best: dict[int, tuple[tuple[Any, ...], str]] = {}
    pairs_checked = 0
    for (expiry, side), group in sorted(groups.items()):
        legs = sorted(group.values(), key=lambda row: (row["strike"], row["osi"]))
        top = retained.setdefault(expiry, [])
        for lower_index, lower in enumerate(legs):
            for higher in legs[lower_index + 1:]:
                pairs_checked += 1
                if progress is not None and pairs_checked % 4096 == 0:
                    progress(pairs_checked)
                if lower["strike"] == higher["strike"]:
                    continue
                buy, sell = (lower, higher) if side == "CALL" else (higher, lower)
                width = round(higher["strike"] - lower["strike"], 6)
                price = price_vertical_quote(
                    buy_last=buy["last"], sell_last=sell["last"],
                    buy_bid=buy["bid"], buy_ask=buy["ask"],
                    sell_bid=sell["bid"], sell_ask=sell["ask"],
                    width=width, max_cost=budget, pricing_mode=pricing_mode,
                    min_reward_risk=minimum,
                    buy_volume=buy["volume"], sell_volume=sell["volume"],
                    buy_open_interest=buy["open_interest"],
                    sell_open_interest=sell["open_interest"],
                )
                if price is None:
                    continue
                debit = price["debit"]
                cost = price["cost"]
                profit = round(100.0 * (width - debit), 2)
                breakeven = round(
                    buy["strike"] + debit if side == "CALL" else buy["strike"] - debit,
                    6,
                )
                ratio = profit / cost
                if not math.isfinite(breakeven) or not math.isfinite(ratio):
                    continue
                rank = (
                    price["grade"], abs(breakeven - target) if target is not None else 0,
                    cost, -ratio, expiry,
                    side, buy["strike"], sell["strike"],
                    buy["osi"], sell["osi"],
                )
                if max_per_expiration is not None and len(top) == max_per_expiration and rank >= top[-1][0]:
                    # A pair worse than this expiry's retained best cannot be
                    # the annual winner. Avoid allocating its identity/payload.
                    continue
                identity = "|".join((
                    ticker, expiry.isoformat(), side,
                    f'{buy["strike"]:.6f}', f'{sell["strike"]:.6f}',
                    buy["osi"], sell["osi"],
                ))
                yearly = annual_best.get(expiry.year)
                if yearly is None or rank < yearly[0]:
                    annual_best[expiry.year] = (rank, identity)
                candidate = {
                    "id": identity, "symbol": ticker, "spot_last": spot,
                    "expiry": expiry, "year": expiry.year, "call_put": side,
                    "buy_strike": buy["strike"], "sell_strike": sell["strike"],
                    "buy_osi": buy["osi"], "sell_osi": sell["osi"],
                    "buy_last": buy["last"], "buy_bid": buy["bid"], "buy_ask": buy["ask"],
                    "sell_last": sell["last"], "sell_bid": sell["bid"], "sell_ask": sell["ask"],
                    "pricing_mode": pricing_mode,
                    **price, "width": width,
                    "max_profit": profit, "max_loss": cost,
                    "breakeven": breakeven, "reward_risk": ratio,
                }
                if candidate_sink is not None:
                    candidate_sink(candidate)
                elif max_per_expiration is None:
                    # Exhaustive case: append O(1), then sort globally once.
                    # Inserting each row into a ranked list would be O(M²).
                    top.append((rank, candidate))
                else:
                    insert_at = bisect_left(top, rank, key=lambda item: item[0])
                    top.insert(insert_at, (rank, candidate))
                    if len(top) > max_per_expiration:
                        top.pop()

    ranked = sorted(
        (item for top in retained.values() for item in top),
        key=lambda item: item[0],
    )
    return [candidate for _, candidate in ranked], {
        identity for _, identity in annual_best.values()
    }


def build_vertical_preview_payload(
    *,
    symbol: str,
    call_put: str,
    expiry: date,
    buy_strike: float,
    sell_strike: float,
    quantity: int,
    limit_price: float,
    order_term: str = "GOOD_FOR_DAY",
    client_order_id: str | None = None,
    min_reward_risk: float = _MIN_REWARD_RISK,
) -> dict[str, Any]:
    """Build a two-leg E*TRADE NET_DEBIT vertical spread preview request."""
    symbol = str(symbol or "").strip().upper()
    if not symbol:
        raise ValueError("A ticker is required.")
    if not isinstance(expiry, date):
        raise ValueError("A valid expiration date is required.")
    validate_vertical(
        call_put=call_put,
        buy_strike=buy_strike,
        sell_strike=sell_strike,
        quantity=quantity,
    )
    term = str(order_term or "").strip().upper()
    if term not in {"GOOD_FOR_DAY", "GOOD_UNTIL_CANCEL"}:
        raise ValueError("Duration must be DAY or GTC.")
    try:
        debit = float(limit_price)
    except (TypeError, ValueError) as exc:
        raise ValueError("Enter a valid debit limit.") from exc
    if not math.isfinite(debit) or debit <= 0:
        raise ValueError("Debit limit must be positive.")
    minimum = _reward_risk_floor(min_reward_risk)
    sent_debit = round(debit, 4)
    width = abs(float(sell_strike) - float(buy_strike))
    if sent_debit <= 0 or width - sent_debit + 1e-8 < minimum * sent_debit:
        raise ValueError(f"Debit limit must keep risk:reward at 1:{minimum:g} or better.")

    client_id = str(client_order_id or new_vertical_client_order_id()).strip()
    if not client_id.isalnum() or len(client_id) > 20:
        raise ValueError("Client order id must be <=20 alphanumeric characters.")

    side = str(call_put).upper()
    qty = int(quantity)
    instruments = []
    for action, strike in (("BUY_OPEN", float(buy_strike)), ("SELL_OPEN", float(sell_strike))):
        instruments.append(
            {
                "Product": {
                    "symbol": symbol,
                    "securityType": "OPTN",
                    "callPut": side,
                    "expiryYear": int(expiry.year),
                    "expiryMonth": int(expiry.month),
                    "expiryDay": int(expiry.day),
                    "strikePrice": strike,
                },
                "orderAction": action,
                "orderedQuantity": qty,
                "quantity": qty,
            }
        )

    return {
        "PreviewOrderRequest": {
            "orderType": "SPREADS",
            "clientOrderId": client_id,
            "Order": [
                {
                    "allOrNone": False,
                    "priceType": "NET_DEBIT",
                    "limitPrice": sent_debit,
                    "stopPrice": 0.0,
                    "orderTerm": term,
                    "marketSession": "REGULAR",
                    "Instrument": instruments,
                }
            ],
        }
    }


def build_place_payload(preview_payload: dict[str, Any], preview_id: Any) -> dict[str, Any]:
    """Convert one successful preview into the exact E*TRADE place request."""
    request = preview_payload.get("PreviewOrderRequest")
    if not isinstance(request, dict) or preview_id in (None, ""):
        raise ValueError("A successful E*TRADE preview is required before placement.")
    return {
        "PlaceOrderRequest": {
            "orderType": request.get("orderType"),
            "clientOrderId": request.get("clientOrderId"),
            "PreviewIds": [{"previewId": preview_id}],
            "Order": request.get("Order") or [],
        }
    }


def preview_details(payload: dict[str, Any]) -> dict[str, Any]:
    """Normalize the fields needed for the Vertical Options review panel."""
    response = _find_key(payload, "PreviewOrderResponse")
    response = response if isinstance(response, dict) else payload
    preview_id = _find_key(response, "previewId")
    messages: list[str] = []
    for item in _as_list(_find_key(response, "Message")):
        if isinstance(item, dict):
            parts = [
                str(part)
                for part in (
                    item.get("type"),
                    item.get("code"),
                    item.get("description") or item.get("message"),
                )
                if part not in (None, "")
            ]
            if parts:
                messages.append(" // ".join(parts))
        elif item not in (None, ""):
            messages.append(str(item))

    def number(*keys: str) -> float | None:
        for key in keys:
            raw = _find_key(response, key)
            try:
                return float(raw)
            except (TypeError, ValueError):
                continue
        return None

    return {
        "preview_id": preview_id,
        "messages": messages,
        "total_order_value": number("totalOrderValue"),
        "estimated_commission": number("estimatedCommission"),
    }


def extract_order_id(payload: dict[str, Any]) -> Any:
    """Return the first E*TRADE order id from a place response."""
    order_ids = _find_key(payload, "OrderIds")
    for item in _as_list(order_ids):
        if isinstance(item, dict):
            order_id = _find_key(item, "orderId")
        else:
            order_id = item
        if order_id not in (None, ""):
            return order_id
    return _find_key(payload, "orderId")
