@st.fragment
def render_rebalance_portfolio(
    client: Any,
    *,
    account_picker: Callable[[str], dict[str, Any] | None],
    refresh_accounts: Callable[[Any], list[dict[str, Any]]],
    account_balance: Callable[..., dict[str, Any]],
    balance_snapshot: Callable[[dict[str, Any]], tuple[float, float, float]],
    touch_session: Callable[[], None],
) -> None:
    st.html(_REBALANCE_CSS)

    with st.container(key="rebalance_root", gap=None):
        if client is None:
            st.info("CONNECT E*TRADE TO LOAD THE SMART REBALANCER.")
            return

        if not st.session_state.get("etrade_accounts"):
            try:
                refresh_accounts(client)
            except Exception as exc:
                st.error(f"E*TRADE ACCOUNTS UNAVAILABLE // {exc}")
                return

        _section("1. ACCOUNT + LIVE BOOK")

        # Intentionally share Risk Sizing's account-state key so changing the
        # account in either workspace keeps both workspaces on the same book.
        account = account_picker("risk_sizing_account")
        if not account:
            st.info("NO E*TRADE BROKERAGE ACCOUNT IS AVAILABLE.")
            return

        account_key = str(account.get("accountIdKey") or "").strip()
        if not account_key:
            st.info("SELECTED E*TRADE ACCOUNT HAS NO ACCOUNT KEY.")
            return

        account_col, refresh_col = st.columns([5.2, 1.5], gap="small", vertical_alignment="bottom")
        with account_col:
            st.html(
                '<div class="reb-note">'
                f'LINKED TO E*TRADE RISK SIZING ACCOUNT // {_account_label(account)}'
                '</div>'
            )
        with refresh_col:
            refresh = st.button(
                "REFRESH REBALANCER",
                type="primary",
                width="stretch",
                key="rebalance_refresh",
            )

        holdings_cache = st.session_state.setdefault("etrade_holdings", {})
        try:
            if refresh or holdings_cache.get(account_key) is None:
                holdings_cache[account_key] = client.get_portfolio(account_key)
                account_balance(client, account, refresh=True)
                touch_session()

            normalized = _normalized_holdings(holdings_cache.get(account_key) or [])
            balance_payload = account_balance(client, account, refresh=False)
            account_total, cash_available, _ = balance_snapshot(balance_payload)
        except ETradeError as exc:
            st.error(f"E*TRADE REBALANCE DATA UNAVAILABLE // {exc}")
            return
        except Exception as exc:
            st.error(f"REBALANCE DATA LOAD FAILED // {exc}")
            return

        if normalized.empty:
            st.info("NO POSITIONS WERE RETURNED FOR THE SELECTED ACCOUNT.")
            return

        market_total = pd.to_numeric(
            normalized.get("Market Value", pd.Series(dtype=float)),
            errors="coerce",
        ).fillna(0.0).sum()
        account_value = float(account_total or (market_total + cash_available))
        cash_available = max(0.0, float(cash_available or 0.0))
        if account_value <= 0:
            st.error("ACCOUNT VALUE IS NOT POSITIVE // REBALANCE MATH IS BLOCKED.")
            return

        active_symbols = (
            normalized["Symbol"].astype(str).str.strip().str.upper().tolist()
            if "Symbol" in normalized.columns
            else []
        )
        account_overrides, risk_intent_state = _load_persisted_intent_overrides(
            account_key,
            active_symbols,
        )
        _sync_risk_intent_browser(account_key, risk_intent_state)

        gain_threshold = _finite(st.session_state.get("risk_gain_threshold"), 5.0)
        classified = classify_holdings(normalized, gain_threshold)
        classified = _apply_intent_overrides(classified, account_overrides)

        state = _load_rebalance_state(account_key)
        if state is None:
            st.info("Restoring saved Rebalance settings…")
            return
        config_rows, config_changed = _config_from_state(
            state,
            classified,
            account_value,
        )
        if config_changed:
            state = _persist_rebalance_state(
                account_key,
                {**state, "rows": config_rows},
            )

        keys = _hydrate_setting_widgets(account_key, state)

        k1, k2, k3, k4 = st.columns(4, gap="small")
        with k1:
            _kpi("ACCOUNT VALUE", _money(account_value))
        with k2:
            _kpi("CASH AVAILABLE", _money(cash_available))
        with k3:
            long_term_count = int(
                classified["Sleeve"].astype(str).str.upper().eq("LONG-TERM").sum()
            )
            _kpi("LONG-TERM FLAGS", f"{long_term_count:,}")
        with k4:
            _kpi("POSITIONS", f"{len(classified):,}")

        _section("2. SMART RULES")
        r1, r2, r3 = st.columns(3, gap="small")
        with r1:
            mode = st.selectbox(
                "Rebalance Destination",
                ("TO BAND", "TO TARGET"),
                key=keys["mode"],
                help=(
                    "TO BAND makes the minimum move just back inside the allowed range. "
                    "TO TARGET restores the exact target weight and therefore creates more turnover."
                ),
            )
        with r2:
            tactical_band = float(
                st.number_input(
                    "Default Tactical Band +/- %",
                    min_value=0.0,
                    max_value=25.0,
                    step=0.25,
                    format="%.2f",
                    key=keys["tactical_band"],
                )
            )
        with r3:
            long_term_band = float(
                st.number_input(
                    "Default Long-Term Band +/- %",
                    min_value=0.0,
                    max_value=25.0,
                    step=0.25,
                    format="%.2f",
                    key=keys["long_term_band"],
                    help="LONG-TERM positions default to a wider band, but each row remains editable.",
                )
            )

        r4, r5, r6 = st.columns(3, gap="small")
        with r4:
            min_trade = float(
                st.number_input(
                    "Minimum Rebalance Trade $",
                    min_value=0.0,
                    max_value=10_000_000.0,
                    step=100.0,
                    format="%.0f",
                    key=keys["min_trade"],
                )
            )
        with r5:
            loss_review_trigger = float(
                st.number_input(
                    "Loss Review Trigger %",
                    min_value=-100.0,
                    max_value=0.0,
                    step=1.0,
                    format="%.1f",
                    key=keys["loss_review_trigger"],
                    help=(
                        "An underweight position at or below this unrealized P&L is flagged REVIEW LOSS "
                        "instead of automatically receiving an ADD proposal."
                    ),
                )
            )
        with r6:
            hard_max_pct = float(
                st.number_input(
                    "Hard Max Position %",
                    min_value=0.0,
                    max_value=100.0,
                    step=1.0,
                    format="%.1f",
                    key=keys["hard_max_pct"],
                    help="0 disables the hard concentration limit.",
                )
            )

        settings = {
            "mode": mode,
            "tactical_band": tactical_band,
            "long_term_band": long_term_band,
            "min_trade": min_trade,
            "loss_review_trigger": loss_review_trigger,
            "hard_max_pct": hard_max_pct,
        }

        if settings != state["settings"]:
            state = _persist_rebalance_state(
                account_key,
                {**state, "settings": settings, "rows": config_rows},
            )

        _section("3. TARGETS + BANDS")
        control_a, control_b, _ = st.columns([1.4, 1.5, 4.0], gap="small")
        reset_targets = control_a.button(
            "RESET TARGETS TO CURRENT",
            width="stretch",
            key="rebalance_reset_targets",
            help="Seeds every target to the position's current account weight. No trades are proposed until you change targets.",
        )
        apply_bands = control_b.button(
            "APPLY DEFAULT BANDS",
            width="stretch",
            key="rebalance_apply_default_bands",
        )

        if reset_targets or apply_bands:
            by_symbol = {row["symbol"]: dict(row) for row in config_rows}
            rebuilt = []
            for _, source in classified.iterrows():
                symbol = str(source.get("Symbol") or "").strip().upper()
                if not symbol:
                    continue
                current_pct = _finite(source.get("Market Value"), 0.0) / account_value * 100.0
                sleeve = str(source.get("Sleeve") or "TACTICAL").strip().upper()
                band = long_term_band if sleeve == "LONG-TERM" else tactical_band
                previous = by_symbol.get(symbol, {})
                rebuilt.append(
                    {
                        "symbol": symbol,
                        "target_pct": (
                            max(0.0, current_pct)
                            if reset_targets
                            else _finite(previous.get("target_pct"), max(0.0, current_pct))
                        ),
                        "band_pct": (
                            band
                            if apply_bands
                            else _finite(previous.get("band_pct"), band)
                        ),
                    }
                )
            config_rows = rebuilt
            state = _persist_rebalance_state(
                account_key,
                {**state, "settings": settings, "rows": config_rows},
            )

        st.caption("Choose a ticker to edit its target and band. A 10% target with a ±2 percentage-point band allows 8–12%. Changes save automatically after Enter or leaving the field.")
        symbols = [row["symbol"] for row in config_rows]
        token = _account_token(account_key)
        picker_key = "rebalance_ticker::" + token
        if picker_key not in st.session_state:
            saved_symbol = state["selected_symbol"]
            st.session_state[picker_key] = saved_symbol if saved_symbol in symbols else symbols[0]
        if st.session_state[picker_key] not in symbols:
            st.session_state[picker_key] = symbols[0]
        ticker_col, target_col, band_col, range_col = st.columns([1.2, 1, 1, 1.3], gap="small", vertical_alignment="bottom")
        with ticker_col:
            symbol = st.selectbox("Ticker", symbols, key=picker_key)
        selected = next(row for row in config_rows if row["symbol"] == symbol)
        # Stable widget keys allow consecutive edits; only rehydrate when the
        # saved row changes externally (restore/reset) or widgets are recreated.
        input_key = f"rebalance_position::{token}::{symbol}"
        row_marker = input_key + "::loaded"
        saved_values = (selected["target_pct"], selected["band_pct"])
        if st.session_state.get(row_marker) != saved_values or input_key + "::target" not in st.session_state:
            st.session_state[input_key + "::target"] = float(selected["target_pct"])
            st.session_state[input_key + "::band"] = float(selected["band_pct"])
        with target_col:
            target = st.number_input("Target weight %", min_value=0.0, max_value=100.0,
                                     step=0.25, format="%.2f", key=input_key + "::target")
        with band_col:
            band = st.number_input("Band ± percentage points", min_value=0.0, max_value=50.0,
                                   step=0.25, format="%.2f", key=input_key + "::band")
        with range_col:
            _kpi("ALLOWED RANGE", f"{max(0, target-band):.2f}% – {min(100, target+band):.2f}%")
        st.session_state[row_marker] = (target, band)
        selected.update(target_pct=target, band_pct=band)
        state = _persist_rebalance_state(account_key, {**state, "rows": config_rows, "selected_symbol": symbol})
        editor = _editor_frame(classified, config_rows, account_value)
        editor["Allowed range"] = [f"{max(0, r['target_pct']-r['band_pct']):.2f}% – {min(100, r['target_pct']+r['band_pct']):.2f}%" for r in config_rows]
        _table(editor, percent_columns={"P&L %", "Current %", "Target %", "Band +/- %"})

        # One writer component per rerun: settings, reset actions, and data-editor
        # changes may all mutate state in the same Streamlit pass.
        _sync_rebalance_state_browser(account_key, state)

        target_total = sum(_finite(row.get("target_pct"), 0.0) for row in config_rows)
        if target_total > 100.0001:
            st.error(
                f"TARGET WEIGHTS TOTAL {target_total:.2f}% // V1 LONG-ONLY TARGETS CANNOT EXCEED 100%. "
                "Reduce one or more targets before a plan is generated."
            )
            return

        plan, summary = _build_rebalance_plan(
            classified,
            account_value=account_value,
            cash_available=cash_available,
            config_rows=config_rows,
            settings=settings,
        )

        _section("4. SMART REBALANCE PLAN")
        p1, p2, p3, p4, p5 = st.columns(5, gap="small")
        with p1:
            _kpi("TARGETS", f"{summary['target_total_pct']:.2f}%")
        with p2:
            _kpi("TARGET CASH", f"{summary['target_cash_pct']:.2f}%")
        with p3:
            _kpi("NEEDS ATTENTION", f"{int(summary['outside_count']):,}")
        with p4:
            _kpi("PROPOSED SELLS", _money(summary["trim_proceeds"]))
        with p5:
            _kpi("PROPOSED BUYS", _money(summary["proposed_buys"]))

        q1, q2, q3 = st.columns(3, gap="small")
        with q1:
            _kpi("GROSS TRADE PLAN", _money(summary["gross_trade"]))
        with q2:
            _kpi("POST-PLAN CASH", _money(summary["post_cash"]))
        with q3:
            _kpi("BUY FUNDING", f"{summary['buy_funding_ratio'] * 100.0:.1f}%")

        _table(
            plan[["Symbol", "Current %", "Range", "Action", "Proposed $", "Post %", "P&L %"]],
            percent_columns={"Current %", "Post %", "P&L %"},
            money_columns={"Proposed $"},
        )
        with st.expander("PLAN DETAILS · sleeves, drift and reasons"):
            _table(plan[["Symbol", "Sleeve", "Drift %", "Raw Gap $", "Reason"]],
                   percent_columns={"Drift %"}, money_columns={"Raw Gap $"})

        export_col, _ = st.columns([1.2, 5.0], gap="small")
        with export_col:
            st.download_button(
                "EXPORT PLAN CSV",
                data=plan.to_csv(index=False).encode("utf-8"),
                file_name="rebalance_plan.csv",
                mime="text/csv",
                width="stretch",
                key="rebalance_export_plan",
            )

        st.html(
            '<div class="reb-note">'
            'SMART RULES // inside band = HOLD // excess cash funds underweights first // required trim proceeds can fund remaining adds // '
            'underweights beyond the loss-review trigger are REVIEW LOSS, not automatic average-downs // LONG-TERM overweights are review flags // '
            'TO BAND minimizes turnover // ANALYSIS ONLY: NO E*TRADE ORDER PREVIEW, PLACE, CHANGE, OR CANCEL.'
            '</div>'
        )


