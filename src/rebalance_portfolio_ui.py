def _account_token(account_key: str) -> str:
    raw = str(account_key or "default").encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:24]


def _session_state_key(account_key: str) -> str:
    return "_rebalance_state::" + _account_token(account_key)


def _browser_storage_key(account_key: str) -> str:
    return "raj-terminal-rebalance-v1:" + _account_token(account_key)


def _finite(value: Any, default: float = 0.0) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return float(default)
    return number if math.isfinite(number) else float(default)


def _clean_state(raw: Any) -> dict[str, Any]:
    if not isinstance(raw, dict):
        raw = {}

    try:
        revision = max(0, int(raw.get("revision", 0) or 0))
    except (TypeError, ValueError):
        revision = 0

    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in raw.get("rows", []) or []:
        if not isinstance(item, dict):
            continue
        symbol = str(item.get("symbol") or "").strip().upper()
        if not symbol or symbol in seen:
            continue
        seen.add(symbol)
        target_pct = min(100.0, max(0.0, _finite(item.get("target_pct"), 0.0)))
        legacy_band = min(50.0, max(0.0, _finite(item.get("band_pct"), 0.0)))
        lower_pct = min(
            target_pct,
            max(
                0.0,
                _finite(item.get("lower_pct"), max(0.0, target_pct - legacy_band)),
            ),
        )
        upper_pct = max(
            target_pct,
            min(
                100.0,
                _finite(item.get("upper_pct"), min(100.0, target_pct + legacy_band)),
            ),
        )
        rows.append(
            {
                "symbol": symbol,
                "target_pct": target_pct,
                "lower_pct": lower_pct,
                "upper_pct": upper_pct,
            }
        )

    source_settings = raw.get("settings") if isinstance(raw.get("settings"), dict) else {}
    mode = str(source_settings.get("mode") or "TO BAND").strip().upper()
    if mode not in {"TO BAND", "TO TARGET"}:
        mode = "TO BAND"

    settings = {
        "mode": mode,
        "tactical_band": min(
            25.0,
            max(0.0, _finite(source_settings.get("tactical_band"), _DEFAULT_TACTICAL_BAND)),
        ),
        "long_term_band": min(
            25.0,
            max(0.0, _finite(source_settings.get("long_term_band"), _DEFAULT_LONG_TERM_BAND)),
        ),
        "min_trade": max(0.0, _finite(source_settings.get("min_trade"), _DEFAULT_MIN_TRADE)),
        "loss_review_trigger": min(
            0.0,
            max(-100.0, _finite(source_settings.get("loss_review_trigger"), _DEFAULT_LOSS_REVIEW_TRIGGER)),
        ),
        "hard_max_pct": min(
            100.0,
            max(0.0, _finite(source_settings.get("hard_max_pct"), _DEFAULT_HARD_MAX)),
        ),
    }

    saved_at = max(0.0, _finite(raw.get("saved_at"), 0.0))
    return {
        "revision": revision,
        "saved_at": saved_at,
        # The shared zero-height browser component uses this timestamp only as
        # a stable change fingerprint. No brokerage snapshot is stored here.
        "portfolio_saved_at": max(
            0.0,
            _finite(raw.get("portfolio_saved_at"), saved_at),
        ),
        "rows": rows,
        "settings": settings,
    }


def _state_payload(state: dict[str, Any]) -> tuple[Any, Any]:
    cleaned = _clean_state(state)
    return cleaned["rows"], cleaned["settings"]


def _load_rebalance_state(account_key: str) -> dict[str, Any]:
    session_key = _session_state_key(account_key)
    session_state = _clean_state(st.session_state.get(session_key))

    with st.container(key="rebalance_state_reader_shell", gap=None):
        browser = _rebalance_state_component(
            storage_key=_browser_storage_key(account_key),
            server_state=session_state,
            key="raj_rebalance_state_reader_" + _account_token(account_key),
            default=None,
        )

    if isinstance(browser, dict) and isinstance(browser.get("state"), dict):
        browser_state = _clean_state(browser["state"])
        if browser_state["revision"] > session_state["revision"] or (
            session_state["revision"] == 0
            and not session_state["rows"]
            and browser_state["rows"]
        ):
            session_state = browser_state

    st.session_state[session_key] = session_state
    return session_state


def _persist_rebalance_state(account_key: str, candidate: dict[str, Any]) -> dict[str, Any]:
    """Update the server copy; browser sync happens once at the end of render."""
    session_key = _session_state_key(account_key)
    current = _clean_state(st.session_state.get(session_key))
    cleaned = _clean_state(candidate)

    if _state_payload(current) == _state_payload(cleaned):
        state = current
    else:
        now = time.time()
        state = {
            **cleaned,
            "revision": current["revision"] + 1,
            "saved_at": now,
            "portfolio_saved_at": now,
        }
        st.session_state[session_key] = state
    return state


def _sync_rebalance_state_browser(account_key: str, state: dict[str, Any]) -> None:
    """Write the final per-rerun state exactly once to avoid duplicate component keys."""
    with st.container(key="rebalance_state_writer_shell", gap=None):
        _rebalance_state_component(
            storage_key=_browser_storage_key(account_key),
            server_state=_clean_state(state),
            key="raj_rebalance_state_writer_" + _account_token(account_key),
            default=None,
        )


