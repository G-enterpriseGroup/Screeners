def _money(value: float) -> str:
    value = _finite(value, 0.0)
    sign = "-" if value < 0 else ""
    return sign + "$" + f"{abs(value):,.0f}"


def _account_label(account: dict[str, Any]) -> str:
    name = str(
        account.get("accountName")
        or account.get("accountDesc")
        or account.get("accountType")
        or "E*TRADE ACCOUNT"
    ).strip()
    raw = str(account.get("accountId") or "")
    return f"{name} // ••••{raw[-4:]}" if raw else name


def _config_from_state(
    state: dict[str, Any],
    classified: pd.DataFrame,
    account_value: float,
) -> tuple[list[dict[str, Any]], bool]:
    existing = {
        str(row.get("symbol") or "").strip().upper(): dict(row)
        for row in state.get("rows", []) or []
        if str(row.get("symbol") or "").strip()
    }
    active: set[str] = set()
    rows: list[dict[str, Any]] = []
    changed = False

    for _, source in classified.iterrows():
        symbol = str(source.get("Symbol") or "").strip().upper()
        if not symbol:
            continue
        active.add(symbol)
        current_pct = (
            _finite(source.get("Market Value"), 0.0) / account_value * 100.0
            if account_value > 0
            else 0.0
        )
        sleeve = str(source.get("Sleeve") or "TACTICAL").strip().upper()
        default_band = (
            state["settings"]["long_term_band"]
            if sleeve == "LONG-TERM"
            else state["settings"]["tactical_band"]
        )
        row = existing.get(symbol)
        if row is None:
            target_pct = max(0.0, current_pct)
            row = {
                "symbol": symbol,
                "target_pct": target_pct,
                "lower_pct": max(0.0, target_pct - default_band),
                "upper_pct": min(100.0, target_pct + default_band),
            }
            changed = True
        target_pct = min(
            100.0,
            max(0.0, _finite(row.get("target_pct"), current_pct)),
        )
        lower_pct = min(
            target_pct,
            max(0.0, _finite(row.get("lower_pct"), max(0.0, target_pct - default_band))),
        )
        upper_pct = max(
            target_pct,
            min(100.0, _finite(row.get("upper_pct"), min(100.0, target_pct + default_band))),
        )
        rows.append(
            {
                "symbol": symbol,
                "target_pct": target_pct,
                "lower_pct": lower_pct,
                "upper_pct": upper_pct,
            }
        )

    if set(existing) != active:
        changed = True
    return rows, changed


