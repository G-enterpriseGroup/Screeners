def _table(frame: pd.DataFrame, *, percent_columns: set[str] | None = None,
           money_columns: set[str] | None = None) -> None:
    """Feature-local, width-fitting Risk-style table; escape all broker text."""
    percent_columns = percent_columns or set()
    money_columns = money_columns or set()
    headers = "".join(f"<th>{escape(str(column))}</th>" for column in frame.columns)
    rows = []
    for _, record in frame.iterrows():
        cells = []
        for column, value in record.items():
            text = str(value)
            tone = ""
            if column in percent_columns:
                text = f"{_finite(value):.2f}%"
            if column in money_columns:
                text = _money(value)
            if column in {"P&L %", "Proposed $"}:
                tone = "reb-positive" if _finite(value) > 0 else "reb-negative" if _finite(value) < 0 else ""
            if column == "Action":
                tone = "reb-review" if "REVIEW" in text else "reb-positive" if text == "ADD" else ""
            cells.append(f'<td class="{tone}">{escape(text)}</td>')
        rows.append("<tr>" + "".join(cells) + "</tr>")
    st.html('<table class="reb-table"><thead><tr>' + headers + '</tr></thead><tbody>' + "".join(rows) + '</tbody></table>')


def _money(value: float) -> str:
    value = _finite(value, 0.0)
    sign = "-" if value < 0 else ""
    return sign + "$" + f"{abs(value):,.0f}"


def _account_label(account: dict[str, Any]) -> str:
    name = str(
        account.get("accountName")
        or account.get("accountDesc")
        or account.get("accountType")
        or "E*TRADE ACCOUNT"
    ).strip()
    raw = str(account.get("accountId") or "")
    return f"{name} // ••••{raw[-4:]}" if raw else name


def _config_from_state(
    state: dict[str, Any],
    classified: pd.DataFrame,
    account_value: float,
) -> tuple[list[dict[str, Any]], bool]:
    existing = {
        str(row.get("symbol") or "").strip().upper(): dict(row)
        for row in state.get("rows", []) or []
        if str(row.get("symbol") or "").strip()
    }
    rows: list[dict[str, Any]] = []
    changed = False

    for _, source in classified.iterrows():
        symbol = str(source.get("Symbol") or "").strip().upper()
        if not symbol:
            continue
        current_pct = (
            _finite(source.get("Market Value"), 0.0) / account_value * 100.0
            if account_value > 0
            else 0.0
        )
        sleeve = str(source.get("Sleeve") or "TACTICAL").strip().upper()
        default_band = (
            state["settings"]["long_term_band"]
            if sleeve == "LONG-TERM"
            else state["settings"]["tactical_band"]
        )
        row = existing.get(symbol)
        if row is None:
            row = {
                "symbol": symbol,
                "target_pct": max(0.0, current_pct),
                "band_pct": default_band,
            }
            changed = True
        rows.append(
            {
                "symbol": symbol,
                "target_pct": min(100.0, max(0.0, _finite(row.get("target_pct"), current_pct))),
                "band_pct": min(50.0, max(0.0, _finite(row.get("band_pct"), default_band))),
            }
        )

    return rows, changed


def _settings_widget_keys(account_key: str) -> dict[str, str]:
    token = _account_token(account_key)
    return {
        "mode": f"rebalance_mode::{token}",
        "tactical_band": f"rebalance_tactical_band::{token}",
        "long_term_band": f"rebalance_long_term_band::{token}",
        "min_trade": f"rebalance_min_trade::{token}",
        "loss_review_trigger": f"rebalance_loss_trigger::{token}",
        "hard_max_pct": f"rebalance_hard_max::{token}",
    }


def _hydrate_setting_widgets(account_key: str, state: dict[str, Any]) -> dict[str, str]:
    keys = _settings_widget_keys(account_key)
    marker = "_rebalance_loaded_revision::" + _account_token(account_key)
    if st.session_state.get(marker) != state["revision"] or any(key not in st.session_state for key in keys.values()):
        for field, key in keys.items():
            st.session_state[key] = state["settings"][field]
        st.session_state[marker] = state["revision"]
    return keys


def _editor_frame(
    classified: pd.DataFrame,
    config_rows: list[dict[str, Any]],
    account_value: float,
) -> pd.DataFrame:
    cfg = {row["symbol"]: row for row in config_rows}
    rows = []
    for _, source in classified.iterrows():
        symbol = str(source.get("Symbol") or "").strip().upper()
        if not symbol:
            continue
        market_value = _finite(source.get("Market Value"), 0.0)
        rows.append(
            {
                "Symbol": symbol,
                "Sleeve": str(source.get("Sleeve") or "TACTICAL"),
                "P&L %": _finite(source.get("Gain/Loss %"), 0.0),
                "Current %": (market_value / account_value * 100.0) if account_value > 0 else 0.0,
                "Target %": _finite(cfg.get(symbol, {}).get("target_pct"), 0.0),
                "Band +/- %": _finite(cfg.get(symbol, {}).get("band_pct"), 0.0),
            }
        )
    return pd.DataFrame(rows)



