_DEFAULT_TACTICAL_BAND = 2.0
_DEFAULT_LONG_TERM_BAND = 4.0
_DEFAULT_MIN_TRADE = 500.0
_DEFAULT_LOSS_REVIEW_TRIGGER = -10.0
_DEFAULT_HARD_MAX = 25.0
_BAND_REENTRY_BUFFER = 0.10

