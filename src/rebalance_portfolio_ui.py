def _inside_band_goal(target: float, band: float, side: str) -> float:
    if band <= 0:
        return max(0.0, target)
    buffer = min(_BAND_REENTRY_BUFFER, band / 2.0)
    if side == "UPPER":
        return max(target, target + band - buffer)
    return min(target, max(0.0, target - band + buffer))


def _build_rebalance_plan(
    holdings: pd.DataFrame,
    *,
    account_value: float,
    cash_available: float,
    config_rows: list[dict[str, Any]],
    settings: dict[str, Any],
) -> tuple[pd.DataFrame, dict[str, float]]:
    """Return a deterministic, read-only smart rebalance proposal.

    Rules:
    - positions inside their target band do not trade;
    - TO BAND moves only just inside the breached band, TO TARGET restores target;
    - underweights at/below the loss-review trigger are never automatically added;
    - LONG-TERM overweights are flagged for review rather than treated as routine trims;
    - trades below the minimum-dollar threshold are suppressed;
    - excess cash is used first, then proceeds from required trims;
    - buys are prorated when funding is insufficient.
    """
    account_value = max(0.0, _finite(account_value, 0.0))
    cash_available = max(0.0, _finite(cash_available, 0.0))
    clean_settings = _clean_state({"settings": settings})["settings"]
    mode = clean_settings["mode"]
    min_trade = clean_settings["min_trade"]
    loss_trigger = clean_settings["loss_review_trigger"]
    hard_max = clean_settings["hard_max_pct"]

    config = {
        str(row.get("symbol") or "").strip().upper(): {
            "target_pct": min(100.0, max(0.0, _finite(row.get("target_pct"), 0.0))),
            "band_pct": min(50.0, max(0.0, _finite(row.get("band_pct"), 0.0))),
        }
        for row in config_rows
        if str(row.get("symbol") or "").strip()
    }

    records: list[dict[str, Any]] = []
    target_total = 0.0

    for _, source in holdings.iterrows():
        symbol = str(source.get("Symbol") or "").strip().upper()
        if not symbol:
            continue
        cfg = config.get(symbol, {"target_pct": 0.0, "band_pct": 0.0})
        target = cfg["target_pct"]
        band = cfg["band_pct"]
        target_total += target

        market_value = _finite(source.get("Market Value"), 0.0)
        pnl_pct = _finite(source.get("Gain/Loss %"), 0.0)
        sleeve = str(source.get("Sleeve") or "TACTICAL").strip().upper()
        current_pct = (market_value / account_value * 100.0) if account_value > 0 else 0.0
        lower = max(0.0, target - band)
        upper = min(100.0, target + band)
        drift = current_pct - target

        action = "HOLD"
        reason = "INSIDE BAND"
        raw_trade = 0.0
        buy_eligible = False

        if market_value < -0.005:
            action = "REVIEW SHORT"
            reason = "SHORT / NEGATIVE MARKET VALUE IS OUTSIDE V1 LONG-ONLY MATH"
        else:
            hard_breach = hard_max > 0 and current_pct > hard_max + 1e-9
            overweight = hard_breach or current_pct > upper + 1e-9
            underweight = current_pct < lower - 1e-9

            if overweight:
                if mode == "TO TARGET":
                    goal_pct = target
                else:
                    goal_pct = _inside_band_goal(target, band, "UPPER")
                if hard_breach:
                    goal_pct = min(
                        goal_pct,
                        max(0.0, hard_max - min(_BAND_REENTRY_BUFFER, hard_max / 2.0)),
                    )
                goal_value = account_value * goal_pct / 100.0
                raw_trade = goal_value - market_value
                if sleeve == "LONG-TERM" and not hard_breach:
                    action = "LONG-TERM TRIM REVIEW"
                    reason = "ABOVE BAND // LONG-TERM FLAG"
                elif hard_breach:
                    action = "HARD LIMIT REVIEW"
                    reason = f"ABOVE {hard_max:.2f}% HARD MAX"
                else:
                    action = "TRIM"
                    reason = "ABOVE UPPER BAND"

            elif underweight:
                if pnl_pct <= loss_trigger:
                    action = "REVIEW LOSS"
                    reason = f"UNDERWEIGHT // P&L <= {loss_trigger:.2f}%"
                    if mode == "TO TARGET":
                        goal_pct = target
                    else:
                        goal_pct = _inside_band_goal(target, band, "LOWER")
                    raw_trade = account_value * goal_pct / 100.0 - market_value
                else:
                    action = "ADD"
                    reason = "BELOW LOWER BAND"
                    buy_eligible = True
                    if mode == "TO TARGET":
                        goal_pct = target
                    else:
                        goal_pct = _inside_band_goal(target, band, "LOWER")
                    raw_trade = account_value * goal_pct / 100.0 - market_value

        if abs(raw_trade) > 0 and abs(raw_trade) < min_trade:
            action = "HOLD // BELOW MIN"
            reason = f"RAW GAP < ${min_trade:,.0f} MINIMUM"
            raw_trade = 0.0
            buy_eligible = False

        records.append(
            {
                "Symbol": symbol,
                "Sleeve": sleeve,
                "P&L %": pnl_pct,
                "Market Value": market_value,
                "Current %": current_pct,
                "Target %": target,
                "Band +/- %": band,
                "Range": f"{lower:.2f}%–{upper:.2f}%",
                "Drift %": drift,
                "Action": action,
                "Reason": reason,
                "Raw Gap $": raw_trade,
                "_buy_eligible": buy_eligible,
            }
        )

    target_cash_pct = max(0.0, 100.0 - target_total)
    target_cash_value = account_value * target_cash_pct / 100.0

    trim_proceeds = sum(
        max(0.0, -float(row["Raw Gap $"]))
        for row in records
        if float(row["Raw Gap $"]) < 0
    )
    excess_cash = max(0.0, cash_available - target_cash_value)
    funding = excess_cash + trim_proceeds

    buy_demand = sum(
        max(0.0, float(row["Raw Gap $"]))
        for row in records
        if row["_buy_eligible"] and float(row["Raw Gap $"]) > 0
    )
    buy_factor = min(1.0, funding / buy_demand) if buy_demand > 1e-9 else 0.0

    proposed_buys = 0.0
    proposed_sells = 0.0
    outside_count = 0

    for row in records:
        raw_trade = float(row["Raw Gap $"])
        proposed = raw_trade if raw_trade < 0 else 0.0

        if row["_buy_eligible"] and raw_trade > 0:
            proposed = raw_trade * buy_factor
            if proposed + 1e-9 < min_trade:
                proposed = 0.0
                if buy_factor <= 1e-9:
                    row["Action"] = "WAIT // NO FUNDING"
                    row["Reason"] = "UNDERWEIGHT // NO EXCESS CASH OR TRIM PROCEEDS"
                else:
                    row["Action"] = "HOLD // BELOW MIN"
                    row["Reason"] = f"FUNDED TRADE < ${min_trade:,.0f} MINIMUM"

        if row["Action"] == "REVIEW LOSS":
            proposed = 0.0

        post_value = float(row["Market Value"]) + proposed
        post_pct = (post_value / account_value * 100.0) if account_value > 0 else 0.0
        row["Proposed $"] = proposed
        row["Post %"] = post_pct

        if proposed > 0:
            proposed_buys += proposed
        elif proposed < 0:
            proposed_sells += -proposed

        if not str(row["Action"]).startswith("HOLD"):
            outside_count += 1

    post_cash = cash_available + proposed_sells - proposed_buys
    gross_trade = proposed_sells + proposed_buys

    public_columns = [
        "Symbol",
        "Sleeve",
        "P&L %",
        "Market Value",
        "Current %",
        "Target %",
        "Band +/- %",
        "Range",
        "Drift %",
        "Action",
        "Raw Gap $",
        "Proposed $",
        "Post %",
        "Reason",
    ]
    plan = pd.DataFrame(records)
    if plan.empty:
        plan = pd.DataFrame(columns=public_columns)
    else:
        plan = plan[public_columns]

    summary = {
        "target_total_pct": target_total,
        "target_cash_pct": target_cash_pct,
        "target_cash_value": target_cash_value,
        "excess_cash": excess_cash,
        "trim_proceeds": proposed_sells,
        "proposed_buys": proposed_buys,
        "gross_trade": gross_trade,
        "post_cash": post_cash,
        "outside_count": float(outside_count),
        "buy_funding_ratio": buy_factor,
    }
    return plan, summary


