def _delete_href(ticker: str) -> str:
    """Build a same-page delete URL while preserving unrelated query state."""
    params: dict[str, Any] = {}
    try:
        for key in st.query_params:
            values = st.query_params.get_all(key)
            params[key] = values if len(values) > 1 else (values[0] if values else "")
    except Exception:
        params = {}
    params["gex_delete"] = ticker
    return "?" + urlencode(params, doseq=True)


def _inject_row_trash(markup: str) -> str:
    """Place one left-aligned clickable trash icon inside every ticker cell."""
    if 'class="gexv3-summary"' not in markup:
        return markup

    def replace_symbol(match: re.Match[str]) -> str:
        ticker = html.unescape(match.group(1)).strip().upper()
        ticker_html = html.escape(ticker)
        href = html.escape(_delete_href(ticker), quote=True)
        return (
            '<td class="sym">'
            '<span class="gexv3-symbol-wrap">'
            f'<a class="gexv3-trash-link" href="{href}" target="_self" '
            f'aria-label="Delete {ticker_html} from GEX" '
            f'title="Delete {ticker_html} from GEX">🗑</a>'
            f'<span class="gexv3-symbol-text">{ticker_html}</span>'
            '</span>'
            '</td>'
        )

    return re.sub(
        r'<td class="sym">([^<]+)</td>',
        replace_symbol,
        markup,
    )


def _gamma_regime(result: dict[str, Any]) -> tuple[str, str]:
    """Classify spot relative to gamma flip with a small neutral noise band."""
    try:
        spot = float(result.get("spot"))
        flip = float(result.get("gammaFlip"))
    except (TypeError, ValueError):
        return "NEUTRAL", "neutral"
    if spot <= 0 or flip <= 0:
        return "NEUTRAL", "neutral"

    distance = (spot - flip) / flip
    if abs(distance) <= _GAMMA_NEUTRAL_BAND:
        return "NEUTRAL", "neutral"
    if distance > 0:
        return "POSITIVE", "positive"
    return "NEGATIVE", "negative"


def _range_visual(result: dict[str, Any]) -> str:
    """Build an interactive line/dot range with gamma-flip regime metadata."""
    try:
        spot = float(result["spot"])
        put_wall = float(result["putWall"]["strike"])
        call_wall = float(result["callWall"]["strike"])
    except (KeyError, TypeError, ValueError):
        return '<span class="gexv3-range-meta neutral">RANGE WAITING</span>'

    try:
        gamma_flip = float(result.get("gammaFlip"))
        has_flip = gamma_flip > 0
    except (TypeError, ValueError):
        gamma_flip = 0.0
        has_flip = False

    points = [put_wall, spot, call_wall]
    if has_flip:
        points.append(gamma_flip)
    low = min(points)
    high = max(points)
    span = high - low

    def position(value: float) -> float:
        if span <= 0:
            return 50.0
        return max(3.0, min(97.0, 3.0 + 94.0 * ((value - low) / span)))

    def dot(kind: str, label: str, value: float) -> str:
        tip = html.escape(f"{label} ${value:,.2f}", quote=True)
        return (
            f'<span class="gexv3-range-dot {kind}" tabindex="0" role="img" '
            f'aria-label="{tip}" data-tip="{tip}" '
            f'style="left:{position(value):.2f}%"></span>'
        )

    regime, tone = _gamma_regime(result)
    flip_text = f"${gamma_flip:,.2f}" if has_flip else "—"
    distance_text = "—"
    zone = ""
    flip_dot = ""
    if has_flip:
        distance_pct = ((spot - gamma_flip) / gamma_flip) * 100.0
        distance_text = f"{distance_pct:+.2f}%"
        flip_position = position(gamma_flip)
        spot_position = position(spot)
        zone_left = min(flip_position, spot_position)
        zone_width = max(0.7, abs(spot_position - flip_position))
        zone = (
            f'<span class="gexv3-range-zone {tone}" '
            f'style="left:{zone_left:.2f}%;width:{zone_width:.2f}%"></span>'
        )
        flip_dot = dot("flip", "GAMMA FLIP", gamma_flip)

    range_label = html.escape(
        f"PUT WALL ${put_wall:,.2f}; GAMMA FLIP {flip_text}; "
        f"SPOT ${spot:,.2f}; CALL WALL ${call_wall:,.2f}",
        quote=True,
    )
    return (
        f'<div class="gexv3-range-mini" aria-label="{range_label}">'
        '<span class="gexv3-range-line"></span>'
        f"{zone}"
        f'{dot("put", "PUT WALL", put_wall)}'
        f"{flip_dot}"
        f'{dot("spot", "SPOT", spot)}'
        f'{dot("call", "CALL WALL", call_wall)}'
        "</div>"
        f'<div class="gexv3-range-meta {tone}">'
        f"GF {flip_text} // {regime} GAMMA // Δ {distance_text}"
        "</div>"
    )


def _decorate_overview(markup: str, vault_key: str) -> str:
    """Add row trash, wider range column, and gamma regime visualization."""
    if 'class="gexv3-summary"' not in markup:
        return markup

    if "<colgroup>" not in markup:
        colgroup = (
            "<colgroup>"
            '<col style="width:12%"><col style="width:6%"><col style="width:10%">'
            '<col style="width:10%"><col style="width:10%"><col style="width:10%">'
            '<col style="width:28%"><col style="width:14%">'
            "</colgroup>"
        )
        markup = markup.replace(
            '<table class="gexv3-summary"><thead>',
            '<table class="gexv3-summary">' + colgroup + "<thead>",
            1,
        )

    result_map = _base.core._results(str(vault_key or "default"))

    def decorate_row(match: re.Match[str]) -> str:
        inner = match.group(1)
        ticker_match = re.search(r'<td class="sym">([^<]+)</td>', inner)
        if not ticker_match:
            return match.group(0)
        ticker = html.unescape(ticker_match.group(1)).strip().upper()
        result = result_map.get(ticker)
        if not result:
            return match.group(0)

        status, tone = _base._range_status(result)
        legacy = f'<td class="{tone}">{status}</td>'
        replacement = f'<td class="gexv3-range-col">{_range_visual(result)}</td>'
        inner = inner.replace(legacy, replacement, 1)
        return "<tr>" + inner + "</tr>"

    markup = re.sub(r"<tr>(.*?)</tr>", decorate_row, markup, flags=re.DOTALL)
    return _inject_row_trash(markup)


def _consume_delete_request(vault_key: str) -> None:
    """Persist a row-trash request, clear only that query parameter, and rerun."""
    try:
        raw = st.query_params.get("gex_delete")
    except Exception:
        raw = None
    ticker = _base.core._normalize_ticker(raw)
    if not ticker:
        return

    state = copy.deepcopy(_base.core._load_state(str(vault_key or "default")))
    result_map = _base.core._results(str(vault_key or "default"))
    if ticker in state.get("tickers", []):
        _base._remove_ticker(str(vault_key or "default"), state, result_map, ticker)

    try:
        del st.query_params["gex_delete"]
    except Exception:
        pass
    st.rerun()


# ==============================
# TRADINGVIEW / PINE ROUTER BRIDGE
# ==============================
# The supplied Google Apps Script is the MASTER A6 serialization contract.
# Successful tickers keep its full human-readable summary + packed rows, while
# failed tickers keep the Apps Script ``Ticker:`` / ``ERROR:`` block. The fixed
# Pine router ignores metadata and consumes the packed row types after matching
# the ticker header, so one failed symbol must never hide the copyable A6 block.
_PINE_TEXT_LIMIT = 40_960
_PINE_REQUIRED_TYPES = {"SPOT", "CALLWALL", "PUTWALL", "MAXCALLOI", "MAXPUTOI"}


def _pine_router_block(result: dict[str, Any]) -> str:
    """Emit only the rows consumed by Pine; retained as a compact diagnostic."""
    symbol = _base.core._normalize_ticker(result.get("symbol"))
    if not symbol:
        return ""
    packed_rows = _base._packed_gamma_lines(result)
    return "\n".join([f"Ticker: {symbol}", *packed_rows])


def _pine_master_bridge_text(result_map: dict[str, Any], tickers: list[str]) -> str:
    """Build a compact all-successful-ticker payload for parser diagnostics."""
    blocks: list[str] = []
    for raw_ticker in tickers:
        ticker = _base.core._normalize_ticker(raw_ticker)
        result = result_map.get(ticker)
        if not result:
            continue
        block = _pine_router_block(result)
        if block:
            blocks.append(block)
    return "\n\n".join(blocks).strip()


def _google_sheets_master_text(
    result_map: dict[str, Any],
    tickers: list[str],
    failures: dict[str, str] | None = None,
) -> str:
    """Mirror ``refreshGEX`` -> ``allOutputLines`` -> TradingView A6 exactly.

    The supplied Apps Script appends successful ``summaryText.split('\\n')``
    rows plus one extra blank row. Failed tickers append ``Ticker:``, ``ERROR:``,
    and one blank row. Joining with ``\\n`` and trimming produces the exact A6
    shape expected by the user's existing Pine input workflow.
    """
    normalized_failures = {
        _base.core._normalize_ticker(key): " ".join(str(value).split())
        for key, value in (failures or {}).items()
        if _base.core._normalize_ticker(key)
    }
    all_output_lines: list[str] = []

    for raw_ticker in tickers:
        ticker = _base.core._normalize_ticker(raw_ticker)
        if not ticker:
            continue

        if ticker in normalized_failures:
            all_output_lines.extend(
                [
                    f"Ticker: {ticker}",
                    f"ERROR: {normalized_failures[ticker]}",
                    "",
                ]
            )
            continue

        result = result_map.get(ticker)
        if result:
            summary = _base._google_sheets_summary_text(result)
            all_output_lines.extend(summary.split("\n"))
            all_output_lines.append("")
            continue

        all_output_lines.extend(
            [
                f"Ticker: {ticker}",
                "ERROR: No refreshed GEX result available.",
                "",
            ]
        )

    if not all_output_lines:
        all_output_lines.append("")
    return "\n".join(all_output_lines).strip()


def _pine_router_headers(text: str) -> list[str]:
    """Return normalized Ticker headers exactly as the Pine router sees them."""
    return [
        _base.core._normalize_ticker(value)
        for value in re.findall(r"(?m)^Ticker:\s*([^\r\n]+)\s*$", str(text or ""))
        if _base.core._normalize_ticker(value)
    ]


def _pine_ticker_block(text: str, ticker: str) -> str:
    """Extract one routed block using the same Ticker-header boundary Pine uses."""
    target = _base.core._normalize_ticker(ticker)
    if not target:
        return ""
    normalized = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    active = False
    out: list[str] = []
    for row in normalized.split("\n"):
        header = re.match(r"^\s*Ticker:\s*([^\r\n]+?)\s*$", row, flags=re.IGNORECASE)
        if header:
            found = _base.core._normalize_ticker(header.group(1))
            if active and found != target:
                break
            active = found == target
        if active:
            out.append(row)
    return "\n".join(out).strip()


def _pine_parsed_types(block: str) -> list[str]:
    """Replica of the fixed Pine row parser for Streamlit-side preflight checks."""
    parsed: list[str] = []
    for raw_row in str(block or "").replace("\r", "").split("\n"):
        compact = raw_row.replace("|", ",").replace(" ", "").replace("\t", "")
        parts = compact.split(",")
        if len(parts) < 2:
            continue
        typ = parts[0].strip().upper()
        is_packed = (
            typ in {"SPOT", "GFLIP", "CALLWALL", "PUTWALL", "MAXCALLOI", "MAXPUTOI"}
            or typ.startswith("GEXPOS")
            or typ.startswith("GEXNEG")
        )
        if not is_packed:
            continue
        try:
            float(parts[1])
        except (TypeError, ValueError):
            continue
        parsed.append(typ)
    return parsed


def _pine_ticker_issues(text: str, ticker: str) -> tuple[list[str], int]:
    """Validate one ticker exactly enough to guarantee Pine has drawable levels."""
    target = _base.core._normalize_ticker(ticker)
    block = _pine_ticker_block(text, target)
    if not block:
        return [f"{target}:NO_HEADER"], 0
    parsed = _pine_parsed_types(block)
    parsed_set = set(parsed)
    issues = [f"{target}:NO_{typ}" for typ in sorted(_PINE_REQUIRED_TYPES - parsed_set)]
    if not any(typ.startswith("GEXPOS") or typ.startswith("GEXNEG") for typ in parsed):
        issues.append(f"{target}:NO_GEX")
    return issues, len(parsed)


def _pine_master_issues(text: str, expected: list[str]) -> tuple[list[str], dict[str, int]]:
    """Run the fixed Pine routing/parsing contract against successful tickers."""
    issues: list[str] = []
    counts: dict[str, int] = {}
    headers = _pine_router_headers(text)
    duplicate_headers = sorted({ticker for ticker in headers if headers.count(ticker) > 1})
    issues.extend(f"{ticker}:DUPLICATE_HEADER" for ticker in duplicate_headers)
    for ticker in expected:
        ticker_issues, parsed_count = _pine_ticker_issues(text, ticker)
        counts[ticker] = parsed_count
        issues.extend(ticker_issues)
    return issues, counts


