def render_gex(
    client: Any,
    vault_key: str,
    touch_session: Any,
    *,
    background_client_factory: Callable[[], Any] | None = None,
) -> None:
    """Render stable GEX v3 with non-blocking refresh-all and row enhancements."""
    vault_key = str(vault_key or "default")
    _consume_delete_request(vault_key)
    _sync_background_results(vault_key)

    # CSS must exist before the animated status element is rendered.
    st.html(_ROW_ACTION_CSS)
    _render_background_status(vault_key)

    original_markdown = st.markdown
    original_button = st.button
    original_tradingview = _base._render_tradingview
    start_requested = {"value": False}

    def row_action_markdown(body: Any, *args: Any, **kwargs: Any):
        if isinstance(body, str) and 'class="gexv3-summary"' in body:
            body = _decorate_overview(body, vault_key)
        return original_markdown(body, *args, **kwargs)

    def background_button(label: Any, *args: Any, **kwargs: Any):
        if kwargs.get("key") != "gexv3_refresh_all":
            return original_button(label, *args, **kwargs)

        if background_client_factory is None:
            # Safe fallback: preserve the legacy synchronous behavior if a
            # dedicated background client cannot be created.
            return original_button(label, *args, **kwargs)

        job = _background_job(vault_key)
        if job and job.get("status") in {"QUEUED", "RUNNING"}:
            kwargs["disabled"] = True
            label = f"↻ GEX {job['workers']}-WAY {job['completed']}/{job['total']}"
        clicked = original_button(label, *args, **kwargs)
        if clicked:
            start_requested["value"] = True
            # Return False so the preserved base renderer does NOT enter its
            # synchronous multi-ticker refresh loop.
            return False
        return clicked

    def tradingview_renderer(state: dict[str, Any], result_map: dict[str, Any]) -> None:
        job = _background_job(vault_key) or {}
        failures = dict(job.get("failures") or {})
        _render_tradingview_pine(state, result_map, failures)

    st.markdown = row_action_markdown
    st.button = background_button
    _base._render_tradingview = tradingview_renderer
    try:
        _base.render_gex(client, vault_key, touch_session)
    finally:
        _base._render_tradingview = original_tradingview
        st.button = original_button
        st.markdown = original_markdown

    if start_requested["value"]:
        state_snapshot = copy.deepcopy(
            st.session_state.get("_gex_state") or _base.core.DEFAULT_STATE
        )
        started = _start_background_refresh(
            vault_key,
            state_snapshot,
            background_client_factory,
        )
        if started:
            if callable(touch_session):
                try:
                    touch_session()
                except Exception:
                    pass
            st.toast("4-WAY BACKGROUND GEX REFRESH STARTED // switch tabs and keep working")
            st.rerun()


