"""GEX-only runtime telemetry shared by the production GEX wrappers.

OWNERSHIP / EDITING NOTES
-------------------------
EDIT THIS FILE FOR:
- thread-safe GEX background request counters and recent progress messages;
- formatting backend telemetry for the GEX hover log.

DO NOT EDIT THIS FILE FOR:
- GEX formulas, Pine serialization, Risk Sizing, OAuth UI, Holdings, or navigation.

This module is deliberately Streamlit-free so E*TRADE worker threads can report
progress without touching ``st.session_state`` or any UI API.
"""

from __future__ import annotations

import hashlib
import threading
import time
from typing import Any


# ==============================
# TELEMETRY STATE
# ==============================
_LOCK = threading.RLock()
_LOG_LIMIT = 22
_STATE: dict[str, dict[str, Any]] = {}


def namespace_for_token(oauth_token: Any) -> str:
    """Match the non-reversible namespace used by the GEX market-data cache."""
    token = str(oauth_token or "").strip()
    if not token:
        return ""
    return hashlib.sha256(token.encode("utf-8")).hexdigest()[:32]


def _blank(now: float | None = None) -> dict[str, Any]:
    stamp = float(now or time.time())
    return {
        "started_at": stamp,
        "last_at": stamp,
        "cache_hits": 0,
        "live_started": 0,
        "live_done": 0,
        "live_failed": 0,
        "inflight": 0,
        "chain_queued": 0,
        "chain_started": 0,
        "chain_done": 0,
        "chain_failed": 0,
        "batch_quotes": 0,
        "recent": [],
    }


def reset(namespace: str, message: str = "REFRESH ALL STARTED") -> None:
    namespace = str(namespace or "")
    if not namespace:
        return
    now = time.time()
    with _LOCK:
        _STATE[namespace] = _blank(now)
        _append_locked(_STATE[namespace], message, now)


def _row(namespace: str) -> dict[str, Any] | None:
    namespace = str(namespace or "")
    if not namespace:
        return None
    row = _STATE.get(namespace)
    if row is None:
        row = _blank()
        _STATE[namespace] = row
    return row


def _append_locked(row: dict[str, Any], message: str, now: float | None = None) -> None:
    stamp = float(now or time.time())
    started = float(row.get("started_at", stamp) or stamp)
    elapsed = max(0.0, stamp - started)
    text = f"+{elapsed:6.1f}s  {str(message or '').strip()}"
    recent = row.setdefault("recent", [])
    recent.append(text)
    del recent[:-_LOG_LIMIT]
    row["last_at"] = stamp


def note(namespace: str, message: str) -> None:
    with _LOCK:
        row = _row(namespace)
        if row is not None:
            _append_locked(row, message)


def cache_hit(namespace: str, resource_type: str, resource_key: str) -> None:
    with _LOCK:
        row = _row(namespace)
        if row is None:
            return
        row["cache_hits"] = int(row.get("cache_hits", 0) or 0) + 1
        if resource_type == "option_chain":
            label = str(resource_key).split(":", 1)[0]
            _append_locked(row, f"CACHE HIT CHAIN // {label}")


def chain_queued(namespace: str, resource_key: str) -> None:
    with _LOCK:
        row = _row(namespace)
        if row is None:
            return
        row["chain_queued"] = int(row.get("chain_queued", 0) or 0) + 1
        parts = str(resource_key).split(":")
        label = " ".join(parts[:2]) if len(parts) >= 2 else str(resource_key)
        _append_locked(row, f"QUEUE CHAIN // {label}")


def batch_quote(namespace: str, symbol_count: int, phase: str) -> None:
    with _LOCK:
        row = _row(namespace)
        if row is None:
            return
        if str(phase).upper() == "START":
            row["batch_quotes"] = int(row.get("batch_quotes", 0) or 0) + 1
        _append_locked(row, f"BATCH QUOTE {str(phase).upper()} // {int(symbol_count)} SYMBOLS")


def live_start(namespace: str, resource_type: str, resource_key: str) -> float:
    started = time.monotonic()
    with _LOCK:
        row = _row(namespace)
        if row is None:
            return started
        row["live_started"] = int(row.get("live_started", 0) or 0) + 1
        row["inflight"] = int(row.get("inflight", 0) or 0) + 1
        if resource_type == "option_chain":
            row["chain_started"] = int(row.get("chain_started", 0) or 0) + 1
        short_key = str(resource_key)
        if resource_type == "option_chain":
            parts = short_key.split(":")
            short_key = " ".join(parts[:2]) if len(parts) >= 2 else short_key
        _append_locked(row, f"LIVE {resource_type.upper()} START // {short_key}")
    return started


def live_done(
    namespace: str,
    resource_type: str,
    resource_key: str,
    started: float,
    *,
    ok: bool,
) -> None:
    elapsed = max(0.0, time.monotonic() - float(started))
    with _LOCK:
        row = _row(namespace)
        if row is None:
            return
        row["inflight"] = max(0, int(row.get("inflight", 0) or 0) - 1)
        short_key = str(resource_key)
        if resource_type == "option_chain":
            parts = short_key.split(":")
            short_key = " ".join(parts[:2]) if len(parts) >= 2 else short_key
        if ok:
            row["live_done"] = int(row.get("live_done", 0) or 0) + 1
            if resource_type == "option_chain":
                row["chain_done"] = int(row.get("chain_done", 0) or 0) + 1
            _append_locked(
                row,
                f"LIVE {resource_type.upper()} DONE // {short_key} // {elapsed:.1f}s",
            )
        else:
            row["live_failed"] = int(row.get("live_failed", 0) or 0) + 1
            if resource_type == "option_chain":
                row["chain_failed"] = int(row.get("chain_failed", 0) or 0) + 1
            _append_locked(
                row,
                f"LIVE {resource_type.upper()} FAIL // {short_key} // {elapsed:.1f}s",
            )


def snapshot(namespace: str) -> dict[str, Any]:
    namespace = str(namespace or "")
    if not namespace:
        return _blank()
    with _LOCK:
        row = _STATE.get(namespace)
        if row is None:
            return _blank()
        return {
            "started_at": float(row.get("started_at", 0.0) or 0.0),
            "last_at": float(row.get("last_at", 0.0) or 0.0),
            "cache_hits": int(row.get("cache_hits", 0) or 0),
            "live_started": int(row.get("live_started", 0) or 0),
            "live_done": int(row.get("live_done", 0) or 0),
            "live_failed": int(row.get("live_failed", 0) or 0),
            "inflight": int(row.get("inflight", 0) or 0),
            "chain_queued": int(row.get("chain_queued", 0) or 0),
            "chain_started": int(row.get("chain_started", 0) or 0),
            "chain_done": int(row.get("chain_done", 0) or 0),
            "chain_failed": int(row.get("chain_failed", 0) or 0),
            "batch_quotes": int(row.get("batch_quotes", 0) or 0),
            "recent": list(row.get("recent") or []),
        }


