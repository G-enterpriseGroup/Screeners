def _apply_iv_rank_history(
    vault_key: str,
    state: dict[str, Any],
    result_map: dict[str, Any],
) -> dict[str, Any]:
    """Attach rolling IV Rank + valuation text from E*TRADE IV observations.

    Current IV is a constant-30-day ATM observation built from E*TRADE
    OptionGreeks.iv. One observation per ticker/day is kept for 365 days.
    Until ten daily observations exist, the column shows the current E*TRADE IV
    plus history progress instead of fabricating a rank. A trailing ``P`` marks
    ranks whose stored history does not yet span a full 365 calendar days.
    """
    history_map = state.setdefault("iv_history", {})
    changed = False

    for raw_ticker in state.get("tickers", []):
        ticker = _normalize_ticker(raw_ticker)
        result = result_map.get(ticker)
        if not ticker or not isinstance(result, dict):
            continue

        try:
            current_iv = float(result.get("representativeIv"))
        except (TypeError, ValueError):
            current_iv = 0.0
        if not math.isfinite(current_iv) or not (0.0 < current_iv < 5.0):
            result["ivRank"] = None
            result["ivRankDisplay"] = "N/A | No IV"
            result["ivRankTone"] = "orange"
            continue

        raw_day = str(result.get("updated") or "")[:10]
        try:
            observation_day = date.fromisoformat(raw_day)
        except ValueError:
            observation_day = date.today()
            raw_day = observation_day.isoformat()
        cutoff = observation_day - timedelta(days=IV_RANK_LOOKBACK_DAYS)

        by_day: dict[str, float] = {}
        for row in history_map.get(ticker, []) or []:
            if not isinstance(row, dict):
                continue
            day_text = str(row.get("date") or "")[:10]
            try:
                day_value = date.fromisoformat(day_text)
                iv_value = float(row.get("iv"))
            except (TypeError, ValueError):
                continue
            if day_value >= cutoff and math.isfinite(iv_value) and 0.0 < iv_value < 5.0:
                by_day[day_text] = iv_value

        by_day[raw_day] = current_iv
        compact = [{"date": day_text, "iv": by_day[day_text]} for day_text in sorted(by_day)]
        if compact != (history_map.get(ticker, []) or []):
            history_map[ticker] = compact
            changed = True

        values = [float(row["iv"]) for row in compact]
        count = len(values)
        result["ivRankHistoryCount"] = count
        result["ivRankCurrentIv"] = current_iv
        result["ivRankLowIv"] = min(values)
        result["ivRankHighIv"] = max(values)
        if count < IV_RANK_MIN_OBSERVATIONS:
            result["ivRank"] = None
            result["ivRankDisplay"] = (
                f"IV {current_iv * 100.0:.1f}% | {count}/{IV_RANK_MIN_OBSERVATIONS}"
            )
            result["ivRankTone"] = "orange"
            result["ivRankProvisional"] = True
            continue

        low_iv = min(values)
        high_iv = max(values)
        if high_iv - low_iv <= 1e-12:
            rank = 50.0
        else:
            rank = max(0.0, min(100.0, (current_iv - low_iv) / (high_iv - low_iv) * 100.0))

        if rank < 30.0:
            rank_reference, rank_tone = "LOW", "green"
        elif rank > 70.0:
            rank_reference, rank_tone = "HIGH", "red"
        else:
            rank_reference, rank_tone = "MID", "orange"

        first_day = date.fromisoformat(compact[0]["date"])
        span_days = max(0, (observation_day - first_day).days)
        provisional = span_days < IV_RANK_FULL_SPAN_DAYS
        rank_text = f"{rank:.1f}P" if provisional else f"{rank:.1f}"
        result["ivRank"] = rank
        result["ivRankDisplay"] = f"IVR {rank_text}"
        result["ivRankReference"] = rank_reference
        result["ivRankTone"] = rank_tone
        result["ivRankProvisional"] = provisional

    if changed:
        return _save_state(vault_key, state)
    return state


