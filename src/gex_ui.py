def _estimate_gamma_flip(
    contracts: list[dict[str, Any]],
    spot: float,
    strikes: list[float] | None = None,
) -> float | None:
    """Match Raj's supplied script: 160 samples across spot +/-20%.

    The whole scan is evaluated in one NumPy matrix instead of running 1,000
    separate Python/NumPy passes. The first sign crossing is linearly
    interpolated; if no crossing exists, return the sampled price with minimum
    absolute net gamma, matching the supplied Apps Script fallback.
    """
    del strikes
    valid = [contract for contract in contracts if int(contract.get("dte", 0) or 0) > 0]
    if not valid or spot <= 0:
        return None

    c_strikes = np.asarray([contract["strike"] for contract in valid], dtype=float)[None, :]
    c_iv = np.maximum(np.asarray([contract["iv"] for contract in valid], dtype=float), 0.05)[None, :]
    c_t = np.maximum(
        np.asarray([contract["dte"] for contract in valid], dtype=float) / 365.0,
        1.0 / 365.0,
    )[None, :]
    c_sqrt_t = np.sqrt(c_t)
    c_oi = np.asarray([contract["oi"] for contract in valid], dtype=float)[None, :]
    c_sign = np.asarray(
        [1.0 if contract["cp"] == "C" else -1.0 for contract in valid],
        dtype=float,
    )[None, :]

    scan_low = max(0.01, spot * (1.0 - GAMMA_FLIP_RANGE_PCT))
    scan_high = spot * (1.0 + GAMMA_FLIP_RANGE_PCT)
    scan = np.linspace(scan_low, scan_high, GAMMA_FLIP_STEPS + 1, dtype=float)
    test_spots = scan[:, None]

    d1 = (np.log(test_spots / c_strikes) + (0.5 * c_iv * c_iv) * c_t) / (c_iv * c_sqrt_t)
    gamma = (
        np.exp(-0.5 * d1 * d1)
        / math.sqrt(2.0 * math.pi)
        / (test_spots * c_iv * c_sqrt_t)
    )
    exposure = gamma * c_oi * CONTRACT_SIZE * test_spots * test_spots * 0.01
    totals = np.sum(c_sign * exposure, axis=1)

    for index in range(1, len(scan)):
        previous = float(totals[index - 1])
        current = float(totals[index])
        crossed = (previous <= 0.0 <= current) or (previous >= 0.0 >= current)
        if not crossed:
            continue
        denominator = abs(previous) + abs(current)
        if denominator <= 0:
            return float(scan[index])
        fraction = abs(previous) / denominator
        return float(scan[index - 1] + (scan[index] - scan[index - 1]) * fraction)

    return float(scan[int(np.argmin(np.abs(totals)))])


def _build_gex(
    client: Any,
    symbol: str,
    max_dte: int,
    timezone_name: str,
    wall_value_mode: str,
    *,
    force_refresh: bool = False,
) -> dict[str, Any]:
    """Build one ticker using the supplied-script wall/flip definitions."""
    symbol = _normalize_ticker(symbol)
    if not symbol:
        raise _legacy.ETradeError("Enter a ticker first.")
    if client is None:
        raise _legacy.ETradeError("Connect E*TRADE first, or seed a cached option-chain snapshot.")

    quote = _legacy.quote_summary(_legacy._call_api(client, "get_quote", symbol, force_refresh=force_refresh))
    spot = float(quote["last"])
    expiration_payload = _legacy._call_api(
        client,
        "get_option_expirations",
        symbol,
        force_refresh=force_refresh,
    )
    expirations = _legacy.option_expiration_dates(expiration_payload)
    tz = ZoneInfo(timezone_name)
    today = datetime.now(tz).date()

    iv_targets = _iv_rank_expirations(expiration_payload, today)

    eligible: list[tuple[int, int, int, int]] = []
    for year, month, day in expirations:
        expiry = datetime(year, month, day, tzinfo=tz).date()
        dte = max((expiry - today).days, 0)
        if 0 <= dte <= int(max_dte):
            eligible.append((year, month, day, dte))
    if not eligible:
        raise _legacy.ETradeError(
            f"No E*TRADE option expirations were found at or below {max_dte} DTE for {symbol}."
        )

    contracts: list[dict[str, Any]] = []
    expiries_used: list[str] = []
    chain_errors: list[str] = []
    representative_iv: float | None = None
    iv_expiry = ""
    iv_dte: int | None = IV_RANK_TARGET_DTE
    iv_expiry_type = ""
    iv_target_map = {
        (year, month, day): (target_dte, expiry_type)
        for year, month, day, target_dte, expiry_type in iv_targets
    }
    iv_call_observations: dict[int, float] = {}
    iv_put_observations: dict[int, float] = {}
    iv_observation_meta: dict[int, tuple[str, str]] = {}
    iv_target_attempted: set[tuple[int, int, int]] = set()

    for year, month, day, dte in eligible:
        try:
            chain = _legacy._call_api(
                client,
                "get_option_chain",
                symbol,
                year,
                month,
                day,
                no_of_strikes=100,
                chain_type="CALLPUT",
                force_refresh=force_refresh,
            )
            target_meta = iv_target_map.get((year, month, day))
            if target_meta is not None:
                iv_target_attempted.add((year, month, day))
                target_dte, expiry_type = target_meta
                call_iv = _vega_weighted_side_iv(chain, spot, "Call")
                put_iv = _vega_weighted_side_iv(chain, spot, "Put")
                if call_iv is not None:
                    iv_call_observations[int(target_dte)] = call_iv
                if put_iv is not None:
                    iv_put_observations[int(target_dte)] = put_iv
                if call_iv is not None or put_iv is not None:
                    iv_observation_meta[int(target_dte)] = (
                        f"{year:04d}-{month:02d}-{day:02d}",
                        str(expiry_type or ""),
                    )

            parsed = _parse_contracts(chain, dte, spot)
            if parsed:
                contracts.extend(parsed)
                expiries_used.append(f"{year:04d}-{month:02d}-{day:02d}")
        except Exception as exc:
            chain_errors.append(f"{year:04d}-{month:02d}-{day:02d}: {exc}")

    if not contracts:
        detail = f" Last chain error: {chain_errors[-1]}" if chain_errors else ""
        raise _legacy.ETradeError(
            f"No usable E*TRADE option contracts with open interest were found for {symbol}.{detail}"
        )

    # IV Rank / IV-HV must not change definition when Raj changes GEX max DTE.
    # Reuse already-fetched GEX chains first. For a missing 30-day bracket,
    # fetch a compact E*TRADE CALLPUT chain. The four nearest contracts per side
    # are then Vega-weighted, matching Fidelity's documented IVX construction.
    for year, month, day, target_dte, expiry_type in iv_targets:
        target_key = (year, month, day)
        side_ready = (
            int(target_dte) in iv_call_observations
            or int(target_dte) in iv_put_observations
        )
        if side_ready or target_key in iv_target_attempted:
            continue
        try:
            iv_chain = _legacy._call_api(
                client,
                "get_option_chain",
                symbol,
                year,
                month,
                day,
                no_of_strikes=IV_RANK_ATM_STRIKES,
                chain_type="CALLPUT",
                force_refresh=force_refresh,
            )
            call_iv = _vega_weighted_side_iv(iv_chain, spot, "Call")
            put_iv = _vega_weighted_side_iv(iv_chain, spot, "Put")
            if call_iv is not None:
                iv_call_observations[int(target_dte)] = call_iv
            if put_iv is not None:
                iv_put_observations[int(target_dte)] = put_iv
            if call_iv is not None or put_iv is not None:
                iv_observation_meta[int(target_dte)] = (
                    f"{year:04d}-{month:02d}-{day:02d}",
                    str(expiry_type or ""),
                )
        except Exception as exc:
            chain_errors.append(
                f"IV {year:04d}-{month:02d}-{day:02d}: {exc}"
            )

    representative_iv, iv_call_30, iv_put_30 = _ivx30_from_chains(
        iv_call_observations,
        iv_put_observations,
    )
    iv_method = (
        "FIDELITY-STYLE IVX30 // 4 NEAR ATM/SIDE // VEGA-WEIGHTED // SQRT-DTE"
        if representative_iv is not None
        else ""
    )
    if representative_iv is not None and iv_observation_meta:
        ordered_dtes = sorted(iv_observation_meta)
        iv_expiry = " / ".join(iv_observation_meta[dte][0] for dte in ordered_dtes)
        iv_expiry_type = " / ".join(
            iv_observation_meta[dte][1] or "UNSPECIFIED"
            for dte in ordered_dtes
        )

    # Last-resort fallback preserves a current E*TRADE IV value for symbols
    # whose chain is missing usable Vega on the 30-day bracket. The UI exposes
    # the fallback method rather than pretending it is the primary IVX method.
    if representative_iv is None:
        representative_iv = _representative_iv(contracts, spot)
        if representative_iv is not None:
            observed_dtes = sorted(
                {
                    int(contract.get("dte", 0) or 0)
                    for contract in contracts
                    if contract.get("iv_from_feed")
                }
            )
            if observed_dtes:
                thirty_plus = [value for value in observed_dtes if value >= IV_RANK_TARGET_DTE]
                iv_dte = min(thirty_plus) if thirty_plus else max(observed_dtes)
            iv_expiry_type = "GEX_FALLBACK"
            iv_method = "E*TRADE ATM FALLBACK"

    hv_result = load_30d_historical_volatility(symbol)
    try:
        historical_volatility_30 = float(hv_result.get("historicalVolatility"))
    except (TypeError, ValueError):
        historical_volatility_30 = 0.0
    if not math.isfinite(historical_volatility_30) or historical_volatility_30 <= 0:
        historical_volatility_30 = None

    iv_hv_ratio = (
        float(representative_iv) / historical_volatility_30
        if representative_iv is not None and historical_volatility_30 is not None
        else None
    )
    if iv_hv_ratio is None:
        iv_hv_label, iv_hv_tone = "HV N/A", "orange"
    elif iv_hv_ratio > 1.0:
        iv_hv_label, iv_hv_tone = "RICH", "red"
    elif iv_hv_ratio < 1.0:
        iv_hv_label, iv_hv_tone = "CHEAP", "green"
    else:
        iv_hv_label, iv_hv_tone = "FAIR", "orange"

    aggregate: dict[float, dict[str, float]] = {}
    for contract in contracts:
        strike = contract["strike"]
        row = aggregate.setdefault(
            strike,
            {
                "strike": strike,
                "call_oi": 0.0,
                "put_oi": 0.0,
                "call_gex": 0.0,
                "put_gex": 0.0,
                "net_gex": 0.0,
                "cum_gex": 0.0,
                "rank": 0,
            },
        )
        exposure = contract["gamma_now"] * contract["oi"] * CONTRACT_SIZE * spot * spot * 0.01
        if contract["cp"] == "C":
            row["call_oi"] += contract["oi"]
            row["call_gex"] += exposure
            row["net_gex"] += exposure
        else:
            row["put_oi"] += contract["oi"]
            row["put_gex"] -= exposure
            row["net_gex"] -= exposure

    rows = sorted(aggregate.values(), key=lambda row: row["strike"])
    cumulative = 0.0
    for row in rows:
        cumulative += row["net_gex"]
        row["cum_gex"] = cumulative

    ranked = sorted(rows, key=lambda row: abs(row["net_gex"]), reverse=True)
    for rank, row in enumerate(ranked, 1):
        row["rank"] = rank

    max_call_oi = max(rows, key=lambda row: row["call_oi"])
    max_put_oi = max(rows, key=lambda row: row["put_oi"])
    call_wall_raw = max(rows, key=lambda row: row["call_gex"])
    put_wall_raw = min(rows, key=lambda row: row["put_gex"])
    if call_wall_raw["call_gex"] <= 0:
        call_wall_raw = max_call_oi
    if put_wall_raw["put_gex"] >= 0:
        put_wall_raw = max_put_oi

    gamma_flip = _estimate_gamma_flip(contracts, spot)
    wall_value_mode = str(wall_value_mode or "NET_GEX").upper()
    if wall_value_mode == "COMPONENT_GEX":
        call_wall_value = call_wall_raw["call_gex"]
        put_wall_value = put_wall_raw["put_gex"]
    else:
        call_wall_value = call_wall_raw["net_gex"]
        put_wall_value = put_wall_raw["net_gex"]

    call_wall = {"strike": call_wall_raw["strike"], "value": call_wall_value}
    put_wall = {"strike": put_wall_raw["strike"], "value": put_wall_value}
    top_gex = ranked[:TOP_N]
    net_current = sum(row["net_gex"] for row in rows)

    packed_rows = [f"SPOT,{_legacy._fmt_num(spot)},0"]
    if gamma_flip:
        packed_rows.append(f"GFLIP,{_legacy._fmt_num(gamma_flip)},0")
    packed_rows.extend(
        [
            f"CALLWALL,{_legacy._fmt_num(call_wall['strike'])},{_legacy._fmt_num(call_wall['value'], 2)}",
            f"PUTWALL,{_legacy._fmt_num(put_wall['strike'])},{_legacy._fmt_num(put_wall['value'], 2)}",
            f"MAXCALLOI,{_legacy._fmt_num(max_call_oi['strike'])},{_legacy._fmt_num(max_call_oi['call_oi'], 0)}",
            f"MAXPUTOI,{_legacy._fmt_num(max_put_oi['strike'])},{_legacy._fmt_num(max_put_oi['put_oi'], 0)}",
        ]
    )
    for index, values in enumerate(top_gex, 1):
        tag = "GEXPOS" if values["net_gex"] >= 0 else "GEXNEG"
        packed_rows.append(
            f"{tag}{index},{_legacy._fmt_num(values['strike'])},{_legacy._fmt_num(values['net_gex'], 2)}"
        )
    packed = "\n".join(packed_rows)

    updated = datetime.now(tz)
    summary_text = (
        f"Ticker: {symbol}\n"
        f"Mode: BARCHART_STYLE\n"
        f"Spot: {_legacy._fmt_num(spot)}\n"
        f"Max DTE Used: {max_dte}\n"
        f"Contracts Used: {len(contracts)}\n"
        f"Net Current GEX: {net_current:,.2f}\n"
        f"Source URL: E*TRADE API /v1/market/optionchains\n\n"
        "PASTE EVERYTHING BELOW INTO PINE INPUT: Packed Gamma Levels\n"
        "------------------------------------------------------------\n"
        f"{packed}\n"
    )

    return {
        "symbol": symbol,
        "mode": "BARCHART_STYLE",
        "spot": spot,
        "maxDte": int(max_dte),
        "contractsUsed": len(contracts),
        "netCurrent": net_current,
        "sourceUrl": "E*TRADE API /v1/market/optionchains",
        "representativeIv": representative_iv,
        "ivSource": "E*TRADE OptionGreeks.iv + OptionGreeks.vega",
        "ivMethod": iv_method,
        "ivExpiry": iv_expiry,
        "ivDte": iv_dte,
        "ivExpiryType": iv_expiry_type,
        "ivCall30": iv_call_30,
        "ivPut30": iv_put_30,
        "historicalVolatility30": historical_volatility_30,
        "historicalVolatilitySource": str(hv_result.get("source") or ""),
        "historicalVolatilityAsOf": str(hv_result.get("asOf") or ""),
        "historicalVolatilityStatus": str(hv_result.get("status") or ""),
        "historicalVolatilityObservations": int(hv_result.get("observations") or 0),
        "ivHvRatio": iv_hv_ratio,
        "ivHvPercent": iv_hv_ratio * 100.0 if iv_hv_ratio is not None else None,
        "ivHvSpread": (
            float(representative_iv) - historical_volatility_30
            if representative_iv is not None and historical_volatility_30 is not None
            else None
        ),
        "ivHvLabel": iv_hv_label,
        "ivHvTone": iv_hv_tone,
        "gammaFlip": gamma_flip,
        "callWall": call_wall,
        "putWall": put_wall,
        "maxCallOi": max_call_oi,
        "maxPutOi": max_put_oi,
        "topGex": top_gex,
        "packed": packed,
        "summaryText": summary_text,
        "rawRows": rows,
        "spotRangeVisual": _legacy._spot_range_visual(
            spot,
            put_wall["strike"],
            gamma_flip,
            call_wall["strike"],
        ),
        "updated": updated.isoformat(),
        "expiriesUsed": expiries_used,
        "chainErrors": chain_errors,
    }


def _refresh_one(
    client: Any,
    vault_key: str,
    state: dict[str, Any],
    symbol: str,
    touch_session: Any,
    *,
    force_refresh: bool = True,
) -> dict[str, Any]:
    symbol = _normalize_ticker(symbol)
    dte = int(state.get("dte_overrides", {}).get(symbol, state["global_dte"]))
    result = _build_gex(
        client,
        symbol,
        dte,
        state["timezone"],
        state["wall_value_mode"],
        force_refresh=force_refresh,
    )
    _results(vault_key)[symbol] = result
    if callable(touch_session):
        try:
            touch_session()
        except Exception:
            pass
    return result


def __getattr__(name: str) -> Any:
    """Delegate unchanged UI/format/plot helpers to the preserved legacy module."""
    return getattr(_legacy, name)
