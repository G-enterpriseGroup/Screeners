def _iv_rank_expirations(
    expiration_payload: dict[str, Any],
    today: date,
) -> list[tuple[int, int, int, int, str]]:
    """Return E*TRADE expiries that bracket a constant 30-day IV observation.

    The documented E*TRADE API gives contract-level OptionGreeks.iv but not a
    ready-made historical IV Rank. Using the nearest expiry below and above 30
    calendar days lets us build a stable 30-day ATM IV series from E*TRADE data
    without coupling IV Rank to the user's GEX max-DTE setting.
    """
    candidates: list[tuple[int, int, int, int, str]] = []
    raw_dates = _legacy._as_list(_legacy._find_key(expiration_payload, "ExpirationDate"))
    for item in raw_dates:
        if not isinstance(item, dict):
            continue
        try:
            year = int(item.get("year"))
            month = int(item.get("month"))
            day = int(item.get("day"))
            expiry = date(year, month, day)
        except (TypeError, ValueError):
            continue
        dte = (expiry - today).days
        if dte <= 0:
            continue
        expiry_type = str(item.get("expiryType") or "").strip().upper()
        candidates.append((year, month, day, dte, expiry_type))

    if not candidates:
        return []

    candidates.sort(key=lambda row: (row[3], row[0], row[1], row[2]))
    exact = [row for row in candidates if row[3] == IV_RANK_TARGET_DTE]
    if exact:
        return [exact[0]]

    lower = [row for row in candidates if row[3] < IV_RANK_TARGET_DTE]
    upper = [row for row in candidates if row[3] > IV_RANK_TARGET_DTE]
    selected: list[tuple[int, int, int, int, str]] = []
    if lower:
        selected.append(max(lower, key=lambda row: row[3]))
    if upper:
        selected.append(min(upper, key=lambda row: row[3]))
    return selected or [min(candidates, key=lambda row: abs(row[3] - IV_RANK_TARGET_DTE))]


def _sqrt_dte_interpolate(observations: dict[int, float]) -> float | None:
    """Interpolate volatility linearly in sqrt(days), matching Fidelity IVX."""
    clean = {
        int(dte): float(iv)
        for dte, iv in observations.items()
        if int(dte) > 0 and math.isfinite(float(iv)) and 0.0 < float(iv) < 5.0
    }
    if not clean:
        return None
    if IV_RANK_TARGET_DTE in clean:
        return clean[IV_RANK_TARGET_DTE]

    lower = [dte for dte in clean if dte < IV_RANK_TARGET_DTE]
    upper = [dte for dte in clean if dte > IV_RANK_TARGET_DTE]
    if lower and upper:
        d1 = max(lower)
        d2 = min(upper)
        root1 = math.sqrt(float(d1))
        root2 = math.sqrt(float(d2))
        target_root = math.sqrt(float(IV_RANK_TARGET_DTE))
        span = root2 - root1
        if span > 0:
            w1 = (root2 - target_root) / span
            w2 = (target_root - root1) / span
            return (clean[d1] * w1) + (clean[d2] * w2)

    nearest = min(clean, key=lambda dte: abs(dte - IV_RANK_TARGET_DTE))
    return clean[nearest]


def _vega_weighted_side_iv(
    chain: dict[str, Any],
    spot: float,
    side_name: str,
) -> float | None:
    """Return Vega-weighted IV for the four contracts nearest spot on one side."""
    if spot <= 0:
        return None

    candidates: list[tuple[float, float, float]] = []
    pairs = _legacy._as_list(_legacy._find_key(chain, "OptionPair"))
    for pair in pairs:
        if not isinstance(pair, dict):
            continue
        option = pair.get(side_name) or pair.get(side_name.lower())
        if not isinstance(option, dict):
            continue

        strike = _legacy._number(option, "strikePrice", "strike")
        if strike is None or float(strike) <= 0:
            continue
        greeks = (
            option.get("OptionGreeks")
            or option.get("optionGreeks")
            or option.get("optionGreek")
            or {}
        )
        if not isinstance(greeks, dict):
            continue

        iv_raw = (
            _legacy._find_key(greeks, "iv")
            or _legacy._find_key(greeks, "impliedVolatility")
            or _legacy._find_key(greeks, "implied_volatility")
        )
        iv = _normalize_observed_iv(iv_raw)
        vega = _legacy._number(greeks, "vega")
        if iv is None or vega is None or not math.isfinite(float(vega)) or float(vega) <= 0:
            continue

        candidates.append(
            (abs(float(strike) - spot), iv, float(vega))
        )

    candidates.sort(key=lambda row: row[0])
    selected = candidates[:IV_RANK_NEAR_CONTRACTS_PER_SIDE]
    if not selected:
        return None

    total_vega = sum(row[2] for row in selected)
    if total_vega <= 0:
        return None
    return sum(row[1] * row[2] for row in selected) / total_vega


def _ivx30_from_chains(
    call_observations: dict[int, float],
    put_observations: dict[int, float],
) -> tuple[float | None, float | None, float | None]:
    """Return mean/call/put 30-day IV using Fidelity-style IVX interpolation."""
    call_30 = _sqrt_dte_interpolate(call_observations)
    put_30 = _sqrt_dte_interpolate(put_observations)
    available = [value for value in (call_30, put_30) if value is not None]
    mean_30 = float(sum(available) / len(available)) if available else None
    return mean_30, call_30, put_30

def _normalize_observed_iv(raw: Any) -> float | None:
    try:
        iv = float(raw)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(iv) or iv <= 0:
        return None
    if iv > 5.0:
        iv /= 100.0
    return iv if 0.0 < iv < 5.0 else None


def _atm_iv_from_chain(chain: dict[str, Any], spot: float) -> float | None:
    """Return E*TRADE ATM call/put IV for one expiry without requiring OI."""
    if spot <= 0:
        return None

    observations: list[tuple[float, float]] = []
    pairs = _legacy._as_list(_legacy._find_key(chain, "OptionPair"))
    for pair in pairs:
        if not isinstance(pair, dict):
            continue
        for side_name in ("Call", "Put"):
            option = pair.get(side_name) or pair.get(side_name.lower())
            if not isinstance(option, dict):
                continue
            strike = _legacy._number(option, "strikePrice", "strike")
            if strike is None or float(strike) <= 0:
                continue
            greeks = (
                option.get("OptionGreeks")
                or option.get("optionGreeks")
                or option.get("optionGreek")
                or {}
            )
            iv_raw = None
            if isinstance(greeks, dict):
                iv_raw = (
                    _legacy._find_key(greeks, "iv")
                    or _legacy._find_key(greeks, "impliedVolatility")
                    or _legacy._find_key(greeks, "implied_volatility")
                )
            if iv_raw is None:
                iv_raw = (
                    _legacy._find_key(option, "iv")
                    or _legacy._find_key(option, "impliedVolatility")
                    or _legacy._find_key(option, "implied_volatility")
                )
            iv = _normalize_observed_iv(iv_raw)
            if iv is not None:
                observations.append((abs(float(strike) - spot), iv))

    if not observations:
        return None

    nearest = min(distance for distance, _ in observations)
    atm = [iv for distance, iv in observations if abs(distance - nearest) <= 1e-9]
    return float(sum(atm) / len(atm)) if atm else None


def _parse_contracts(chain: dict[str, Any], dte: int, spot: float) -> list[dict[str, Any]]:
    contracts: list[dict[str, Any]] = []
    pairs = _legacy._as_list(_legacy._find_key(chain, "OptionPair"))
    for pair in pairs:
        if not isinstance(pair, dict):
            continue
        for cp, side_name in (("C", "Call"), ("P", "Put")):
            option = pair.get(side_name) or pair.get(side_name.lower())
            if not isinstance(option, dict):
                continue
            strike = _legacy._number(option, "strikePrice", "strike")
            oi = _legacy._number(option, "openInterest", "open_interest", "oi")
            if strike is None or oi is None or oi <= 0:
                continue

            greeks = (
                option.get("OptionGreeks")
                or option.get("optionGreeks")
                or option.get("optionGreek")
                or {}
            )
            gamma_feed = _legacy._number(greeks, "gamma") if isinstance(greeks, dict) else None
            iv_raw = None
            if isinstance(greeks, dict):
                iv_raw = (
                    _legacy._find_key(greeks, "iv")
                    or _legacy._find_key(greeks, "impliedVolatility")
                    or _legacy._find_key(greeks, "implied_volatility")
                )
            if iv_raw is None:
                iv_raw = (
                    _legacy._find_key(option, "iv")
                    or _legacy._find_key(option, "impliedVolatility")
                    or _legacy._find_key(option, "implied_volatility")
                )

            feed_iv = _normalize_observed_iv(iv_raw)
            iv = feed_iv if feed_iv is not None else DEFAULT_IV
            gamma_now = (
                float(gamma_feed)
                if gamma_feed is not None and gamma_feed > 0
                else _legacy._bs_gamma(spot, float(strike), iv, dte)
            )
            contracts.append(
                {
                    "cp": cp,
                    "strike": float(strike),
                    "dte": int(dte),
                    "oi": float(oi),
                    "iv": float(iv),
                    "iv_from_feed": feed_iv is not None,
                    "gamma_now": float(gamma_now),
                }
            )
    return contracts


def _representative_iv(contracts: list[dict[str, Any]], spot: float) -> float | None:
    """Return one consistent E*TRADE ATM IV observation for IV Rank history."""
    observed = [
        contract
        for contract in contracts
        if contract.get("iv_from_feed")
        and int(contract.get("dte", 0) or 0) > 0
        and float(contract.get("iv", 0.0) or 0.0) > 0
    ]
    if not observed or spot <= 0:
        return None

    dtes = sorted({int(contract["dte"]) for contract in observed})
    thirty_plus = [dte for dte in dtes if dte >= 30]
    target_dte = min(thirty_plus) if thirty_plus else max(dtes)
    target = [contract for contract in observed if int(contract["dte"]) == target_dte]
    if not target:
        return None

    nearest = min(abs(float(contract["strike"]) - spot) for contract in target)
    atm = [
        float(contract["iv"])
        for contract in target
        if abs(abs(float(contract["strike"]) - spot) - nearest) <= 1e-9
    ]
    return float(sum(atm) / len(atm)) if atm else None


