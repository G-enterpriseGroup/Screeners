def _normalize_ticker(value: Any) -> str:
    return _legacy._normalize_ticker(value)


def _clean_state(raw: Any) -> dict[str, Any]:
    """Preserve legacy state plus production GEX-only settings and IV history."""
    state = _legacy._clean_state(raw)
    # E*TRADE expirations are not limited to the legacy preset menu (e.g. 23D).
    # Preserve exact per-ticker snapped integers across vault/browser reloads.
    if isinstance(raw, dict) and isinstance(raw.get("dte_overrides"), dict):
        state["dte_overrides"] = {}
        for symbol, value in raw["dte_overrides"].items():
            ticker = _normalize_ticker(symbol)
            try:
                number = float(value)
            except (TypeError, ValueError):
                continue
            if ticker in state["tickers"] and not isinstance(value, bool) and math.isfinite(number) and number.is_integer() and 0 <= number <= 3650:
                state["dte_overrides"][ticker] = int(number)
    history_map: dict[str, list[dict[str, Any]]] = {}
    raw_method = (
        str(raw.get("iv_history_method") or "").strip()
        if isinstance(raw, dict)
        else ""
    )
    raw_history = raw.get("iv_history") if isinstance(raw, dict) else None
    if raw_method == IV_RANK_HISTORY_METHOD and isinstance(raw_history, dict):
        for raw_ticker, rows in raw_history.items():
            ticker = _normalize_ticker(raw_ticker)
            if not ticker or not isinstance(rows, list):
                continue
            by_day: dict[str, float] = {}
            for row in rows[-400:]:
                if not isinstance(row, dict):
                    continue
                day = str(row.get("date") or "")[:10]
                try:
                    date.fromisoformat(day)
                    iv = float(row.get("iv"))
                except (TypeError, ValueError):
                    continue
                if math.isfinite(iv) and 0.0 < iv < 5.0:
                    by_day[day] = iv
            cleaned = [
                {"date": day, "iv": by_day[day]}
                for day in sorted(by_day)[-370:]
            ]
            if cleaned:
                history_map[ticker] = cleaned
    state["iv_history"] = history_map
    state["iv_history_method"] = IV_RANK_HISTORY_METHOD

    raw_auto_refresh = (
        raw.get("auto_refresh_on_login", True)
        if isinstance(raw, dict)
        else True
    )
    if isinstance(raw_auto_refresh, bool):
        auto_refresh_on_login = raw_auto_refresh
    else:
        auto_refresh_on_login = str(raw_auto_refresh).strip().lower() in {
            "1",
            "true",
            "yes",
            "on",
        }
    state["auto_refresh_on_login"] = auto_refresh_on_login

    raw_master_source = (
        str(raw.get("master_a6_source") or "").strip().upper()
        if isinstance(raw, dict)
        else ""
    )
    state["master_a6_source"] = (
        raw_master_source if raw_master_source in {"CBOE", "ETRADE"} else "CBOE"
    )
    return state


def _load_state(vault_key: str) -> dict[str, Any]:
    """Legacy-compatible state load that retains ``iv_history``."""
    key = _legacy._state_key(vault_key)
    session = st.session_state.get("_gex_state")
    if isinstance(session, dict):
        state = _clean_state(session)
    else:
        state = _clean_state(_legacy._gex_state_vault().get(key, DEFAULT_STATE))
        st.session_state["_gex_state"] = copy.deepcopy(state)

    browser = _legacy._gex_state_component(
        storage_key="raj-terminal-" + key,
        server_state=state,
        key="raj_gex_state_v1",
        default=None,
    )
    if isinstance(browser, dict) and isinstance(browser.get("state"), dict):
        browser_state = _clean_state(browser["state"])
        if browser_state["revision"] > state["revision"] or (
            state["revision"] == 0
            and not state["tickers"]
            and browser_state["tickers"]
        ):
            state = browser_state
            st.session_state["_gex_state"] = copy.deepcopy(state)
            _legacy._gex_state_vault()[key] = copy.deepcopy(state)
            st.rerun()
    return state


def _save_state(vault_key: str, state: dict[str, Any]) -> dict[str, Any]:
    state = _clean_state(state)
    state["revision"] = int(state.get("revision", 0) or 0) + 1
    st.session_state["_gex_state"] = copy.deepcopy(state)
    _legacy._gex_state_vault()[_legacy._state_key(vault_key)] = copy.deepcopy(state)
    return state


