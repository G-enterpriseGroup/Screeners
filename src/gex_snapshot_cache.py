"""Browser backup of last successful GEX calculations, never broker credentials.

OWNERSHIP / EDITING NOTES
EDIT THIS FILE FOR: GEX-only snapshot hydration and persistent browser backups.
DO NOT EDIT THIS FILE FOR: GEX math, OAuth, orders, other features or shared CSS.
"""
from __future__ import annotations

import base64
import copy
import hashlib
import json
import os
import threading
import time
import zlib
from datetime import datetime
from pathlib import Path

import streamlit as st
import streamlit.components.v1 as components

from src import gex_ui
from src.gex_cboe import cboe_snapshot

# IndexedDB avoids localStorage's small quota for full multi-ticker snapshots.
# Only public aggregate calculations enter this zero-height transport.
_MEMORY = components.declare_component(
    "raj_gex_snapshot_memory_v1",
    path=str(Path(__file__).parent / "components" / "gex_snapshot_memory_v1"),
)
_MAX_BYTES = 128 * 1024 * 1024
_SERVER_CACHE_DIR = Path(__file__).resolve().parents[1] / '.gex_snapshot_cache'
_SERVER_CACHE_LOCK = threading.RLock()
_MEMORY_CSS = '<style>.st-key-gex_snapshot_reader,.st-key-gex_snapshot_writer{display:none!important}</style>'


def _unpack(state: dict) -> dict:
    if not isinstance(state, dict):
        return {}
    try:
        compressed = base64.b64decode(state.get("packed", ""), validate=True)
        decoder = zlib.decompressobj()
        raw = decoder.decompress(compressed, _MAX_BYTES + 1)
        if len(raw) > _MAX_BYTES or not decoder.eof:
            return {}
        if hashlib.sha256(raw).hexdigest() != state.get("digest"):
            return {}
        result = json.loads(raw)
        return result if isinstance(result, dict) else {}
    except (ValueError, TypeError, zlib.error):
        return {}


def _stamp(result: dict) -> float:
    try:
        return datetime.fromisoformat(str(result.get("snapshotFetchedAt") or result.get("updated"))).timestamp()
    except (ValueError, TypeError):
        return 0.0


def _restore(vault_key: str, saved: dict) -> None:
    cboe_backup = saved.get("cboe")
    cboe_backup = cboe_backup if isinstance(cboe_backup, dict) else {}
    for current, backup in (
        (cboe_snapshot(vault_key)["results"], cboe_backup.get("results")),
        (gex_ui._results(vault_key), saved.get("etrade")),
    ):
        if not isinstance(backup, dict):
            continue
        for ticker, result in backup.items():
            if isinstance(result, dict) and (ticker not in current or _stamp(result) > _stamp(current[ticker])):
                current[ticker] = copy.deepcopy(result)
    snapshot = cboe_snapshot(vault_key)
    if not snapshot.get("updated"):
        snapshot["updated"] = str(cboe_backup.get("updated") or "")
        failures = cboe_backup.get("failures")
        snapshot["failures"] = copy.deepcopy(failures) if isinstance(failures, dict) else {}


# ==============================
# READ BEFORE WRITE / NO TTL
# ==============================
def _token(vault_key: str) -> str:
    return hashlib.sha256(str(vault_key or "default").encode()).hexdigest()[:24]


def _server_snapshot_path(vault_key: str) -> Path:
    # Hash vault identity; never put authentication data in filenames or contents.
    return _SERVER_CACHE_DIR / (_token(vault_key) + ".json")


def _read_server_snapshot(vault_key: str) -> None:
    try:
        with _SERVER_CACHE_LOCK:
            path = _server_snapshot_path(vault_key)
            if not path.is_file() or path.stat().st_size > _MAX_BYTES:
                return
            saved = json.loads(path.read_text(encoding="utf-8"))
        _restore(vault_key, saved if isinstance(saved, dict) else {})
    except (OSError, ValueError, TypeError):
        return  # Browser backup remains available.


def _save_server_snapshot(vault_key: str) -> None:
    # Last-successful results are never cleared when a refresh fails.
    state = {"cboe": cboe_snapshot(vault_key), "etrade": gex_ui._results(vault_key)}
    with _SERVER_CACHE_LOCK:
        _SERVER_CACHE_DIR.mkdir(parents=True, exist_ok=True)
        path = _server_snapshot_path(vault_key)
        temp = path.with_suffix(".tmp")
        try:
            temp.write_text(json.dumps(state, allow_nan=False), encoding="utf-8")
            os.replace(temp, path)
        finally:
            temp.unlink(missing_ok=True)


def hydrate_gex_snapshots(vault_key: str) -> bool:
    token = _token(vault_key)
    ready_key = "_gex_snapshot_ready_" + token
    if not st.session_state.get('_gex_server_snapshot_loaded_' + token):
        _read_server_snapshot(vault_key)
        st.session_state['_gex_server_snapshot_loaded_' + token] = True
    if st.session_state.get(ready_key):
        return True
    with st.container(key="gex_snapshot_reader", gap=None):
        # Keep style output in this hidden body container. Streamlit's shared
        # st.html event container can overwrite later root styles on fragment reruns.
        st.markdown(_MEMORY_CSS, unsafe_allow_html=True)
        browser = _MEMORY(
            storage_key="raj-terminal-gex-snapshots-v1:" + token,
            mode="read", hydrated=False, server_state={}, height=0,
            key="gex_snapshot_read_" + token, default=None,
        )
    if not isinstance(browser, dict) or browser.get("source") not in {"browser", "empty"}:
        return False
    saved = browser.get("state")
    saved = saved if isinstance(saved, dict) else {}
    _restore(vault_key, _unpack(saved) or _unpack(saved.get("previous") or {}))
    st.session_state[ready_key] = True
    return True


def persist_gex_snapshots(vault_key: str) -> None:
    token = _token(vault_key)
    _save_server_snapshot(vault_key)
    if not st.session_state.get("_gex_snapshot_ready_" + token):
        return
    raw = json.dumps({"cboe": cboe_snapshot(vault_key), "etrade": gex_ui._results(vault_key)},
                     sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    digest = hashlib.sha256(raw).hexdigest()
    state_key = "_gex_snapshot_envelope_" + token
    envelope = st.session_state.get(state_key) or {}
    if envelope.get("digest") != digest:
        envelope = {
            "revision": int(time.time() * 1_000_000), "digest": digest,
            "packed": base64.b64encode(zlib.compress(raw)).decode("ascii"),
        }
        st.session_state[state_key] = envelope
    # CSS must be emitted every render, including fragment-only reruns.
    with st.container(key="gex_snapshot_writer", gap=None):
        st.markdown(_MEMORY_CSS, unsafe_allow_html=True)
        status = _MEMORY(storage_key="raj-terminal-gex-snapshots-v1:" + token,
                         mode="write", hydrated=True, server_state=envelope, height=0,
                         key="gex_snapshot_write_" + token, default=None)
    if isinstance(status, dict) and status.get("saved") is False and status.get("digest") == digest:
        st.warning("GEX snapshot could not be saved in this browser. Allow site storage to keep GEX after a restart.")
