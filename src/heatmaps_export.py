from __future__ import annotations

import io
import math

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from reportlab.pdfgen import canvas
from reportlab.lib.colors import HexColor


def _cells(years, rows, fed, winner, label_func, shade_func):
    values = [abs(float(x)) for _, line in rows for x in line
              if x is not None and math.isfinite(float(x))]
    scale = max(3.0, float(np.percentile(values, 85))) if values else 10.0
    table = [("FED TARGET / MOVES", [(v, {"up": "#4e3516", "down": "#173d35",
        "flat": "#242424"}.get(d, "#242424"), "#ffffff") for v, _, d in fed], None)]
    for ticker, line in rows:
        vals = []
        for value in line:
            bg, fg = shade_func(value, scale)
            vals.append((f"{value:+.1f}%" if value is not None and math.isfinite(float(value))
                         else "-", bg, fg))
        table.append((label_func(ticker), vals, ticker))
    return table


def export_annual_heatmap(years, rows, fed, winner, label_func, shade_func, *, as_pdf=True):
    """Render ALL year columns, selectable vector PDF or 2x raster PNG."""
    table = _cells(years, rows, fed, winner, label_func, shade_func)
    left, cw, right, height, top = 260, 88, 96, 38, 98
    w = left + cw * len(years) + right
    h = top + height * (len(table) + 1) + 36
    scale = 1 if as_pdf else 2
    if as_pdf:
        output = io.BytesIO()
        page = canvas.Canvas(output, pagesize=(w, h), pageCompression=1)
        page.setTitle("Raj Terminal - Annual Sector Heatmap")
        def rectangle(x, y, ww, hh, color):
            page.setFillColor(HexColor(color))
            page.rect(x, h-y-hh, ww-1, hh-1, stroke=0, fill=1)
        def text(x, y, value, *, color="#ffffff", font=11, bold=False):
            page.setFillColor(HexColor(color))
            page.setFont("Courier-Bold" if bold else "Courier", font)
            page.drawString(x, h-y-font, str(value))
    else:
        img = Image.new("RGB", (w*scale, h*scale), "#080808")
        draw = ImageDraw.Draw(img)
        try:
            regular = ImageFont.truetype("DejaVuSansMono.ttf", 11*scale)
            heavy = ImageFont.truetype("DejaVuSansMono-Bold.ttf", 11*scale)
            title_font = ImageFont.truetype("DejaVuSansMono-Bold.ttf", 15*scale)
        except OSError:
            regular = heavy = title_font = ImageFont.load_default()
        def rectangle(x, y, ww, hh, color):
            draw.rectangle((x*scale, y*scale, (x+ww-1)*scale,
                            (y+hh-1)*scale), fill=color)
        def text(x, y, value, *, color="#ffffff", font=11, bold=False):
            draw.text((x*scale, y*scale), str(value), fill=color,
                      font=title_font if font >= 15 else heavy if bold else regular)

    text(10, 12, "RAJ TERMINAL // ANNUAL SECTOR HEATMAP",
         color="#ff9d32", font=15, bold=True)
    text(10, 40, "SECTOR RETURNS + SPY / QQQ BENCHMARKS + FED POLICY",
         color="#aab0b7", font=11)
    text(10, 57, "Adjusted-close performance; latest year may be incomplete.",
         color="#aab0b7", font=11)
    y = top
    rectangle(0, y, left, height, "#171717")
    text(9, y+12, "SECTOR / TICKER", color="#ff9d32", bold=True)
    for i, year in enumerate(years):
        x = left + i*cw
        rectangle(x, y, cw, height, "#171717")
        text(x+22, y+12, str(year), color="#ff9d32", bold=True)
    end_x = left + len(years)*cw
    rectangle(end_x, y, right, height, "#171717")
    text(end_x+21, y+12, "R / G", color="#ff9d32", bold=True)
    for row_no, (name, values, ticker) in enumerate(table):
        y = top + (row_no+1)*height
        is_benchmark = ticker in ("SPY", "QQQ", "SPY+QQQ 50/50")
        background = "#ffe100" if ticker == winner else "#26212f" if is_benchmark else "#181818"
        fg = "#000000" if ticker == winner else "#c6b7ff" if is_benchmark else "#ff9d32"
        rectangle(0, y, left, height, background)
        shown = name if len(name) <= 33 else name[:30]+"..."
        text(8, y+13, shown, color=fg, bold=True)
        for i, (value, bg, fg) in enumerate(values):
            x = left+i*cw
            rectangle(x, y, cw, height, bg)
            if row_no == 0 and " " in value:
                parts = value.replace("↑", "UP").replace("↓", "DN").rsplit(" ", 1)
                text(x+8, y+5, parts[0], font=10, bold=True)
                text(x+15, y+21, parts[1], font=10, bold=True)
            else:
                text(x+10, y+13, value, color=fg, bold=True)
        rectangle(end_x, y, right, height, "#151515")
        if row_no:
            original = rows[row_no-1][1]
            red = sum(v is not None and math.isfinite(float(v)) and v < 0 for v in original)
            green = sum(v is not None and math.isfinite(float(v)) and v > 0 for v in original)
            text(end_x+10, y+13, f"R {red} G {green}", bold=True)
    text(10, h-23, "Source: Yahoo Finance adjusted-close prices; Fed target data: FRED.",
         color="#aab0b7", font=10)
    if as_pdf:
        page.showPage()
        page.save()
    else:
        img.save(output := io.BytesIO(), format="PNG", optimize=True)
    return output.getvalue()
