from __future__ import annotations

from datetime import date
from typing import Any, Iterable

import pandas as pd


CONTRACT_SIZE = 100


def validate_share_quantity(shares: int) -> int:
    """Require whole 100-share lots so each share is covered by one listed put."""
    try:
        value = int(shares)
    except (TypeError, ValueError) as exc:
        raise ValueError("Shares must be a whole number.") from exc
    if value < CONTRACT_SIZE or value % CONTRACT_SIZE != 0:
        raise ValueError(
            "Protective Puts requires shares in 100-share lots (100, 200, 300, ...)."
        )
    return value


def protective_put_metrics(
    *,
    stock_price: float,
    strike: float,
    premium_per_share: float,
    shares: int,
) -> dict[str, float | int]:
    """Return fully hedged protective-put economics for one premium reference."""
    protected_shares = validate_share_quantity(shares)
    stock_price = float(stock_price)
    strike = float(strike)
    premium_per_share = float(premium_per_share)
    if stock_price <= 0 or strike <= 0:
        raise ValueError("Stock price and strike must be greater than zero.")
    if premium_per_share < 0:
        raise ValueError("Put premium cannot be negative.")

    contracts = protected_shares // CONTRACT_SIZE
    stock_cost = stock_price * protected_shares
    put_cost = premium_per_share * CONTRACT_SIZE * contracts
    floor_value = strike * protected_shares
    max_loss = max(0.0, stock_cost + put_cost - floor_value)
    max_loss_per_share = max_loss / protected_shares
    max_loss_pct = (max_loss / stock_cost * 100.0) if stock_cost else 0.0
    breakeven = stock_price + (put_cost / protected_shares)

    return {
        "contracts": contracts,
        "stock_cost": stock_cost,
        "put_cost": put_cost,
        "floor_value": floor_value,
        "max_loss": max_loss,
        "max_loss_per_share": max_loss_per_share,
        "max_loss_pct": max_loss_pct,
        "breakeven": breakeven,
    }


def build_put_analysis(
    rows: Iterable[dict[str, Any]],
    *,
    expiry: date,
    stock_price: float,
    shares: int,
    today: date,
) -> pd.DataFrame:
    """Convert normalized E*TRADE puts into the legacy married-put analytics."""
    protected_shares = validate_share_quantity(shares)
    records: list[dict[str, Any]] = []
    dte = max(0, (expiry - today).days)

    for row in rows:
        if str(row.get("call_put") or "").upper() != "PUT":
            continue
        try:
            strike = float(row.get("strike"))
        except (TypeError, ValueError):
            continue

        def metrics_for(value: Any):
            try:
                premium = float(value)
            except (TypeError, ValueError):
                return None
            if premium < 0:
                return None
            return protective_put_metrics(
                stock_price=stock_price,
                strike=strike,
                premium_per_share=premium,
                shares=protected_shares,
            )

        ask_metrics = metrics_for(row.get("ask"))
        last_metrics = metrics_for(row.get("last"))
        records.append(
            {
                "Expiration": expiry.strftime("%m-%d-%y"),
                "DTE": dte,
                "Contract": str(row.get("osi") or ""),
                "Strike": strike,
                "Bid": row.get("bid"),
                "Ask": row.get("ask"),
                "Last": row.get("last"),
                "Volume": row.get("volume"),
                "Open Interest": row.get("open_interest"),
                "Contracts": protected_shares // CONTRACT_SIZE,
                "Put Cost (Ask)": None if ask_metrics is None else ask_metrics["put_cost"],
                "Max Loss (Ask)": None if ask_metrics is None else ask_metrics["max_loss"],
                "Max Loss % (Ask)": None if ask_metrics is None else ask_metrics["max_loss_pct"],
                "Breakeven (Ask)": None if ask_metrics is None else ask_metrics["breakeven"],
                "Put Cost (Last)": None if last_metrics is None else last_metrics["put_cost"],
                "Max Loss (Last)": None if last_metrics is None else last_metrics["max_loss"],
                "Max Loss % (Last)": None if last_metrics is None else last_metrics["max_loss_pct"],
                "Breakeven (Last)": None if last_metrics is None else last_metrics["breakeven"],
            }
        )

    if not records:
        return pd.DataFrame()
    return pd.DataFrame.from_records(records).sort_values(["Strike"]).reset_index(drop=True)


# ==============================
# LOWEST-COST NEAR-ZERO DIRECT MARRIED PUTS BY EXPIRATION
# ==============================
def cheapest_near_zero_put_by_expiration(
    frame: pd.DataFrame, *, target_dte: int,
) -> pd.DataFrame:
    """Select one honest, ASK-funded stock+put floor per listed expiration.

    Prefer the lowest premium of zero-loss-floor puts. If zero cannot be
    reached, select the contract with the smallest *actual* maximum loss,
    then lowest premium. Highlight the expiration nearest the chosen horizon.
    This is a direct matched-underlying married put, NOT an ETF proxy hedge.
    """
    columns = (
        "Expiration", "DTE", "Strike", "Ask", "Contracts",
        "Put Cost (Ask)", "Max Loss (Ask)", "Max Loss % (Ask)",
        "Breakeven (Ask)", "Contract", "Target Met", "Status",
        "Priority Expiration",
    )
    if frame.empty:
        return pd.DataFrame(columns=columns)
    if int(target_dte) < 0:
        raise ValueError("Target expiration days must be nonnegative.")
    data = frame.copy()
    for col in ("DTE", "Strike", "Ask", "Put Cost (Ask)",
                "Max Loss (Ask)", "Max Loss % (Ask)"):
        data[col] = pd.to_numeric(data[col], errors="coerce")
    # A zero/negative ASK or NaN/inf is not an executable purchase quote.
    data = data.replace([float("inf"), float("-inf")], float("nan"))
    data = data.dropna(subset=[
        "DTE", "Strike", "Ask", "Put Cost (Ask)", "Max Loss (Ask)",
    ])
    data = data[
        data["Ask"].gt(0) & data["Strike"].gt(0)
        & data["Put Cost (Ask)"].ge(0) & data["Max Loss (Ask)"].ge(0)
    ]
    if data.empty:
        return pd.DataFrame(columns=columns)
    data["Target Met"] = data["Max Loss (Ask)"].le(0.005)
    data["_priority"] = ~data["Target Met"]
    data = data.sort_values(
        ["Expiration", "_priority", "Max Loss (Ask)", "Put Cost (Ask)", "Strike"],
        kind="stable",
    )
    zero = data.loc[data["Target Met"]].sort_values(
        ["Expiration", "Put Cost (Ask)", "Strike"], kind="stable",
    ).drop_duplicates("Expiration")
    fallback = data.loc[~data["Target Met"]].drop_duplicates("Expiration")
    best = pd.concat([zero, fallback], ignore_index=True)
    best = best.sort_values(
        ["Expiration", "_priority", "Max Loss (Ask)", "Put Cost (Ask)"],
        kind="stable",
    ).drop_duplicates("Expiration").drop(columns=["_priority"])
    best["Status"] = best["Target Met"].map({
        True: "ZERO-LOSS FLOOR", False: "MINIMUM AVAILABLE LOSS",
    })
    best["Priority Expiration"] = False
    ordered = best.sort_values(
        ["DTE", "Put Cost (Ask)", "Expiration"], kind="stable",
    ).reset_index(drop=True)
    chosen = ordered.assign(
        _gap=(ordered["DTE"] - int(target_dte)).abs()
    ).sort_values(
        ["_gap", "Put Cost (Ask)", "DTE"], kind="stable",
    ).index[0]
    ordered.loc[chosen, "Priority Expiration"] = True
    return ordered[[col for col in columns if col in ordered.columns]].copy()


# ==============================
# PORTFOLIO ETF-PUT HEDGE SCENARIO MATH
# ==============================
def portfolio_hedge_candidates(
    rows: Iterable[dict[str, Any]], *, symbol: str, expiry: date,
    spot: float, exposure: float, stress_pct: float, beta: float,
    target_loss_pct: float, premium_limit_pct: float, today: date,
) -> pd.DataFrame:
    """Find put quantities meeting modeled stress loss; not guaranteed max loss."""
    import math

    values = (spot, exposure, stress_pct, beta, target_loss_pct, premium_limit_pct)
    if any(not math.isfinite(float(value)) for value in values):
        raise ValueError("Portfolio hedge inputs must be finite")
    if spot <= 0 or exposure <= 0 or not 0 < stress_pct < 100 or beta <= 0:
        raise ValueError("Invalid price, exposure, stress scenario or beta")
    if not 0 <= target_loss_pct < 100 or not 0 < premium_limit_pct <= 100:
        raise ValueError("Invalid target remaining loss or premium budget")

    portfolio_loss = min(exposure, exposure * beta * stress_pct / 100)
    allowed_loss = exposure * target_loss_pct / 100
    required_cover = portfolio_loss - allowed_loss
    if required_cover <= 0:
        return pd.DataFrame()
    stressed_spot = spot * (1 - stress_pct / 100)
    records: list[dict[str, Any]] = []

    for row in rows:
        if str(row.get("call_put") or "").upper() != "PUT":
            continue
        try:
            strike, ask = float(row.get("strike")), float(row.get("ask"))
        except (ValueError, TypeError):
            continue
        if not all(math.isfinite(v) for v in (strike, ask)) or strike <= 0 or ask <= 0:
            continue
        intrinsic = max(0.0, strike - stressed_spot) * CONTRACT_SIZE
        cost_each = ask * CONTRACT_SIZE
        net_cover_each = intrinsic - cost_each
        if net_cover_each <= 0:
            continue
        contracts = max(1, math.ceil(required_cover / net_cover_each - 1e-10))
        if contracts > 10000:
            continue
        premium = contracts * cost_each
        if premium > exposure * premium_limit_pct / 100 + 1e-8:
            continue
        payoff = contracts * intrinsic
        net_pnl = payoff - portfolio_loss - premium
        remaining_loss = max(0.0, -net_pnl)
        if remaining_loss > allowed_loss + 1e-6:
            continue
        records.append({
            "Proxy": symbol, "Expiration": expiry.strftime("%m-%d-%y"),
            "DTE": max(0, (expiry - today).days), "Strike": strike,
            "Spot": spot, "Ask": ask, "Contracts": contracts,
            "Put Cost": premium, "Cost %": premium / exposure * 100,
            "Stress Put Payout": payoff, "Stress Net P&L": net_pnl,
            "Stress Remaining Loss": remaining_loss,
            "Stress Loss %": remaining_loss / exposure * 100,
            "Volume": row.get("volume"), "Open Interest": row.get("open_interest"),
            "Contract": str(row.get("osi") or ""),
            "Implied Volatility": row.get("implied_volatility"),
            "Cost of Put (Ask)": direct_cost_ask,
            "Max Loss (Ask)": direct_loss_ask,
            "Max Loss Calc (Ask)": (
                f"max(0, ({spot:.2f} + {ask:.2f} - {strike:.2f}) × 100)"
            ),
            "Cost of Put (Last)": direct_cost_last,
            "Max Loss (Last)": direct_loss_last,
            "Max Loss Calc (Last)": (
                "" if last_quote is None else
                f"max(0, ({spot:.2f} + {last_quote:.2f} - {strike:.2f}) × 100)"
            ),
        })
    return pd.DataFrame.from_records(records)


# ==============================
# COMPLETE PROXY PUT CHAIN / SCENARIO RANKING
# ==============================
def portfolio_chain_scenario(
    rows: Iterable[dict[str, Any]], *, symbol: str, expiry: date,
    spot: float, exposure: float, stress_pct: float,
    beta: float, today: date, max_contracts: int = 250,
) -> pd.DataFrame:
    """Keep every valid ASK put, even if no contract can achieve a $0 scenario.

    Index puts do not give a portfolio loss floor. We rank only the modeled
    expiration-date stress result, including each put's entire purchase cost.
    A net-negative hedge is retained as a lower-ranked visible chain quote.
    """
    import math
    if not all(math.isfinite(float(v)) for v in (spot, exposure, stress_pct, beta)):
        raise ValueError("Scenario inputs must be finite")
    if spot <= 0 or exposure <= 0 or not 0 < stress_pct < 100 or beta <= 0:
        raise ValueError("Invalid portfolio scenario")
    if not 1 <= max_contracts <= 10000:
        raise ValueError("Invalid order-quantity safety bound")
    portfolio_loss = min(exposure, exposure * stress_pct * beta / 100)
    stressed_spot = spot * (1.0 - stress_pct / 100)
    records = []
    for row in rows:
        if str(row.get("call_put") or "").upper() != "PUT":
            continue
        try:
            strike, ask = float(row.get("strike")), float(row.get("ask"))
        except (ValueError, TypeError):
            continue
        if not all(math.isfinite(x) for x in (strike, ask)) or strike <= 0 or ask <= 0:
            continue
        payoff_each = max(0.0, strike - stressed_spot) * CONTRACT_SIZE
        premium_each = ask * CONTRACT_SIZE
        net_cover_each = payoff_each - premium_each
        if net_cover_each > 0:
            contracts = max(1, math.ceil(portfolio_loss / net_cover_each - 1e-10))
        else:
            contracts = 1
        # Display unachievable hedge quantities honestly; do not silently
        # cap requested hedges and show "fully protected".
        orderable = contracts <= max_contracts
        if not orderable:
            contracts = max_contracts
        # Ghotra Married Put columns: explicitly a *100-share example in
        # this proxy ETF*, never the guaranteed loss of unrelated holdings.
        # ASK is the purchase-side estimate; LAST is informational only.
        direct_cost_ask = ask * CONTRACT_SIZE
        direct_loss_ask = max(0.0, (spot + ask - strike) * CONTRACT_SIZE)
        try:
            last_quote = float(row.get("last"))
            if not math.isfinite(last_quote) or last_quote < 0:
                last_quote = None
        except (TypeError, ValueError):
            last_quote = None
        direct_cost_last = None if last_quote is None else last_quote * CONTRACT_SIZE
        direct_loss_last = (
            None if last_quote is None
            else max(0.0, (spot + last_quote - strike) * CONTRACT_SIZE)
        )
        total_premium = premium_each * contracts
        payoff = payoff_each * contracts
        remaining = max(0.0, portfolio_loss + total_premium - payoff)
        records.append({
            "Proxy": symbol, "Expiration": expiry.strftime("%m-%d-%y"),
            "DTE": max(0, (expiry-today).days), "Strike": strike,
            "Ask": ask, "Bid": row.get("bid"), "Last": row.get("last"),
            "Volume": row.get("volume"), "Open Interest": row.get("open_interest"),
            "Contracts": contracts, "Put Cost": total_premium,
            "Cost %": 100 * total_premium / exposure,
            "Stress Put Payout": payoff, "Stress Remaining Loss": remaining,
            "Stress Loss %": 100 * remaining / exposure,
            "Near Zero Scenario": remaining <= .005, "Orderable": orderable,
            "Contract": str(row.get("osi") or ""),
        })
    return pd.DataFrame.from_records(records)


def rank_portfolio_chain(
    frame: pd.DataFrame, *, preferred_dte: int = 60,
    direct_100_share_example: bool = False,
) -> pd.DataFrame:
    """Closest modeled stress loss first, then premium; mark cheapest per expiry."""
    if frame.empty:
        return frame.copy()
    ranked = frame.copy()
    ranked["DTE Gap"] = (ranked["DTE"] - preferred_dte).abs()
    sort_columns = (
        ["Max Loss (Ask)", "Cost of Put (Ask)", "DTE Gap", "Proxy", "Expiration", "Strike"]
        if direct_100_share_example
        else ["Stress Remaining Loss", "Put Cost", "DTE Gap", "Proxy", "Expiration", "Strike"]
    )
    ranked = ranked.sort_values(
        sort_columns, kind="stable", na_position="last",
    ).reset_index(drop=True)
    ranked["Best / Expiration"] = ~ranked.duplicated(["Proxy", "Expiration"])
    ranked["Priority"] = False
    ranked.loc[0, "Priority"] = True
    return ranked


