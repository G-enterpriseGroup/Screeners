def _render_tradingview_pine_compatible(
    state: dict[str, Any],
    result_map: dict[str, Any],
    failures: dict[str, str] | None = None,
) -> None:
    """Emit full metadata + packed gamma rows for every TradingView ticker block."""
    saved: list[str] = []
    for value in state.get("tickers", []):
        ticker = _core._normalize_ticker(value)
        if ticker and ticker not in saved:
            saved.append(ticker)
    if not saved:
        st.info("Add GEX tickers first.")
        return

    normalized_failures = {
        _core._normalize_ticker(key): str(value)
        for key, value in (failures or {}).items()
        if _core._normalize_ticker(key)
    }
    available = [
        ticker for ticker in saved
        if ticker in result_map and ticker not in normalized_failures
    ]
    if not available:
        st.info("Refresh GEX first. The TradingView bridge is built from refreshed ticker results.")
        return

    master_label = "MASTER A6 // FULL TICKER BLOCKS — COPY THIS"
    compact_label = "COMPACT PINE // OPTIONAL DIAGNOSTIC"
    choice = st.selectbox(
        "PACKED GAMMA BLOCK",
        [master_label, compact_label] + available,
        key="gexv3_bridge_choice_full_ticker_v5",
    )
    is_master = choice == master_label
    is_compact = choice == compact_label

    if is_master:
        parser_text = _proven._google_sheets_master_text(
            result_map, saved, normalized_failures
        ).strip()
        filename = "raj_terminal_MASTER_A6_TRADINGVIEW_FULL.txt"
        expected_headers = saved
        parser_expected = available
        mode_text = "FULL TICKER METADATA + PACKED GAMMA LEVELS"
    elif is_compact:
        parser_text = _proven._pine_master_bridge_text(result_map, available).strip()
        filename = "raj_terminal_MASTER_A6_COMPACT_DIAGNOSTIC.txt"
        expected_headers = available
        parser_expected = available
        mode_text = "COMPACT TICKER + PACKED ROWS // OPTIONAL"
    else:
        parser_text = _proven._base._google_sheets_summary_text(result_map[choice]).strip()
        filename = f"{choice}_gex_tradingview_full.txt"
        expected_headers = [choice]
        parser_expected = [choice]
        mode_text = f"{choice} // FULL TICKER METADATA + PACKED GAMMA LEVELS"

    # Exactly one pair of outer quotes around the complete multiline paste.
    text = f'"{parser_text}"'
    byte_count = len(text.encode("utf-8"))
    headers = _proven._pine_router_headers(parser_text)
    missing_headers = [ticker for ticker in expected_headers if ticker not in headers]
    pine_issues, parsed_counts = _proven._pine_master_issues(parser_text, parser_expected)
    too_large = byte_count > _proven._PINE_TEXT_LIMIT
    quoted_ok = text.startswith('"') and text.endswith('"')
    transport_ok = not missing_headers and not pine_issues and not too_large and quoted_ok

    st.caption(
        "TRADINGVIEW BRIDGE // " + mode_text
        + f" // {len(headers)}/{len(expected_headers)} HEADERS // "
        + f"{byte_count:,}/{_proven._PINE_TEXT_LIMIT:,} CHARS"
    )

    if transport_ok:
        min_rows = min(parsed_counts.values()) if parsed_counts else 0
        max_rows = max(parsed_counts.values()) if parsed_counts else 0
        if is_master and normalized_failures:
            st.warning(
                f"TRADINGVIEW MASTER READY // {len(available)} DATA BLOCKS // "
                f"{len(normalized_failures)} ERROR BLOCKS // {min_rows}-{max_rows} DRAWABLE ROWS PER SUCCESSFUL TICKER"
            )
        elif is_master:
            st.success(
                f"TRADINGVIEW MASTER CHECK PASS // {len(available)}/{len(saved)} TICKERS // "
                f"{min_rows}-{max_rows} DRAWABLE PACKED ROWS EACH"
            )
        elif is_compact:
            st.success(f"COMPACT DIAGNOSTIC CHECK PASS // {len(available)} TICKERS")
        else:
            st.success(
                f"{choice} // PINE ROUTER CHECK PASS // "
                f"{parsed_counts.get(choice, 0)} DRAWABLE PACKED ROWS"
            )
    else:
        details = list(missing_headers) + list(pine_issues)
        if too_large:
            details.append("TEXT_LIMIT")
        if not quoted_ok:
            details.append("MISSING_OUTER_DOUBLE_QUOTES")
        st.error("PINE ROUTER CHECK FAILED // " + ", ".join(details[:16]))

    verify_ticker = st.selectbox(
        "PINE CHART TICKER CHECK",
        available,
        key="gexv3_pine_chart_ticker_check_full_v5",
        help="Pick the same symbol as the TradingView chart. This validates the exact full block you should paste.",
    )
    target_issues, target_count = _proven._pine_ticker_issues(parser_text, verify_ticker)
    if target_issues:
        st.error(f"{verify_ticker} // PINE TARGET FAIL // " + ", ".join(target_issues))
    else:
        st.success(f"{verify_ticker} // PINE TARGET PASS // {target_count} DRAWABLE PACKED ROWS")

    if is_master:
        st.markdown(
            '**COPY FOR TRADINGVIEW includes for EVERY successful ticker: `Ticker`, `Mode`, `Spot`, `Max DTE Used`, `Contracts Used`, `Net Current GEX`, `Source URL`, then the gamma levels. One opening and one closing `"` are already included around the entire payload.**'
        )
    elif is_compact:
        st.markdown('**OPTIONAL DIAGNOSTIC ONLY // outer `"` characters are included.**')
    else:
        st.markdown(
            f'**{choice} FULL BLOCK // metadata first, gamma levels second. Outer `"` characters are included.**'
        )

    st.html(_proven._TRADINGVIEW_CODE_CSS)
    st.html(_TRADINGVIEW_COPY_BUTTON_CSS)
    with st.container(key="gexv3_bridge_code"):
        st.code(text or "", language=None, wrap_lines=False)
    st.download_button(
        "DOWNLOAD MASTER A6" if is_master else "DOWNLOAD PACKED GAMMA BLOCK",
        data=text,
        file_name=filename,
        mime="text/plain",
        width="stretch",
        disabled=not bool(text.strip()),
        key="gexv3_download_bridge",
    )


# ==============================
# LIVE BACKGROUND REFRESH STATUS
# ==============================
# Poll only while Refresh All is QUEUED/RUNNING. The background worker remains
# detached from Streamlit; this fragment only reads the thread-safe job registry
# on the UI thread. When another ticker finishes, request a normal app rerun so
# the newly synced GEX row appears immediately without a browser refresh/login.
_GEX_LIVE_STATUS_POLL_SECONDS = 1.0
_GEX_LIVE_STATUS_SESSION_KEY = "_gexv3_live_background_snapshot"
_GEX_AUTO_REFRESH_WIDGET_KEY = "gexv3_auto_refresh_on_login"
_GEX_AUTO_REFRESH_REVISION_KEY = "_gexv3_auto_refresh_widget_revision"
_GEX_AUTO_LOGIN_MARKER_KEY = "_gexv3_auto_refresh_login_marker"
_ORIGINAL_RENDER_BACKGROUND_STATUS = _proven._render_background_status


def _background_status_snapshot(job: dict[str, Any] | None) -> tuple[Any, ...] | None:
    """Return only fields whose UI changes should trigger a full GEX rerender."""
    if not job:
        return None
    return (
        str(job.get("status") or ""),
        int(job.get("completed", 0) or 0),
        int(job.get("total", 0) or 0),
        int(job.get("updated", 0) or 0),
        str(job.get("current") or ""),
        len(dict(job.get("failures") or {})),
    )


@st.fragment(run_every=_GEX_LIVE_STATUS_POLL_SECONDS)
def _render_live_background_status_fragment(vault_key: str) -> None:
    """Refresh visible GEX job progress and promote completed rows into the app."""
    _ORIGINAL_RENDER_BACKGROUND_STATUS(vault_key)
    job = _proven._background_job(vault_key)
    snapshot = _background_status_snapshot(job)
    if snapshot is None:
        st.session_state.pop(_GEX_LIVE_STATUS_SESSION_KEY, None)
        return

    total = max(0, int(job.get("total", 0) or 0))
    completed = max(0, int(job.get("completed", 0) or 0))
    updated = max(0, int(job.get("updated", 0) or 0))
    progress = min(1.0, completed / total) if total else 0.0
    percent = int(round(progress * 100.0))
    current = str(job.get("current") or "").strip()
    active_symbols = [value.strip() for value in current.split(",") if value.strip()]
    if len(active_symbols) > 3:
        current = ", ".join(active_symbols[:3]) + f" +{len(active_symbols) - 3}"
    active_text = f" // ACTIVE {current}" if current else ""
    st.progress(
        progress,
        text=(
            f"GEX LOADING // {completed}/{total} PROCESSED // "
            f"{updated} UPDATED // {percent}%{active_text}"
        ),
    )

    previous = st.session_state.get(_GEX_LIVE_STATUS_SESSION_KEY)
    st.session_state[_GEX_LIVE_STATUS_SESSION_KEY] = snapshot
    if previous is None:
        return

    previous = tuple(previous)
    status = str(snapshot[0])
    progress_changed = (
        snapshot[1] != previous[1]
        or snapshot[2] != previous[2]
        or snapshot[3] != previous[3]
    )
    terminal_status_changed = (
        snapshot[0] != previous[0]
        and status not in {"QUEUED", "RUNNING"}
    )

    if progress_changed or terminal_status_changed:
        # Default st.rerun() scope is the full app. That is intentional here:
        # completed worker results were just synced into the normal GEX result
        # vault and the Overview/Analytics/TradingView panes should see them now.
        st.rerun()


def _render_background_status_live(vault_key: str) -> None:
    """Use 1-second native polling only for an active background GEX job."""
    job = _proven._background_job(vault_key)
    status = str((job or {}).get("status") or "")
    if status in {"QUEUED", "RUNNING"}:
        _render_live_background_status_fragment(vault_key)
        return

    st.session_state.pop(_GEX_LIVE_STATUS_SESSION_KEY, None)
    _ORIGINAL_RENDER_BACKGROUND_STATUS(vault_key)


# ==============================
# SAVED LOGIN AUTO-REFRESH SETTING
# ==============================
def _render_auto_refresh_setting(
    vault_key: str,
    state: dict[str, Any],
) -> dict[str, Any]:
    """Render and persist the GEX auto-refresh-on-login toggle."""
    st.markdown("**LOGIN REFRESH**")
    revision = int(state.get("revision", 0) or 0)
    synced_revision = st.session_state.get(_GEX_AUTO_REFRESH_REVISION_KEY)
    if synced_revision != revision:
        st.session_state[_GEX_AUTO_REFRESH_WIDGET_KEY] = bool(
            state.get("auto_refresh_on_login", True)
        )
        st.session_state[_GEX_AUTO_REFRESH_REVISION_KEY] = revision

    enabled = st.toggle(
        "AUTO REFRESH ALL GEX ON E*TRADE LOGIN",
        key=_GEX_AUTO_REFRESH_WIDGET_KEY,
        help=(
            "When enabled, Raj's Terminal starts one background Refresh All after "
            "an authenticated E*TRADE login, even if another top-level tab is active."
        ),
    )
    saved = bool(state.get("auto_refresh_on_login", True))
    if enabled != saved:
        state["auto_refresh_on_login"] = bool(enabled)
        state = _core._save_state(vault_key, state)
        st.session_state[_GEX_AUTO_REFRESH_REVISION_KEY] = int(
            state.get("revision", 0) or 0
        )
        st.toast(
            "GEX AUTO REFRESH ON LOGIN // "
            + ("ON" if enabled else "OFF")
            + " // SAVED"
        )
        st.rerun()

    st.caption(
        "SAVED ACROSS SESSIONS // "
        + ("ON // one Refresh All starts after login" if enabled else "OFF // manual refresh only")
    )
    st.divider()
    return state


def _maybe_start_login_auto_refresh(
    vault_key: str,
    state: dict[str, Any],
    live_client: Any,
    background_client_factory: Callable[[], Any] | None,
    login_marker: str,
    touch_session: Any,
    *,
    rerun_on_start: bool = True,
) -> bool:
    """Start exactly one automatic Refresh All for the current authenticated login."""
    if not bool(state.get("auto_refresh_on_login", True)):
        return False
    if live_client is None:
        return False
    if not login_marker or background_client_factory is None:
        return False
    if not state.get("tickers"):
        return False

    marker_key = f"{_GEX_AUTO_LOGIN_MARKER_KEY}:{str(vault_key or 'default')[:32]}"
    if st.session_state.get(marker_key) == login_marker:
        return False

    job = _proven._background_job(vault_key)
    if job and str(job.get("status") or "") in {"QUEUED", "RUNNING"}:
        # A manual Refresh All started first; treat it as satisfying this login.
        st.session_state[marker_key] = login_marker
        return False

    started = _proven._start_background_refresh(
        vault_key,
        copy.deepcopy(state),
        background_client_factory,
    )
    if not started:
        return False

    st.session_state[marker_key] = login_marker
    if callable(touch_session):
        try:
            touch_session()
        except Exception:
            pass
    st.toast("GEX AUTO REFRESH STARTED // E*TRADE LOGIN DETECTED")
    if rerun_on_start:
        st.rerun()
    return True


def maybe_auto_refresh_on_login(
    client: Any,
    vault_key: str,
    touch_session: Any,
    *,
    background_client_factory: Callable[[], Any] | None = None,
    login_marker: str = "",
) -> bool:
    """Start saved GEX auto-refresh from a non-GEX top-level tab after login.

    The existing GEX state component is zero-height, so loading the browser-saved
    setting here does not reserve page space. The normal GEX renderer owns this
    path when GEX itself is the active top-level tab, avoiding duplicate component
    keys in one Streamlit run.
    """
    vault_key = str(vault_key or "default")
    state = copy.deepcopy(_core._load_state(vault_key))
    state = _proven._base._seed_default_tickers(vault_key, state)
    _core._sync_browser_state(vault_key, state)
    return _maybe_start_login_auto_refresh(
        vault_key,
        state,
        client,
        background_client_factory,
        login_marker,
        touch_session,
        rerun_on_start=False,
    )


