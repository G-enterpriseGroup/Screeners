# The workspace-level background client applies one shared ~3.7 MARKET
# request-starts/sec gate across quotes, expiration lists, and option chains.
# Four ticker workers can leave that gate idle whenever E*TRADE responses take
# several seconds, especially while each ticker is waiting for its expiration
# list before chain prefetch can begin. Twenty ticker workers match the existing
# twenty chain-fetch slots so Refresh All keeps the bounded MARKET pipeline full
# without increasing the request-start rate or changing any GEX calculation.
_BACKGROUND_TICKER_WORKERS = 20
_proven._BACKGROUND_MAX_WORKERS = _BACKGROUND_TICKER_WORKERS


# ==============================
# IV RANK OVERVIEW OVERLAY
# ==============================
def _inject_iv_rank_column(markup: str, vault_key: str) -> str:
    """Add one compact ``IV RANK / REF`` cell without touching Pine/A6 output."""
    if 'class="gexv3-summary"' not in markup or "<th>IV RANK / REF</th>" in markup:
        return markup

    markup = markup.replace(
        "<th>CALL WALL</th><th>RANGE</th>",
        "<th>CALL WALL</th><th>IV RANK / REF</th><th>RANGE</th>",
        1,
    )
    new_colgroup = (
        "<colgroup>"
        '<col style="width:11%"><col style="width:5%"><col style="width:9%">'
        '<col style="width:9%"><col style="width:9%"><col style="width:9%">'
        '<col style="width:13%"><col style="width:26%"><col style="width:9%">'
        "</colgroup>"
    )
    markup = re.sub(
        r"<colgroup>.*?</colgroup>",
        new_colgroup,
        markup,
        count=1,
        flags=re.DOTALL,
    )

    result_map = _core._results(str(vault_key or "default"))

    def add_cell(match: re.Match[str]) -> str:
        inner = match.group(1)
        ticker_match = re.search(r'gexv3-symbol-text">([^<]+)</span>', inner)
        if ticker_match is None:
            return match.group(0)
        ticker = html.unescape(ticker_match.group(1)).strip().upper()
        result = result_map.get(ticker)
        if not isinstance(result, dict):
            iv_cell = '<td class="orange">N/A | Refresh</td>'
            marker = '<td class="orange">REFRESH</td>'
            if marker in inner:
                inner = inner.replace(marker, iv_cell + marker, 1)
            return "<tr>" + inner + "</tr>"

        display = html.escape(str(result.get("ivRankDisplay") or "N/A | Building"))
        tone = str(result.get("ivRankTone") or "orange")
        if tone not in {"green", "red", "orange"}:
            tone = "orange"
        iv_cell = f'<td class="{tone}">{display}</td>'
        marker = '<td class="gexv3-range-col">'
        if marker in inner:
            inner = inner.replace(marker, iv_cell + marker, 1)
        return "<tr>" + inner + "</tr>"

    return re.sub(r"<tr>(.*?)</tr>", add_cell, markup, flags=re.DOTALL)


# ==============================
# TRADINGVIEW / PINE ROUTER COMPATIBILITY
# ==============================
def _render_tradingview_pine_compatible(
    state: dict[str, Any],
    result_map: dict[str, Any],
    failures: dict[str, str] | None = None,
) -> None:
    """Default to the exact compact transport consumed by the GEX TEST router.

    The Pine script routes on ``Ticker: SYMBOL`` and consumes only these packed
    row types: SPOT, GFLIP, CALLWALL, PUTWALL, MAXCALLOI, MAXPUTOI, GEXPOS*, and
    GEXNEG*. The linked Google Sheet's verbose A6 remains available as a separate
    audit/reference option, but it is not the default transport payload.
    """
    saved: list[str] = []
    for value in state.get("tickers", []):
        ticker = _core._normalize_ticker(value)
        if ticker and ticker not in saved:
            saved.append(ticker)
    if not saved:
        st.info("Add GEX tickers first.")
        return

    normalized_failures = {
        _core._normalize_ticker(key): str(value)
        for key, value in (failures or {}).items()
        if _core._normalize_ticker(key)
    }
    available = [
        ticker
        for ticker in saved
        if ticker in result_map and ticker not in normalized_failures
    ]
    if not available:
        st.info("Refresh GEX first. The TradingView bridge is built from refreshed ticker results.")
        return

    master_label = "MASTER A6 // PINE ROUTER SAFE — COPY THIS"
    full_label = "MASTER A6 // GOOGLE SHEETS FULL — REFERENCE"
    options = [master_label, full_label] + available
    choice = st.selectbox(
        "PACKED GAMMA BLOCK",
        options,
        key="gexv3_bridge_choice_pine_safe_v4",
    )

    is_master = choice == master_label
    is_full = choice == full_label
    if is_master:
        text = _proven._pine_master_bridge_text(result_map, available)
        filename = "raj_terminal_MASTER_A6_PINE_SAFE.txt"
        expected = available
        mode_text = "PINE ROUTER SAFE // Ticker: + packed rows only"
    elif is_full:
        text = _proven._google_sheets_master_text(result_map, saved, normalized_failures)
        filename = "raj_terminal_MASTER_A6_google_sheets_full.txt"
        expected = available
        mode_text = "GOOGLE SHEETS A6 // audit/reference only"
    else:
        text = _proven._pine_router_block(result_map[choice])
        filename = f"{choice}_gex_pine_safe.txt"
        expected = [choice]
        mode_text = f"{choice} // PINE ROUTER SAFE SINGLE TICKER"

    # TradingView/Pine treats the complete pasted multiline transport as one
    # string value only when it has one opening and one closing double quote.
    # Keep parser checks on the unquoted payload so the internal router grammar
    # remains exact: Ticker: headers plus packed rows only.
    parser_text = text
    if not is_full:
        text = f'"{parser_text.strip()}"'

    byte_count = len(text.encode("utf-8"))
    headers = _proven._pine_router_headers(parser_text)
    missing_headers = [ticker for ticker in expected if ticker not in headers]
    pine_issues, parsed_counts = _proven._pine_master_issues(parser_text, expected)
    too_large = byte_count > _proven._PINE_TEXT_LIMIT
    quoted_transport_ok = is_full or (text.startswith('"') and text.endswith('"'))
    transport_ok = not missing_headers and not pine_issues and not too_large and quoted_transport_ok

    st.caption(
        "TRADINGVIEW BRIDGE // "
        + mode_text
        + f" // {len(headers)}/{len(expected)} HEADERS // {byte_count:,}/{_proven._PINE_TEXT_LIMIT:,} CHARS"
    )

    if transport_ok:
        min_rows = min(parsed_counts.values()) if parsed_counts else 0
        max_rows = max(parsed_counts.values()) if parsed_counts else 0
        if is_master:
            st.success(
                f"PINE ROUTER CHECK PASS // {len(expected)}/{len(expected)} TICKERS // "
                f"{min_rows}-{max_rows} DRAWABLE PACKED ROWS EACH"
            )
        elif is_full:
            st.success(
                f"GOOGLE SHEETS REFERENCE CHECK PASS // {len(expected)} SUCCESSFUL TICKERS PARSE"
            )
        else:
            st.success(
                f"{choice} // PINE ROUTER CHECK PASS // {parsed_counts.get(choice, 0)} DRAWABLE PACKED ROWS"
            )
    else:
        details = list(missing_headers) + list(pine_issues)
        if too_large:
            details.append("TEXT_LIMIT")
        if not quoted_transport_ok:
            details.append("MISSING_OUTER_DOUBLE_QUOTES")
        st.error("PINE ROUTER CHECK FAILED // " + ", ".join(details[:16]))

    verify_ticker = st.selectbox(
        "PINE CHART TICKER CHECK",
        available,
        key="gexv3_pine_chart_ticker_check_safe_v4",
        help="Pick the same symbol as the TradingView chart. This validates the exact compact payload you should paste.",
    )
    safe_master = _proven._pine_master_bridge_text(result_map, available)
    target_issues, target_count = _proven._pine_ticker_issues(safe_master, verify_ticker)
    if target_issues:
        st.error(f"{verify_ticker} // PINE TARGET FAIL // " + ", ".join(target_issues))
    else:
        st.success(f"{verify_ticker} // PINE TARGET PASS // {target_count} DRAWABLE PACKED ROWS")

    if is_master:
        st.markdown(
            "**COPY THIS ENTIRE BLOCK INTO GEX TEST → Packed Gamma Levels. The opening and closing double quotes are required and are already included.**"
        )
    elif is_full:
        st.markdown(
            "**REFERENCE ONLY // this mirrors the Google Sheet A6, but use the PINE ROUTER SAFE master for TradingView.**"
        )
    else:
        st.markdown("**COPY THIS ENTIRE SINGLE-TICKER BLOCK INTO GEX TEST → Packed Gamma Levels. Keep the opening and closing double quotes.**")

    st.html(_proven._TRADINGVIEW_CODE_CSS)
    with st.container(key="gexv3_bridge_code"):
        st.code(text or "", language=None, wrap_lines=False)
    st.download_button(
        "DOWNLOAD MASTER A6" if is_master else "DOWNLOAD PACKED GAMMA BLOCK",
        data=text,
        file_name=filename,
        mime="text/plain",
        width="stretch",
        disabled=not bool(text.strip()),
        key="gexv3_download_bridge",
    )


