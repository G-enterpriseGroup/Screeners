def _delete_href(ticker: str) -> str:
    params: dict[str, Any] = {}
    try:
        for key in st.query_params:
            value = st.query_params.get_all(key)
            params[key] = value if len(value) > 1 else (value[0] if value else "")
    except Exception:
        params = {}
    params["gex_delete"] = ticker
    return "?" + urlencode(params, doseq=True)


def _inject_row_trash(markup: str) -> str:
    """Add one clickable trash cell beside each ticker in the overview table."""
    if 'class="gexv3-summary"' not in markup:
        return markup

    updated = markup.replace(
        "<th>TICKER</th>",
        '<th class="gexv3-trash-col">DEL</th><th>TICKER</th>',
        1,
    )

    def replace_symbol(match: re.Match[str]) -> str:
        ticker = html.unescape(match.group(1)).strip().upper()
        href = html.escape(_delete_href(ticker), quote=True)
        symbol_cell = match.group(0)
        trash_cell = (
            '<td class="gexv3-trash-col">'
            f'<a class="gexv3-trash-link" href="{href}" target="_self" '
            f'title="Delete {html.escape(ticker)} from GEX">🗑</a>'
            "</td>"
        )
        return trash_cell + symbol_cell

    return re.sub(
        r'<td class="sym">([^<]+)</td>',
        replace_symbol,
        updated,
    )


def _consume_delete_request(vault_key: str) -> None:
    """Persist a row-trash request, clear only that query parameter, and rerun."""
    try:
        raw = st.query_params.get("gex_delete")
    except Exception:
        raw = None
    ticker = _base.core._normalize_ticker(raw)
    if not ticker:
        return

    state = copy.deepcopy(_base.core._load_state(str(vault_key or "default")))
    result_map = _base.core._results(str(vault_key or "default"))
    if ticker in state.get("tickers", []):
        _base._remove_ticker(str(vault_key or "default"), state, result_map, ticker)

    try:
        del st.query_params["gex_delete"]
    except Exception:
        pass
    st.rerun()


# ==============================
# PUBLIC GEX RENDERER
# ==============================
def render_gex(client: Any, vault_key: str, touch_session: Any) -> None:
    """Render stable GEX v3 with row-level delete actions added to Overview."""
    vault_key = str(vault_key or "default")
    _consume_delete_request(vault_key)
    st.html(_ROW_ACTION_CSS)

    original_markdown = st.markdown

    def row_action_markdown(body: Any, *args: Any, **kwargs: Any):
        if isinstance(body, str) and 'class="gexv3-summary"' in body:
            body = _inject_row_trash(body)
        return original_markdown(body, *args, **kwargs)

    st.markdown = row_action_markdown
    try:
        _base.render_gex(client, vault_key, touch_session)
    finally:
        st.markdown = original_markdown


__all__ = ["render_gex"]
