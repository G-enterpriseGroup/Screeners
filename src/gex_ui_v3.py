# The workspace-level background client applies one shared ~3.7 MARKET
# request-starts/sec gate across quotes, expiration lists, and option chains.
# Four ticker workers can leave that gate idle whenever E*TRADE responses take
# several seconds, especially while each ticker is waiting for its expiration
# list before chain prefetch can begin. Twenty ticker workers match the existing
# twenty chain-fetch slots so Refresh All keeps the bounded MARKET pipeline full
# without increasing the request-start rate or changing any GEX calculation.
_BACKGROUND_TICKER_WORKERS = 20
_proven._BACKGROUND_MAX_WORKERS = _BACKGROUND_TICKER_WORKERS


# ==============================
# TRADINGVIEW / PINE EXACT TRANSPORT
# ==============================
# GEX TEST routes on ``Ticker: SYMBOL`` and consumes only comma-packed rows.
# Human-readable Google-Sheets metadata is useful for audit, but it is not Pine
# transport and must not be the default pasted payload.
_PINE_EXACT_MASTER_LABEL = "MASTER A6 // TRADINGVIEW PINE EXACT — COPY THIS"
_PINE_AUDIT_LABEL = "GOOGLE SHEETS FULL // AUDIT ONLY — DO NOT PASTE INTO GEX TEST"
_PINE_PACKED_TYPE_RE = re.compile(
    r"^(?:SPOT|GFLIP|CALLWALL|PUTWALL|MAXCALLOI|MAXPUTOI|GEXPOS\d+|GEXNEG\d+)$"
)


def _pine_exact_line_issues(text: str, expected_tickers: list[str]) -> list[str]:
    """Reject anything the existing GEX TEST parser does not need to consume."""
    issues: list[str] = []
    normalized = str(text or "").replace("\r\n", "\n").replace("\r", "\n")
    seen_headers: list[str] = []

    for line_no, raw_line in enumerate(normalized.split("\n"), 1):
        line = raw_line.strip()
        if not line:
            continue

        header = re.fullmatch(r"Ticker:\s*([^\r\n]+)", line, flags=re.IGNORECASE)
        if header:
            ticker = _core._normalize_ticker(header.group(1))
            if not ticker:
                issues.append(f"LINE_{line_no}:BAD_TICKER_HEADER")
            else:
                seen_headers.append(ticker)
            continue

        parts = [part.strip() for part in line.replace("|", ",").split(",")]
        if len(parts) != 3:
            issues.append(f"LINE_{line_no}:NOT_3_FIELDS")
            continue

        row_type = parts[0].upper()
        if not _PINE_PACKED_TYPE_RE.fullmatch(row_type):
            issues.append(f"LINE_{line_no}:UNSUPPORTED_{row_type[:24] or 'ROW'}")
            continue

        try:
            float(parts[1])
            float(parts[2])
        except (TypeError, ValueError):
            issues.append(f"LINE_{line_no}:NON_NUMERIC")

    expected = [_core._normalize_ticker(value) for value in expected_tickers]
    expected = [value for value in expected if value]
    if seen_headers != expected:
        issues.append("HEADER_ORDER_MISMATCH")

    parser_issues, _ = _proven._pine_master_issues(normalized, expected)
    issues.extend(parser_issues)
    return list(dict.fromkeys(issues))


def _render_tradingview_pine_exact(
    state: dict[str, Any],
    result_map: dict[str, Any],
    failures: dict[str, str] | None = None,
) -> None:
    """Make the exact Pine-consumed transport the first/default copy block."""
    saved: list[str] = []
    for value in state.get("tickers", []):
        ticker = _core._normalize_ticker(value)
        if ticker and ticker not in saved:
            saved.append(ticker)
    if not saved:
        st.info("Add GEX tickers first.")
        return

    normalized_failures = {
        _core._normalize_ticker(key): " ".join(str(value).split())
        for key, value in (failures or {}).items()
        if _core._normalize_ticker(key)
    }
    available = [
        ticker
        for ticker in saved
        if ticker in result_map and ticker not in normalized_failures
    ]
    unavailable = [ticker for ticker in saved if ticker not in available]

    if not available:
        st.warning("NO REFRESHED GEX DATA IS AVAILABLE FOR PINE YET.")
        return

    # New key intentionally resets old sessions whose saved selectbox value was
    # the verbose Google-Sheets master. First option is the Pine-exact transport.
    options = [_PINE_EXACT_MASTER_LABEL, _PINE_AUDIT_LABEL] + available
    choice = st.selectbox(
        "PACKED GAMMA BLOCK",
        options,
        key="gexv3_bridge_choice_pine_exact_v4",
    )

    is_master = choice == _PINE_EXACT_MASTER_LABEL
    is_audit = choice == _PINE_AUDIT_LABEL
    if is_master:
        text = _proven._pine_master_bridge_text(result_map, available)
        filename = "raj_terminal_MASTER_A6_PINE_EXACT.txt"
        expected = available
        mode_text = "PINE EXACT // Ticker: + packed rows only"
    elif is_audit:
        text = _proven._google_sheets_master_text(result_map, saved, normalized_failures)
        filename = "raj_terminal_MASTER_A6_GOOGLE_SHEETS_AUDIT.txt"
        expected = []
        mode_text = "GOOGLE SHEETS AUDIT // NOT FOR GEX TEST INPUT"
    else:
        text = _proven._pine_router_block(result_map[choice])
        filename = f"{choice}_GEX_PINE_EXACT.txt"
        expected = [choice]
        mode_text = f"{choice} // PINE EXACT SINGLE TICKER"

    byte_count = len(text.encode("utf-8"))
    if is_audit:
        line_issues: list[str] = []
    else:
        line_issues = _pine_exact_line_issues(text, expected)

    st.caption(
        "TRADINGVIEW BRIDGE // "
        + mode_text
        + f" // {byte_count:,}/{_proven._PINE_TEXT_LIMIT:,} CHARS"
    )

    if is_audit:
        st.warning(
            "AUDIT FORMAT ONLY // THIS CONTAINS Mode:, Spot:, DTE, Contracts, Net GEX, Source URL, "
            "AND INSTRUCTION TEXT. DO NOT PASTE THIS OPTION INTO GEX TEST."
        )
    elif line_issues:
        st.error("PINE EXACT PREFLIGHT FAILED // " + ", ".join(line_issues[:16]))
    elif byte_count > _proven._PINE_TEXT_LIMIT:
        st.error(
            f"PINE EXACT PAYLOAD IS {byte_count:,} CHARS // ABOVE {_proven._PINE_TEXT_LIMIT:,}; "
            "USE A SINGLE-TICKER BLOCK RATHER THAN PASTING A TRUNCATED MASTER."
        )
    else:
        st.success(
            f"PINE EXACT PREFLIGHT PASS // {len(expected)} TICKER BLOCK(S) // "
            "ONLY Ticker: HEADERS + PACKED ROWS"
        )

    if unavailable and is_master:
        st.warning(
            f"{len(unavailable)} SAVED TICKER(S) HAVE NO CURRENT GEX RESULT AND ARE OMITTED FROM THE PINE MASTER: "
            + ", ".join(unavailable[:16])
        )

    if not is_audit:
        st.caption(
            "GEX TEST LINE CONTRACT // Ticker: SYMBOL → SPOT → optional GFLIP → CALLWALL → PUTWALL → "
            "MAXCALLOI → MAXPUTOI → GEXPOS/GEXNEG. No Mode:, Spot:, DTE, Contracts, Net GEX, "
            "Source URL, instruction, or separator lines are included."
        )

    block_name = "MASTER A6 // PINE EXACT" if is_master else (
        "GOOGLE SHEETS FULL // AUDIT" if is_audit else f"{choice} // PINE EXACT"
    )
    st.markdown(f"**{block_name} // USE COPY MASTER A6 IN THE TOP-RIGHT**")
    st.html(_proven._TRADINGVIEW_CODE_CSS)
    with st.container(key="gexv3_bridge_code"):
        st.code(text or "", language=None, wrap_lines=False)
    st.download_button(
        "DOWNLOAD PINE EXACT MASTER" if is_master else (
            "DOWNLOAD GOOGLE SHEETS AUDIT" if is_audit else "DOWNLOAD PINE EXACT BLOCK"
        ),
        data=text,
        file_name=filename,
        mime="text/plain",
        width="stretch",
        disabled=not bool(text.strip()),
        key="gexv3_download_bridge_pine_exact_v4",
    )


