    def refresh_all_connect_button(label: Any, *args: Any, **kwargs: Any):
        """Route disconnected Refresh All clicks into the existing OAuth start flow."""
        if kwargs.get("key") != "gexv3_refresh_all" or client is not None:
            return original_button(label, *args, **kwargs)

        if callable(connect_etrade):
            # The base GEX renderer disables Refresh All whenever client is None.
            # Override only that disconnected state so this wrapper can receive
            # the click and hand it to the existing E*TRADE authorization flow.
            kwargs["disabled"] = False

        request = st.session_state.get("etrade_request") or {}
        pending_auth_url = (
            str(request.get("authorization_url") or "").strip()
            if isinstance(request, dict)
            else ""
        )

        # Keep exactly one action in the Refresh All slot. Once the OAuth
        # request exists, replace the disconnected Refresh All button with the
        # returned E*TRADE authorization link. After verification succeeds and
        # a live client exists, the normal Refresh All button returns unchanged.
        if pending_auth_url:
            st.link_button(
                "OPEN E*TRADE AUTHORIZATION ↗",
                pending_auth_url,
                width="stretch",
            )
            return False

        clicked = original_button(label, *args, **kwargs)
        if not clicked:
            return False

        if not callable(connect_etrade):
            st.warning("Connect E*TRADE before refreshing GEX.")
            return False

        try:
            started = bool(connect_etrade())
        except Exception as exc:
            st.error(f"E*TRADE connection could not be started: {exc}")
            return False

        if started:
            st.toast("E*TRADE AUTHORIZATION READY // OPEN THE AUTHORIZATION LINK")
            st.rerun()
        return False

