# ==============================
# HISTORY CACHE (PROCESS-LOCAL; NO BROKER DATA IN GITHUB OR BROWSER)
# ==============================

@st.cache_resource
def _history_vault() -> dict[str, Any]:
    """Reuse complete histories across tabs, reruns and browser sessions of this worker."""
    return {"lock": threading.RLock(), "accounts": {}, "lots": {}}


def _identity(tx: dict[str, Any]) -> str:
    identifier = _find(tx, "transactionId")
    if identifier not in (None, ""):
        return str(identifier)
    # Stable identity for a rare transaction lacking E*TRADE's primary key.
    return hashlib.sha256(json.dumps(tx, sort_keys=True, default=str).encode()).hexdigest()


def _merge(old: list[dict[str, Any]], recent: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = {_identity(row): row for row in old if isinstance(row, dict)}
    rows.update({_identity(row): row for row in recent if isinstance(row, dict)})
    return sorted(rows.values(), key=lambda tx: (_when(tx) or datetime.min.replace(tzinfo=_ET), _identity(tx)))


def _sync_history(
    client: Any,
    vault_key: str,
    accounts: list[dict[str, Any]],
    *,
    force: bool = False,
    now: datetime | None = None,
) -> tuple[dict[str, dict[str, Any]], dict[str, str]]:
    """First visit fetches all accounts; subsequent visits fetch ONLY a short overlap.

    A failed read never replaces a good snapshot or advances its checkpoint.
    Concurrent sessions share the lock to avoid duplicate full-history calls.
    """
    today = (now or datetime.now(_ET)).date()
    vault = _history_vault()
    errors: dict[str, str] = {}
    snapshots: dict[str, dict[str, Any]] = {}
    with vault["lock"]:
        for account in accounts:
            key = str(account.get("accountIdKey") or "").strip()
            if not key:
                continue
            scope = (str(vault_key), key)
            saved = vault["accounts"].get(scope)
            live = client is not None and not bool(getattr(client, "is_offline", False))
            needs_sync = live and (
                saved is None or force or time.time() - float(saved.get("synced_at", 0)) >= _SYNC_SECONDS
            )
            if needs_sync:
                if saved:
                    start = max(today - timedelta(days=_HISTORY_DAYS),
                                saved["covered_through"] - timedelta(days=_OVERLAP_DAYS))
                else:
                    start = today - timedelta(days=_HISTORY_DAYS)
                try:
                    fresh = client.get_transactions(key, start_date=start, end_date=today, sort_order="ASC")
                    if not isinstance(fresh, list):
                        raise ValueError("E*TRADE did not return a transaction list.")
                    merged = _merge((saved or {}).get("rows", []), fresh)
                    saved = {
                        "rows": merged,
                        "covered_from": (saved or {}).get("covered_from", start),
                        "covered_through": today,
                        "synced_at": time.time(),
                    }
                    vault["accounts"][scope] = saved
                except Exception as exc:
                    errors[key] = str(exc)[:240]
            if saved:
                snapshots[key] = {
                    "rows": list(saved["rows"]),
                    "covered_from": saved["covered_from"],
                    "covered_through": saved["covered_through"],
                    "synced_at": saved["synced_at"],
                }
    return snapshots, errors


# ==============================
# EQUITY TRADE NORMALIZATION / FIFO
# ==============================

def _equity_trade(tx: dict[str, Any]) -> dict[str, Any] | None:
    symbol, security, option = _instrument(tx)
    if security not in _SHARE_TYPES or option or not symbol:
        return None
    row = _trade_record(tx)
    if row is None:
        return None
    row["symbol"] = symbol
    return row


def _fifo_equity(transactions: list[dict[str, Any]]) -> tuple[dict[str, list[dict[str, Any]]], set[str]]:
    """Match sells against earliest prior purchases; return only unsold BUY shares."""
    trades = [row for tx in transactions if isinstance(tx, dict) if (row := _equity_trade(tx))]
    trades.sort(key=lambda row: (row["when"], str(row["id"])))
    lots: dict[str, deque[dict[str, Any]]] = defaultdict(deque)
    incomplete: set[str] = set()
    for row in trades:
        ticker, action, qty = row["symbol"], row["action"], float(row["quantity"])
        if action == "BUY":
            lots[ticker].append({
                "ticker": ticker, "date": row["when"].date(),
                "cost": float(row["price"]), "qty": qty, "id": str(row["id"]),
            })
        elif action == "SELL":
            while qty > 1e-8 and lots[ticker]:
                first = lots[ticker][0]
                used = min(qty, first["qty"])
                qty -= used
                first["qty"] -= used
                if first["qty"] <= 1e-8:
                    lots[ticker].popleft()
            if qty > 1e-8:
                incomplete.add(ticker)  # sale against a pre-window/unseen purchase
        else:
            incomplete.add(ticker)  # short/buy-to-cover cannot be a long BUY lot
    return {symbol: [dict(lot) for lot in entries if lot["qty"] > 1e-8]
            for symbol, entries in lots.items()}, incomplete


def _shares_held(positions: list[dict[str, Any]]) -> dict[str, float]:
    holdings: dict[str, float] = defaultdict(float)
    for raw in positions:
        if not isinstance(raw, dict):
            continue
        item = normalize_position(raw)
        ticker = str(item["Symbol"]).strip().upper()
        security = str(item["Type"]).strip().upper()
        qty = float(item["Quantity"] or 0)
        if ticker and security in _SHARE_TYPES and math.isfinite(qty) and qty > 0:
            holdings[ticker] += qty
    return dict(holdings)


def _reconcile(
    transactions: list[dict[str, Any]], positions: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Exclude only lot quantities that cannot match current E*TRADE holdings."""
    lots, incomplete = _fifo_equity(transactions)
    holdings = _shares_held(positions)
    valid: list[dict[str, Any]] = []
    gaps: list[dict[str, Any]] = []
    for ticker, actual in sorted(holdings.items()):
        reconstructed = sum(row["qty"] for row in lots.get(ticker, []))
        # Prior unmatched sales can be fully closed, before surviving BUY lots.
        # Once current held shares equal reconstructed open BUY quantities, a
        # historical sale deficit alone must not suppress those acquisitions.
        matched = math.isclose(reconstructed, actual, abs_tol=1e-5, rel_tol=1e-7)
        if matched:
            valid.extend({**lot, "source": "FIFO"} for lot in lots.get(ticker, []))
        else:
            gaps.append({
                "Ticker": ticker, "Held": round(actual, 6), "FIFO Found": round(reconstructed, 6),
                "Reason": "Missing prior buys / sells or corporate action; check older records" if ticker in incomplete
                          else "Broker holdings differ from reconstructed trade lots",
            })
    valid.sort(key=lambda row: (row["ticker"], row["date"], row["id"]))
    return valid, gaps


def _qty_text(quantity: float) -> str:
    return f"{quantity:.8f}".rstrip("0").rstrip(".")


def _pine_rows(lots: list[dict[str, Any]]) -> str:
    """Exactly: TICKER MM.DD.YYYY COST QTY B (one unsold acquisition lot per line)."""
    return "\n".join(
        f"{lot['ticker']} {lot['date']:%m.%d.%Y} {lot['cost']:.4f}".rstrip("0").rstrip(".")
        + f" {_qty_text(lot['qty'])} B"
        for lot in lots
    )


