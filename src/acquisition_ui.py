def _save_blotter_column(scope: str, label: str, keys: dict[str, str], records: list[dict[str, Any]], clear: bool = False) -> None:
    preferences = st.session_state["_acquisition_blotter_preferences"][scope]
    rules = [rule for rule in preferences["rules"] if rule["field"] != label]
    if not clear:
        presence = st.session_state[keys["presence"]]
        if presence == "MISSING ONLY":
            rules.append({"field": label, "op": "is_missing"})
        else:
            if presence == "KNOWN ONLY":
                rules.append({"field": label, "op": "is_known"})
            kind = _VERTICAL_FILTER_FIELDS[label][1]
            if kind == "choice" and st.session_state[keys["selection"]] == "SELECT VALUES":
                rules.append({"field": label, "op": "in", "values": list(st.session_state[keys["values"]])})
            elif kind in {"number", "date"}:
                low, high = (st.session_state[keys[name]] for name in ("min", "max"))
                if low is not None or high is not None:
                    rules.append({"field": label, "op": "between", "min": low.isoformat() if isinstance(low, date) else low,
                                  "max": high.isoformat() if isinstance(high, date) else high})
            elif kind == "text" and st.session_state[keys["value"]] != "":
                rules.append({"field": label, "op": {"CONTAINS": "contains", "EQUALS": "eq", "DOES NOT EQUAL": "ne"}[
                    st.session_state[keys["operation"]]], "value": st.session_state[keys["value"]]})
    try:
        _filter_vertical_records(records, rules)
    except ValueError as exc:
        preferences["error"] = str(exc)
        return
    preferences.update(rules=rules, error=None, revision=preferences["revision"] + 1, header_page=0)


def _blotter_component_context(source_fingerprint: str, preferences: dict[str, Any]) -> str:
    state = {"source": source_fingerprint, "tickers": preferences["tickers"],
             "rules": preferences["rules"], "revision": preferences["revision"]}
    return hashlib.sha256(json.dumps(state, sort_keys=True).encode()).hexdigest()


def _sort_vertical_records(records: list[dict[str, Any]], sort: dict[str, str] | None) -> list[dict[str, Any]]:
    if sort is None:
        return list(records)
    if (not isinstance(sort, dict) or not isinstance(sort.get("field"), str)
            or sort["field"] not in _VERTICAL_TABLE_WIDTHS
            or not isinstance(sort.get("direction"), str) or sort["direction"] not in {"asc", "desc"}):
        raise ValueError("Choose a valid blotter sort column and direction")
    key, kind = _VERTICAL_FILTER_FIELDS[sort["field"]]
    def value(row):
        raw = row.get(key)
        if raw is None or raw == "":
            return None
        if kind == "number":
            return _vertical_filter_number(raw)
        if kind == "date":
            try:
                parsed = datetime.fromisoformat(str(raw))
                return (parsed if parsed.tzinfo else parsed.replace(tzinfo=_ET)).timestamp()
            except (TypeError, ValueError, OverflowError, OSError):
                return None
        return str(raw).casefold()
    known, missing = [], []
    for row in records:
        parsed = value(row)
        (missing if parsed is None else known).append(row if parsed is None else (parsed, row))
    return [row for _, row in sorted(known, key=lambda item: item[0], reverse=sort["direction"] == "desc")] + missing


def _apply_blotter_table_event(scope: str, widget_key: str, records: list[dict[str, Any]], source_fingerprint: str) -> None:
    """Accept view controls only; broker records and financial totals stay server-owned."""
    preferences = st.session_state["_acquisition_blotter_preferences"][scope]
    event = st.session_state.get(widget_key)
    if (not isinstance(event, dict) or event.get("scope") != scope
            or event.get("context") != _blotter_component_context(source_fingerprint, preferences)
            or type(event.get("revision")) is not int
            or event["revision"] != preferences.get("header_revision", 0) + 1):
        return
    try:
        if set(event) != {"scope", "context", "revision", "filters", "sort", "page"}:
            raise ValueError("The table accepts filter, sort and page controls only")
        rules = event["filters"]
        if (not isinstance(rules, list) or len(rules) > 24
                or any(not isinstance(rule, dict) or not isinstance(rule.get("field"), str)
                       or rule["field"] not in _VERTICAL_TABLE_WIDTHS for rule in rules)):
            raise ValueError("Choose valid table column filters")
        _filter_vertical_records(records, rules)
        _sort_vertical_records([], event["sort"])
        if type(event["page"]) is not int or event["page"] < 0:
            raise ValueError("Choose a valid table page")
        preferences.update(header_rules=rules, header_sort=event["sort"], header_page=event["page"], header_error=None)
    except (ValueError, TypeError) as exc:
        preferences["header_error"] = str(exc)
    preferences["header_revision"] = event["revision"]


@st.fragment
def _render_vertical_blotter(payload: dict[str, Any] | None, vault_key: str, account: str,
                              covered_from: date | None, covered_through: date | None,
                              cache_message: str = "", cache_error: str = "", synced_at: float | None = None) -> None:
    """Filter cached lifecycle copies locally; this fragment never reads broker/archive data."""
    st.html('<div class="acq-section">VERTICAL SPREAD BLOTTER // REALIZED P&amp;L</div>')
    coverage = (f"{covered_from:%m/%d/%Y} – {covered_through:%m/%d/%Y}"
                if covered_from and covered_through else "NO RETAINED HISTORY")
    st.caption("ALL RETAINED SOURCE HISTORY // " + coverage + " // Older records unavailable to this archive are excluded.")
    try:
        timestamp = _vertical_filter_number(synced_at)
        last_sync = datetime.fromtimestamp(timestamp, _ET).strftime("%m/%d/%Y %I:%M %p ET") if timestamp and timestamp > 0 else "UNKNOWN"
    except (ValueError, OverflowError, OSError):
        last_sync = "UNKNOWN"
    st.caption("SOURCE // E*TRADE TRANSACTIONS · CACHED SPREAD CASH REPORT // LAST SUCCESSFUL HISTORY SYNC " + last_sync)
    records = _vertical_filter_records(payload or {})
    scope = hashlib.sha256(json.dumps([str(vault_key), str(account)]).encode()).hexdigest()[:16]
    preferences = st.session_state.setdefault("_acquisition_blotter_preferences", {}).setdefault(
        scope, {"tickers": None, "rules": [], "revision": 0, "error": None},
    )
    for name, default in (("header_rules", []), ("header_sort", None), ("header_page", 0),
                          ("header_revision", 0), ("header_error", None)):
        preferences.setdefault(name, default)
    ticker_key = "acquisition_blotter_tickers_" + scope
    symbols = sorted({row["ticker"] for row in records})
    selected = preferences["tickers"]
    st.session_state[ticker_key] = (["ALL TICKERS"] if selected is None else [value for value in selected if value in symbols])
    ticker_col, filter_col, reset_col = st.columns([4.4, 1.7, 1.7], gap="small", vertical_alignment="bottom")
    with ticker_col:
        st.multiselect("BLOTTER TICKERS", ["ALL TICKERS", *symbols], key=ticker_key,
                       on_change=_remember_blotter_tickers, args=(scope, ticker_key),
                       help="ALL TICKERS includes all retained spreads. Clear the selection to show none.")
    with filter_col:
        with st.popover("COLUMN FILTERS", width="stretch"):
            label = st.selectbox("FILTER COLUMN", list(_VERTICAL_FILTER_FIELDS),
                                 index=list(_VERTICAL_FILTER_FIELDS).index("Realized P&L"), key="acquisition_blotter_column_" + scope)
            field, kind = _VERTICAL_FILTER_FIELDS[label]
            active = [rule for rule in preferences["rules"] if rule["field"] == label]
            prefix = f"acquisition_blotter_rule_{scope}_{label}_{preferences['revision']}_"
            keys = {name: prefix + name for name in ("presence", "selection", "values", "min", "max", "operation", "value")}
            presence = next(("MISSING ONLY" if rule["op"] == "is_missing" else "KNOWN ONLY"
                             for rule in active if rule["op"] in {"is_missing", "is_known"}), "ANY")
            with st.form(prefix + "form", border=False):
                st.selectbox("VALUE STATUS", ["ANY", "KNOWN ONLY", "MISSING ONLY"],
                             index=["ANY", "KNOWN ONLY", "MISSING ONLY"].index(presence), key=keys["presence"])
                if kind == "choice":
                    choice = next((rule for rule in active if rule["op"] == "in"), None)
                    st.selectbox("MATCH", ["ALL VALUES", "SELECT VALUES"], index=int(choice is not None), key=keys["selection"])
                    options = sorted({str(row[field]) for row in records if row.get(field) is not None and row[field] != ""})
                    st.multiselect("VALUES", options, default=[value for value in (choice or {}).get("values", []) if value in options], key=keys["values"])
                elif kind in {"number", "date"}:
                    bounds = next((rule for rule in active if rule["op"] == "between"), {})
                    low, high = bounds.get("min"), bounds.get("max")
                    low_col, high_col = st.columns(2, gap="small")
                    for column, name, value in ((low_col, "min", low), (high_col, "max", high)):
                        with column:
                            if kind == "number":
                                st.number_input("MINIMUM" if name == "min" else "MAXIMUM", value=float(value) if value is not None else None,
                                                step=1.0, format="%.4f", key=keys[name])
                            else:
                                st.date_input("FROM" if name == "min" else "THROUGH", value=date.fromisoformat(value) if value else None,
                                              min_value=date(1900, 1, 1), max_value=date(2200, 12, 31), format="MM/DD/YYYY", key=keys[name])
                else:
                    text_rule = next((rule for rule in active if rule["op"] in {"contains", "eq", "ne"}), {})
                    operations = ["CONTAINS", "EQUALS", "DOES NOT EQUAL"]
                    operation = {"contains": 0, "eq": 1, "ne": 2}.get(text_rule.get("op"), 0)
                    st.selectbox("MATCH", operations, index=operation, key=keys["operation"])
                    st.text_input("VALUE", value=text_rule.get("value", ""), key=keys["value"])
                apply_col, clear_col = st.columns(2, gap="small")
                with apply_col:
                    st.form_submit_button("APPLY COLUMN", on_click=_save_blotter_column, args=(scope, label, keys, records), width="stretch")
                with clear_col:
                    st.form_submit_button("CLEAR COLUMN", on_click=_save_blotter_column, args=(scope, label, keys, records, True), width="stretch")
            st.caption("Columns combine with AND. Blank bounds leave that side open; zero is a real value.")
            if preferences["rules"]:
                st.caption("ACTIVE COLUMNS // " + " · ".join(dict.fromkeys(rule["field"] for rule in preferences["rules"])))
    with reset_col:
        st.button("RESET FILTERS", key="acquisition_blotter_reset_" + scope,
                  on_click=_reset_blotter_filters, args=(scope, ticker_key), width="stretch")
    if preferences.get("error"):
        st.error(preferences["error"])
    rules = list(preferences["rules"])
    rules.extend(preferences["header_rules"])
    if preferences["tickers"] is not None:
        rules.append({"field": "Ticker", "op": "in", "values": preferences["tickers"]})
    filtered = _sort_vertical_records(_filter_vertical_records(records, rules), preferences["header_sort"])
    totals = _vertical_filtered_totals(filtered)
    for group in totals["groups"]:
        for subtotal in [group, *group["evidence"]]:
            subtotal["display"] = {
                key: ("—" if subtotal[key] is None else
                      f'{subtotal[key]:+,.2f}' if key in {"pnl", "gains", "losses"} and subtotal[key] else
                      f'{subtotal[key]:,.8f}'.rstrip("0").rstrip(".") if key == "contracts" else
                      f'{subtotal[key]:,.2f}')
                for key in ("pnl", "gains", "losses", "entry_cost", "exit_cash", "fees", "contracts")
            }
    page_size = 100
    preferences["header_page"] = min(preferences["header_page"], max(0, (len(filtered) - 1) // page_size))
    offset = preferences["header_page"] * page_size
    frame = (_vertical_blotter_frame(filtered) if filtered else pd.DataFrame(columns=list(_VERTICAL_TABLE_WIDTHS)))
    displayed = frame.iloc[offset:offset + page_size].astype(object)
    displayed = displayed.where(pd.notna(displayed), None).to_dict("records")
    columns = []
    for label, width in _VERTICAL_TABLE_WIDTHS.items():
        field, kind = _VERTICAL_FILTER_FIELDS[label]
        choices = sorted({str(row[field]) for row in records if row.get(field) is not None and row[field] != ""}) if kind == "choice" else []
        columns.append({"label": label, "kind": kind, "width": width, "choices": choices})
    source_fingerprint = str((payload or {}).get("source_fingerprint") or "")
    table_key = "acquisition_blotter_table_" + scope
    _ACQ_VERTICAL_TABLE(
        scope=scope, context=_blotter_component_context(source_fingerprint, preferences),
        columns=columns, rows=displayed, header_rules=preferences["header_rules"], sort=preferences["header_sort"],
        page=preferences["header_page"], page_size=page_size, total_filtered=len(filtered), total_source=len(records),
        totals=totals, ack_revision=preferences["header_revision"], error=preferences["header_error"] or "",
        key=table_key, default=None,
        on_change=lambda: _apply_blotter_table_event(scope, table_key, records, source_fingerprint),
    )
    st.download_button("DOWNLOAD FILTERED .CSV", data=frame.to_csv(index=False),
                       file_name="acquisition_vertical_pnl.csv", mime="text/csv", disabled=frame.empty,
                       key="acquisition_blotter_csv_" + scope, on_click="ignore")
    st.caption("GREEN + = gain; RED − = loss; blank P&L = unknown. Net cash includes fees; negative Entry Cost is a credit. "
               "EXPIRED uses broker-confirmed expiry and its record date; past-date open/review quantities remain unverified. "
               "INFERRED marks timestamp-only pairing; open quantities have no live valuation.")
    if cache_error:
        st.warning("VERTICAL GITHUB CACHE PENDING // " + cache_error)
    elif cache_message:
        st.caption(cache_message)


def render_acquisition(
    client: Any,
    *,
    vault_key: str,
    refresh_accounts: Callable[[Any], list[dict[str, Any]]] | None = None,
    touch_session: Callable[[], Any] | None = None,
) -> None:
    """Render compact Risk Sizing-themed, strictly read-only Acquisition workspace."""
    st.html(_CSS)
    with st.container(key="acquisition_root", gap=None):
        accounts = [row for row in (st.session_state.get("etrade_accounts") or [])
                    if isinstance(row, dict) and row.get("accountIdKey")]
        if not accounts and client is not None and refresh_accounts:
            try:
                accounts = refresh_accounts(client)
            except Exception as exc:
                st.warning(f"E*TRADE ACCOUNTS UNAVAILABLE // {exc}")
                return
        accounts = [row for row in accounts if isinstance(row, dict) and row.get("accountIdKey")]
        if not accounts:
            st.info("CONNECT E*TRADE TO LOAD ACQUISITION HISTORY.")
            return
        by_key = {str(row["accountIdKey"]): row for row in accounts}
        picker_key = "acquisition_account_key"
        # Default each new Acquisition session to Raj while allowing the
        # user to switch accounts without resetting on normal Streamlit reruns.
        initial_key = "_acquisition_default_account_initialized"
        account_scope = (str(vault_key), tuple(sorted(by_key)))
        if st.session_state.get(initial_key) != account_scope:
            st.session_state[picker_key] = _default_account(accounts)
            st.session_state[initial_key] = account_scope
        elif str(st.session_state.get(picker_key) or "") not in by_key:
            st.session_state[picker_key] = _default_account(accounts)

        left, right = st.columns([5, 1.65], gap="small", vertical_alignment="bottom")
        with left:
            chosen = st.selectbox("E*TRADE ACCOUNT", list(by_key), key=picker_key,
                                  format_func=lambda key: _account_label(by_key[key]))
        with right:
            sync = st.button("SYNC NEW TRADES", type="primary", width="stretch",
                             key="acquisition_sync", disabled=client is None or bool(getattr(client, "is_offline", False)))

        with st.spinner("Reading cached share history / syncing only new transactions..."):
            snapshots, errors = _sync_history(client, vault_key, accounts, force=sync)
        vault = _history_vault()
        saved = snapshots.get(chosen)
        vertical_payload = _cached_verticals(saved["rows"], vault_key, chosen) if saved else None
        private_scope = (str(vault_key), str(chosen))
        cache_message = ("PRIVATE GITHUB BLOTTER SAVED // VERSIONED REPORT + RAW HISTORY" if vertical_payload and
                         vault.get("vertical_cache_saved", {}).get(private_scope) == vertical_payload["source_fingerprint"] else
                         "VERTICAL BLOTTER CACHED IN THIS PROCESS // PRIVATE GITHUB REPORT NOT YET VERIFIED SAVED")
        _render_vertical_blotter(vertical_payload, vault_key, chosen,
                                 saved.get("covered_from") if saved else None, saved.get("covered_through") if saved else None,
                                 cache_message if saved else "", vault.get("vertical_cache_error", {}).get(private_scope, ""),
                                 synced_at=saved.get("synced_at") if saved else None)
        detail_error = vault.get("option_detail_error", {}).get(private_scope)
        if detail_error:
            st.warning("BROKER ORDER EVIDENCE PENDING // " + detail_error)
        if not vault.get("archive_configured"):
            st.warning(
                "GITHUB ARCHIVE NOT ACTIVE // " +
                errors.get(
                    "archive",
                    "ARCHIVE SETTINGS MISSING // Add [acquisition] archive_key and "
                    "[github] bridge_token in Streamlit Secrets.",
                ) +
                " // Histories are currently memory-only."
            )
        elif vault.get("archive_dirty", {}).get((str(vault_key), str(chosen)), False):
            st.warning("GITHUB ARCHIVE PENDING // local history is not yet durably backed up.")
        else:
            st.caption("ENCRYPTED GITHUB ARCHIVE ACTIVE // ACCOUNT-ISOLATED")
        if touch_session and client is not None and not bool(getattr(client, "is_offline", False)):
            touch_session()
        account_errors = [
            f"{_account_label(by_key[key])}: {message}"
            for key, message in errors.items() if key in by_key
        ]
        if errors.get("blotter"):
            st.html(
                '<div class="acq-alert" role="alert"><strong>PRIVATE GITHUB BLOTTER NOT UPDATED</strong> // '
                + html.escape(errors["blotter"])
                + ' // The encrypted archive is preserved separately.</div>'
            )
        if account_errors:
            st.warning("HISTORY / ARCHIVE SYNC INCOMPLETE // " + "; ".join(account_errors))
        if not saved:
            st.info("NO CACHED TRANSACTIONS FOR THIS ACCOUNT. CONNECT E*TRADE AND SYNC.")
            return
        if client is None:
            st.warning("E*TRADE OFFLINE // cached trades may not match current holdings.")
            return
        try:
            portfolio = client.get_portfolio(chosen, force_refresh=sync)
        except TypeError:
            portfolio = client.get_portfolio(chosen)
        except Exception as exc:
            st.warning(f"CURRENT HOLDINGS UNAVAILABLE // {exc}")
            return
        if not isinstance(portfolio, list):
            st.warning("CURRENT HOLDINGS COULD NOT BE VERIFIED.")
            return
        valid, gaps = _reconcile(saved["rows"], portfolio)
        valid, gaps = _recover_broker_lots(
            client, vault_key, chosen, portfolio, valid, gaps, force=sync,
        )
        covered = saved["covered_from"]
        through = saved["covered_through"]
        st.html(
            '<div class="acq-status">'
            f'FIFO // {len(valid):,} VERIFIED OPEN BUY LOTS // '
            f'{len(gaps):,} UNRECONCILED SYMBOLS // {len(saved["rows"]):,} CACHED TRANSACTIONS // '
            f'HISTORY WINDOW {covered:%m/%d/%Y} – {through:%m/%d/%Y} // '
            'API MAXIMUM: 2 YEARS // ENCRYPTED GITHUB HISTORY WHEN ENABLED // 7-DAY OVERLAP'
            '</div>'
        )
        st.html('<div class="acq-section">OPEN EQUITY ACQUISITIONS // FIFO</div>')
        if valid:
            frame = pd.DataFrame([{
                "Ticker": lot["ticker"], "Acquired": lot["date"].strftime("%m/%d/%Y"),
                "Share Cost": round(lot["cost"], 4), "Open Shares": round(lot["qty"], 8),
                "Source": lot.get("source", "FIFO"),
            } for lot in valid])
            st.dataframe(frame, hide_index=True, width="stretch", row_height=32)
        else:
            st.info("NO VERIFIED OPEN EQUITY LOTS FOUND IN THIS ACCOUNT.")
        if gaps:
            st.warning(
                "UNVERIFIED OPEN LOTS EXCLUDED FROM FIFO EXPORT. Older than two years, transfers, "
                "splits, reinvestments, or missing API records can cause gaps. "
                "Do not rely on FIFO for these positions until older history is reconciled."
            )
            st.dataframe(pd.DataFrame(gaps), hide_index=True, width="stretch", row_height=32)
        history_lines = share_blotter(saved["rows"], _equity_trade).splitlines()
        history_symbols = {line.partition(" ")[0] for line in history_lines}
        holding_symbols = sorted(_shares_held(portfolio))
        choices = sorted(set(holding_symbols) | history_symbols)
        scope = hashlib.sha256(json.dumps([str(vault_key), str(chosen)]).encode()).hexdigest()[:16]
        preferences = st.session_state.setdefault("_acquisition_copy_preferences", {}).setdefault(
            scope, {"tickers": holding_symbols, "mode": "BOUGHT + SOLD"},
        )
        mode_key = "acquisition_copy_mode_" + scope
        st.session_state[mode_key] = preferences["mode"]
        vertical_mode = "VERTICALS // OPENED + CLOSED"
        heading = "COPY VERTICAL SPREAD HISTORY" if preferences["mode"] == vertical_mode else "COPY INTO TRADINGVIEW PINE SCRIPT"
        st.html('<div class="acq-section">' + heading + '</div>')
        mode_col, ticker_col = st.columns([2, 5], gap="small", vertical_alignment="bottom")
        with mode_col:
            mode = st.selectbox(
                "COPY RECORDS", ["BOUGHT + SOLD", "OPEN LOTS // FIFO", vertical_mode], key=mode_key,
                on_change=_remember_copy_preference, args=(scope, "mode", mode_key),
            )
        verticals, review = ((_vertical_event_rows(vertical_payload, "events"), _vertical_event_rows(vertical_payload, "review"))
                             if mode == vertical_mode and vertical_payload else ([], []))
        if vertical_payload:
            consumed_expirations = {str(identity) for row in vertical_payload["blotter"] if row["status"] == "EXPIRED"
                                    for identity in row["close_ids"]}
            review = [leg for leg in review if not (leg.get("lifecycle") == "EXPIRATION"
                      and str(leg.get("id")) in consumed_expirations)]
        setting = "vertical_tickers" if mode == vertical_mode else "tickers"
        if mode == vertical_mode:
            choices = sorted({row["ticker"] for row in verticals + review})
            preferences.setdefault(setting, choices)
        ticker_key = "acquisition_copy_" + setting + "_" + scope
        st.session_state[ticker_key] = [ticker for ticker in preferences[setting] if ticker in choices]
        with ticker_col:
            selected = set(st.multiselect(
                "TICKERS TO INCLUDE", choices, key=ticker_key,
                on_change=_remember_copy_preference, args=(scope, setting, ticker_key),
                help=("Choose option underlyings from this account's cached execution history." if mode == vertical_mode else
                      "Choose current holdings or tickers from this account's cached buy/sell history, including fully sold positions."),
            ))
        if mode == vertical_mode:
            matched = [row for row in verticals if row["ticker"] in selected]
            text = _vertical_text(matched)
            st.caption(
                "OPENED = BTO + STO; CLOSED = STC + BTC. Same underlying, expiration, type and balanced contracts. "
                "LONG / SHORT identify the original sides. ORDER = shared broker order; TIME // INFERRED = exact intraday time only. "
                "NET = premium per share before fees; split fills use quantity-weighted premiums. "
                "Event quantities do not establish a flat position or lifetime P&L; history is limited to the window above."
            )
            if matched:
                with st.expander("OPENED / CLOSED EXECUTION DETAILS"):
                    st.dataframe(pd.DataFrame([{
                    "Ticker": row["ticker"], "Date": row["when"].strftime("%m/%d/%Y"),
                    "Event": row["event"], "Expiry": row["expiry"].strftime("%m/%d/%Y"),
                    "Type": row["type"], "Long": row["long"], "Short": row["short"], "Contracts": row["qty"],
                    "Net Premium": round(abs(row["net"]), 8), "Flow": row["cash_flow"], "Match": row["match"],
                    } for row in matched]), hide_index=True, width="stretch", row_height=32)
            else:
                st.info("NO MATCHED VERTICAL OPEN/CLOSE EVENTS FOR THE SELECTED TICKERS.")
            pending = [row for row in review if row["ticker"] in selected]
            if pending:
                with st.expander(f"UNPAIRED OPTION LEGS // {len(pending):,} // REVIEW"):
                    st.caption("These legs are excluded from the vertical text. Same expiration alone cannot identify a spread.")
                    st.dataframe(pd.DataFrame([{
                        "Ticker": row["ticker"], "Date": row["when"].strftime("%m/%d/%Y") if row["when"] else "UNKNOWN",
                        "Action": row["action"] or "UNKNOWN", "Expiry": str(row["expiry"] or "UNKNOWN"),
                        "Type": row["type"], "Strike": row["strike"], "Contracts": row["qty"], "Reason": row["reason"],
                    } for row in pending]), hide_index=True, width="stretch", row_height=32)
        elif mode == "BOUGHT + SOLD":
            text = "\n".join(line for line in history_lines if line.partition(" ")[0] in selected)
            st.caption(
                "FORMAT // TICKER MM.DD.YYYY PRICE QTY B/S  |  B = BOUGHT; S = SOLD. "
                "Original recorded trades, including closed positions; limited to the cached history window above."
            )
            missing = sorted(selected - history_symbols)
            if missing:
                st.caption(
                    "NO RECORDED BUY/SELL TRADES // " + ", ".join(missing)
                    + ". Use OPEN LOTS // FIFO for verified surviving lots available above."
                )
        else:
            text = _pine_rows([lot for lot in valid if lot["ticker"] in selected])
            st.caption(
                "FORMAT // TICKER MM.DD.YYYY COST QTY B  |  FIFO from transactions when complete; "
                "E*TRADE LOT = broker-reported surviving lot where older history is missing "
                "(specific-lot selection may differ from FIFO). Closed sales are omitted."
            )
        visible_text = st.text_area(
            "PINE SCRIPT TEXT", value=text,
            height=min(360, max(88, 22 * max(1, len(text.splitlines())))),
            key=f"acquisition_export_{chosen}_{hashlib.sha256(text.encode()).hexdigest()[:12]}",
            label_visibility="collapsed",
        )
        download_col, copy_col, archive_col, _ = st.columns(
            [1.15, 1.15, 2.2, 5.5], gap="small", vertical_alignment="center",
        )
        with download_col:
            st.download_button("DOWNLOAD .TXT", text or "",
                               file_name=("acquisition_verticals.txt" if mode == vertical_mode else
                                          "acquisition_bought_sold.txt" if mode == "BOUGHT + SOLD" else "acquisition_open_fifo.txt"),
                               mime="text/plain", disabled=not bool(text), key="acquisition_download")
        with copy_col:
            _acq_copy(data=visible_text, key="acquisition_copy_pine_button")
        with archive_col:
            # This link targets only the verified PRIVATE plaintext trade
            # blotter; the legacy encrypted backup remains a recovery fallback.
            blotter_url = vault.get("vertical_cache_url" if mode == vertical_mode else "blotter_url", {}).get((str(vault_key), str(chosen)))
            if blotter_url:
                st.link_button(
                    "VIEW GITHUB ARCHIVE", blotter_url,
                    help=("Opens the saved vertical P&L CSV in your private Portfolio GitHub repository." if mode == vertical_mode else
                          "Opens the full historical BUY/SELL share blotter in your private Portfolio GitHub repository."),
                    width="stretch",
                )
            else:
                st.button(
                    "VIEW GITHUB ARCHIVE", disabled=True, key="acquisition_archive_unavailable",
                    help="Readable history available after a successful private GitHub archival sync; "
                         "the existing encrypted recovery archive remains intact.",
                    width="stretch",
                )


