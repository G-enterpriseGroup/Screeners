@st.cache_resource
def _history_vault() -> dict[str, Any]:
    """Reuse complete histories across tabs, reruns and browser sessions of this worker."""
    return {"lock": threading.RLock(), "accounts": {}, "lots": {}}


def _archive_client() -> GitHubAcquisitionArchive | None:
    config = ArchiveConfig.from_runtime()
    return GitHubAcquisitionArchive(config) if config else None


def _archive_snapshot(snapshot: dict[str, Any]) -> dict[str, Any]:
    """Use ISO dates in portable encrypted JSON, never pickle/account data on disk."""
    return {
        "rows": list(snapshot["rows"]),
        "covered_from": snapshot["covered_from"].isoformat(),
        "covered_through": snapshot["covered_through"].isoformat(),
        "synced_at": float(snapshot["synced_at"]),
    }


def _restore_archive(snapshot: dict[str, Any]) -> dict[str, Any]:
    return {
        "rows": list(snapshot["rows"]),
        "covered_from": date.fromisoformat(snapshot["covered_from"]),
        "covered_through": date.fromisoformat(snapshot["covered_through"]),
        "synced_at": float(snapshot.get("synced_at") or 0),
    }


def _identity(tx: dict[str, Any]) -> str:
    identifier = _find(tx, "transactionId")
    if identifier not in (None, ""):
        return str(identifier)
    # Stable identity for a rare transaction lacking E*TRADE's primary key.
    return hashlib.sha256(json.dumps(tx, sort_keys=True, default=str).encode()).hexdigest()


def _option_source_digest(tx):
    return hashlib.sha256(json.dumps({key: value for key, value in tx.items()
                                     if key != "_acquisition_option_detail"},
                                    sort_keys=True, default=str).encode()).hexdigest()


def _merge(old: list[dict[str, Any]], recent: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = {_identity(row): row for row in old if isinstance(row, dict)}
    for row in recent:
        if not isinstance(row, dict):
            continue
        previous = rows.get(_identity(row))
        if (previous and _option_source_digest(previous) == _option_source_digest(row)
                and (not _cached_option_detail(row)
                     or (_option_detail_order(previous) and not _option_detail_order(row)))
                and _cached_option_detail(previous)):
            row = {**row, "_acquisition_option_detail": previous["_acquisition_option_detail"]}
        rows[_identity(row)] = row
    return sorted(rows.values(), key=lambda tx: (_when(tx) or datetime.min.replace(tzinfo=_ET), _identity(tx)))


def _readable_account_identity(account: dict[str, Any]) -> tuple[str, str]:
    name = str(account.get("accountName") or account.get("accountDesc") or
               account.get("accountType") or "E*TRADE Account").strip()
    number = str(account.get("accountId") or "")
    return name or "E*TRADE Account", "".join(c for c in number if c.isdigit())[-4:]


def _private_blotter_digest(saved: dict[str, Any], account: dict[str, Any]) -> str:
    name, last_four = _readable_account_identity(account)
    content = {**_archive_snapshot(saved), "name": name, "last_four": last_four,
               "vertical_algorithm": _VERTICAL_CACHE_VERSION}
    return hashlib.sha256(json.dumps(content, sort_keys=True, default=str).encode()).hexdigest()


def _sync_history(
    client: Any,
    vault_key: str,
    accounts: list[dict[str, Any]],
    *,
    force: bool = False,
    now: datetime | None = None,
) -> tuple[dict[str, dict[str, Any]], dict[str, str]]:
    """Restore encrypted GitHub history first, then query only recent E*TRADE activity.

    No archive update occurs unless a complete broker page scan succeeded.
    A failed GitHub read/write cannot erase an existing snapshot or token.
    """
    today = (now or datetime.now(_ET)).date()
    vault = _history_vault()
    errors: dict[str, str] = {}
    snapshots: dict[str, dict[str, Any]] = {}
    try:
        archive = _archive_client()
    except ArchiveError as exc:
        archive = None
        errors["archive"] = str(exc)
    # The private writer is optional and never blocks legacy encrypted restore.
    # In fixture tests the archive client can be injected without secrets.
    private_config = ArchiveConfig.from_runtime() if archive else None
    private_blotter = PrivateTradeBlotter(private_config) if private_config else None
    # A widget/filter rerun must not perform a GitHub metadata request. Keep
    # fresh private verification for actual restore/publish work only.
    with vault["lock"]:
        private_work = False
        for account in accounts:
            key = str(account.get("accountIdKey") or "").strip()
            if not key:
                continue
            scope = (str(vault_key), key)
            saved = vault["accounts"].get(scope)
            retry = vault.get("blotter_retry_at", {}).get(scope, 0)
            detail_work = (saved is not None and _option_detail_getter(client) is not None
                           and not bool(getattr(client, "is_offline", False))
                           and time.time() >= vault.get("option_detail_retry_at", {}).get(scope, 0)
                           and any(_needs_option_detail(row) for row in saved["rows"]))
            private_work |= (scope not in vault.get("private_loaded", set()) or force or
                             detail_work or
                             (saved is not None and (time.time() >= retry) and (
                                 scope not in vault.get("archive_loaded", set()) or
                                 time.time() - float(saved.get("synced_at", 0)) >= _SYNC_SECONDS or
                                 _private_blotter_digest(saved, account) != vault.get("blotter_digest", {}).get(scope) or
                                 bool(vault.get("vertical_cache_error", {}).get(scope)))))
    if not private_work:
        private_blotter = None
    if private_blotter is not None:
        # One credential preflight for the ENTIRE account batch. GitHub uses
        # HTTP 404 when a PAT cannot see a private repository. Do not retry
        # that same unauthorized request for every linked E*TRADE account.
        try:
            private_blotter._verify_private()
        except ArchiveError as exc:
            errors["blotter"] = str(exc)
            private_blotter = None
    with vault["lock"]:
        vault["archive_configured"] = archive is not None
        for account in accounts:
            key = str(account.get("accountIdKey") or "").strip()
            if not key:
                continue
            scope = (str(vault_key), key)
            saved = vault["accounts"].get(scope)
            private_ready = True
            # Restore full saved private history BEFORE querying E*TRADE. This
            # protects older-than-two-year executions if encrypted history
            # or process memory is incomplete after a restart/redeploy.
            private_loaded = vault.setdefault("private_loaded", set())
            if private_blotter is not None and scope not in private_loaded:
                try:
                    historical = private_blotter.read_snapshot(key, preverified=True)
                    if historical is not None:
                        recovered = {
                            "rows": list(historical["rows"]),
                            "covered_from": date.fromisoformat(historical["covered_from"]),
                            "covered_through": date.fromisoformat(historical["covered_through"]),
                            "synced_at": float(historical.get("synced_at") or 0),
                        }
                        if saved is not None:
                            recovered["rows"] = _merge(recovered["rows"], saved["rows"])
                            recovered["covered_from"] = min(recovered["covered_from"], saved["covered_from"])
                            recovered["covered_through"] = max(recovered["covered_through"], saved["covered_through"])
                            recovered["synced_at"] = float(saved["synced_at"])
                        saved = recovered
                        vault["accounts"][scope] = saved
                        if archive is not None:
                            vault.setdefault("archive_dirty", {})[scope] = True
                    private_loaded.add(scope)
                except (ArchiveError, ValueError, KeyError, TypeError):
                    # Never upload a reduced two-year ledger when the private
                    # lifetime history was unreadable: preserve remote intact.
                    private_ready = False
                    errors[key] = "PRIVATE GITHUB HISTORY RESTORE FAILED — archived trades untouched."
            loaded = vault.setdefault("archive_loaded", set())
            eligible = archive is not None
            if archive is not None and scope not in loaded:
                if not force and time.time() < vault.setdefault("archive_retry_at", {}).get(scope, 0):
                    eligible = False  # Rate-limit failed restore attempts.
                else:
                    try:
                        remote = archive.read(key)
                        if remote is not None:
                            vault.setdefault("archive_exists", {})[scope] = True
                            recovered = _restore_archive(remote)
                            if saved is not None:
                                # Prefer the more recent durable transaction
                                # correction on duplicate IDs; never discard older
                                # records found in either history source.
                                if float(saved.get("synced_at", 0)) > float(recovered.get("synced_at", 0)):
                                    recovered["rows"] = _merge(recovered["rows"], saved["rows"])
                                else:
                                    recovered["rows"] = _merge(saved["rows"], recovered["rows"])
                                recovered["covered_from"] = min(recovered["covered_from"], saved["covered_from"])
                                recovered["covered_through"] = max(recovered["covered_through"], saved["covered_through"])
                                recovered["synced_at"] = max(recovered["synced_at"], saved["synced_at"])
                            saved = recovered
                            vault["accounts"][scope] = saved
                        else:
                            vault.setdefault("archive_exists", {})[scope] = False
                        if remote is None and saved is not None:
                            # Archive was newly enabled on an existing worker:
                            # seed the saved in-memory ledger even without fresh trades.
                            vault.setdefault("archive_dirty", {})[scope] = True
                        loaded.add(scope)
                        vault.setdefault("archive_dirty", {}).setdefault(scope, False)
                        vault.setdefault("archive_retry_at", {}).pop(scope, None)
                    except (ArchiveError, ValueError):
                        eligible = False
                        vault.setdefault("archive_retry_at", {})[scope] = time.time() + 300
                        errors[key] = "GITHUB RESTORE FAILED — history remains in memory; no remote overwrite."
            elif archive is None:
                eligible = False

            live = client is not None and not bool(getattr(client, "is_offline", False))
            needs_sync = live and private_ready and not (
                archive is not None and not eligible and saved is None
            ) and (
                saved is None or force or time.time() - float(saved.get("synced_at", 0)) >= _SYNC_SECONDS
            )
            if needs_sync:
                if saved:
                    start = max(today - timedelta(days=_HISTORY_DAYS),
                                min(today, saved["covered_through"]) - timedelta(days=_OVERLAP_DAYS))
                else:
                    start = today - timedelta(days=_HISTORY_DAYS)
                try:
                    fresh = client.get_transactions(key, start_date=start, end_date=today, sort_order="ASC")
                    if not isinstance(fresh, list):
                        raise ValueError("E*TRADE did not return a transaction list.")
                    saved = {
                        "rows": _merge((saved or {}).get("rows", []), fresh),
                        "covered_from": (saved or {}).get("covered_from", start),
                        "covered_through": today,
                        "synced_at": time.time(),
                    }
                    vault["accounts"][scope] = saved
                    vault.setdefault("archive_dirty", {})[scope] = True
                except Exception as exc:
                    errors[key] = str(exc)[:240]

            detail_retry = vault.setdefault("option_detail_retry_at", {}).get(scope, 0)
            if live and private_ready and saved is not None and (force or time.time() >= detail_retry):
                detailed, detail_error = _hydrate_option_details(client, key, saved["rows"], force=force)
                if detailed != saved["rows"]:
                    saved = {**saved, "rows": detailed}
                    vault["accounts"][scope] = saved
                    vault.setdefault("archive_dirty", {})[scope] = True
                if detail_error:
                    vault["option_detail_retry_at"][scope] = time.time() + 1800
                    vault.setdefault("option_detail_error", {})[scope] = detail_error
                else:
                    vault["option_detail_retry_at"].pop(scope, None)
                    vault.setdefault("option_detail_error", {}).pop(scope, None)

            dirty = vault.setdefault("archive_dirty", {}).get(scope, False)
            next_retry = vault.setdefault("archive_retry_at", {}).get(scope, 0)
            if archive is not None and eligible and saved is not None and dirty and (force or time.time() >= next_retry):
                try:
                    merged = archive.save(key, _archive_snapshot(saved), _merge)
                    saved = _restore_archive(merged)
                    vault["accounts"][scope] = saved
                    vault["archive_dirty"][scope] = False
                    vault.setdefault("archive_verified_at", {})[scope] = time.time()
                    vault.setdefault("archive_exists", {})[scope] = True
                    vault["archive_retry_at"].pop(scope, None)
                except ArchiveError:
                    errors[key] = "GITHUB BACKUP FAILED — in-memory history retained; retry later."
                    vault["archive_retry_at"][scope] = time.time() + 300
            if saved and private_blotter is not None and private_ready:
                # Private plaintext historical blotter, isolated from public
                # code repo. Skip repeat GitHub requests for unchanged history.
                name, last_four = _readable_account_identity(account)
                source = _vertical_source_fingerprint(saved["rows"])
                if vault.setdefault("vertical_loaded", {}).get(scope) != _VERTICAL_CACHE_VERSION:
                    try:
                        cached = private_blotter.read_vertical_cache(key, preverified=True)
                        if _valid_vertical_cache(cached, source):
                            vault.setdefault("vertical_cache", {})[scope] = cached
                            vault.setdefault("vertical_cache_saved", {})[scope] = source
                    except ArchiveError:
                        vault.setdefault("vertical_cache_error", {})[scope] = "Saved vertical cache unavailable; rebuilding from preserved raw history."
                    vault["vertical_loaded"][scope] = _VERTICAL_CACHE_VERSION
                digest = _private_blotter_digest(saved, account)
                previous = vault.setdefault("blotter_digest", {}).get(scope)
                retry_at = vault.setdefault("blotter_retry_at", {}).get(scope, 0)
                if (digest != previous or vault.get("vertical_cache_error", {}).get(scope)) and (force or time.time() >= retry_at):
                    try:
                        readable_snapshot = _archive_snapshot(saved)
                        readable_snapshot.update(account_name=name, account_last_four=last_four)
                        url = private_blotter.save(
                            key, readable_snapshot, _merge, _equity_trade,
                            build_verticals=lambda rows: _cached_verticals(rows, vault_key, key),
                        )
                        canonical = getattr(private_blotter, "canonical_snapshot", None)
                        if isinstance(canonical, dict) and canonical.get("account") == key:
                            saved = _restore_archive(canonical)
                            vault["accounts"][scope] = saved
                            canonical_source = _vertical_source_fingerprint(saved["rows"])
                            if canonical_source != source and archive is not None:
                                vault["archive_dirty"][scope] = True
                            source = canonical_source
                            digest = _private_blotter_digest(saved, account)
                        vault["blotter_digest"][scope] = digest
                        vault.setdefault("blotter_url", {})[scope] = url
                        vault["blotter_retry_at"].pop(scope, None)
                        vertical_error = getattr(private_blotter, "vertical_error", "")
                        if vertical_error:
                            vault.setdefault("vertical_cache_error", {})[scope] = vertical_error
                            vault["blotter_retry_at"][scope] = time.time() + 300
                        else:
                            published = getattr(private_blotter, "vertical_payload", None)
                            if _valid_vertical_cache(published, source):
                                vault.setdefault("vertical_cache", {})[scope] = published
                                vault.setdefault("vertical_cache_saved", {})[scope] = source
                                vault.setdefault("vertical_cache_url", {})[scope] = url.rsplit("/", 1)[0] + "/vertical_blotter.csv"
                            vault.setdefault("vertical_cache_error", {}).pop(scope, None)
                    except ArchiveError as exc:
                        errors[key] = "PRIVATE GITHUB BLOTTER NOT UPDATED // " + str(exc)
                        vault["blotter_retry_at"][scope] = time.time() + 300
            if saved:
                snapshots[key] = {
                    "rows": list(saved["rows"]),
                    "covered_from": saved["covered_from"],
                    "covered_through": saved["covered_through"],
                    "synced_at": saved["synced_at"],
                }
    return snapshots, errors

