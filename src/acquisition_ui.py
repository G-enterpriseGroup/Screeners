def _account_label(account: dict[str, Any]) -> str:
    name = str(account.get("accountName") or account.get("accountDesc") or account.get("accountType") or "ACCOUNT").strip()
    digits = str(account.get("accountId") or "").strip()
    return f"{name} // ••••{digits[-4:]}" if digits else name


def _default_account(accounts: list[dict[str, Any]]) -> str:
    for account in accounts:
        description = " ".join(str(account.get(field) or "") for field in ("accountName", "accountDesc")).lower()
        if "raj" in description:
            return str(account["accountIdKey"])
    for account in accounts:
        if str(account.get("accountId") or "").endswith("5474"):
            return str(account["accountIdKey"])
    return str(accounts[0]["accountIdKey"])


def render_acquisition(
    client: Any,
    *,
    vault_key: str,
    refresh_accounts: Callable[[Any], list[dict[str, Any]]] | None = None,
    touch_session: Callable[[], Any] | None = None,
) -> None:
    """Render compact Risk Sizing-themed, strictly read-only Acquisition workspace."""
    st.html(_CSS)
    with st.container(key="acquisition_root", gap=None):
        accounts = [row for row in (st.session_state.get("etrade_accounts") or [])
                    if isinstance(row, dict) and row.get("accountIdKey")]
        if not accounts and client is not None and refresh_accounts:
            try:
                accounts = refresh_accounts(client)
            except Exception as exc:
                st.warning(f"E*TRADE ACCOUNTS UNAVAILABLE // {exc}")
                return
        accounts = [row for row in accounts if isinstance(row, dict) and row.get("accountIdKey")]
        if not accounts:
            st.info("CONNECT E*TRADE TO LOAD ACQUISITION HISTORY.")
            return
        by_key = {str(row["accountIdKey"]): row for row in accounts}
        picker_key = "acquisition_account_key"
        if str(st.session_state.get(picker_key) or "") not in by_key:
            st.session_state[picker_key] = _default_account(accounts)

        left, right = st.columns([5, 1.65], gap="small", vertical_alignment="bottom")
        with left:
            chosen = st.selectbox("E*TRADE ACCOUNT", list(by_key), key=picker_key,
                                  format_func=lambda key: _account_label(by_key[key]))
        with right:
            sync = st.button("SYNC NEW TRADES", type="primary", width="stretch",
                             key="acquisition_sync", disabled=client is None or bool(getattr(client, "is_offline", False)))

        with st.spinner("Reading cached share history / syncing only new transactions..."):
            snapshots, errors = _sync_history(client, vault_key, accounts, force=sync)
        if touch_session and client is not None and not bool(getattr(client, "is_offline", False)):
            touch_session()
        if errors:
            st.warning("HISTORY SYNC INCOMPLETE // " + "; ".join(
                f"{_account_label(by_key[key])}: {message}" for key, message in errors.items() if key in by_key))
        saved = snapshots.get(chosen)
        if not saved:
            st.info("NO CACHED TRANSACTIONS FOR THIS ACCOUNT. CONNECT E*TRADE AND SYNC.")
            return
        if client is None:
            st.warning("E*TRADE OFFLINE // cached trades may not match current holdings.")
            return
        try:
            portfolio = client.get_portfolio(chosen, force_refresh=sync)
        except TypeError:
            portfolio = client.get_portfolio(chosen)
        except Exception as exc:
            st.warning(f"CURRENT HOLDINGS UNAVAILABLE // {exc}")
            return
        if not isinstance(portfolio, list):
            st.warning("CURRENT HOLDINGS COULD NOT BE VERIFIED.")
            return
        valid, gaps = _reconcile(saved["rows"], portfolio)
        recovered, gaps = _recover_lots(client, vault_key, chosen, portfolio, gaps, force=sync)
        valid.extend(recovered)
        valid.sort(key=lambda lot: (lot["ticker"], lot["date"], lot["id"]))
        text = _pine_rows(valid)
        covered = saved["covered_from"]
        through = saved["covered_through"]
        st.html(
            '<div class="acq-status">'
            f'FIFO // {len(valid):,} VERIFIED OPEN BUY LOTS // '
            f'{len(gaps):,} UNRECONCILED SYMBOLS // {len(saved["rows"]):,} CACHED TRANSACTIONS // '
            f'HISTORY WINDOW {covered:%m/%d/%Y} – {through:%m/%d/%Y} // '
            'E*TRADE TAX LOT RECOVERY // PROCESS CACHE // SYNC: 7-DAY OVERLAP'
            '</div>'
        )
        st.html('<div class="acq-section">OPEN EQUITY ACQUISITIONS // FIFO</div>')
        if valid:
            frame = pd.DataFrame([{
                "Ticker": lot["ticker"], "Acquired": lot["date"].strftime("%m/%d/%Y"),
                "Share Cost": round(lot["cost"], 4), "Open Shares": round(lot["qty"], 8),
                "Source": lot.get("source", "TRANSACTION FIFO"),
            } for lot in valid])
            st.dataframe(frame, hide_index=True, width="stretch", row_height=32)
        else:
            st.info("NO VERIFIED OPEN EQUITY LOTS FOUND IN THIS ACCOUNT.")
        if gaps:
            st.warning(
                "UNVERIFIED LOTS EXCLUDED FROM EXPORT. Older than two years, transfers, "
                "splits, reinvestments, or missing API records can cause gaps. "
                "Do not rely on FIFO for these positions until older history is reconciled."
            )
            st.dataframe(pd.DataFrame(gaps), hide_index=True, width="stretch", row_height=32)
        st.html('<div class="acq-section">COPY INTO TRADINGVIEW PINE SCRIPT</div>')
        st.caption("FORMAT // TICKER MM.DD.YYYY COST QTY B  |  Each line is the remaining unsold portion of a BUY; closed shares are omitted.")
        st.text_area(
            "PINE SCRIPT TEXT", value=text,
            height=min(360, max(88, 22 * max(1, len(valid)))),
            key=f"acquisition_export_{chosen}_{hashlib.sha256(text.encode()).hexdigest()[:12]}",
            label_visibility="collapsed",
        )
        st.download_button("DOWNLOAD .TXT", text or "", file_name="acquisition_open_fifo.txt",
                           mime="text/plain", disabled=not bool(text), key="acquisition_download")


