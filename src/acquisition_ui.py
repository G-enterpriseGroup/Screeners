def _option_detail_matches(tx, response):
    """A detail lookup may prove an order only for the exact source execution."""
    try:
        detail = response.get("TransactionDetailsResponse", response)
        if not isinstance(detail, dict) or str(detail.get("transactionId")) != str(tx.get("transactionId")):
            return False
        account = str(_find(tx, "accountId", "accountIdKey") or "")
        if not account or str(_find(detail, "accountId", "accountIdKey") or "") != account:
            return False
        when, other = _when({"transactionDate": tx.get("transactionDate")}), _when({"transactionDate": detail.get("transactionDate")})
        if when is None or other is None or when != other:
            return False
        broker, confirmed = _find(tx, "brokerage") or {}, _find(detail, "brokerage") or {}
        product, actual = _find(broker, "product") or {}, _find(confirmed, "product") or {}
        if not isinstance(product, dict) or not isinstance(actual, dict):
            return False
        for field in ("symbol", "securityType", "callPut", "optionRootSymbol", "rootSymbol", "securitySubType"):
            value = str(product.get(field) or "").strip().upper()
            if (field in {"symbol", "securityType", "callPut"} or value) and value != str(actual.get(field) or "").strip().upper():
                return False
        for field in ("expiryYear", "expiryMonth", "expiryDay", "strikePrice"):
            values = [product.get(field), actual.get(field)]
            if any(value is None or isinstance(value, bool) for value in values):
                return False
            values = list(map(float, values))
            if field == "expiryYear":
                values = [value + 2000 if 0 <= value < 100 else value for value in values]
            if not all(math.isfinite(value) for value in values) or values[0] != values[1]:
                return False
        for field in ("quantity", "price", "amount", "optionMultiplier", "multiplier"):
            left, right = _find(tx, field), _find(detail, field)
            if left is None and field not in {"quantity", "price", "amount"}:
                continue
            if left is None or right is None or isinstance(left, bool) or isinstance(right, bool):
                return False
            left, right = float(left), float(right)
            if not math.isfinite(left) or not math.isfinite(right) or left != right:
                return False
        for field in ("settlementCurrency", "paymentCurrency"):
            value = str(_find(broker, field) or _find(broker, "currency") or "").upper()
            if not value or value != str(_find(confirmed, field) or _find(confirmed, "currency") or "").upper():
                return False
        def actions(row):
            broker = _find(row, "brokerage") or row
            names = {re.sub(r"[^A-Z]", "", str(source.get(field) or "").upper())
                     for source in (row, broker) for field in ("transactionType", "orderAction", "transactionShortDesc")}
            if any(re.search(r"REVERSE|REVERSAL|CANCEL|EXERCIS|ASSIGN|EXPIR", name) for name in names):
                return set()
            return {_OPTION_ACTION_ALIASES[name] for name in names if name in _OPTION_ACTION_ALIASES}
        source_actions, detail_actions = actions(tx), actions(detail)
        if len(source_actions) != 1 or (detail_actions and detail_actions != source_actions):
            return False
        for source in (tx, broker, detail, confirmed):
            for field in ("transactionType", "orderAction", "transactionShortDesc"):
                raw = re.sub(r"[^A-Z]", "", str(source.get(field) or "").upper())
                if re.search(r"REVERSE|REVERSAL|CANCEL|EXERCIS|ASSIGN|EXPIR", raw):
                    return False
                if raw in {"BUY", "BOUGHT", "SELL", "SOLD"} and ((raw in {"BUY", "BOUGHT"}) != (next(iter(source_actions)) in {"BTO", "BTC"})):
                    return False
        for source, contract in ((tx, product), (detail, actual)):
            root = str(_find(contract, "optionRootSymbol", "rootSymbol") or contract.get("symbol") or "").upper()
            year = int(contract["expiryYear"])
            expiry = date(year + 2000 if 0 <= year < 100 else year, int(contract["expiryMonth"]), int(contract["expiryDay"]))
            for value in (_find(source, "osiKey"), _find(source, "osiSymbol"),
                          _find(_find(contract, "productId") or {}, "symbol")):
                osi = str(value or "").upper().replace(" ", "")
                if osi in {"", root, str(contract.get("symbol") or "").upper()}:
                    continue
                identity = re.fullmatch(r"([A-Z][A-Z0-9.]*?)-{0,5}(\d{6})([CP])(\d{8})", osi)
                if (identity is None or identity[1] != root or identity[2] != expiry.strftime("%y%m%d")
                        or identity[3] != str(contract["callPut"])[0].upper()
                        or int(identity[4]) / 1000 != float(contract["strikePrice"])):
                    return False
        for field in ("contract_context", "optionsAdjustedFlag"):
            if tx.get(field) is not None and detail.get(field) is not None and tx[field] != detail[field]:
                return False
        for field in ("reversalFlag", "isReversal", "reversed", "optionsAdjustedFlag"):
            if any(str(_find(row, field) or "").lower() in {"true", "1", "yes", "y"} for row in (tx, detail)):
                return False
        return True
    except (AttributeError, TypeError, ValueError, OverflowError):
        return False


def _cached_option_detail(tx):
    metadata = tx.get("_acquisition_option_detail")
    try:
        if not isinstance(metadata, dict) or metadata.get("base_digest") != _option_source_digest(tx):
            return None
        response = json.loads(metadata["payload_json"])
        return response if _option_detail_matches(tx, response) else None
    except (KeyError, TypeError, ValueError):
        return None


def _option_detail_order(tx):
    response = _cached_option_detail(tx)
    if response is None:
        return ""
    detail = response.get("TransactionDetailsResponse", response)
    value = _find(_find(detail, "brokerage") or detail, "orderNo", "orderId", "orderNumber")
    order = str(value or "").strip()
    return order if not isinstance(value, bool) and re.fullmatch(r"[0-9]+", order) and int(order) > 0 else ""


def _needs_option_detail(tx, force=False):
    if not isinstance(tx, dict) or isinstance(tx.get("transactionDate"), bool):
        return False
    product = _find(tx, "product") or {}
    broker = _find(tx, "brokerage") or tx
    if not isinstance(product, dict) or not isinstance(broker, dict):
        return False
    if str(_find(product, "securityType", "typeCode") or "").upper() not in {"OPTN", "OPTION", "OPTIONS", "EQUITY_OPTION"}:
        return False
    names = {re.sub(r"[^A-Z]", "", str(source.get(field) or "").upper())
             for source in (tx, broker) for field in ("transactionType", "orderAction", "transactionShortDesc")}
    order = str(_find(broker, "orderNo", "orderId", "orderNumber") or "").strip()
    identifier, store = str(tx.get("transactionId") or ""), tx.get("storeId", 0)
    return (any(name in _OPTION_ACTION_ALIASES for name in names)
            and not any(re.search(r"REVERSE|REVERSAL|CANCEL|EXERCIS|ASSIGN|EXPIR", name) for name in names)
            and (not order or re.fullmatch(r"0+(?:\.0+)?", order) is not None)
            and not (_cached_option_detail(tx) is not None and (not force or _option_detail_order(tx)))
            and re.fullmatch(r"[0-9]+", identifier) is not None and int(identifier) > 0
            and not isinstance(store, bool) and isinstance(store, int) and store >= 0)


def _option_detail_getter(client):
    try:
        getter = getattr(client, "get_transaction_details", None)
        return getter if callable(getter) else None
    except (AttributeError, AssertionError):
        return None


def _hydrate_option_details(client, account, rows, *, force=False):
    """Read and retain order evidence once; filters never enter this sync path."""
    getter = _option_detail_getter(client)
    if getter is None or bool(getattr(client, "is_offline", False)):
        return rows, ""
    output = list(rows)
    # Retained older executions may have aged out of the broker detail window.
    # Verify recent activity first so one such failure cannot starve new trades.
    ordered = sorted(enumerate(rows), key=lambda item: _when(item[1]) or datetime.min.replace(tzinfo=_ET), reverse=True)
    for index, tx in ordered:
        if not _needs_option_detail(tx, force):
            continue
        identifier = str(tx.get("transactionId") or "")
        try:
            store = tx.get("storeId", 0)
            response = getter(account, identifier, store_id=store)
            if not _option_detail_matches(tx, response):
                return output, "Option order verification returned a different or incomplete execution; cash history retained."
            # Opaque JSON prevents recursive legacy field lookup from consuming proof fields.
            output[index] = {**tx, "_acquisition_option_detail": {
                "base_digest": _option_source_digest(tx), "payload_json": json.dumps(response, sort_keys=True)}}
        except Exception:
            return output, "Option order verification is temporarily unavailable; cached cash history and prior evidence retained."
    return output, ""


def _settled_option_rows(transactions, aliases):
    """Prefer a unique settled execution over its provisional cash-identical alias.

    Keep the raw ledger intact. Pending fees/timestamps/IDs can change on posting;
    contract, account, trade day, direction, signed quantity, price and cash cannot.
    """
    pending, settled = defaultdict(list), defaultdict(list)
    for tx in transactions:
        try:
            product = _find(tx, "product") or _find(tx, "productId") or {}
            if not isinstance(product, dict) or str(_find(product, "securityType", "typeCode") or "").upper() not in {
                    "OPTN", "OPTION", "OPTIONS", "EQUITY_OPTION"}:
                continue
            broker = _find(tx, "brokerage") or tx
            if not isinstance(broker, dict):
                continue
            when = _when({"transactionDate": _find(tx, "transactionDate")})
            account = str(_find(tx, "accountId", "accountIdKey") or "").strip()
            numbers = [_find(broker, "quantity"), _find(broker, "price"), _find(tx, "amount"),
                       _find(tx, "postDate"), _find(broker, "settlementDate")]
            if any(value is None or isinstance(value, bool) for value in numbers):
                continue
            quantity, price, cash, posted, settlement = map(float, numbers)
            if (not account or when is None or not all(math.isfinite(value) for value in (
                    quantity, price, cash, posted, settlement)) or not quantity or not abs(quantity).is_integer()
                    or price < 0 or posted < 0 or settlement < 0):
                continue
            currency = tuple(str(_find(broker, field) or _find(broker, "currency") or "").upper()
                             for field in ("settlementCurrency", "paymentCurrency"))
            if not all(currency) or currency[0] != currency[1]:
                continue
            if any(str(_find(tx, field) or "").lower() in {"true", "1", "yes", "y"}
                   for field in ("reversalFlag", "isReversal", "reversed", "optionsAdjustedFlag")):
                continue
            if any(re.search(r"REVERSE|REVERSAL|CANCEL|EXERCIS|ASSIGN|" +
                             (r"EXPIRED|EXPIRATION" if field in {"description", "transactionDescription"} else r"EXPIR"),
                             re.sub(r"[^A-Z]", "", str(source.get(field) or "").upper()))
                   for source in (tx, broker)
                   for field in ("transactionType", "orderAction", "transactionShortDesc", "description", "transactionDescription")):
                continue
            actions = {aliases[normalized] for source in (broker, tx)
                       for field in ("orderAction", "transactionType", "transactionShortDesc")
                       if (normalized := re.sub(r"[^A-Z]", "", str(_find(source, field) or "").upper())) in aliases}
            raw = re.sub(r"[^A-Z]", "", str(tx.get("transactionType") or broker.get("transactionType") or "").upper())
            description = str(tx.get("description") or "").upper()
            if len(actions) == 1 and posted > 0 and settlement > 0:
                action = next(iter(actions))
                target = settled
            elif not actions and raw in {"BOUGHT", "BUY", "SOLD", "SELL"} and posted == settlement == 0:
                phase = re.search(r"\b(OPENING|CLOSING)\s*$", description)
                if not phase:
                    continue
                buying = raw in {"BOUGHT", "BUY"}
                action = ("BTO" if buying else "STO") if phase[1] == "OPENING" else ("BTC" if buying else "STC")
                target = pending
            else:
                continue
            if (quantity > 0) != (action in {"BTO", "BTC"}):
                continue
            # Product JSON retains every supplied root/adjustment/context field.
            key = (account, when.date(), json.dumps(product, sort_keys=True, default=str),
                   action, quantity, price, cash, currency,
                   str(_find(broker, "optionMultiplier", "multiplier") or ""),
                   str(_find(broker, "orderNo", "orderId", "orderNumber") or ""),
                   tuple(str(_find(tx, field) or "").upper().replace(" ", "") for field in ("osiKey", "osiSymbol")),
                   json.dumps(tx.get("contract_context"), sort_keys=True, default=str))
            target[key].append(tx)
        except (TypeError, ValueError, OverflowError):
            continue
    superseded, provenance = set(), {}
    for key, candidates in pending.items():
        matches = settled.get(key, [])
        if len(candidates) == len(matches) == 1 and _identity(candidates[0]) != _identity(matches[0]):
            identifier = _identity(candidates[0])
            superseded.add(identifier)
            provenance[_identity(matches[0])] = [identifier]
    return [tx for tx in transactions if _identity(tx) not in superseded], provenance


def _vertical_history(transactions: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Pair recorded option executions; never infer a position's lifetime P&L.

    A shared order is preferred. An exact intraday timestamp is weaker evidence
    and is explicitly labeled inferred; a shared date/expiration is insufficient.
    """
    aliases = _OPTION_ACTION_ALIASES
    groups: dict[tuple[Any, ...], list[dict[str, Any]]] = defaultdict(list)
    blocked = set()
    blocked_orders = set()
    review = []
    def expiry(product):
        values = [_find(product, field) for field in ("expiryYear", "expiryMonth", "expiryDay")]
        if any(isinstance(value, bool) for value in values):
            raise ValueError("Invalid option expiration")
        year, month, day = map(int, values)
        # Transaction history can contain OSI-style two-digit years even
        # though the documented Product schema specifies four digits.
        return date(year + 2000 if 0 <= year < 100 else year, month, day)
    rows = {_identity(tx): tx for tx in transactions if isinstance(tx, dict)}
    executions, superseded = _settled_option_rows(list(rows.values()), aliases)
    # A partial detail lookup must not split a previously valid timestamp pair.
    cohorts = defaultdict(list)
    for tx in executions:
        product = _find(tx, "product") or {}
        if str(_find(product, "securityType", "typeCode") or "").upper() in {"OPTN", "OPTION", "OPTIONS", "EQUITY_OPTION"}:
            broker = _find(tx, "brokerage") or tx
            raw_order = str(_find(broker, "orderNo", "orderId", "orderNumber") or "").strip()
            if re.fullmatch(r"0+(?:\.0+)?", raw_order):
                raw_order = ""
            cohorts[(str(_find(tx, "accountId", "accountIdKey") or ""),
                     _when({"transactionDate": _find(tx, "transactionDate")}))].append((tx, raw_order, _option_detail_order(tx)))
    ready_orders = {_identity(tx): proof for cohort in cohorts.values() if all(raw or proof for _, raw, proof in cohort)
                    for tx, _, proof in cohort if proof}
    for tx in executions:
        product = _find(tx, "product") or _find(tx, "productId") or {}
        if not isinstance(product, dict):
            continue
        security = str(_find(product, "securityType", "typeCode") or "").upper()
        if security not in {"OPTN", "OPTION", "OPTIONS", "EQUITY_OPTION"}:
            continue
        broker = _find(tx, "brokerage") or tx
        ticker = str(_find(product, "symbol") or "UNKNOWN").strip().upper()
        when = _when({"transactionDate": _find(tx, "transactionDate")})
        order = str(_find(broker, "orderNo", "orderId", "orderNumber") or "").strip()
        if re.fullmatch(r"0+(?:\.0+)?", order):
            order = ""
        detail_order = _option_detail_order(tx)
        if not order:
            order = ready_orders.get(_identity(tx), "")
        account = str(_find(tx, "accountId", "accountIdKey") or "")
        bucket = (account, when.date() if when else None, order) if order else (account, when)
        leg = {"ticker": ticker, "when": when, "expiry": None,
               "type": str(_find(product, "callPut") or "").upper(),
               "strike": None, "qty": None, "action": "", "order": order,
               "account": account, "root": str(_find(product, "optionRootSymbol", "rootSymbol") or "").upper()}
        # Preserve contract context even for an assignment/unpaired leg, so it
        # can interrupt an otherwise misleading later round-trip P&L match.
        try:
            leg["expiry"] = expiry(product)
            leg["strike"] = float(_find(product, "strikePrice"))
        except (TypeError, ValueError, OverflowError):
            pass
        try:
            if isinstance(_find(tx, "transactionDate"), bool) or isinstance(_find(broker, "orderNo", "orderId", "orderNumber"), bool):
                raise ValueError("Invalid execution date or order reference")
            if detail_order and order and detail_order != order:
                raise ValueError("Transaction list and broker detail order references conflict")
            if any(str(_find(tx, field) or "").lower() in {"true", "1", "yes", "y"}
                   for field in ("reversalFlag", "isReversal", "reversed")):
                raise ValueError("Reversed option transaction requires review")
            disposition = {re.sub(r"[^A-Z]", "", str(_find(source, field) or "").upper())
                           for source in (broker, tx) for field in ("transactionType", "transactionShortDesc")}
            is_expiry = bool(disposition & {"OPTIONEXPIRED", "OPTIONEXPIRATION", "EXPIRATION", "EXPIRED"})
            found = set()
            for source in (broker, tx):
                for field in ("orderAction", "transactionType", "transactionShortDesc", "description", "transactionDescription"):
                    raw = str(_find(source, field) or "").upper()
                    if field in {"transactionType", "transactionShortDesc"} and re.search(r"\b(?:EXERCIS\w*|ASSIGN\w*)", raw):
                        raise ValueError("Exercise, assignment or expiration is not a paired cash close")
                    if field in {"transactionType", "transactionShortDesc"} and re.search(r"\bEXPIR\w*", raw) and not is_expiry:
                        raise ValueError("Ambiguous option expiration requires review")
                    if re.search(r"\b(?:REVERSE\w*|REVERSAL|CANCEL\w*)\b", raw):
                        raise ValueError("Reversed or canceled option transaction requires review")
                    action = aliases.get(re.sub(r"[^A-Z]", "", raw))
                    if action:
                        found.add(action)
                    for phrase in re.findall(r"\b(?:BUY|BOUGHT|SELL|SOLD)[ _-]+(?:TO[ _-]+)?(?:OPEN|CLOSE)\b", raw):
                        if action := aliases.get(re.sub(r"[^A-Z]", "", phrase)):
                            found.add(action)
            if is_expiry and found:
                raise ValueError("Expiration conflicts with an opening or closing trade action")
            if not is_expiry and len(found) != 1:
                raise ValueError("Explicit buy/sell TO OPEN or TO CLOSE is missing or conflicting")
            leg["action"] = "EXPIRATION" if is_expiry else found.pop()
            leg["expiry"] = expiry(product)
            raw_numbers = (_find(product, "strikePrice"), _find(broker, "quantity"), _find(broker, "price"))
            if any(isinstance(value, bool) for value in raw_numbers):
                raise ValueError("Invalid option execution numbers")
            leg["strike"], quantity, price = map(float, raw_numbers)
            leg["qty"] = abs(quantity)
            if (not re.fullmatch(r"[A-Z][A-Z0-9.^/-]{0,20}", ticker)
                    or leg["type"] not in {"CALL", "PUT"} or when is None
                    or not math.isfinite(leg["strike"]) or leg["strike"] <= 0
                    or not math.isfinite(leg["qty"]) or leg["qty"] <= 0 or not leg["qty"].is_integer()
                    or not math.isfinite(price) or price < 0):
                raise ValueError("Incomplete option contract, execution date, quantity or premium")
            root = str(_find(product, "optionRootSymbol", "rootSymbol") or ticker).upper()
            product_id_symbol = str(_find(_find(product, "productId") or {}, "symbol") or "").upper().replace(" ", "")
            roots = set()
            for raw_osi in (_find(tx, "osiKey"), _find(tx, "osiSymbol"), product_id_symbol):
                osi = str(raw_osi or "").upper().replace(" ", "")
                if osi in {"", ticker, root}:
                    continue
                identity = re.fullmatch(r"([A-Z][A-Z0-9.]*?)-{0,5}(\d{6})([CP])(\d{8})", osi)
                if (identity is None or identity[2] != leg["expiry"].strftime("%y%m%d")
                        or identity[3] != leg["type"][0] or int(identity[4]) / 1000 != leg["strike"]
                        or (_find(product, "optionRootSymbol", "rootSymbol") and identity[1] != root)):
                    raise ValueError("Option symbol conflicts with the recorded contract")
                roots.add(identity[1])
            if len(roots) > 1:
                raise ValueError("Conflicting option contract roots")
            if roots:
                root = roots.pop()
            adjusted = str(_find(tx, "optionsAdjustedFlag") or "false").lower()
            if adjusted not in {"false", "0", "n", "no"}:
                raise ValueError("Adjusted contract requires review")
            multiplier = _find(broker, "optionMultiplier", "multiplier")
            if multiplier is not None:
                if isinstance(multiplier, bool):
                    raise ValueError("Invalid contract multiplier")
                multiplier = float(multiplier)
                if not math.isfinite(multiplier) or multiplier <= 0:
                    raise ValueError("Invalid contract multiplier")
            currency = tuple(str(_find(broker, field) or _find(broker, "currency") or "").upper()
                             for field in ("settlementCurrency", "paymentCurrency"))
            if not is_expiry and not order and any(stamp.time().replace(tzinfo=None) == datetime.min.time()
                                 for stamp in (when, when.astimezone(timezone.utc))):
                raise ValueError("No shared order reference or precise intraday execution time")
            phase = "OPENED" if leg["action"] in {"BTO", "STO"} else "CLOSED"
            def recorded_number(field):
                raw = _find(tx, field)
                try:
                    value = float(raw)
                    return value if not isinstance(raw, bool) and math.isfinite(value) else None
                except (TypeError, ValueError, OverflowError):
                    return None
            fee = recorded_number("fee")
            cash = recorded_number("amount")
            cash_basis = "RECORDED CASH" if cash is not None else "UNAVAILABLE"
            expected_cash = (price * leg["qty"] * multiplier * (-1 if leg["action"] in {"BTO", "BTC"} else 1) - fee
                             if multiplier is not None and fee is not None else None)
            inconsistent_cash = cash is not None and expected_cash is not None and abs(cash - expected_cash) > .03
            if cash is None and multiplier is not None and fee is not None:
                cash = expected_cash
                cash_basis = "PREMIUM + FEES"
            if cash is not None and (inconsistent_cash or not math.isfinite(cash) or (leg["action"] in {"BTO", "BTC"} and cash > 0)):
                cash, cash_basis = None, "UNAVAILABLE"
            leg.update(price=price, bucket=bucket, event=phase, root=root,
                       multiplier=multiplier, currency=currency, fee=fee, cash=cash,
                       cash_basis=cash_basis, id=_identity(tx), superseded_ids=superseded.get(_identity(tx), []),
                       subtype=str(_find(product, "securitySubType") or ""))
            if is_expiry:
                if (recorded_number("amount") != 0 or price != 0 or fee not in (None, 0)
                        or (_find(tx, "fee") is not None and fee is None)
                        or not currency[0] or currency[0] != currency[1] or when.date() < leg["expiry"]):
                    raise ValueError("Expiration requires explicit zero cash, zero premium and a date at or after contract expiry")
                leg.update(lifecycle="EXPIRATION", signed_qty=quantity, cash=0.0, cash_basis="RECORDED CASH",
                           reason="Broker-recorded expiration; requires exact remaining two-leg allocation")
                review.append(leg)
                continue
            groups[(bucket, ticker, root, leg["expiry"], leg["type"], multiplier, currency,
                    str(_find(product, "securitySubType") or ""), phase)].append(leg)
        except (TypeError, ValueError, OverflowError) as exc:
            leg["reason"] = str(exc)
            review.append(leg)
            blocked.add(bucket)
            if order:
                blocked_orders.add((account, order))
    events = []
    for legs in groups.values():
        contracts = {(leg["strike"], leg["action"]) for leg in legs}
        long_action, short_action = ("BTO", "STO") if legs[0]["event"] == "OPENED" else ("STC", "BTC")
        longs = [leg for leg in legs if leg["action"] == long_action]
        shorts = [leg for leg in legs if leg["action"] == short_action]
        long_qty = sum(leg["qty"] for leg in longs)
        short_qty = sum(leg["qty"] for leg in shorts)
        account = legs[0]["bucket"][0]
        if (legs[0]["bucket"] in blocked or (legs[0]["order"] and
                ((account, legs[0]["order"]) in blocked_orders or ("", legs[0]["order"]) in blocked_orders))
                or len(contracts) != 2 or not longs or not shorts
                or longs[0]["strike"] == shorts[0]["strike"] or long_qty != short_qty):
            for leg in legs:
                review.append({**leg, "reason": "Ambiguous, incomplete or unbalanced option legs; no vertical inferred"})
            continue
        long_price = math.fsum(leg["price"] * (leg["qty"] / long_qty) for leg in longs)
        short_price = math.fsum(leg["price"] * (leg["qty"] / short_qty) for leg in shorts)
        net = round(long_price - short_price, 8)
        cash_flow = ("DEBIT" if legs[0]["event"] == "OPENED" else "CREDIT") if net > 0 else (
            ("CREDIT" if legs[0]["event"] == "OPENED" else "DEBIT") if net < 0 else "EVEN")
        events.append({"ticker": legs[0]["ticker"], "when": max(leg["when"] for leg in legs),
                       "expiry": legs[0]["expiry"], "type": legs[0]["type"],
                       "long": longs[0]["strike"], "short": shorts[0]["strike"], "qty": long_qty,
                       "long_price": long_price, "short_price": short_price, "net": net,
                       "event": legs[0]["event"], "cash_flow": cash_flow, "order": legs[0]["order"],
                       "match": "ORDER" if legs[0]["order"] else "TIME // INFERRED",
                       "account": account, "root": legs[0]["root"], "multiplier": legs[0]["multiplier"],
                       "currency": legs[0]["currency"], "subtype": legs[0]["subtype"],
                       "ids": sorted(leg["id"] for leg in legs),
                       "superseded_ids": sorted(identifier for leg in legs for identifier in leg["superseded_ids"]),
                       "fee": math.fsum(leg["fee"] for leg in legs) if all(leg["fee"] is not None for leg in legs) else None,
                       "cash": math.fsum(leg["cash"] for leg in legs) if all(leg["cash"] is not None for leg in legs) else None,
                       "cash_basis": ("RECORDED CASH" if all(leg["cash_basis"] == "RECORDED CASH" for leg in legs)
                                      else "PREMIUM + FEES" if all(leg["cash"] is not None for leg in legs) else "UNAVAILABLE")})
    events.sort(key=lambda event: (event["when"], event["ticker"], event["order"], event["long"], event["short"]))
    return events, review


def _vertical_blotter(events: list[dict[str, Any]], review: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Match exact recorded spread events FIFO without inventing missing cash or legs."""
    def number(value):
        if isinstance(value, bool):
            return None
        try:
            value = float(value)
            return value if math.isfinite(value) else None
        except (TypeError, ValueError, OverflowError):
            return None

    def stamp(value):
        if isinstance(value, str):
            try:
                value = datetime.fromisoformat(value)
            except ValueError:
                return None
        return (value if value.tzinfo else value.replace(tzinfo=_ET)) if isinstance(value, datetime) else None

    def total(values):
        try:
            return number(math.fsum(values))
        except (OverflowError, TypeError, ValueError):
            return None

    def iso(value):
        return value.isoformat() if isinstance(value, (date, datetime)) else str(value) if value else None

    def ids(event):
        return sorted(str(value) for value in event.get("ids", [event["id"]] if event.get("id") is not None else []) if value is not None)

    def currencies(event):
        value = event.get("currency") or ("", "")
        if isinstance(value, str):
            value = (value, value)
        return tuple(str(item or "").strip().upper() for item in value)

    def currency(event):
        value = currencies(event)
        return value[0] if len(value) == 2 and value[0] and value[0] == value[1] else ""

    def identity(event):
        return (str(event.get("account") or ""), event.get("ticker"), event.get("root"),
                iso(event.get("expiry")), event.get("type"), number(event.get("long")),
                number(event.get("short")), number(event.get("multiplier")), currencies(event),
                event.get("subtype") or "", json.dumps(event.get("contract_context"), sort_keys=True, default=str))

    def related(leg, event):
        for field in ("account", "ticker", "type"):
            value, other = leg.get(field), event.get(field)
            if value not in (None, "", "UNKNOWN") and other not in (None, "", "UNKNOWN") and value != other:
                return False
        root = leg.get("rawroot") or leg.get("root")
        if root and event.get("root") and root != event["root"]:
            return False
        if leg.get("expiry") and iso(leg["expiry"]) != iso(event.get("expiry")):
            return False
        leg_currency, event_currency = currencies(leg), currencies(event)
        if all(leg_currency) and all(event_currency) and leg_currency != event_currency:
            return False
        leg_multiplier, event_multiplier = number(leg.get("multiplier")), number(event.get("multiplier"))
        if leg_multiplier is not None and event_multiplier is not None and leg_multiplier != event_multiplier:
            return False
        for field in ("subtype", "contract_context"):
            if field in leg and field in event and leg[field] is not None and event[field] is not None and leg[field] != event[field]:
                return False
        strike = number(leg.get("strike"))
        return strike is None or strike in (number(event.get("long")), number(event.get("short")))

    def allocated(event, field, quantity):
        value, total = number(event.get(field)), number(event.get("qty"))
        return number(value * (quantity / total)) if value is not None and total and total > 0 else None

    def row(event, quantity, status, opening=None, closing=None, basis=""):
        open_fee = allocated(opening, "fee", quantity) if opening else 0.0
        close_fee = allocated(closing, "fee", quantity) if closing else 0.0
        fees = total((open_fee, close_fee)) if (opening or closing) and open_fee is not None and close_fee is not None else None
        pnl = None
        if opening and closing and status in {"CLOSED", "EXPIRED"}:
            open_cash, close_cash = allocated(opening, "cash", quantity), allocated(closing, "cash", quantity)
            if not currency(event):
                basis += "; currency unavailable or settlement/payment currency differs"
            elif open_cash is None or close_cash is None:
                basis += "; recorded cash or a verified premium/fee cash basis is unavailable"
            else:
                pnl = total((open_cash, close_cash))
                basis += "; " + str(opening.get("cash_basis") or "UNAVAILABLE") + " / " + str(closing.get("cash_basis") or "UNAVAILABLE")
        inferred = any(item and item.get("match") == "TIME // INFERRED" for item in (event, opening, closing))
        if inferred:
            basis += "; timestamp pairing is inferred"
        result = {"ticker": str(event.get("ticker") or "UNKNOWN"), "type": str(event.get("type") or ""),
                "expiry": iso(event.get("expiry")), "long": number(event.get("long")), "short": number(event.get("short")),
                "qty": number(quantity), "status": status,
                "opened": iso(stamp(opening.get("when"))) if opening else None,
                "closed": iso(stamp(closing.get("when"))) if closing else None,
                "open_net": number(opening.get("net")) if opening else None,
                "close_net": number(closing.get("net")) if closing else None,
                "fees": round(fees, 8) if fees is not None else None,
                "pnl": round(pnl, 8) if pnl is not None else None, "currency": currency(event),
                "match": "TIME // INFERRED" if inferred else "ORDER", "basis": basis,
                "open_ids": ids(opening) if opening else [], "close_ids": ids(closing) if closing else []}
        sources[id(result)] = event
        return result

    sources = {}
    expiry_proof = [leg for leg in review if leg.get("lifecycle") == "EXPIRATION"]
    ordinary_review = [leg for leg in review if leg.get("lifecycle") != "EXPIRATION"]
    barriers = {}
    simultaneous = defaultdict(list)
    for event in events:
        key = identity(event)
        if key not in barriers:
            relevant = [leg for leg in ordinary_review if related(leg, event)]
            barriers[key] = (min((stamp(leg.get("when")) or datetime.min.replace(tzinfo=_ET)) for leg in relevant)
                             if relevant else None)
        if event.get("event") in {"OPENED", "CLOSED"}:
            simultaneous[(key, stamp(event.get("when")), event["event"])].append(event)
    for (key, when, _), cohort in simultaneous.items():
        if len(cohort) > 1 and len({allocated(event, "cash", 1) for event in cohort}) > 1:
            when = when or datetime.min.replace(tzinfo=_ET)
            barriers[key] = min(barriers[key], when) if barriers[key] else when

    lots = defaultdict(deque)
    expiry_conflicts = set()
    output = []
    ordered = sorted(events, key=lambda event: (stamp(event.get("when")) or datetime.min.replace(tzinfo=_ET),
                                                event.get("event") == "OPENED", ids(event)))
    for event in ordered:
        key, when, quantity = identity(event), stamp(event.get("when")), number(event.get("qty"))
        opening = event if event.get("event") == "OPENED" else None
        closing = event if event.get("event") == "CLOSED" else None
        if when is None or not quantity or quantity <= 0 or not quantity.is_integer() or not (opening or closing):
            output.append(row(event, quantity, "REVIEW", opening, closing, "Invalid spread event; no FIFO match"))
            continue
        if closing and any(related(leg, event) and leg.get("expiry") and when.date() > leg["expiry"] for leg in expiry_proof):
            expiry_conflicts.add(key)
            output.append(row(event, quantity, "REVIEW", closing=closing,
                              basis="A close dated after recorded contract expiration cannot consume FIFO inventory"))
            continue
        if barriers[key] is not None and when >= barriers[key]:
            output.append(row(event, quantity, "REVIEW", opening, closing,
                              "Unpaired leg activity or ambiguous execution sequence interrupts this contract's FIFO history"))
            continue
        if opening:
            lots[key].append({"event": opening, "remaining": quantity})
            continue
        remaining = quantity
        while remaining > 0 and lots[key]:
            lot = lots[key][0]
            matched = min(remaining, lot["remaining"])
            output.append(row(event, matched, "CLOSED", lot["event"], event, "Exact-contract FIFO cash match"))
            lot["remaining"] -= matched
            remaining -= matched
            if lot["remaining"] == 0:
                lots[key].popleft()
        if remaining:
            output.append(row(event, remaining, "UNMATCHED CLOSE", closing=event,
                              basis="Opening spread is unavailable in retained history; no realized P&L"))
    # An expiration record disposes of one contract, not an arbitrary spread.
    # Anchor both signed legs to a unique remaining spread before consuming it.
    expiry_groups = defaultdict(list)
    for index, leg in enumerate(expiry_proof):
        candidates = []
        signed = number(leg.get("signed_qty"))
        for key, queue in lots.items():
            if not queue:
                continue
            event = queue[0]["event"]
            if related(leg, event) and signed is not None and (
                    (signed < 0 and number(leg.get("strike")) == number(event.get("long"))) or
                    (signed > 0 and number(leg.get("strike")) == number(event.get("short")))):
                candidates.append(key)
        if len(candidates) == 1:
            expiry_groups[candidates[0]].append((index, leg))
    consumed = set()
    for key, evidence in sorted(expiry_groups.items(), key=lambda item: max(stamp(leg.get("when")) for _, leg in item[1])):
        when = max(stamp(leg.get("when")) for _, leg in evidence)
        queue = lots[key]
        if not queue or barriers[key] is not None or key in expiry_conflicts or when is None:
            continue
        longs = [(index, leg) for index, leg in evidence if number(leg.get("signed_qty")) < 0]
        shorts = [(index, leg) for index, leg in evidence if number(leg.get("signed_qty")) > 0]
        long_qty = total(number(leg.get("qty")) for _, leg in longs)
        short_qty = total(number(leg.get("qty")) for _, leg in shorts)
        if (not longs or not shorts or not long_qty or long_qty != short_qty
                or long_qty > sum(lot["remaining"] for lot in queue)
                or any(stamp(lot["event"]["when"]) >= when or stamp(lot["event"]["when"]).date() > lot["event"]["expiry"] for lot in queue)):
            continue
        event = queue[0]["event"]
        closing = {**event, "when":when,"event":"EXPIRED","qty":long_qty,"net":0.0,"cash":0.0,
                   "fee":total(number(leg.get("fee")) for _, leg in evidence) if all(number(leg.get("fee")) is not None for _, leg in evidence) else None,
                   "ids":sorted(str(leg["id"]) for _, leg in evidence),"cash_basis":"BROKER ZERO-CASH EXPIRATION"}
        remaining = long_qty
        while remaining:
            lot = queue[0]
            matched = min(remaining, lot["remaining"])
            output.append(row(closing, matched, "EXPIRED", lot["event"], closing,
                              "Exact-contract FIFO; both signed legs have broker-confirmed zero-cash expiration; closed date is broker evidence date"))
            lot["remaining"] -= matched
            remaining -= matched
            if lot["remaining"] == 0:
                queue.popleft()
        consumed.update(index for index, _ in evidence)
    unresolved = [leg for index, leg in enumerate(expiry_proof) if index not in consumed]
    for key, queue in lots.items():
        for lot in queue:
            interrupted = barriers[key] is not None or any(related(leg, lot["event"]) for leg in unresolved)
            output.append(row(lot["event"], lot["remaining"], "REVIEW" if interrupted else "OPEN", opening=lot["event"],
                              basis=("Unpaired leg activity interrupts the remaining FIFO quantity; no realized P&L" if interrupted else
                                     "Remaining recorded FIFO opening quantity; no realized P&L")))
    for item in output:
        terminal = item["status"] in {"CLOSED", "EXPIRED"}
        evidence = expiry_proof if item["status"] == "CLOSED" else unresolved
        closed = stamp(item["closed"])
        if terminal and any(related(leg, sources[id(item)]) and (
                (closed.date() > leg["expiry"] if item["status"] == "CLOSED" and leg.get("expiry") else
                 stamp(leg.get("when")) is None or closed >= stamp(leg["when"]))) for leg in evidence):
            item.update(status="REVIEW", pnl=None,
                        basis="Expiration evidence conflicts with a later or unresolved lifecycle allocation; no realized P&L")
    resolved_ids = {identifier for item in output if item["status"] == "EXPIRED" for identifier in item["close_ids"]}
    for leg in review:
        if leg.get("lifecycle") == "EXPIRATION" and str(leg.get("id")) in resolved_ids:
            continue
        action = leg.get("action")
        event = {**leg, "long": leg.get("strike") if action in {"BTO", "STC"} else None,
                 "short": leg.get("strike") if action in {"STO", "BTC"} else None}
        output.append(row(event, number(leg.get("qty")), "REVIEW",
                          opening=event if action in {"BTO", "STO"} else None,
                          closing=event if action in {"STC", "BTC"} else None,
                          basis=str(leg.get("reason") or "Unpaired option leg requires review")))
    output.sort(key=lambda item: (item["closed"] or item["opened"] or "", item["ticker"], item["status"],
                                  item["open_ids"], item["close_ids"]))
    return output


def _vertical_text(events: list[dict[str, Any]]) -> str:
    def number(value):
        return f"{value:.8f}".rstrip("0").rstrip(".")
    return "\n".join(
        f'{row["ticker"]} {row["when"]:%m.%d.%Y} {row["event"]} {number(row["qty"])} '
        f'{row["type"]} EXP {row["expiry"]:%m.%d.%Y} LONG {number(row["long"])} SHORT {number(row["short"])} '
        f'NET {number(abs(row["net"]))} {row["cash_flow"]} [{row["match"]}]'
        for row in events
    )


def _vertical_source_fingerprint(rows: list[dict[str, Any]]) -> str:
    return hashlib.sha256(json.dumps(_merge([], rows), sort_keys=True, separators=(",", ":"), default=str).encode()).hexdigest()


def _vertical_result_fingerprint(payload: dict[str, Any]) -> str:
    result = {key: payload[key] for key in ("events", "review", "blotter")}
    return hashlib.sha256(json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def _build_vertical_cache(rows: list[dict[str, Any]]) -> dict[str, Any]:
    events, review = _vertical_history(rows)
    payload = {"schema_version": 1, "algorithm_version": _VERTICAL_CACHE_VERSION,
               "source_fingerprint": _vertical_source_fingerprint(rows),
               "events": events, "review": review, "blotter": _vertical_blotter(events, review)}
    # Native ISO dates and finite JSON numbers keep GitHub reloads independent
    # of the current Python process or pandas serialization behavior.
    def native(value):
        if isinstance(value, (date, datetime)):
            return value.isoformat()
        if isinstance(value, dict):
            return {key: native(child) for key, child in value.items()}
        if isinstance(value, (list, tuple)):
            return [native(child) for child in value]
        if isinstance(value, float) and not math.isfinite(value):
            return None
        return value
    payload = native(payload)
    payload["result_fingerprint"] = _vertical_result_fingerprint(payload)
    return payload


def _valid_vertical_cache(payload: Any, source: str) -> bool:
    try:
        valid = (isinstance(payload, dict) and payload["schema_version"] == 1
                and payload["algorithm_version"] == _VERTICAL_CACHE_VERSION
                and payload["source_fingerprint"] == source
                and all(isinstance(payload[key], list) and all(isinstance(row, dict) for row in payload[key])
                        for key in ("events", "review", "blotter"))
                and payload["result_fingerprint"] == _vertical_result_fingerprint(payload))
        if not valid:
            return False
        def finite_number(value):
            return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)
        for event in payload["events"]:
            if not {"ticker", "when", "expiry", "type", "long", "short", "qty", "net", "event", "match"} <= event.keys():
                return False
            datetime.fromisoformat(event["when"])
            date.fromisoformat(event["expiry"])
            if (not all(finite_number(event[key]) for key in ("long", "short", "qty", "net"))
                    or event["qty"] <= 0 or event["long"] <= 0 or event["short"] <= 0):
                return False
        for leg in payload["review"]:
            if not {"ticker", "when", "expiry", "type", "strike", "qty", "action", "reason"} <= leg.keys():
                return False
            if leg["when"]:
                datetime.fromisoformat(leg["when"])
            if leg["expiry"]:
                date.fromisoformat(leg["expiry"])
        for row in payload["blotter"]:
            if not {"ticker", "type", "expiry", "long", "short", "qty", "status", "opened", "closed", "open_net", "close_net", "fees", "pnl", "currency", "match", "basis", "open_ids", "close_ids"} <= row.keys():
                return False
            for key in ("opened", "closed"):
                if row[key]:
                    datetime.fromisoformat(row[key])
            if row["expiry"]:
                date.fromisoformat(row["expiry"])
            if any(row[key] is not None and not finite_number(row[key])
                   for key in ("long", "short", "qty", "open_net", "close_net", "fees", "pnl")):
                return False
        return True
    except (KeyError, TypeError, ValueError):
        return False


