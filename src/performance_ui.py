# REALIZED TRADE ANALYTICS
# ==============================

def _build_trade_events(transactions: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    trades = [row for tx in transactions if (row := _trade_record(tx)) is not None]
    trades.sort(key=lambda row: (row["when"], row["id"]))
    income = [row for tx in transactions if (row := _income_record(tx)) is not None]
    income.sort(key=lambda row: row["when"])

    longs: dict[tuple[str, str, str], list[dict[str, float]]] = defaultdict(list)
    shorts: dict[tuple[str, str, str], list[dict[str, float]]] = defaultdict(list)
    closes: dict[tuple[str, tuple[str, str, str]], dict[str, Any]] = {}

    def close(trade: dict[str, Any], pnl: float, basis: float) -> None:
        key = (trade["id"], trade["key"])
        row = closes.setdefault(key, {"id": trade["id"], "when": trade["when"], "symbol": trade["symbol"], "pnl": 0.0, "cost_basis": 0.0})
        row["pnl"] += float(pnl)
        row["cost_basis"] += abs(float(basis))

    for trade in trades:
        qty = float(trade["quantity"])
        fee_each = float(trade["fee"]) / qty if qty else 0.0
        px = float(trade["price"]) * float(trade["multiplier"])
        key = trade["key"]
        action = trade["action"]

        if action in {"BUY", "BUY_TO_COVER"}:
            remaining = qty
            while remaining > 1e-9 and shorts[key]:
                lot = shorts[key][0]
                closed = min(remaining, lot["qty"])
                cost = px + fee_each
                close(trade, (lot["unit"] - cost) * closed, lot["unit"] * closed)
                lot["qty"] -= closed
                remaining -= closed
                if lot["qty"] <= 1e-9:
                    shorts[key].pop(0)
            if remaining > 1e-9:
                longs[key].append({"qty": remaining, "unit": px + fee_each})
            continue

        if action == "SELL_SHORT":
            shorts[key].append({"qty": qty, "unit": px - fee_each})
            continue

        if action == "SELL":
            remaining = qty
            while remaining > 1e-9 and longs[key]:
                lot = longs[key][0]
                closed = min(remaining, lot["qty"])
                proceeds = px - fee_each
                close(trade, (proceeds - lot["unit"]) * closed, lot["unit"] * closed)
                lot["qty"] -= closed
                remaining -= closed
                if lot["qty"] <= 1e-9:
                    longs[key].pop(0)
            if remaining > 1e-9:
                shorts[key].append({"qty": remaining, "unit": px - fee_each})

    return sorted(closes.values(), key=lambda row: (row["when"], row["id"])), income


def _period_metrics(
    events: list[dict[str, Any]],
    income: list[dict[str, Any]],
    start: date,
    *,
    account_value: float | None,
) -> dict[str, float | None]:
    selected = [row for row in events if row["when"].date() >= start]
    selected_income = [row for row in income if row["when"].date() >= start]
    realized = sum(float(row["pnl"]) for row in selected)
    cash_income = sum(float(row["amount"]) for row in selected_income)
    net = realized + cash_income
    basis = sum(float(row["cost_basis"]) for row in selected)
    wins = [float(row["pnl"]) for row in selected if float(row["pnl"]) > 1e-9]
    losses = [float(row["pnl"]) for row in selected if float(row["pnl"]) < -1e-9]
    decided = len(wins) + len(losses)

    running = peak = worst_dd = 0.0
    points = [(row["when"], float(row["pnl"])) for row in selected]
    points += [(row["when"], float(row["amount"])) for row in selected_income]
    for _, amount in sorted(points, key=lambda item: item[0]):
        running += amount
        peak = max(peak, running)
        worst_dd = min(worst_dd, running - peak)

    return {
        "net_pnl": net,
        "return_pct": (100.0 * net / basis) if basis > 1e-9 else None,
        "win_rate": (100.0 * len(wins) / decided) if decided else None,
        "profit_factor": (sum(wins) / abs(sum(losses))) if losses else (math.inf if wins else None),
        "max_drawdown_pct": (100.0 * worst_dd / account_value) if account_value and account_value > 1e-9 else None,
        "cost_basis": basis,
    }


