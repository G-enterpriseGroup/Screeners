def _client_call(client: Any, method: str, account_key: str) -> Any:
    fn = getattr(client, method)
    try:
        return fn(account_key, force_refresh=True)
    except TypeError:
        return fn(account_key)


def _snapshot(client: Any, account_key: str) -> dict[str, Any]:
    raw = _client_call(client, "get_portfolio", account_key)
    balance = _client_call(client, "get_balance", account_key)
    positions = [normalize_position(row) for row in raw if isinstance(row, dict)]
    day_gain = sum(float(row.get("day_gain") or 0.0) for row in positions)
    market_value = sum(float(row.get("market_value") or 0.0) for row in positions)
    total_gain = sum(float(row.get("total_gain") or 0.0) for row in positions)
    total_cost = sum(float(row.get("total_cost") or 0.0) for row in positions)
    day_base = market_value - day_gain
    return {
        "day_gain": day_gain,
        "day_return": (100.0 * day_gain / day_base) if abs(day_base) > 1e-9 else None,
        "unrealized": total_gain,
        "total_cost": total_cost,
        "account_value": total_account_value(balance),
    }


def _money(value: float | None) -> str:
    if value is None or not math.isfinite(float(value)):
        return "—"
    value = float(value)
    sign = "+" if value > 0 else "-" if value < 0 else ""
    return sign + "$" + f"{abs(value):,.0f}"


def _pct(value: float | None) -> str:
    if value is None or not math.isfinite(float(value)):
        return "—"
    value = float(value)
    return ("+" if value > 0 else "") + f"{value:.2f}%"


def _ratio(value: float | None) -> str:
    if value is None:
        return "—"
    return "∞" if math.isinf(float(value)) else f"{float(value):.2f}"


def _scorecard(today: dict[str, Any], mtd: dict[str, Any], ytd: dict[str, Any], all_time: dict[str, Any]) -> pd.DataFrame:
    return pd.DataFrame(
        [
            ["Net P&L", _money(today.get("net_pnl")), _money(mtd.get("net_pnl")), _money(ytd.get("net_pnl")), _money(all_time.get("net_pnl"))],
            ["Return", _pct(today.get("return_pct")), _pct(mtd.get("return_pct")), _pct(ytd.get("return_pct")), _pct(all_time.get("return_pct"))],
            ["Win Rate", "—", _pct(mtd.get("win_rate")), _pct(ytd.get("win_rate")), _pct(all_time.get("win_rate"))],
            ["Profit Factor", "—", _ratio(mtd.get("profit_factor")), _ratio(ytd.get("profit_factor")), _ratio(all_time.get("profit_factor"))],
            ["Max Drawdown", "—", _pct(mtd.get("max_drawdown_pct")), _pct(ytd.get("max_drawdown_pct")), _pct(all_time.get("max_drawdown_pct"))],
        ],
        columns=["PERFORMANCE", "TODAY", "MTD", "YTD", "ALL-TIME"],
    )


def _curve(events: list[dict[str, Any]], income: list[dict[str, Any]], unrealized: float) -> pd.DataFrame:
    daily: dict[date, float] = defaultdict(float)
    for row in events:
        daily[row["when"].date()] += float(row["pnl"])
    for row in income:
        daily[row["when"].date()] += float(row["amount"])
    running = 0.0
    rows: list[tuple[datetime, float]] = []
    for day in sorted(daily):
        running += daily[day]
        rows.append((datetime(day.year, day.month, day.day, 16, tzinfo=_ET), running))
    rows.append((datetime.now(_ET), running + float(unrealized)))
    return pd.DataFrame(rows, columns=["Date", "Net P&L"])


def _chart(frame: pd.DataFrame, key: str) -> None:
    fig = go.Figure(go.Scatter(
        x=frame["Date"],
        y=frame["Net P&L"],
        mode="lines",
        line={"color": "#fb8b1e", "width": 2.4},
        hovertemplate="%{x|%b %d %Y %I:%M %p}<br>NET P&L $%{y:,.2f}<extra></extra>",
    ))
    fig.add_hline(y=0, line_width=1, line_color="#444444")
    fig.update_layout(
        height=350,
        margin={"l": 10, "r": 10, "t": 34, "b": 8},
        paper_bgcolor="#000000",
        plot_bgcolor="#000000",
        font={"family": "Courier New", "color": "#d7d7d7", "size": 11},
        title={"text": "LIVE CUMULATIVE NET P&L // REALIZED HISTORY + CURRENT UNREALIZED", "font": {"color": "#fb8b1e", "size": 13}},
        xaxis={"gridcolor": "#1c1c1c", "title": ""},
        yaxis={"gridcolor": "#1c1c1c", "tickprefix": "$", "tickformat": ",.0f", "title": ""},
        showlegend=False,
    )
    st.plotly_chart(fig, width="stretch", config={"displayModeBar": False}, key=key)


