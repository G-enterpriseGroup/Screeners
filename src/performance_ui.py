def _cache_key(account_key: str) -> str:
    return f"performance_transactions::{account_key}"


def _load_transactions(client: Any, account_key: str, force: bool) -> list[dict[str, Any]]:
    key = _cache_key(account_key)
    if force:
        st.session_state.pop(key, None)
    if isinstance(st.session_state.get(key), list):
        return st.session_state[key]
    end = datetime.now(_ET).date()
    rows = client.get_transactions(account_key, start_date=end - timedelta(days=_HISTORY_DAYS), end_date=end, sort_order="ASC")
    rows = [row for row in rows if isinstance(row, dict)]
    st.session_state[key] = rows
    return rows


def _account_label(account: dict[str, Any]) -> str:
    name = str(account.get("accountName") or account.get("accountDesc") or account.get("accountType") or "E*TRADE ACCOUNT").strip()
    raw = str(account.get("accountId") or "")
    return f"{name} // ••••{raw[-4:]}" if raw else name


def _default_account(accounts: list[dict[str, Any]]) -> str:
    for account in accounts:
        if str(account.get("accountId") or "").endswith(_DEFAULT_ACCOUNT_SUFFIX):
            return str(account.get("accountIdKey") or "")
    return str(accounts[0].get("accountIdKey") or "") if accounts else ""


@st.fragment(run_every=_LIVE_REFRESH_SECONDS)
def _live(client: Any, account: dict[str, Any], transactions: list[dict[str, Any]], touch_session: Callable[[], Any] | None) -> None:
    account_key = str(account.get("accountIdKey") or "").strip()
    try:
        snapshot = _snapshot(client, account_key)
        if touch_session:
            touch_session()
    except Exception as exc:
        st.error(f"PERFORMANCE LIVE DATA UNAVAILABLE // {exc}")
        return

    events, income = _build_trade_events(transactions)
    now = datetime.now(_ET)
    today_date = now.date()
    history_dates = [stamp.date() for tx in transactions if (stamp := _when(tx)) is not None]
    history_start = min(history_dates) if history_dates else today_date

    today = {"net_pnl": snapshot["day_gain"], "return_pct": snapshot["day_return"]}
    mtd = _period_metrics(events, income, today_date.replace(day=1), account_value=snapshot["account_value"])
    ytd = _period_metrics(events, income, date(today_date.year, 1, 1), account_value=snapshot["account_value"])
    all_time = _period_metrics(events, income, history_start, account_value=snapshot["account_value"])
    all_time["net_pnl"] = float(all_time.get("net_pnl") or 0.0) + float(snapshot["unrealized"])
    basis = float(all_time.get("cost_basis") or 0.0) + max(0.0, float(snapshot["total_cost"] or 0.0))
    all_time["return_pct"] = (100.0 * float(all_time["net_pnl"]) / basis) if basis > 1e-9 else None

    cols = st.columns(4, gap="small")
    for col, label, value in zip(
        cols,
        ("ACCOUNT VALUE", "TODAY NET P&L", "CURRENT UNREALIZED", "LIVE UPDATE"),
        (_money(snapshot["account_value"]), _money(snapshot["day_gain"]), _money(snapshot["unrealized"]), now.strftime("%I:%M:%S %p ET")),
    ):
        with col:
            _kpi(label, value)

    _section("PERFORMANCE SCORECARD")
    st.dataframe(_scorecard(today, mtd, ytd, all_time), hide_index=True, width="stretch", row_height=36)

    _section("LIVE PERFORMANCE CURVE")
    suffix = str(account.get("accountId") or account_key)[-6:]
    _chart(_curve(events, income, float(snapshot["unrealized"])), f"performance_curve_{suffix}")

    st.html(
        '<div class="perf-status">'
        f'HISTORY COVERAGE // EARLIEST E*TRADE TRANSACTION LOADED: {history_start:%b %d, %Y} // '
        f'{len(transactions):,} TRANSACTIONS // {len(events):,} CLOSED TRADE EVENTS // '
        'TODAY = live mark-to-market. MTD/YTD trade stats = realized FIFO trade P&L plus dividend/interest cash. '
        'ALL-TIME adds current unrealized P&L. Return is cost-basis return, not TWR/XIRR; Max Drawdown is realized-P&L drawdown versus current account value. '
        'If the account predates the E*TRADE API history window, ALL-TIME is partial until older history is seeded; missing history is never invented.'
        '</div>'
    )


def render_performance(
    client: Any,
    *,
    refresh_accounts: Callable[[Any], list[dict[str, Any]]] | None = None,
    touch_session: Callable[[], Any] | None = None,
) -> None:
    st.html(_PERFORMANCE_CSS)
    with st.container(key="performance_root", gap=None):
        if client is None:
            st.info("CONNECT E*TRADE TO LOAD LIVE PERFORMANCE.")
            return

        accounts = [row for row in (st.session_state.get("etrade_accounts") or []) if isinstance(row, dict)]
        if not accounts and refresh_accounts is not None:
            try:
                accounts = refresh_accounts(client)
            except Exception as exc:
                st.error(f"E*TRADE ACCOUNTS UNAVAILABLE // {exc}")
                return
        accounts = [row for row in accounts if str(row.get("accountIdKey") or "").strip()]
        if not accounts:
            st.info("NO E*TRADE BROKERAGE ACCOUNTS ARE AVAILABLE.")
            return

        by_key = {str(row.get("accountIdKey") or "").strip(): row for row in accounts}
        state_key = "performance_account_key"
        if str(st.session_state.get(state_key) or "") not in by_key:
            st.session_state[state_key] = _default_account(accounts)

        picker, refresh = st.columns([5.2, 1.5], gap="small", vertical_alignment="bottom")
        with picker:
            selected = st.selectbox("E*TRADE Account", list(by_key), key=state_key, format_func=lambda key: _account_label(by_key[key]))
        with refresh:
            force = st.button("REFRESH PERFORMANCE", type="primary", width="stretch", key="performance_refresh")

        if force:
            st.session_state.pop(_cache_key(selected), None)
            invalidate = getattr(client, "invalidate", None)
            if callable(invalidate):
                invalidate("portfolio", "balance")

        try:
            transactions = _load_transactions(client, selected, force)
            if touch_session:
                touch_session()
        except AttributeError:
            transactions = []
            st.warning("LIVE TRANSACTION HISTORY IS NOT AVAILABLE IN OFFLINE SNAPSHOT MODE.")
        except ETradeError as exc:
            transactions = []
            st.warning(f"E*TRADE TRANSACTION HISTORY UNAVAILABLE // {exc}")
        except Exception as exc:
            transactions = []
            st.warning(f"PERFORMANCE HISTORY LOAD FAILED // {exc}")

        _live(client, by_key[selected], transactions, touch_session)


