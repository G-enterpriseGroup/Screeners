def _find(value: Any, *keys: str) -> Any:
    wanted = {str(key).casefold() for key in keys}
    if isinstance(value, dict):
        for key, child in value.items():
            if str(key).casefold() in wanted:
                return child
        for child in value.values():
            found = _find(child, *keys)
            if found is not None:
                return found
    elif isinstance(value, list):
        for child in value:
            found = _find(child, *keys)
            if found is not None:
                return found
    return None


def _dict(value: Any, *keys: str) -> dict[str, Any]:
    child = _find(value, *keys)
    return child if isinstance(child, dict) else {}


def _num(value: Any, *keys: str) -> float | None:
    try:
        number = float(_find(value, *keys))
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _when(tx: dict[str, Any]) -> datetime | None:
    raw = _find(tx, "transactionDate", "postDate", "settlementDate")
    try:
        value = float(raw)
        if value > 10_000_000_000:
            value /= 1000.0
        return datetime.fromtimestamp(value, tz=_ET)
    except (TypeError, ValueError, OSError, OverflowError):
        return None


def _action(tx: dict[str, Any]) -> str:
    brokerage = _dict(tx, "brokerage")
    raw = str(
        _find(brokerage, "transactionType")
        or _find(tx, "transactionType")
        or _find(tx, "transactionShortDesc")
        or _find(tx, "transactionDescription")
        or _find(tx, "description")
        or ""
    ).upper().replace("-", "_").replace(" ", "_")
    if "BUY_TO_COVER" in raw or "BOUGHT_TO_COVER" in raw:
        return "BUY_TO_COVER"
    if "SELL_SHORT" in raw or "SOLD_SHORT" in raw or "SHORT_SALE" in raw:
        return "SELL_SHORT"
    if "BUY" in raw or "BOUGHT" in raw:
        return "BUY"
    if "SELL" in raw or "SOLD" in raw:
        return "SELL"
    return ""


def _instrument(tx: dict[str, Any]) -> tuple[str, str, str]:
    product = _dict(tx, "product") or _dict(tx, "productId")
    symbol = str(
        _find(product, "displaySymbol", "symbol")
        or _find(tx, "displaySymbol", "symbol")
        or ""
    ).strip().upper()
    security = str(
        _find(product, "securityType", "typeCode")
        or _find(tx, "securityType", "typeCode")
        or "EQ"
    ).strip().upper()
    option = "|".join(
        str(value)
        for key in ("callPut", "strikePrice", "expiryYear", "expiryMonth", "expiryDay")
        if (value := _find(product, key)) not in (None, "")
    )
    return symbol, security, option


def _trade_record(tx: dict[str, Any]) -> dict[str, Any] | None:
    action = _action(tx)
    if not action:
        return None
    brokerage = _dict(tx, "brokerage")
    when = _when(tx)
    symbol, security, option = _instrument(tx)
    qty = abs(_num(brokerage, "quantity") or _num(tx, "quantity") or 0.0)
    price = _num(brokerage, "price")
    if price is None:
        price = _num(tx, "price")
    fee = abs(_num(brokerage, "fee") or _num(tx, "fee", "commission") or 0.0)
    if not symbol or when is None or qty <= 0 or price is None or price < 0:
        return None
    multiplier = _num(brokerage, "optionMultiplier", "multiplier")
    if multiplier is None:
        multiplier = 100.0 if "OPT" in security else 1.0
    return {
        "id": str(_find(tx, "transactionId") or f"{when.timestamp()}:{symbol}:{action}"),
        "when": when,
        "key": (symbol, security, option),
        "symbol": symbol,
        "action": action,
        "quantity": float(qty),
        "price": float(price),
        "fee": float(fee),
        "multiplier": float(multiplier),
    }


def _income_record(tx: dict[str, Any]) -> dict[str, Any] | None:
    if _action(tx):
        return None
    when = _when(tx)
    amount = _num(tx, "amount")
    text = " ".join(
        str(_find(tx, key) or "")
        for key in ("transactionType", "transactionShortDesc", "transactionDescription", "description", "description2", "memo")
    ).lower()
    if when is not None and amount is not None and ("dividend" in text or "interest" in text):
        return {"when": when, "amount": float(amount)}
    return None


