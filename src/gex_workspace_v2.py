def _is_style_only_markdown(body: Any) -> bool:
    """Return True only for a standalone <style>...</style> markdown body."""
    if not isinstance(body, str):
        return False
    stripped = body.strip()
    return stripped.startswith("<style>") and stripped.endswith("</style>")


# ==============================
# E*TRADE / TERMINAL CONTEXT
# ==============================

def _discover_terminal_context() -> tuple[Any, str, Any]:
    """Resolve the live terminal client, access-code vault key, and touch hook.

    This is context plumbing only. GEX calculations and presentation belong in
    `src/gex_ui_v3.py`.
    """
    candidates: list[dict[str, Any]] = []
    main = sys.modules.get("__main__")
    if main is not None:
        candidates.append(vars(main))
    for frame in inspect.stack()[1:18]:
        candidates.append(frame.frame.f_globals)

    for scope in candidates:
        live_factory = scope.get("_live_etrade_client")
        factory = live_factory if callable(live_factory) else scope.get("_etrade_client")
        hash_fn = scope.get("_trade_access_code_hash")
        touch = scope.get("_touch_etrade_session")
        if not callable(factory):
            continue

        try:
            client = factory()
        except Exception:
            client = None
        try:
            vault_key = str(hash_fn()) if callable(hash_fn) else "default"
        except Exception:
            vault_key = "default"
        return client, vault_key or "default", touch

    return None, "default", None


# ==============================
# SAFE GEX RENDER BRIDGE
# ==============================

def _render_with_style_only_html(client: Any, vault_key: str, touch: Any) -> None:
    """Render GEX while routing only style-only markdown through ``st.html``.

    `src.gex_ui_v3_base.py` emits its feature CSS with a standalone
    ``st.markdown(<style>...</style>)`` call. For GEX only, route that exact
    style-only case through ``st.html`` so Streamlit applies it without adding
    a visible layout row. All normal markdown is passed through unchanged.

    This intentionally does NOT concatenate CSS with visible content and does
    NOT use negative margins. The original ``st.markdown`` is always restored.
    """
    original_markdown = st.markdown

    def gex_markdown(body: Any, *args: Any, **kwargs: Any):
        if _is_style_only_markdown(body):
            st.html(str(body))
            return None
        return original_markdown(body, *args, **kwargs)

    st.markdown = gex_markdown
    try:
        _render_gex_v3(client, vault_key, touch)
    finally:
        st.markdown = original_markdown


# ==============================
# PUBLIC GEX ENTRYPOINT
# ==============================

def render_gex() -> None:
    """Render only the GEX feature without visible CSS/spacer rows."""
    client, vault_key, touch = _discover_terminal_context()

    # Style-only HTML is applied without creating a visible Streamlit row.
    st.html(_gex_subtab_skin_css())
    _render_with_style_only_html(client, vault_key, touch)


