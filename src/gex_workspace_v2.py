def _background_client_factory(scope: dict[str, Any]) -> Callable[[], Any] | None:
    """Capture a cache-aware thread-safe E*TRADE client factory.

    Background workers must not read ``st.session_state`` or call terminal
    helpers after the worker starts. Capture credential/token strings, GEX DTE
    settings, timezone, and the non-reversible cache namespace here. Every live
    request in the prefetch pool builds its own OAuth session, so no requests
    share one ``OAuth1Session`` across threads.
    """
    credentials_factory = scope.get("_etrade_credentials")
    if not callable(credentials_factory):
        return None

    try:
        consumer_key, consumer_secret, environment = credentials_factory()
    except Exception:
        return None

    token = st.session_state.get("etrade_access_token") or {}
    oauth_token = str(token.get("oauth_token") or "").strip()
    oauth_secret = str(token.get("oauth_token_secret") or "").strip()
    consumer_key = str(consumer_key or "").strip()
    consumer_secret = str(consumer_secret or "").strip()
    environment = str(environment or "live").strip() or "live"

    if not (consumer_key and consumer_secret and oauth_token and oauth_secret):
        return None

    state = st.session_state.get("_gex_state") or {}
    try:
        global_dte = int(state.get("global_dte", 45) or 45)
    except Exception:
        global_dte = 45
    overrides = state.get("dte_overrides") or {}
    dte_by_symbol: dict[str, int] = {}
    for raw_symbol in state.get("tickers", []) or []:
        symbol = str(raw_symbol or "").strip().upper()
        if not symbol:
            continue
        try:
            dte_by_symbol[symbol] = int(overrides.get(symbol, global_dte) or global_dte)
        except Exception:
            dte_by_symbol[symbol] = global_dte
    timezone_name = str(state.get("timezone") or "America/New_York")

    cache_namespace = _gex_cache_namespace(oauth_token)

    def raw_client_factory(
        _consumer_key: str = consumer_key,
        _consumer_secret: str = consumer_secret,
        _oauth_token: str = oauth_token,
        _oauth_secret: str = oauth_secret,
        _environment: str = environment,
    ) -> ETradeClient:
        return ETradeClient(
            _consumer_key,
            _consumer_secret,
            _oauth_token,
            _oauth_secret,
            _environment,
        )

    def build_client(
        _cache_namespace: str = cache_namespace,
        _dte_by_symbol: dict[str, int] = dte_by_symbol,
        _timezone_name: str = timezone_name,
    ) -> _GEXBackgroundCachedClient:
        return _GEXBackgroundCachedClient(
            raw_client_factory(),
            _cache_namespace,
            raw_client_factory,
            _dte_by_symbol,
            _timezone_name,
        )

    return build_client


def _discover_terminal_context() -> tuple[
    Any,
    str,
    Any,
    Callable[[], Any] | None,
    str,
]:
    """Resolve live GEX context, background-client factory, and login marker."""
    candidates: list[dict[str, Any]] = []
    main = sys.modules.get("__main__")
    if main is not None:
        candidates.append(vars(main))
    for frame in inspect.stack()[1:18]:
        candidates.append(frame.frame.f_globals)

    for scope in candidates:
        live_factory = scope.get("_live_etrade_client")
        factory = live_factory if callable(live_factory) else scope.get("_etrade_client")
        hash_fn = scope.get("_trade_access_code_hash")
        touch = scope.get("_touch_etrade_session")
        if not callable(factory):
            continue

        try:
            client = factory()
        except Exception:
            client = None
        try:
            vault_key = str(hash_fn()) if callable(hash_fn) else "default"
        except Exception:
            vault_key = "default"
        token = st.session_state.get("etrade_access_token") or {}
        oauth_token = str(token.get("oauth_token") or "").strip()
        issued_at = str(token.get("issued_at") or "").strip()
        login_marker = ""
        if oauth_token:
            login_marker = hashlib.sha256(
                f"{oauth_token}|{issued_at}".encode("utf-8")
            ).hexdigest()[:24]

        return (
            client,
            vault_key or "default",
            touch,
            _background_client_factory(scope),
            login_marker,
        )

    return None, "default", None, None, ""


