def _is_style_only_markdown(body: Any) -> bool:
    """Return True only for a standalone <style>...</style> markdown body."""
    if not isinstance(body, str):
        return False
    stripped = body.strip()
    return stripped.startswith("<style>") and stripped.endswith("</style>")


def _gex_progress_log(vault_key: str) -> str:
    """Build a compact, non-sensitive live process log for the spinner tooltip."""
    job = background_refresh_status(str(vault_key or "default")) or {}
    status = str(job.get("status") or "WAITING")
    total = int(job.get("total", 0) or 0)
    completed = int(job.get("completed", 0) or 0)
    updated = int(job.get("updated", 0) or 0)
    active = str(job.get("current") or "NONE")
    failures = dict(job.get("failures") or {})
    started_at = float(job.get("started_at", 0.0) or 0.0)
    finished_at = float(job.get("finished_at", 0.0) or 0.0)
    end_at = finished_at if finished_at > 0 else time.time()
    elapsed = max(0.0, end_at - started_at) if started_at > 0 else 0.0

    lines = [
        "GEX PROCESS LOG",
        f"BUILD      {GEX_BUILD_VERSION}",
        f"STATUS     {status} // ELAPSED {elapsed:,.1f}s",
        f"PROGRESS   {completed}/{total} PROCESSED // {updated} UPDATED",
        f"ACTIVE     {active}",
        "FLOW       BATCH QUOTES -> EXPIRATIONS -> OPTION CHAINS -> GEX CALC -> MERGE",
        "ENGINE     20 CALC WORKERS // 20 FETCH SLOTS // 3.7 REQUEST STARTS/SEC",
        "CACHE      QUOTES 5M // CHAINS 5M // EXPIRATIONS 6H",
    ]
    if failures:
        lines.append(f"FAILURES   {len(failures)}")
        for ticker, message in list(failures.items())[:3]:
            clean = " ".join(str(message).split())[:90]
            lines.append(f"FAIL       {ticker} // {clean}")
    else:
        lines.append("FAILURES   0")
    lines.append("TIP        THIS SNAPSHOT REFRESHES WHEN THE GEX PAGE RERUNS")
    return "\n".join(lines)


def _decorate_gex_running_status(body: Any, vault_key: str) -> Any:
    """Attach the live process log to the existing spinning GEX status icon."""
    if not isinstance(body, str) or 'class="gexv3-running-status"' not in body:
        return body
    marker = '<span class="gexv3-running-icon">↻</span>'
    if marker not in body:
        return body
    log_attr = html.escape(_gex_progress_log(vault_key), quote=True).replace("\n", "&#10;")
    wrapped = (
        '<span class="gexv3-progress-hover" tabindex="0" '
        'aria-label="Hover for GEX process log" '
        f'data-log="{log_attr}">'
        f"{marker}"
        "</span>"
    )
    return body.replace(marker, wrapped, 1)


# ==============================
# BACKGROUND MARKET-DATA CACHE / PIPELINE
# ==============================
# The original terminal routes live E*TRADE reads through a short-lived smart
# cache. The detached GEX worker cannot safely call that Streamlit/session-aware
# wrapper from a background thread, so keep an equivalent GEX-only process cache
# here. This restores the original fast behavior without touching Streamlit from
# worker threads and without changing GEX formulas.
#
# E*TRADE documents a typical MARKET throttle of 4 requests/second. The top-level
# ticker pool and the chain-prefetch pool may keep more requests in flight than
# that because HTTPS responses can take several seconds; the shared start-rate
# gate below remains authoritative and spaces live MARKET request starts just
# under 4/sec. This hides network latency without increasing request-start rate.
#
# Refresh All uses one coherent quote snapshot for the same five-minute window
# as its option-chain snapshot. Manual single-ticker refresh remains a hard live
# refresh through the foreground terminal client.
_GEX_BACKGROUND_TTLS = {
    "quote": 5 * 60,
    "option_expirations": 6 * 60 * 60,
    "option_chain": 5 * 60,
}
_GEX_BACKGROUND_CACHE_RETENTION = 24 * 60 * 60
_GEX_BACKGROUND_CACHE_LIMIT = 1200
_GEX_BACKGROUND_CACHE_LOCK = threading.RLock()
_GEX_BACKGROUND_CACHE: dict[tuple[str, str, str], dict[str, Any]] = {}

# 0.27s between request starts ~= 3.70 MARKET requests/sec. The slight headroom
# below 4/sec avoids a boundary burst while keeping the pipeline full.
_GEX_MARKET_REQUEST_INTERVAL_SECONDS = 0.27
_GEX_MARKET_GATE_LOCK = threading.Lock()
_GEX_MARKET_NEXT_START = 0.0

# Twenty request workers are enough to hide roughly five seconds of network
# latency while the global gate still controls the actual E*TRADE request rate.
_GEX_CHAIN_PREFETCH_EXECUTOR = ThreadPoolExecutor(
    max_workers=20,
    thread_name_prefix="raj-gex-chain",
)
_GEX_CHAIN_PREFETCH_LOCK = threading.RLock()
_GEX_CHAIN_PREFETCH_FUTURES: dict[tuple[str, str, str], Future[Any]] = {}

# E*TRADE's quote endpoint accepts up to 50 symbols in one request when
# overrideSymbolCount=true. Refresh All therefore coalesces the watchlist into
# one INTRADAY quote request instead of spending one MARKET request per ticker.
_GEX_BATCH_QUOTE_LOCK = threading.RLock()
_GEX_BATCH_QUOTE_FUTURES: dict[tuple[str, tuple[str, ...]], Future[Any]] = {}


def _gex_cache_namespace(oauth_token: str) -> str:
    """Return a non-reversible namespace; never put the OAuth token in cache keys."""
    return hashlib.sha256(str(oauth_token).encode("utf-8")).hexdigest()[:32]


def _gex_market_rate_gate() -> None:
    """Space uncached E*TRADE MARKET request starts just below four per second."""
    global _GEX_MARKET_NEXT_START
    with _GEX_MARKET_GATE_LOCK:
        now = time.monotonic()
        wait_for = max(0.0, _GEX_MARKET_NEXT_START - now)
        if wait_for > 0:
            time.sleep(wait_for)
        started = time.monotonic()
        _GEX_MARKET_NEXT_START = started + _GEX_MARKET_REQUEST_INTERVAL_SECONDS


def _prune_gex_background_cache(namespace: str, now: float) -> None:
    keys = [key for key in _GEX_BACKGROUND_CACHE if key[0] == namespace]
    for key in keys:
        loaded_at = float(_GEX_BACKGROUND_CACHE[key].get("loaded_at", 0.0) or 0.0)
        if now - loaded_at > _GEX_BACKGROUND_CACHE_RETENTION:
            _GEX_BACKGROUND_CACHE.pop(key, None)

    keys = [key for key in _GEX_BACKGROUND_CACHE if key[0] == namespace]
    if len(keys) <= _GEX_BACKGROUND_CACHE_LIMIT:
        return
    keys.sort(
        key=lambda key: float(
            _GEX_BACKGROUND_CACHE[key].get("loaded_at", 0.0) or 0.0
        )
    )
    for key in keys[: len(keys) - _GEX_BACKGROUND_CACHE_LIMIT]:
        _GEX_BACKGROUND_CACHE.pop(key, None)


def _gex_cached_market_read(
    namespace: str,
    resource_type: str,
    resource_key: str,
    loader: Callable[[], Any],
) -> Any:
    """Return fresh cached market data or load it once from E*TRADE.

    Cache hits return immediately. Only true live requests pass through the
    shared MARKET rate gate. If a live request fails after a prior successful
    load, keep the last-known payload available to the calculation instead of
    losing the whole ticker.
    """
    ttl = int(_GEX_BACKGROUND_TTLS[resource_type])
    now = time.time()
    key = (namespace, resource_type, str(resource_key))
    stale_value: Any = None

    with _GEX_BACKGROUND_CACHE_LOCK:
        _prune_gex_background_cache(namespace, now)
        entry = _GEX_BACKGROUND_CACHE.get(key)
        if entry is not None:
            stale_value = entry.get("value")
            age = now - float(entry.get("loaded_at", 0.0) or 0.0)
            if age < ttl:
                return stale_value

    try:
        _gex_market_rate_gate()
        value = loader()
    except Exception:
        if stale_value is not None:
            return stale_value
        raise

    with _GEX_BACKGROUND_CACHE_LOCK:
        _GEX_BACKGROUND_CACHE[key] = {
            "loaded_at": time.time(),
            "value": value,
        }
        _prune_gex_background_cache(namespace, time.time())
    return value


def _gex_prefetch_future(
    namespace: str,
    resource_type: str,
    resource_key: str,
) -> Future[Any] | None:
    key = (namespace, resource_type, str(resource_key))
    with _GEX_CHAIN_PREFETCH_LOCK:
        return _GEX_CHAIN_PREFETCH_FUTURES.get(key)


def _schedule_gex_prefetch(
    namespace: str,
    resource_type: str,
    resource_key: str,
    loader: Callable[[], Any],
) -> Future[Any] | None:
    """Schedule one cache-coalesced background market read if it is not fresh."""
    key = (namespace, resource_type, str(resource_key))
    now = time.time()
    ttl = int(_GEX_BACKGROUND_TTLS[resource_type])

    with _GEX_BACKGROUND_CACHE_LOCK:
        entry = _GEX_BACKGROUND_CACHE.get(key)
        if entry is not None:
            age = now - float(entry.get("loaded_at", 0.0) or 0.0)
            if age < ttl:
                return None

    with _GEX_CHAIN_PREFETCH_LOCK:
        existing = _GEX_CHAIN_PREFETCH_FUTURES.get(key)
        if existing is not None and not existing.done():
            return existing

        future = _GEX_CHAIN_PREFETCH_EXECUTOR.submit(
            _gex_cached_market_read,
            namespace,
            resource_type,
            str(resource_key),
            loader,
        )
        _GEX_CHAIN_PREFETCH_FUTURES[key] = future

        def cleanup(done: Future[Any], _key=key) -> None:
            with _GEX_CHAIN_PREFETCH_LOCK:
                if _GEX_CHAIN_PREFETCH_FUTURES.get(_key) is done:
                    _GEX_CHAIN_PREFETCH_FUTURES.pop(_key, None)

        future.add_done_callback(cleanup)
        return future


def _gex_quote_records(payload: dict[str, Any]) -> list[dict[str, Any]]:
    """Extract QuoteData records without depending on response-key casing."""
    for node in walk_dicts(payload):
        for key, value in node.items():
            if str(key).casefold() != "quotedata":
                continue
            if isinstance(value, list):
                return [row for row in value if isinstance(row, dict)]
            if isinstance(value, dict):
                return [value]
    return []


def _schedule_gex_batch_quotes(
    namespace: str,
    symbols: list[str],
    raw_client_factory: Callable[[], ETradeClient],
) -> Future[Any] | None:
    """Fetch up to 50 watchlist quotes in one E*TRADE MARKET request."""
    normalized = tuple(
        sorted({str(symbol).strip().upper() for symbol in symbols if str(symbol).strip()})
    )[:50]
    if not normalized:
        return None

    now = time.time()
    ttl = int(_GEX_BACKGROUND_TTLS["quote"])
    with _GEX_BACKGROUND_CACHE_LOCK:
        missing = []
        for symbol in normalized:
            entry = _GEX_BACKGROUND_CACHE.get((namespace, "quote", symbol))
            age = (
                now - float(entry.get("loaded_at", 0.0) or 0.0)
                if entry is not None
                else float("inf")
            )
            if entry is None or age >= ttl:
                missing.append(symbol)
    if not missing:
        return None

    request_symbols = tuple(missing[:50])
    future_key = (namespace, request_symbols)
    with _GEX_BATCH_QUOTE_LOCK:
        existing = _GEX_BATCH_QUOTE_FUTURES.get(future_key)
        if existing is not None and not existing.done():
            return existing

        def load_batch() -> int:
            _gex_market_rate_gate()
            raw = raw_client_factory()
            payload = raw._get(
                "/v1/market/quote/" + ",".join(request_symbols),
                {
                    "detailFlag": "INTRADAY",
                    "overrideSymbolCount": "true",
                    "skipMiniOptionsCheck": "true",
                },
            )
            loaded_at = time.time()
            loaded = 0
            with _GEX_BACKGROUND_CACHE_LOCK:
                for record in _gex_quote_records(payload):
                    try:
                        symbol = str(quote_summary(record).get("symbol") or "").strip().upper()
                    except Exception:
                        continue
                    if not symbol:
                        continue
                    _GEX_BACKGROUND_CACHE[(namespace, "quote", symbol)] = {
                        "loaded_at": loaded_at,
                        "value": record,
                    }
                    loaded += 1
                _prune_gex_background_cache(namespace, loaded_at)
            return loaded

        future = _GEX_CHAIN_PREFETCH_EXECUTOR.submit(load_batch)
        _GEX_BATCH_QUOTE_FUTURES[future_key] = future

        def cleanup(done: Future[Any], _key=future_key) -> None:
            with _GEX_BATCH_QUOTE_LOCK:
                if _GEX_BATCH_QUOTE_FUTURES.get(_key) is done:
                    _GEX_BATCH_QUOTE_FUTURES.pop(_key, None)

        future.add_done_callback(cleanup)
        return future


class _GEXBackgroundCachedClient:
    """Cache-aware market client used only by GEX Refresh All.

    ``core._build_gex(..., force_refresh=True)`` historically meant that every
    refresh-all pass bypassed the terminal cache. For a 49-ticker watchlist that
    can cause hundreds of duplicate option-chain requests. This adapter accepts
    the force-refresh keyword for compatibility but intentionally treats Refresh
    All as "ensure data is fresh within the terminal TTL". A manual single-ticker
    refresh still uses the foreground client and retains its existing hard-refresh
    behavior.

    After the expiration list arrives, every eligible chain for that ticker is
    queued immediately. ``core._build_gex`` still consumes those expirations in
    the exact same order and runs the exact same calculation; its synchronous
    chain calls simply wait on the already-running prefetch future when needed.
    """

    def __init__(
        self,
        client: ETradeClient,
        namespace: str,
        raw_client_factory: Callable[[], ETradeClient],
        dte_by_symbol: dict[str, int],
        timezone_name: str,
    ) -> None:
        self._client = client
        self._namespace = namespace
        self._raw_client_factory = raw_client_factory
        self._dte_by_symbol = dict(dte_by_symbol)
        self._timezone_name = str(timezone_name or "America/New_York")

    @staticmethod
    def _chain_resource_key(
        symbol: str,
        expiry_year: int,
        expiry_month: int,
        expiry_day: int,
        no_of_strikes: int | None,
        chain_type: str,
    ) -> str:
        strikes_key = "ALL" if no_of_strikes is None else str(int(no_of_strikes))
        return (
            f"{symbol}:{int(expiry_year):04d}-{int(expiry_month):02d}-{int(expiry_day):02d}:"
            f"{str(chain_type).upper()}:{strikes_key}"
        )

    def _prefetch_eligible_chains(self, symbol: str, payload: dict[str, Any]) -> None:
        max_dte = int(self._dte_by_symbol.get(symbol, 45) or 45)
        try:
            tz = ZoneInfo(self._timezone_name)
        except Exception:
            tz = ZoneInfo("America/New_York")
        today = datetime.now(tz).date()

        for year, month, day in option_expiration_dates(payload):
            expiry = datetime(year, month, day, tzinfo=tz).date()
            dte = max((expiry - today).days, 0)
            if not (0 <= dte <= max_dte):
                continue

            resource_key = self._chain_resource_key(
                symbol,
                year,
                month,
                day,
                100,
                "CALLPUT",
            )

            def load_chain(
                _symbol=symbol,
                _year=year,
                _month=month,
                _day=day,
            ) -> dict[str, Any]:
                raw = self._raw_client_factory()
                return raw.get_option_chain(
                    _symbol,
                    int(_year),
                    int(_month),
                    int(_day),
                    no_of_strikes=100,
                    chain_type="CALLPUT",
                )

            _schedule_gex_prefetch(
                self._namespace,
                "option_chain",
                resource_key,
                load_chain,
            )

    def get_quote(self, symbol: str, force_refresh: bool = False) -> dict[str, Any]:
        symbol = str(symbol).strip().upper()
        symbols = list(self._dte_by_symbol)
        if symbol and symbol not in symbols:
            symbols.append(symbol)
        try:
            future = _schedule_gex_batch_quotes(
                self._namespace,
                symbols,
                self._raw_client_factory,
            )
            if future is not None:
                future.result()
        except Exception:
            # If the bulk endpoint ever rejects one symbol, preserve the proven
            # single-symbol path rather than failing the entire GEX ticker.
            pass
        return _gex_cached_market_read(
            self._namespace,
            "quote",
            symbol,
            lambda: self._client.get_quote(symbol),
        )

    def get_option_expirations(
        self,
        symbol: str,
        force_refresh: bool = False,
    ) -> dict[str, Any]:
        symbol = str(symbol).strip().upper()
        payload = _gex_cached_market_read(
            self._namespace,
            "option_expirations",
            symbol,
            lambda: self._client.get_option_expirations(symbol),
        )
        self._prefetch_eligible_chains(symbol, payload)
        return payload

    def get_option_chain(
        self,
        symbol: str,
        expiry_year: int,
        expiry_month: int,
        expiry_day: int,
        no_of_strikes: int | None = 100,
        chain_type: str = "CALLPUT",
        force_refresh: bool = False,
    ) -> dict[str, Any]:
        symbol = str(symbol).strip().upper()
        chain_type = str(chain_type).upper()
        resource_key = self._chain_resource_key(
            symbol,
            expiry_year,
            expiry_month,
            expiry_day,
            no_of_strikes,
            chain_type,
        )

        prefetched = _gex_prefetch_future(
            self._namespace,
            "option_chain",
            resource_key,
        )
        if prefetched is not None:
            try:
                return prefetched.result()
            except Exception:
                # Fall through to the normal stale-safe cache path. If the
                # prefetch failed transiently, this gives the request one normal
                # retry without changing calculation semantics.
                pass

        return _gex_cached_market_read(
            self._namespace,
            "option_chain",
            resource_key,
            lambda: self._client.get_option_chain(
                symbol,
                int(expiry_year),
                int(expiry_month),
                int(expiry_day),
                no_of_strikes=no_of_strikes,
                chain_type=chain_type,
            ),
        )


