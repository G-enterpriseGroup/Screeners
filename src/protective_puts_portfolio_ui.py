def _preferred_account_index(accounts: list[dict[str, Any]]) -> int:
    """Default to the Raj Singh brokerage account, never a random first account."""
    for index, account in enumerate(accounts):
        name = str(account.get("accountName") or account.get("accountDesc") or "").strip()
        if name.casefold() == "raj singh":
            return index
    # Match the canonical E*TRADE Risk Sizing default if its display name is absent.
    for index, account in enumerate(accounts):
        if str(account.get("accountId") or "").endswith("5474"):
            return index
    return 0


def _safe_account_index(
    accounts: list[dict[str, Any]], current: Any, initialized: bool,
) -> int:
    """Restore saved account selection without ever indexing a missing session key."""
    if initialized and type(current) is int and 0 <= current < len(accounts):
        return current
    return _preferred_account_index(accounts)


def _account_token(account_key: str) -> str:
    """Separate accounts without exposing account keys in localStorage names."""
    return hashlib.sha256(account_key.encode("utf-8")).hexdigest()[:24]


def _selected_symbols(value: Any) -> list[str]:
    """Keep valid saved ticker intentions even across partial holdings snapshots."""
    if not isinstance(value, list):
        return []
    return sorted({
        symbol for raw in value
        if re.fullmatch(r"[A-Z][A-Z0-9.-]{0,12}",
                        symbol := str(raw).strip().upper())
    })


def _selection_session_key(account_key: str) -> str:
    return "_pp_hedge_selected_v1::" + _account_token(account_key)


def _load_selection(account_key: str) -> dict[str, Any] | None:
    """Read and reconcile browser state before rendering editable checkboxes."""
    token = _account_token(account_key)
    session_key = _selection_session_key(account_key)
    if session_key not in st.session_state:
        with st.container(key="pp_hedge_selection_reader_shell", gap=None):
            restored = _SELECTION_COMPONENT(
                storage_key=_SELECTION_STORAGE_PREFIX + "::" + token,
                server_state={"revision": 0, "tickers": []},
                mode="read", hydrated=False,
                key="pp_hedge_reader_" + token, default=None,
            )
        if not isinstance(restored, dict) or restored.get("source") not in {"browser", "empty"}:
            return None  # Never draw unchecked boxes before storage is hydrated.
        browser_state = restored.get("state") if isinstance(restored.get("state"), dict) else {}
        stored = browser_state.get("tickers")
        selected = _selected_symbols(stored)
        try:
            revision = max(0, int(browser_state.get("revision") or 0))
        except (TypeError, ValueError, OverflowError):
            revision = 0
        if selected != stored and stored is not None:
            revision += 1
        st.session_state[session_key] = {"revision": revision, "tickers": selected}

    state = st.session_state[session_key]
    selected = _selected_symbols(state.get("tickers"))
    if selected != state.get("tickers"):
        state = {"revision": int(state.get("revision") or 0) + 1, "tickers": selected}
        st.session_state[session_key] = state
    return state


def _toggle_selection(account_key: str, symbol: str, widget_key: str) -> None:
    """Persist each explicit checkbox click independently of Streamlit widgets."""
    session_key = _selection_session_key(account_key)
    state = st.session_state.get(session_key)
    if not isinstance(state, dict):
        return
    selected = set(state.get("tickers") or [])
    if st.session_state.get(widget_key, False):
        selected.add(symbol)
    else:
        selected.discard(symbol)
    st.session_state[session_key] = {
        "revision": int(state.get("revision") or 0) + 1,
        "tickers": sorted(selected),
    }


def _write_selection(account_key: str) -> None:
    """Write only after browser hydration; storage keeps four prior backups."""
    token = _account_token(account_key)
    state = st.session_state.get(_selection_session_key(account_key))
    if not isinstance(state, dict):
        return
    with st.container(key="pp_hedge_selection_writer_shell", gap=None):
        _SELECTION_COMPONENT(
            storage_key=_SELECTION_STORAGE_PREFIX + "::" + token,
            server_state=state, mode="write", hydrated=True,
            key="pp_hedge_writer_" + token, default=None,
        )



