def _chain_cell_markup(row: dict[str, Any]) -> str:
    """One readable Ghotra-style quote table, with per-contract loss math."""
    tone = ("pp-chain-top" if row.get("Priority") else
            "pp-chain-best" if row.get("Best / Expiration") else "")

    def price(value: Any) -> str:
        try:
            return "—" if pd.isna(value) else "$" + f"{float(value):,.2f}"
        except (TypeError, ValueError):
            return "—"

    # The original complete ASK-based calculation is preserved in the tooltip.
    # A compact numbers-only rendering makes it readable inside the table.
    expression = str(row.get("Max Loss Calc (Ask)") or "—")
    match = re.search(
        r"\(\s*([\d.,]+)\s*\+\s*([\d.,]+)\s*-\s*([\d.,]+)\s*\)\s*[×x*]\s*100",
        expression,
    )
    if match:
        a, b, k = (f"{float(value.replace(',', '')):,.2f}" for value in match.groups())
        compact_calc = f"100×({a}+{b}−{k})⁺"
    else:
        compact_calc = expression

    rows = [
        ("Proxy", str(row["Proxy"])),
        ("Contract", str(row.get("Contract") or "—")),
        ("Expiration", str(row["Expiration"])),
        ("DTE", str(int(row["DTE"]))),
        ("Strike", price(row["Strike"])),
        ("Bid", price(row["Bid"])),
        ("Ask", price(row["Ask"])),
        ("Cost of Put (Ask)", price(row["Cost of Put (Ask)"])),
        ("Max Loss (Ask)", price(row["Max Loss (Ask)"])),
        ("Max Loss Calc (Ask)", compact_calc),
        ("Contracts", str(int(row["Contracts"]))),
        ("Open Interest", str(int(row["Open Interest"]))
         if pd.notna(row["Open Interest"]) else "—"),
    ]
    return '<div class="pp-chain-cells ' + tone + '">' + "".join(
        '<span title="' + html.escape(
            f"{name}: {expression if name == 'Max Loss Calc (Ask)' else value}"
            + (f" // LAST {price(row.get('Last'))} // VOL {row.get('Volume')}"
               if name == "Contract" else ""),
            quote=True,
        ) + '">' + html.escape(value) + '</span>'
        for name, value in rows
    ) + "</div>"


def _annual_lowest_loss_ids(data: pd.DataFrame) -> set[str]:
    """One valid lowest whole-contract modeled loss per ETF/year.

    Compare the complete loaded ASK chain, breaking loss ties by lower premium,
    DTE, strike and exact contract; never claim a basket protection guarantee.
    """
    if data.empty:
        return set()
    work = data.copy()
    work["_year"] = pd.to_datetime(
        work["Expiration"], format="%m-%d-%y", errors="coerce",
    ).dt.year
    metric = ("ETF-Equivalent Max Loss (Ask)" if
              "ETF-Equivalent Max Loss (Ask)" in work else "Max Loss (Ask)")
    work["_loss"] = pd.to_numeric(work[metric], errors="coerce")
    premium_col = "Put Cost" if "Put Cost" in work else "Cost of Put (Ask)"
    work["_premium"] = pd.to_numeric(work[premium_col], errors="coerce")
    work["_ask"] = pd.to_numeric(work["Ask"], errors="coerce")
    work = work.loc[
        work["_year"].notna()
        & work["_loss"].ge(0) & work["_loss"].lt(float("inf"))
        & work["_premium"].ge(0) & work["_premium"].lt(float("inf"))
        & work["_ask"].gt(0) & work["_ask"].lt(float("inf"))
        & work["Orderable"].eq(True)
    ]
    if work.empty:
        return set()
    ordered = work.sort_values(
        ["Proxy", "_year", "_loss", "_premium", "DTE", "Strike", "Contract"],
        ascending=[True] * 7, kind="stable",
    )
    return {
        _contract_identity(row)
        for row in ordered.drop_duplicates(["Proxy", "_year"]).to_dict("records")
    }


def _chain_scroll_values(
    row: dict[str, Any], hedge_exposure: float = 0.0,
) -> dict[str, Any]:
    """One executable whole-PUT payoff and matching selected ETF proxy shares."""
    def price(value: Any) -> str:
        try:
            return "—" if pd.isna(value) else f"${float(value):,.2f}"
        except (TypeError, ValueError):
            return "—"

    contracts = int(row["Contracts"])
    exposure = float(hedge_exposure or 0.0)
    if exposure > 0:
        spot, strike, ask = (
            float(row["Spot"]), float(row["Strike"]), float(row["Ask"])
        )
        equivalent_shares = exposure / spot
        beta = float(row.get("Model Beta") or 1.0)
        max_loss, worst_spot = proxy_put_max_loss(
            spot=spot, strike=strike, ask=ask,
            contracts=contracts, basket_value=exposure, beta=beta,
        )
        zero_pl = proxy_put_expiry_pnl(
            spot=spot, strike=strike, ask=ask, contracts=contracts,
            basket_value=exposure, expiry_spot=0.0, beta=beta,
        )
        strike_pl = proxy_put_expiry_pnl(
            spot=spot, strike=strike, ask=ask, contracts=contracts,
            basket_value=exposure, expiry_spot=strike, beta=beta,
        )
        expression = (
            f"MAX LOSS = max(0, -min(P/L ETF@0 ${zero_pl:,.2f}, "
            f"P/L ETF@STRIKE ${strike_pl:,.2f}"
            + (f", P/L @ BETA FLOOR" if beta > 1 else "")
            + f")) = ${max_loss:,.2f} // WORST ETF PRICE ${worst_spot:,.2f}"
            f" // FULL PUT PREMIUM ${ask * 100 * contracts:,.2f}"
            f" // BASKET ${exposure:,.2f} / ETF SPOT ${spot:,.2f}"
            f" = {equivalent_shares:.4f} SHARES; {contracts} x 100-SH PUTS"
        )
        compact_calc = f"0/K: {max(0,-zero_pl):,.0f}/{max(0,-strike_pl):,.0f}"
        display_loss = max_loss
        qty_title = (
            f"PUT QTY {contracts} (EACH PUT COVERS 100 SHARES) // "
            f"BASKET ${exposure:,.2f} ÷ ETF SPOT ${spot:,.2f} "
            f"= {equivalent_shares:,.2f} ETF-EQUIVALENT SHARES"
        )
    else:
        # Direct 100-share example already has the exact whole-contract
        # matched-ETF maximum loss calculated in portfolio_chain_scenario.
        equivalent_shares = 100.0 * contracts
        display_loss = row["Max Loss (Ask)"]
        expression = str(row.get("Max Loss Calc (Ask)") or "—")
        match = re.search(
            r"\(\s*([\d.,]+)\s*\+\s*([\d.,]+)\s*-\s*([\d.,]+)\s*\)\s*[×x*]\s*100",
            expression,
        )
        if match:
            a, b, k = (f"{float(v.replace(',', '')):,.2f}" for v in match.groups())
            compact_calc = f"100×({a}+{b}−{k})⁺"
        else:
            compact_calc = expression
        qty_title = (
            f"PUT QTY {contracts} // {equivalent_shares:,.0f} ETF SHARES REPRESENTED "
            "AT 100 SHARES PER PUT CONTRACT"
        )
    qty_value = f"{contracts} / {equivalent_shares:,.1f} SH"
    oi = row.get("Open Interest")
    values = [
        str(row["Proxy"]), str(row.get("Contract") or "—"),
        str(row["Expiration"]), str(int(row["DTE"])),
        price(strike), price(row["Bid"]), price(ask),
        price(row["Cost of Put (Ask)"]), price(max_loss),
        compact_calc, qty_value, str(int(oi)) if pd.notna(oi) else "—",
    ]
    return {
        "values": values, "calc": expression, "qty_title": qty_title,
        "last": price(row.get("Last")), "volume": str(row.get("Volume") or "—"),
    }


def _toggle_contract_buy(state_key: str, scope_key: str, identity: str) -> None:
    """Toggle an exact contract from a full-cell BUY control; never place an order."""
    state = st.session_state.get(state_key)
    if not isinstance(state, dict) or state.get("scope") != scope_key:
        return
    checked = set(state.get("ids") or set())
    if identity in checked:
        checked.remove(identity)
    else:
        checked.add(identity)
    state["ids"] = checked
    st.session_state[state_key] = state


def _render_risk_slide(
    result: dict[str, Any], chosen: list[dict[str, Any]],
    money: Callable, metric_markup: Callable,
) -> None:
    """E*TRADE-style benchmark-move grid + expiry P/L curve for CHECKED PUTS only."""
    if not chosen:
        return  # No checked BUY = no risk slide, no imaginary unhedged chart.
    import plotly.graph_objects as go

    options = [_contract_identity(row) for row in chosen]
    if len(chosen) > 1:
        selection_hash = hashlib.sha256(repr(sorted(options)).encode("utf-8")).hexdigest()[:12]
        selected_id = st.selectbox(
            "RISK SLIDE // CHECKED PUT", options, key="pp_risk_slide_" + selection_hash,
            format_func=lambda identity: next(
                (f'{r["Proxy"]} {r["Expiration"]} ${float(r["Strike"]):,.2f} '
                 f'PUT × {int(r["Contracts"])}' for r in chosen
                 if _contract_identity(r) == identity), identity,
            ),
            help="Only checked PUT rows appear. Each contract is modeled separately, not summed into a fictitious combined portfolio.",
        )
        row = next(r for r in chosen if _contract_identity(r) == selected_id)
    else:
        row = chosen[0]

    spot, strike, ask = float(row["Spot"]), float(row["Strike"]), float(row["Ask"])
    contracts = int(row["Contracts"])
    beta = float(result.get("beta") or 1.0)
    selected_basket = float(result.get("exposure") or 0.0)
    basket = selected_basket if selected_basket > 0 else 100.0 * spot
    shares = basket / spot
    premium = 100.0 * ask * contracts
    loss, worst_price = proxy_put_max_loss(
        spot=spot, strike=strike, ask=ask, contracts=contracts,
        basket_value=basket, beta=beta,
    )
    strike_move = 100.0 * (strike / spot - 1.0)
    # Include the strike even if it falls just outside the standard ±20% grid.
    moves = sorted(set(
        [-100, -75, -50, -40, -30, -25, -20, -15, -10, -5, -2,
         0, 2, 5, 10, 15, 20, 25, 30, 40, 50, 75, 100]
        + [strike_move, strike_move - .001, strike_move + .001]
    ))
    def unhedged_pnl(future: float) -> float:
        return max(0.0, basket * (1.0 + beta * (future / spot - 1.0))) - basket

    profile = []
    for move in moves:
        future = max(0.0, spot * (1.0 + move / 100.0))
        pnl = proxy_put_expiry_pnl(
            spot=spot, strike=strike, ask=ask, contracts=contracts,
            basket_value=basket, expiry_spot=future, beta=beta,
        )
        profile.append((move, future, unhedged_pnl(future), pnl))
    st.html('<div class="pp-section">CHECKED PUT RISK SLIDE // EXPIRATION P/L</div>')
    st.html(metric_markup([
        ("Selected PUT", f'{row["Proxy"]} ${strike:,.2f} P', "orange"),
        ("ETF-Equivalent Shares", f"{shares:,.2f}", "blue"),
        ("Whole PUT Contracts", str(contracts), "orange"),
        ("ASK Premium", money(premium), "orange"),
        ("Worst @ ETF Price", money(worst_price), "red"),
        ("Modeled Max Loss*", money(loss), "red" if loss > 0 else "green"),
    ]))
    fig = go.Figure()
    fig.add_trace(go.Scatter(
        x=[r[0] for r in profile], y=[r[2] for r in profile],
        name="No PUT / basket", mode="lines",
        line={"color": "#8d8d97", "width": 2, "dash": "dot"},
        hovertemplate="S&P 500 move (assumed ETF move) %{x:.1f}%"
                      "<br>Unhedged basket P/L $%{y:,.2f}<extra></extra>",
    ))
    fig.add_trace(go.Scatter(
        x=[r[0] for r in profile], y=[r[3] for r in profile],
        name="Basket + checked PUT", mode="lines",
        line={"color": "#fb8b1e", "width": 3},
        hovertemplate="S&P 500 move (assumed ETF move) %{x:.1f}%"
                      "<br>Hedged P/L $%{y:,.2f}<extra></extra>",
    ))
    fig.add_hline(y=0, line_width=1, line_dash="dash", line_color="#878787")
    fig.add_vline(
        x=strike_move, line_dash="dot", line_color="#a3e635",
        annotation_text=f"PUT STRIKE {strike:,.0f}",
        annotation_position="top right",
    )
    fig.add_vline(x=0, line_dash="dot", line_color="#4aa5df")
    fig.update_layout(
        height=310, margin={"l": 8, "r": 8, "b": 14, "t": 6},
        paper_bgcolor="#000", plot_bgcolor="#080808",
        font={"color": "#f5b66e", "family": "Courier New", "size": 11},
        xaxis={"title": "S&P 500 MOVE (%) // SAME ETF MOVE ASSUMED",
               "gridcolor": "#262626", "zeroline": False},
        yaxis={"title": "PROFIT / LOSS ($)", "gridcolor": "#262626",
               "tickprefix": "$", "tickformat": ",.0f"},
        legend={"orientation": "h", "y": 1.13, "x": 0},
        hovermode="x unified",
    )
    grid_moves = sorted(set(
        [-20, -15, -10, -5, -2, 0, 2, 5, 10, 15, 20, round(strike_move, 4)]
    ))
    grid_rows = []
    for move in grid_moves:
        future = spot * (1.0 + move / 100.0)
        grid_rows.append({
            "S&P 500 %*": f"{move:+.2f}%",
            "ETF PRICE": money(future),
            "NO PUT P/L": money(unhedged_pnl(future)),
            "WITH PUT P/L": money(proxy_put_expiry_pnl(
                spot=spot, strike=strike, ask=ask, contracts=contracts,
                basket_value=basket, expiry_spot=future, beta=beta,
            )),
        })
    left, right = st.columns([2.0, 1.15], gap="small", vertical_alignment="top")
    with left:
        st.plotly_chart(fig, width="stretch", config={"displayModeBar": False})
    with right:
        st.dataframe(
            pd.DataFrame(grid_rows), hide_index=True, height=310, width="stretch",
        )
    st.caption(
        f'SELECTED CONTRACT ONLY // ${basket:,.2f} BASKET AS {shares:,.2f} '
        f'{row["Proxy"]}-EQUIVALENT SHARES // {contracts} PUT(S) × 100 SHARES; '
        f'FULL ${premium:,.2f} ASK PREMIUM INCLUDED. *S&P 500 MOVES ARE A '
        'SCENARIO AXIS; ETF IS ASSUMED TO MOVE BY THE SAME % AND BASKET BY '
        f'BETA {beta:.2f}, NOT HISTORICAL CORRELATIONS. '
        'EXPIRATION INTRINSIC VALUE ONLY: NO CURRENT-DATE GREEKS, IV CHANGES, '
        'DIVIDENDS OR FEES. NOT E*TRADE\'S PROPRIETARY RISK MODEL OR A '
        'GUARANTEED LOSS LIMIT FOR MIXED HOLDINGS.'
    )


