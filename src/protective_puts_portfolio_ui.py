def render_portfolio_hedge(
    client, touch_session, *, get_expirations, get_chain,
    market_today, live_etrade, money, metric_markup,
):
    """Enter tickers + Enter to scan full quoted puts; safe reviewed execution."""
    with st.container(key="pp_portfolio_hedge", gap="small"):
        st.html(_CSS)
        with st.expander("EDIT INVESTMENTS / ACCOUNT (SAVED CHECKMARKS)", expanded=False):
            book = _holdings(client, touch_session, live_etrade)
        account_key, selected = book if book is not None else ("", [])
        exposure = sum(float(row["Market Value"]) for row in selected)
        if selected:
            st.caption(f'PORTFOLIO // {len(selected)} TICKERS // {money(exposure)}')
        else:
            st.caption(
                "TICKER-ONLY MODE // the Married Put columns illustrate 100 "
                "shares of each entered ETF at its current price. "
                "Select holdings above to also model your portfolio."
            )
        st.html('<div class="pp-section">ENTER PUT TICKERS // PRESS ENTER TO SCAN</div>')
        entered = st.text_input(
            "PUT TICKER", value="", key="pp_hedge_proxies",
            placeholder="SPY  //  TYPE + ENTER",
            on_change=_run_enter_scan,
            help="Enter a ticker and press Enter to scan. Comma-separated tickers also work.",
        )
        # Keep model constants stable and documented; no seven-input setup.
        # Matched ETF married-put max loss is shown separately for 100 shares.
        dte, stress, beta = 60, 15.0, 1.0
        proxies = list(dict.fromkeys(
            s for s in re.split(r"[\s,;]+", entered.strip().upper()) if s
        ))
        if not (1 <= len(proxies) <= 5 and all(
            re.fullmatch(r"[A-Z][A-Z0-9.\-]{0,9}", s) for s in proxies
        )):
            st.warning("ENTER 1–5 VALID PUT TICKERS (E.G. SPY,QQQ) AND PRESS ENTER.")
            return
        fingerprint = (
            account_key,
            tuple(sorted((row["Symbol"], round(float(row["Market Value"]), 2))
                         for row in selected)),
            tuple(proxies), dte, stress, beta,
        )
        scan_now = bool(st.session_state.pop("_pp_hedge_scan_on_enter", False))
        with st.expander("REFRESH EXISTING CHAIN", expanded=False):
            if st.button("REFRESH PRICES", width="stretch", key="pp_hedge_scan"):
                scan_now = True
        if scan_now:
            # New scan invalidates any prior expiry dropdown and order preview.
            st.session_state.pop("pp_chain_expiry_choice", None)
            st.session_state.pop("pp_hedge_order_preview", None)
            errors = []
            work = []
            all_expiries = {}
            today = market_today()
            for sym in proxies:
                try:
                    if live_etrade(client):
                        quote = quote_summary(client.get_quote(sym))
                        touch_session()
                    else:
                        quote = public_quote(sym)
                    spot = float(quote.get("last") or 0)
                    if spot <= 0:
                        raise ValueError("Put underlying quote unavailable.")
                    expiries, _ = get_expirations(client, sym, touch_session)
                    future = sorted(set(x for x in expiries if x >= today))
                    all_expiries[sym] = (spot, future)
                    if not future:
                        errors.append(f"{sym}: no future put expirations found.")
                        continue
                    # Quoting every daily expiry at once causes 4,000+ row
                    # reruns and hundreds of broker calls. Load a spread of
                    # near/mid/long expiries; the dropdown below exposes ALL
                    # actual dates and loads any other date on demand.
                    for expiry in _sample_expirations(future, today, dte):
                        work.append((sym, spot, expiry))
                except Exception as exc:
                    errors.append(f"{sym} quote/expiry: {exc}")
            raw_frames = []
            progress = st.progress(0.0, text="Fetching put option chains...")
            for index, (sym, spot, expiry) in enumerate(work, 1):
                try:
                    chain, _, source = get_chain(client, sym, expiry, touch_session)
                    raw_frames.append((sym, spot, expiry, chain, source))
                except Exception as exc:
                    errors.append(f"{sym} {expiry:%m-%d-%y}: {exc}")
                progress.progress(
                    index / max(1, len(work)),
                    text=f"FETCHING {sym} {expiry:%m-%d-%y} ({index}/{len(work)})",
                )
            progress.empty()
            st.session_state["pp_hedge_raw_scan"] = {
                "tickers": tuple(proxies), "frames": raw_frames,
                "errors": errors, "scan_id": int(time.time() * 1000),
                "chains_requested": len(work),
                "available_expirations": all_expiries,
                "attempted_dates": {(sym, expiry) for sym, _, expiry in work},
                "loaded_version": 1,
            }
        raw = st.session_state.get("pp_hedge_raw_scan")
        if isinstance(raw, dict) and raw.get("tickers") == tuple(proxies):
            # Expiry choice includes every available broker-listed future date,
            # irrespective of how many option chains have been downloaded.
            calendar = raw.get("available_expirations") or {}
            listed_dates = sorted({
                expiry for _, dates in calendar.values() for expiry in dates
            })
            if listed_dates:
                available_choices = ["ALL", *listed_dates]
                current = st.session_state.get("pp_chain_expiry_choice")
                if current not in available_choices:
                    st.session_state["pp_chain_expiry_choice"] = "ALL"
                choice = st.selectbox(
                    "ALL LISTED EXPIRATIONS // SELECT ANY DATE TO FETCH ITS PUTS",
                    available_choices, key="pp_chain_expiry_choice",
                    on_change=_reset_chain_page,
                    format_func=lambda value: (
                        "ALL SCANNED EXPIRATIONS" if value == "ALL"
                        else f"{value:%m-%d-%Y} // {(value-market_today()).days} DTE"
                    ),
                )
                if choice != "ALL":
                    for sym, (spot, dates) in calendar.items():
                        if choice not in dates:
                            continue
                        pair = (sym, choice)
                        if pair in raw["attempted_dates"]:
                            continue
                        raw["attempted_dates"].add(pair)
                        try:
                            chain, _, source = get_chain(client, sym, choice, touch_session)
                            raw["frames"].append((sym, spot, choice, chain, source))
                        except Exception as exc:
                            raw["errors"].append(f"{sym} {choice:%m-%d-%y}: {exc}")
                        raw["loaded_version"] += 1
                        st.session_state.pop("pp_hedge_order_preview", None)
            else:
                choice = "ALL"
            cache_scope = (
                raw["scan_id"], raw.get("loaded_version", 1),
                fingerprint, market_today(),
            )
            cache = st.session_state.get("_pp_hedge_ranked_result_cache")
            if isinstance(cache, dict) and cache.get("scope") == cache_scope:
                result = cache["result"]
            else:
                today = market_today()
                frames = []
                for sym, spot, expiry, chain, source in raw.get("frames", []):
                    try:
                        reference_exposure = exposure if exposure > 0 else spot * 100.0
                        f = portfolio_chain_scenario(
                            chain, symbol=sym, expiry=expiry, spot=spot,
                            exposure=reference_exposure, stress_pct=stress, beta=beta,
                            today=today, max_contracts=MAX_PUT_CONTRACTS,
                        )
                        if not f.empty:
                            if exposure <= 0:
                                # Ticker-only: one put, not a fictitious bulk hedge.
                                f["Contracts"] = 1
                                f["Put Cost"] = f["Cost of Put (Ask)"]
                                f["Cost %"] = 100.0 * f["Put Cost"] / reference_exposure
                                f["Stress Put Payout"] = (
                                    (f["Strike"] - spot * (1 - stress / 100)).clip(lower=0) * 100
                                )
                                f["Stress Remaining Loss"] = (
                                    reference_exposure * stress / 100
                                    + f["Put Cost"] - f["Stress Put Payout"]
                                ).clip(lower=0)
                                f["Near Zero Scenario"] = f["Stress Remaining Loss"].le(.005)
                                f["Orderable"] = True
                            f["Source"] = source
                            frames.append(f)
                    except Exception as exc:
                        raw.setdefault("errors", []).append(f"{sym} {expiry}: {exc}")
                direct_example = exposure <= 0
                data = rank_portfolio_chain(
                    pd.concat(frames, ignore_index=True) if frames else pd.DataFrame(),
                    preferred_dte=dte, direct_100_share_example=direct_example,
                )
                result = {
                    "fingerprint": fingerprint, "data": data,
                    "exposure": exposure,
                    "stress_loss": min(exposure, exposure * beta * stress / 100),
                    "stress": stress, "beta": beta,
                    "direct_example": direct_example,
                    "scan_id": raw["scan_id"],
                    "chains": len(raw.get("frames", [])),
                    "listed_count": len(listed_dates),
                    "errors": raw["errors"],
                }
                st.session_state["_pp_hedge_ranked_result_cache"] = {
                    "scope": cache_scope, "result": result,
                }
            result["expiry_choice"] = choice
            _results(result, money, metric_markup, client, touch_session,
                     live_etrade, account_key)
        else:
            st.caption("ENTER A PUT TICKER AND PRESS ENTER TO LOAD ITS OPTION CHAIN.")

