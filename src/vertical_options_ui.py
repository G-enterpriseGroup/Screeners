def _vertical_preview_error(exc: Exception) -> str:
    """Explain known E*TRADE account rejections without suggesting a bypass."""
    message = str(exc)
    if re.search(r"\b3031\b", message) or "unapproved options position" in message.lower():
        return (
            "E*TRADE ERROR 3031 // THIS ACCOUNT CANNOT OPEN THIS SPREAD "
            "WITH ITS OPTIONS APPROVAL AND/OR EXISTING POSITIONS/OPEN ORDERS. "
            "Debit spreads generally require Level 3 options approval and margin. "
            "Check this selected account's approval, positions, and open orders "
            "with E*TRADE. Preview rejected; no order was placed."
        )
    return message

def _render_selected_order(client, touch_session, candidate: dict[str, Any],
                           result: dict[str, Any], broker_live: bool) -> None:
    """Keep the existing reviewed, explicit multi-account order path optional."""
    if not broker_live or result["source"] != "E*TRADE":
        st.info("Reconnect E*TRADE and run a fresh E*TRADE scan before reviewing a live order.")
        return
    if not candidate.get("orderable", False):
        st.warning("UNQUOTED SPREAD // This row is informational only. Select a live quoted spread before E*TRADE review.")
        return
    if time.time() - float(result["loaded_at"]) >= _SCAN_CACHE_SECONDS:
        st.warning("MARKET SNAPSHOT EXPIRED // Scan again before reviewing a live order.")
        return
    accounts = [
        account for account in (st.session_state.get("etrade_accounts") or [])
        if isinstance(account, dict) and _account_key(account)
    ]
    if not accounts:
        try:
            accounts = [
                account for account in client.list_accounts()
                if isinstance(account, dict) and _account_key(account)
            ]
            touch_session()
        except Exception as exc:
            st.error(f"E*TRADE accounts unavailable: {exc}")
            return
    by_account = {_account_key(account): account for account in accounts}
    if not by_account:
        st.warning("No E*TRADE accounts are available for order review.")
        return

    symbol = candidate["symbol"]
    call_put = candidate["call_put"]
    expiry = candidate["expiry"]
    buy_strike = candidate["buy_strike"]
    sell_strike = candidate["sell_strike"]
    order_seed = candidate["id"]
    smart_mode = result.get("pricing_mode", "NORMAL") == "SMART FILL"
    min_reward_risk = result.get("min_reward_risk", _DEFAULT_MIN_REWARD_RISK)
    if st.session_state.get("_vo_order_candidate") != order_seed:
        st.session_state.pop("vo_limit_price", None)  # Remove the old editable debit's stale value.
        st.session_state["vo_qty"] = 1
        st.session_state["vo_duration"] = "GOOD_FOR_DAY"
        st.session_state["_vo_order_candidate"] = order_seed
        st.session_state.pop("vo_review_bundle", None)
        st.session_state.pop("vo_live_confirm", None)
        st.session_state.pop("vo_last_send_results", None)

    # SMART FILL uses DAY orders only: no overnight queued limit chasing.
    if smart_mode:
        st.session_state["vo_duration"] = "GOOD_FOR_DAY"
    account_options = list(by_account)
    current_accounts = [key for key in (st.session_state.get("vo_accounts") or []) if key in by_account]
    st.session_state["vo_accounts"] = current_accounts or _default_account_keys(accounts)
    # Start from the selected NORMAL/SMART NET_DEBIT. Broker review
    # rechecks the same legs and risk cap before any live order is enabled.
    limit_price = round(float(candidate["debit"]), 2)
    ladder = (smart_fill_ladder(candidate, result["max_cost"], min_reward_risk=min_reward_risk)
              if smart_mode and candidate.get("basis") == "SMART" else
              [limit_price] if smart_mode and candidate.get("basis") == "MID" else [])
    if smart_mode and not ladder:
        st.warning("SMART FILL PRICING UNAVAILABLE // Rescan a live quoted spread.")
        return
    controls = st.columns([.85, .9, 2.0, 1.3] if smart_mode else [.85, .9, 2.5], gap="small")
    quantity = int(controls[0].number_input(
        "Qty", min_value=1, max_value=5000, step=1, key="vo_qty",
    ))
    order_term = controls[1].selectbox(
        "Duration", ["GOOD_FOR_DAY"] if smart_mode else ["GOOD_FOR_DAY", "GOOD_UNTIL_CANCEL"],
        key="vo_duration",
        format_func=lambda value: "DAY" if value == "GOOD_FOR_DAY" else "GTC",
    )
    selected_accounts = controls[2].multiselect(
        "Accounts", account_options, key="vo_accounts",
        format_func=lambda key: _account_label(by_account[key]),
        help="For live submission, the same reviewed spread is placed once in EACH selected account. Saving Terminal drafts never sends to E*TRADE.",
    )
    account_keys = [key for key in selected_accounts if key in by_account]
    if smart_mode:
        limit_price = float(controls[3].selectbox(
            "SMART LIMIT", ladder,
            key="vo_smart_rung_" + result["scope"] + "_" + hashlib.sha256(
                order_seed.encode("utf-8")
            ).hexdigest()[:10],
            format_func=lambda value: f"${value:.2f} / ${value * 100:.0f}",
            help="Manual price ladder; selecting another rung NEVER places, "
                 "changes or queues an order. A new E*TRADE preview is required.",
        ))
    try:
        validate_vertical(
            call_put=call_put, buy_strike=buy_strike,
            sell_strike=sell_strike, quantity=quantity,
        )
        validation_error = ""
    except ValueError as exc:
        validation_error = str(exc)
        st.error(validation_error)
    if not math.isfinite(limit_price) or limit_price < .01:
        validation_error = "Checked spread's Last debit is too small to order. Rescan."
        st.error(validation_error)
    elif limit_price >= candidate["width"]:
        validation_error = "Checked spread's Last debit must stay below its width. Rescan."
        st.error(validation_error)
    elif result["max_cost"] is not None and limit_price * 100 > result["max_cost"] + 1e-6:
        validation_error = "Selected debit exceeds your maximum cost."
        st.error(validation_error)
    elif candidate["width"] - limit_price + 1e-8 < min_reward_risk * limit_price:
        validation_error = f"Selected debit fails the minimum 1:{min_reward_risk:g} reward-to-risk."
        st.error(validation_error)

    fingerprint = _review_fingerprint(
        symbol=symbol, call_put=call_put, expiry=expiry,
        buy_strike=buy_strike, sell_strike=sell_strike, quantity=quantity,
        limit_price=limit_price, min_reward_risk=min_reward_risk,
        order_term=order_term, account_keys=account_keys,
    )
    review_bundle = st.session_state.get("vo_review_bundle")
    if isinstance(review_bundle, dict) and review_bundle.get("fingerprint") != fingerprint:
        st.session_state.pop("vo_review_bundle", None)
        st.session_state.pop("vo_live_confirm", None)
        review_bundle = None

    st.markdown(
        '<div class="vo-summary">'
        + html.escape(
            f'{symbol} // {call_put} DEBIT // BUY {quantity} {_date_label(expiry)} {buy_strike:g} '
            f'+ SELL {quantity} {_date_label(expiry)} {sell_strike:g} // '
            f'CHECKED {candidate["basis"]} DEBIT {_money(limit_price)} PER SPREAD // '
            f'TOTAL ORDER DEBIT {_money(limit_price * 100 * quantity)} // '
            f'{len(account_keys)} ACCOUNT(S)'
        ) + "</div>",
        unsafe_allow_html=True,
    )
    if smart_mode:
        risk_ratio = (candidate["width"] - limit_price) / limit_price
        live_be = (candidate["buy_strike"] + limit_price if call_put == "CALL"
                   else candidate["buy_strike"] - limit_price)
        st.caption(
            f'SMART FILL // {candidate.get("liquidity_signal", "UNVERIFIED")} '
            f'// SELECTED R:R 1:{risk_ratio:.2f} // SELECTED BREAKEVEN {_money(live_be)} '
            '// VOLUME/OI ARE LEG-LEVEL SIGNALS; ORDER SIZE, QUEUE POSITION, '
            'QUOTE AGE AND ACTUAL FILL PROBABILITY ARE NOT PROVIDED. '
            'MANUAL LIMIT CHOICES ONLY.'
        )
    st.caption(
        f'Pricing: {candidate["basis"]} // spread market BID {_money(candidate.get("spread_bid"))} / '
        f'MID {_money(candidate.get("spread_mid"))} / ASK {_money(candidate.get("spread_ask"))}. '
        'ASK = BUY option ask − SELL option bid. MID/LAST can remain unfilled; '
        'quotes will be rechecked before E*TRADE preview.'
    )
    st.caption(
        "SAVE CHECKED SPREADS = TERMINAL-ONLY DRAFT; NOT SAVED AT E*TRADE. "
        "REVIEW WITH E*TRADE = PREVIEW ONLY. PLACE LIVE ORDER = BROKER "
        "SUBMISSION THAT MAY APPEAR AS QUEUED AND MAY EXECUTE. "
        "The E*TRADE public API cannot create broker-side Saved orders."
    )
    preview_click = st.button(
        f"REVIEW WITH E*TRADE // {len(account_keys)} ACCOUNT(S)",
        key="vo_preview", type="primary", use_container_width=True,
        disabled=bool(validation_error) or not account_keys,
    )
    if preview_click:
        # Requote only on an explicit Review click: no broker traffic on
        # checkbox, filter, order quantity, or OptionStrat interactions.
        try:
            latest = _chain(client, symbol, expiry, touch_session)
            def exact_leg(strike: float, osi: str) -> dict[str, Any]:
                for row in latest:
                    if (row.get("call_put") == call_put
                            and abs(float(row.get("strike") or 0) - strike) < 1e-5
                            and str(row.get("osi") or "") == str(osi or "")):
                        return row
                raise ValueError("Selected contract no longer has a current chain quote.")
            buy_leg = exact_leg(buy_strike, candidate.get("buy_osi", ""))
            sell_leg = exact_leg(sell_strike, candidate.get("sell_osi", ""))
            checked_price = price_vertical_quote(
                buy_last=buy_leg.get("last"), sell_last=sell_leg.get("last"),
                buy_bid=buy_leg.get("bid"), buy_ask=buy_leg.get("ask"),
                sell_bid=sell_leg.get("bid"), sell_ask=sell_leg.get("ask"),
                width=candidate["width"], max_cost=result["max_cost"],
                pricing_mode=result.get("pricing_mode", "NORMAL"),
                min_reward_risk=min_reward_risk,
                buy_volume=buy_leg.get("volume"), sell_volume=sell_leg.get("volume"),
                buy_open_interest=buy_leg.get("open_interest"),
                sell_open_interest=sell_leg.get("open_interest"),
            )
            if (not checked_price or not checked_price["orderable"]
                    or checked_price["basis"] != candidate["basis"]
                    or (smart_mode and (
                        checked_price["debit"] != candidate["debit"]
                        or limit_price < checked_price["spread_mid"] - .005
                        or limit_price > checked_price["spread_ask"] + .005
                        or candidate["width"] - limit_price + 1e-8 < min_reward_risk * limit_price
                        or (result["max_cost"] is not None
                            and limit_price * 100 > result["max_cost"] + 1e-8)
                    ))
                    or (not smart_mode and checked_price["debit"] != limit_price)):
                raise ValueError(
                    "The current spread market/SMART target changed or the selected limit "
                    f"no longer meets your 1:{min_reward_risk:g} and cost criteria. "
                    "SCAN ALL YEARS again before reviewing."
                )
        except Exception as exc:
            st.session_state.pop("vo_review_bundle", None)
            st.session_state.pop("vo_live_confirm", None)
            st.error(f"LIVE SPREAD REQUOTE BLOCKED // {exc}")
            return
        previews: dict[str, Any] = {}
        errors: list[str] = []
        for account_key in account_keys:
            try:
                preview_payload = build_vertical_preview_payload(
                    symbol=symbol, call_put=call_put, expiry=expiry,
                    buy_strike=buy_strike, sell_strike=sell_strike,
                    quantity=quantity, limit_price=limit_price,
                    order_term=order_term,
                    client_order_id=new_vertical_client_order_id("VO"),
                    min_reward_risk=min_reward_risk,
                )
                response = client.preview_order(account_key, preview_payload)
                touch_session()
                details = preview_details(response)
                if details.get("preview_id") in (None, ""):
                    raise ETradeError("E*TRADE preview returned no preview ID.")
                previews[account_key] = {
                    "preview_payload": preview_payload,
                    "place_payload": build_place_payload(preview_payload, details["preview_id"]),
                    "details": details,
                    "account_label": _account_label(by_account[account_key]),
                }
            except Exception as exc:
                errors.append(_account_label(by_account[account_key]) + " // " + _vertical_preview_error(exc))
        if errors:
            st.session_state.pop("vo_review_bundle", None)
            st.session_state.pop("vo_live_confirm", None)
            st.error(
                f"PREVIEW BLOCKED // {len(errors)} OF {len(account_keys)} SELECTED ACCOUNT(S) "
                "REJECTED. NO BROKER ORDER PLACED. All accounts must pass preview "
                "before live submission can be enabled."
            )
            for error in errors:
                st.warning(error)
        elif len(previews) == len(account_keys):
            st.session_state["vo_review_bundle"] = {
                "fingerprint": fingerprint, "previewed_at": time.time(), "previews": previews,
            }
            st.session_state.pop("vo_live_confirm", None)
            st.success("E*TRADE PREVIEW ACCEPTED FOR ALL SELECTED ACCOUNTS // NO ORDER SENT YET")

    review_bundle = st.session_state.get("vo_review_bundle")
    review_fresh = _reviews_are_fresh(review_bundle, fingerprint)
    if review_bundle and not review_fresh:
        st.session_state.pop("vo_review_bundle", None)
        st.session_state.pop("vo_live_confirm", None)
        st.warning("PREVIEW EXPIRED // Review again before sending live orders.")
        review_bundle = None
    if review_bundle and review_fresh:
        previews = review_bundle.get("previews") or {}
        for account_key in account_keys:
            review = previews.get(account_key) or {}
            details = review.get("details") or {}
            st.caption(
                f'{review.get("account_label") or _account_label(by_account[account_key])} // '
                f'Preview ID {details.get("preview_id") or "N/A"} // '
                f'Est. Value {_money(details.get("total_order_value"))} // '
                f'Est. Commission {_money(details.get("estimated_commission"))}'
            )
            for message in details.get("messages") or []:
                st.warning("E*TRADE PREVIEW // " + str(message))
        confirmed = st.checkbox(
            "I AUTHORIZE A LIVE E*TRADE ORDER IN EVERY SELECTED ACCOUNT (MAY QUEUE OR EXECUTE; NOT SAVED)",
            key="vo_live_confirm",
        )
        send_click = st.button(
            f"PLACE LIVE ORDER // {len(account_keys)} ACCOUNT(S) (MAY QUEUE)",
            key="vo_send", type="primary", use_container_width=True, disabled=not confirmed,
        )
        if send_click:
            if not _reviews_are_fresh(st.session_state.get("vo_review_bundle"), fingerprint):
                st.error("PREVIEW EXPIRED // Review again. No order was sent.")
                return
            results: list[dict[str, Any]] = []
            for account_key in account_keys:
                review = previews.get(account_key) or {}
                try:
                    response = client.place_order(account_key, review["place_payload"])
                    touch_session()
                    order_id = extract_order_id(response)
                    if order_id in (None, ""):
                        raise ETradeError("E*TRADE returned no order ID after placement.")
                    results.append({
                        "account": _account_label(by_account[account_key]),
                        "order_id": order_id, "status": "SUBMITTED",
                    })
                except Exception as exc:
                    results.append({
                        "account": _account_label(by_account[account_key]),
                        "order_id": "", "status": "UNCERTAIN / FAILED", "error": str(exc),
                    })
            st.session_state["vo_last_send_results"] = results
            st.session_state.pop("vo_review_bundle", None)
            st.session_state.pop("vo_live_confirm", None)
    for sent in st.session_state.get("vo_last_send_results") or []:
        if sent.get("status") == "SUBMITTED":
            st.success(f'{sent["account"]} // E*TRADE ORDER {sent["order_id"]} // SUBMITTED LIVE (MAY QUEUE/EXECUTE; NOT SAVED)')
        else:
            st.error(
                f'{sent["account"]} // SUBMISSION STATUS UNCERTAIN // '
                f'{sent.get("error") or "Check E*TRADE Orders before retrying."}'
            )


@st.fragment(run_every=.5)
def _render_vertical_options_bootstrap(vault_key: str) -> None:
    """Retry pricing restoration; stop polling on completion or timeout.

    Component replies can race a top-tab rerun. A transient missing reply must
    not leave the workspace cut off until the user switches tabs manually.
    This bootstrap never downloads chains or touches broker orders.
    """
    started = st.session_state.setdefault("_vo_bootstrap_started", time.monotonic())
    pricing_ready = _hydrate_vertical_options_pricing()
    if pricing_ready:
        st.session_state["_vo_workspace_ready"] = vault_key
        st.rerun()
    if time.monotonic() - started >= 12:
        st.session_state["_vo_bootstrap_failed"] = True
        st.rerun()  # Remove the polling fragment and show a stable retry state.
        return
    st.caption("RESTORING VERTICAL OPTIONS PREFERENCES…")



@st.fragment(run_every=1)
def _render_vertical_scan_continuation(client, touch_session) -> None:
    result = st.session_state.get("vo_scan_result") or {}
    if (not result or result.get("scan_complete", True)
            or result.get("symbol") != str(st.session_state.get("vo_symbol_value") or "").strip().upper()
            or not st.session_state.get("vo_auto_finish", True)
            or result.get("stopped_on_errors")
            or st.session_state.get("_vo_auto_scan_error")):
        return
    try:
        st.session_state["vo_scan_result"] = _continue_vertical_scan(result, client, touch_session)
        _remember_scan_snapshot()
    except Exception as exc:
        st.session_state["_vo_auto_scan_error"] = f"AUTO SCAN PAUSED // {exc}"
    st.rerun()  # Redraw the workspace, or remove this timer when finished/paused.


