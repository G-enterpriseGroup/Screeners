        structure_signature = f"{symbol}|{call_put}|{expiry.isoformat()}"
        if st.session_state.get("_vo_structure_seed") != structure_signature:
            atm = _closest_index(strikes, spot)
            if call_put == "CALL":
                buy_idx = min(atm, len(strikes) - 2)
                sell_idx = buy_idx + 1
            else:
                buy_idx = max(1, atm)
