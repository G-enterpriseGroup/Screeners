def _money(value: Any) -> str:
    try:
        return "$" + f"{float(value):,.2f}"
    except (TypeError, ValueError):
        return "—"


def _date_label(value: date) -> str:
    return value.strftime("%b-%d-%y")


def _account_key(account: dict[str, Any]) -> str:
    return str(account.get("accountIdKey") or "").strip()


def _account_label(account: dict[str, Any]) -> str:
    name = str(account.get("accountDesc") or account.get("accountName") or "E*TRADE")
    raw = str(account.get("accountId") or account.get("accountIdKey") or "")
    digits = "".join(ch for ch in raw if ch.isdigit())
    suffix = digits[-4:] if digits else raw[-4:]
    return f"{name} // x{suffix}" if suffix else name


def _default_account_keys(accounts: list[dict[str, Any]]) -> list[str]:
    raw_accounts = st.session_state.get("etrade_accounts") or []
    try:
        index = int(st.session_state.get("risk_sizing_account"))
    except (TypeError, ValueError):
        index = -1
    if 0 <= index < len(raw_accounts) and isinstance(raw_accounts[index], dict):
        wanted = _account_key(raw_accounts[index])
        if any(_account_key(account) == wanted for account in accounts):
            return [wanted]

    for account in accounts:
        raw = str(account.get("accountId") or account.get("accountIdKey") or "")
        digits = "".join(ch for ch in raw if ch.isdigit())
        if digits.endswith(_DEFAULT_ACCOUNT_SUFFIX):
            return [_account_key(account)]
    return [_account_key(accounts[0])] if accounts else []


def _closest_index(values: list[float], spot: float) -> int:
    return min(range(len(values)), key=lambda i: abs(float(values[i]) - float(spot)))


def _metric_markup(items: list[tuple[str, str, str]]) -> str:
    cells = "".join(
        '<div class="vo-card vo-' + html.escape(tone) + '">'
        '<div class="vo-label">' + html.escape(label) + "</div>"
        '<div class="vo-value">' + html.escape(value) + "</div>"
        "</div>"
        for label, value, tone in items
    )
    return '<div class="vo-grid">' + cells + "</div>"


def _expirations(client, symbol: str, touch_session) -> list[date]:
    payload = client.get_option_expirations(symbol)
    touch_session()
    out: list[date] = []
    for year, month, day in option_expiration_dates(payload):
        try:
            out.append(date(year, month, day))
        except ValueError:
            pass
    return sorted(set(out))


def _chain(client, symbol: str, expiry: date, touch_session) -> list[dict[str, Any]]:
    payload = client.get_option_chain(
        symbol,
        expiry.year,
        expiry.month,
        expiry.day,
        no_of_strikes=None,
        chain_type="CALLPUT",
    )
    touch_session()
    return extract_option_rows(payload, expiry)


def _review_fingerprint(
    *,
    symbol: str,
    call_put: str,
    expiry: date,
    buy_strike: float,
    sell_strike: float,
    quantity: int,
    limit_price: float,
    order_term: str,
    account_keys: list[str],
) -> tuple[Any, ...]:
    return (
        symbol,
        call_put,
        expiry.isoformat(),
        round(float(buy_strike), 4),
        round(float(sell_strike), 4),
        int(quantity),
        round(float(limit_price), 4),
        order_term,
        tuple(sorted(account_keys)),
    )


def _reviews_are_fresh(review_bundle: dict[str, Any] | None, fingerprint: tuple[Any, ...]) -> bool:
    if not isinstance(review_bundle, dict) or review_bundle.get("fingerprint") != fingerprint:
        return False
    try:
        age = time.time() - float(review_bundle.get("previewed_at") or 0.0)
    except (TypeError, ValueError):
        return False
    return 0.0 <= age <= _PREVIEW_FRESH_SECONDS


