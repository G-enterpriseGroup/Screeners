def _parse_ticker_list(raw: str) -> list[str]:
    """Read pasted Markdown ticker tables, CSV, or whitespace-separated symbols."""
    tickers: list[str] = []
    seen: set[str] = set()
    for token in re.split(r"[\s,;|]+", str(raw or "").replace("`", "")):
        symbol = token.strip().upper()
        if not symbol or symbol in {"TICKER", "SYMBOL"} or re.fullmatch(r":?-+:?", symbol):
            continue
        if len(symbol) > 12 or not re.fullmatch(r"[A-Z][A-Z0-9]*(?:[.\-][A-Z0-9]+)*", symbol):
            raise ValueError(f"Invalid ticker in pasted list: {symbol}.")
        if symbol not in seen:
            tickers.append(symbol)
            seen.add(symbol)
        if len(tickers) > 100:
            raise ValueError("Ticker list is limited to 100 unique symbols.")
    if not tickers:
        raise ValueError("Paste at least one ticker symbol.")
    return tickers


def _entered_price(value: str, label: str) -> float:
    try:
        amount = float(str(value).strip().replace("$", "").replace(",", ""))
    except (TypeError, ValueError) as exc:
        raise ValueError(f"Enter a valid {label}.") from exc
    if not math.isfinite(amount) or amount <= 0:
        raise ValueError(f"{label} must be greater than zero.")
    return amount


def _entered_reward_risk(value: str) -> float:
    text = str(value).strip()
    if text.startswith("1:"):
        text = text[2:].strip()
    return _entered_price(text, "minimum risk:reward ratio (1:X)")


def _safe_vertical_pair_limit(rows: list[dict[str, Any]]) -> tuple[int | None, int]:
    """Count all potential pairs; disk-backed results never require a row cap."""
    groups: dict[tuple[date, str], set[tuple[float, str]]] = {}
    for item in rows:
        if not isinstance(item, dict):
            continue
        expiry, side = item.get("expiry"), str(item.get("call_put") or "").upper()
        try:
            strike = float(item.get("strike"))
        except (TypeError, ValueError, OverflowError):
            continue
        if not isinstance(expiry, date) or side not in {"CALL", "PUT"}:
            continue
        if not math.isfinite(strike) or strike <= 0:
            continue
        groups.setdefault((expiry, side), set()).add((strike, str(item.get("osi") or "")))
    possible = sum(len(legs) * (len(legs) - 1) // 2 for legs in groups.values())
    return None, possible


def _scan_all_years(client, symbol: str, touch_session, *, refresh: bool = False) -> dict[str, Any]:
    source = "E*TRADE" if client is not None and not bool(getattr(client, "is_offline", False)) else "PUBLIC"
    cache_key = f"{source}:{symbol}"
    cache = st.session_state.setdefault("_vo_chain_cache", {})
    now = time.time()
    for old_key, old_value in list(cache.items()):
        if (not isinstance(old_value, dict)
                or now - float(old_value.get("loaded_at") or 0) >= _SCAN_CACHE_SECONDS):
            cache.pop(old_key, None)
    cached = cache.get(cache_key)
    fresh_cached = (not refresh and isinstance(cached, dict)
                    and now - float(cached.get("loaded_at") or 0) < _SCAN_CACHE_SECONDS)
    if fresh_cached and cached.get("scan_complete", True):
        return cached

    market_client = options_market_client(client)
    if fresh_cached:
        # Continue from the first unvisited expiration; never silently retry
        # already downloaded chains or discard successfully loaded contracts.
        spot, name = cached["spot"], cached["name"]
        quote_payload = None
        expirations = list(cached["expirations"])
        rows = list(cached["rows"])
        errors = list(cached["errors"])
        failed_expirations = list(cached.get("failed_expirations") or [])
        loaded = int(cached["loaded_expirations"])
        start_index = int(cached["next_expiry_index"])
        tv_exchange = cached.get("tv_exchange", "")
    else:
        quote_payload = market_client.get_quote(symbol)
        quote = quote_summary(quote_payload)
        touch_session()
        spot = _entered_price(
            find_number(quote_payload, "lastTrade", "lastPrice"),
            "E*TRADE Last price" if source == "E*TRADE" else "public Last price",
        )
        name = str(quote.get("description") or company_name(symbol) or "").strip()
        record_lookup(symbol, name)
        expirations = [item for item in _expirations(market_client, symbol, touch_session)
                       if item >= date.today()]
        if not expirations:
            raise ValueError(f"No future listed option expirations are available for {symbol}.")
        rows, errors, failed_expirations, loaded, start_index = [], [], [], 0, 0
        tv_exchange = _tradingview_listing_exchange(symbol, quote_payload)

    batch_started = time.monotonic()
    next_index = start_index
    consecutive_failures = 0
    progress = st.progress(
        start_index / len(expirations),
        text=f"LOADING EXPIRATION {start_index + 1}/{len(expirations)} // {symbol}",
    )
    try:
        for index in range(start_index, len(expirations)):
            expiry = expirations[index]
            progress.progress(
                index / len(expirations),
                text=f"LOADING {index + 1}/{len(expirations)} // {_date_label(expiry)} // {symbol}",
            )
            try:
                chain_rows = _chain(market_client, symbol, expiry, touch_session)
                if chain_rows:
                    rows.extend(chain_rows)
                    loaded += 1
                    consecutive_failures = 0
                else:
                    # Empty chains are not connectivity failures: later listed
                    # expirations can still have valid contracts.
                    consecutive_failures = 0
                    errors.append(f"{_date_label(expiry)} // no quoted contracts returned")
            except Exception as exc:
                consecutive_failures += 1
                errors.append(f"{_date_label(expiry)} // {exc}")
                failed_expirations.append(expiry)
            next_index = index + 1
            progress.progress(
                next_index / len(expirations),
                text=f"LOADED {loaded} / {next_index} CHECKED // {len(expirations)} LISTED // {symbol}",
            )
            # Many missing/unauthorized chains should never cause dozens more
            # blocking broker calls. Keep the actual failures visible.
            if consecutive_failures >= 2:
                errors.append("SCAN STOPPED // consecutive chain failures; check source/connection.")
                break
            if (next_index - start_index >= _SCAN_BATCH_EXPIRATIONS
                    or time.monotonic() - batch_started >= _SCAN_BATCH_SECONDS):
                break
    finally:
        progress.empty()
    result = {
        # All continued rows belong to the original snapshot. Continuing must
        # never renew stale contracts or reset checked-spread identities.
        "loaded_at": cached["loaded_at"] if fresh_cached else now,
        "scan_id": cached["scan_id"] if fresh_cached else time.time_ns(),
        "source": source, "symbol": symbol, "spot": spot, "name": name,
        "expirations": expirations, "loaded_expirations": loaded,
        "rows": rows, "errors": errors, "failed_expirations": failed_expirations,
        "tv_exchange": tv_exchange,
        "next_expiry_index": next_index,
        "scan_complete": next_index >= len(expirations),
        "stopped_on_errors": consecutive_failures >= 2,
        "result_stores": cached.get("result_stores", {}) if fresh_cached else {},
    }
    cache[cache_key] = result
    # Bound multi-ticker session memory as well as per-expiry pair retention.
    while len(cache) > 3:
        cache.pop(next(key for key in cache if key != cache_key))
    if not rows and (result["scan_complete"] or consecutive_failures >= 2):
        detail = errors[-2] if len(errors) >= 2 else (errors[-1] if errors else "unknown source error")
        raise ValueError(f"No option contracts loaded // {detail}")
    return result


def _rank_cached_vertical_chains(raw: dict[str, Any], target: float | None,
                                 max_cost: float | None, mode: str,
                                 min_reward_risk: float = _DEFAULT_MIN_REWARD_RISK,
                                 ) -> tuple[VerticalResultStore, set[str], None, int]:
    """Stream every qualifying pair to disk and reuse completed expirations."""
    _, potential_pairs = _safe_vertical_pair_limit(raw["rows"])
    raw.pop("rank_cache", None)  # Release older, truncated in-memory snapshots.
    policies = raw.setdefault("result_stores", {})
    policy = (target, max_cost, mode, min_reward_risk)
    store = policies.pop(policy, None)
    if not isinstance(store, VerticalResultStore):
        store = VerticalResultStore(raw["symbol"], raw["spot"], target, max_cost, mode,
                                    min_reward_risk=min_reward_risk)
    policies[policy] = store
    while len(policies) > 2:
        policies.pop(next(iter(policies)))
    groups: dict[date, list[dict[str, Any]]] = {}
    for row in raw["rows"]:
        groups.setdefault(row["expiry"], []).append(row)
    progress = st.progress(0.0, text="RANKING CALL + PUT SPREADS")
    started = time.monotonic()
    try:
        for index, (expiry, rows) in enumerate(sorted(groups.items())):
            def update(checked, index=index, expiry=expiry):
                progress.progress(index / len(groups),
                    text=f"SCANNING {_date_label(expiry)} // {checked:,} PAIRS CHECKED // {raw['symbol']}")
            update(0)
            added = store.add_expiration(expiry, rows, scan_vertical_candidates, update)
            if added and time.monotonic() - started >= _SCAN_RANK_SECONDS:
                break  # Resume calculation from disk without dropping a pair.
    finally:
        progress.empty()
    return store, store.annual_ids, None, potential_pairs


def _continue_vertical_scan(result: dict[str, Any], client, touch_session) -> dict[str, Any]:
    """Advance this snapshot only; preserve views, filters and checked identities."""
    raw = (st.session_state.get("_vo_chain_cache") or {}).get(f'{result["source"]}:{result["symbol"]}')
    source = "E*TRADE" if client is not None and not bool(getattr(client, "is_offline", False)) else "PUBLIC"
    if (source != result["source"] or not isinstance(raw, dict)
            or raw.get("scan_id") != result.get("raw_scan_id")
            or time.time() - raw["loaded_at"] >= _SCAN_CACHE_SECONDS):
        raise ValueError("QUOTE SNAPSHOT EXPIRED OR SOURCE CHANGED // Press SCAN ALL YEARS again.")
    started = time.monotonic()
    raw = _scan_all_years(client, result["symbol"], touch_session)
    candidates, annual_ids, _, potential_pairs = _rank_cached_vertical_chains(
        raw, result["target"], result["max_cost"], result["pricing_mode"],
        result.get("min_reward_risk", _DEFAULT_MIN_REWARD_RISK),
    )
    return {
        **result, "candidates": candidates, "annual_ids": annual_ids,
        "loaded_expirations": raw["loaded_expirations"], "contract_count": len(raw["rows"]),
        "errors": raw["errors"], "failed_expirations": raw.get("failed_expirations", []),
        "potential_pairs": potential_pairs,
        "chains_complete": raw["scan_complete"], "ranked_expirations": candidates.ranked_expirations,
        "scan_complete": raw["scan_complete"] and candidates.ranked_expirations == raw["loaded_expirations"],
        "next_expiry_index": raw["next_expiry_index"], "pass_seconds": time.monotonic() - started,
        "stopped_on_errors": raw.get("stopped_on_errors", False),
    }

def _optionstrat_url(candidate: dict[str, Any]) -> str:
    """Open the exact two-leg debit spread in OptionStrat's strategy builder."""
    symbol = str(candidate["symbol"]).strip().upper()
    expiry = candidate["expiry"].strftime("%y%m%d")
    def leg(strike: float, side: str, osi: str, short: bool = False) -> str:
        strike_text = f"{float(strike):.8f}".rstrip("0").rstrip(".")
        root = symbol
        # Standard OCC symbols can have a different option root than the
        # underlying (for example SPX weekly options use SPXW).
        match = re.fullmatch(
            r"([A-Z][A-Z0-9.\-]*?)(\d{6})([CP])(\d{1,8}(?:\.\d+)?)",
            str(osi or "").upper().replace(" ", "").lstrip("."),
        )
        if match and match.group(2) == expiry and match.group(3) == side:
            raw_strike = match.group(4)
            parsed_strike = float(raw_strike) / 1000 if len(raw_strike) == 8 else float(raw_strike)
            if abs(parsed_strike - float(strike)) < .0001:
                root = match.group(1).rstrip("-") or symbol
        return ("-" if short else "") + f".{root}{expiry}{side}{strike_text}"
    if candidate["call_put"] == "CALL":
        strategy = "bull-call-spread"
        legs = (leg(candidate["buy_strike"], "C", candidate.get("buy_osi", "")) + ","
                + leg(candidate["sell_strike"], "C", candidate.get("sell_osi", ""), True))
    else:
        strategy = "bear-put-spread"
        legs = (leg(candidate["sell_strike"], "P", candidate.get("sell_osi", ""), True) + ","
                + leg(candidate["buy_strike"], "P", candidate.get("buy_osi", "")))
    return f"https://optionstrat.com/build/{strategy}/{url_quote(symbol, safe='')}/{url_quote(legs, safe='.,-')}"


# Verified TradingView symbol pages; never guess an unverified exchange.
_TV_KNOWN_LISTINGS = {"SOXX": "NASDAQ", "SPY": "AMEX", "SPX": "SP"}


def _tradingview_listing_exchange(symbol: str, quote_payload: dict[str, Any] | None = None) -> str:
    """Use a verified listing or the existing broker quote; never probe for every spread."""
    symbol = str(symbol or "").upper().strip()
    if symbol in _TV_KNOWN_LISTINGS:
        return _TV_KNOWN_LISTINGS[symbol]
    payload = quote_payload or {}
    response = payload.get("QuoteResponse", payload)
    items = response.get("QuoteData", response.get("quoteData", [])) if isinstance(response, dict) else []
    if isinstance(items, dict):
        items = [items]
    row = items[0] if isinstance(items, list) and items and isinstance(items[0], dict) else {}
    details = row.get("All", row.get("all", {}))
    code = str((details or {}).get("primaryExchange") or "").strip().upper()
