# ==============================
def price_vertical_quote(**kwargs: Any) -> dict[str, Any] | None:
    """SMART pays natural ASK only; NORMAL uses a risk-capped MID-to-ASK limit.

    The legacy default remains unchanged for the independent phone workspace.
    No quote, aggressiveness score, volume or open interest guarantees execution.
    """
    mode = kwargs.pop("pricing_mode", "NORMAL")
    if mode not in {"NORMAL", "SMART FILL"}:
        raise ValueError("Invalid Vertical Options pricing mode.")
    minimum = float(kwargs.get("min_reward_risk", 2.0))
    if not math.isfinite(minimum) or minimum <= 0:
        raise ValueError("Minimum reward-to-risk ratio must be positive and finite.")
    kwargs["min_reward_risk"] = max(2.0, minimum)
    if mode == "NORMAL":
        result = _legacy_price(**kwargs, pricing_mode="SMART FILL")
        if result and result["basis"] == "SMART":
            result = {**result, "basis": "LIMIT", "liquidity_signal": "MID-TO-ASK LIMIT"}
        return result
    result = _legacy_price(**kwargs, pricing_mode="NORMAL")
    # Never fall back to MID, LAST or LAST* to make an ASK-ineligible trade
    # appear qualified. Both legs must have a non-crossed quoted market.
    if not result or not result["orderable"] or result["basis"] != "ASK":
        return None
    ask = float(result["spread_ask"])
    debit = math.ceil(ask * 100 - 1e-8) / 100
    width = float(kwargs["width"])
    budget = kwargs.get("max_cost")
    if (not math.isfinite(debit) or debit <= 0 or debit >= width
            or width - debit + 1e-8 < kwargs["min_reward_risk"] * debit
            or (budget is not None and debit * 100 > float(budget) + 1e-8)):
        return None
    return {**result, "debit": debit, "cost": round(debit * 100, 2),
            "basis": "ASK", "liquidity_signal": "NATURAL ASK — FILL NOT GUARANTEED"}


def scan_vertical_candidates(**kwargs: Any):
    """Reuse complete canonical pairing with an explicitly desktop-owned pricer."""
    minimum = float(kwargs.get("min_reward_risk", 2.0))
    if not math.isfinite(minimum) or minimum <= 0:
        raise ValueError("Minimum reward-to-risk ratio must be positive and finite.")
    kwargs["min_reward_risk"] = max(2.0, minimum)
    return _legacy_scan(**kwargs, quote_pricer=price_vertical_quote)


# ==============================
# QUOTE PRESENTATION — NOT FILL PROBABILITY
# ==============================
def quote_ruler(candidate: dict[str, Any]) -> dict[str, Any]:
    def number(value: Any) -> float | None:
        if isinstance(value, bool):
            return None
        try:
            parsed = float(value)
        except (TypeError, ValueError, OverflowError):
            return None
        return parsed if math.isfinite(parsed) else None

    bid, mid, ask, debit = (number(candidate.get(key)) for key in
                            ("spread_bid", "spread_mid", "spread_ask", "debit"))
    if bid is None or ask is None:
        bb, ba, sb, sa = (number(candidate.get(key)) for key in
                          ("buy_bid", "buy_ask", "sell_bid", "sell_ask"))
        if (all(value is not None for value in (bb, ba, sb, sa))
                and 0 <= bb <= ba and 0 <= sb <= sa):
            bid, ask = round(bb - sa, 4), round(ba - sb, 4)
    valid = bid is not None and ask is not None and ask >= bid
    if valid:
        mid = round((bid + ask) / 2, 4)
    else:
        bid = mid = ask = None
    position = None
    if valid and debit is not None:
        position = (50.0 if ask == bid else
                    100.0 * min(1.0, max(0.0, (debit - bid) / (ask - bid))))
    return {"bid": bid, "mid": mid, "ask": ask, "debit": debit,
            "position": position, "quoted": valid,
            "orderable": bool(candidate.get("orderable"))}


def refreshed_ticket(candidate: dict[str, Any], price: dict[str, Any]) -> dict[str, Any]:
    """Copy a selected row at a freshly reviewed limit; never mutate scan storage."""
    debit = float(price["debit"])
    width = float(candidate["width"])
    cost = round(debit * 100, 2)
    profit = round((width - debit) * 100, 2)
    return {**candidate, **price, "cost": cost, "max_loss": cost,
            "max_profit": profit, "reward_risk": profit / cost,
            "breakeven": round(candidate["buy_strike"] +
                               (debit if candidate["call_put"] == "CALL" else -debit), 6)}
