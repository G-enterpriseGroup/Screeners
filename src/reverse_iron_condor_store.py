def _rank(row: dict[str, Any], target: float | None) -> tuple:
    distance = min(abs(row["breakeven"] - target), abs(row["lower_breakeven"] - target)) if target is not None else 0
    return (row["grade"], distance, row["cost"],
            -row["reward_risk"], row["expiry"], row["call_put"],
            row["buy_strike"], row["sell_strike"], row["put_buy_strike"],
            row["put_sell_strike"], row.get("option_root", ""), row["id"])


class _RICSQLResultStore:
    """Bound Python memory by the input chain, write batch and visible page.

    SQLite's page cache is 4 MiB and sort scratch stays on disk. A separate
    connection is opened per operation, including deferred download threads.
    TemporaryDirectory removes scan files when the last cache/export reference
    is released; expired snapshots and evicted policies cannot leak databases.
    """

    def __init__(self, symbol: str, spot: float, target: float | None, max_cost: float | None, mode: str,
                 *, min_reward_risk: float = _MIN_REWARD_RISK, fee_per_spread: float = 0.0):
        self.symbol, self.spot, self.target = symbol, spot, target
        self.max_cost, self.mode = max_cost, mode
        self.min_reward_risk = max(2.0, _reward_risk_floor(min_reward_risk))
        self.fee_per_spread = float(fee_per_spread)
        if isinstance(fee_per_spread, bool) or not math.isfinite(self.fee_per_spread) or self.fee_per_spread < 0:
            raise ValueError("Estimated fees must be finite and nonnegative.")
        self._directory = tempfile.TemporaryDirectory(prefix="terminal_ric_")
        self._cleanup = weakref.finalize(self, self._directory.cleanup)
        self.path = Path(self._directory.name) / "spreads.sqlite3"
        self._lock = threading.RLock()
        self._count = 0
        self._completed: dict[date, int] = {}
        self._annual: dict[int, dict[str, Any]] = {}
        self._minimum_expiry: date | None = None
        self._indexes = {}
        self._analyzed_count = -1
        self._choices_cache = None
        self._fill_values_cache = {}
        with self._connect() as db:
            db.execute("PRAGMA journal_mode=WAL")
            db.execute("""CREATE TABLE spreads (
                id TEXT PRIMARY KEY, expiry TEXT NOT NULL, side TEXT NOT NULL,
                grade INTEGER NOT NULL, distance REAL NOT NULL, cost REAL NOT NULL,
                ratio REAL NOT NULL, breakeven REAL NOT NULL, profit REAL NOT NULL,
                width REAL NOT NULL, buy REAL NOT NULL, sell REAL NOT NULL,
                buy_last REAL, sell_last REAL, buy_osi TEXT NOT NULL, sell_osi TEXT NOT NULL,
                details TEXT NOT NULL
            )""")
            db.execute(f"CREATE INDEX canonical ON spreads ({_CANONICAL_ORDER})")
            db.execute("CREATE INDEX expiry_side ON spreads (expiry, side)")
            db.execute("CREATE INDEX side_expiry ON spreads (side, expiry)")
            db.execute("CREATE INDEX target_distance ON spreads (distance, id)")

    @contextmanager
    def _connect(self):
        db = sqlite3.connect(self.path, timeout=30)
        db.execute("PRAGMA cache_size=-4096")
        db.execute("PRAGMA temp_store=FILE")
        try:
            with db:
                yield db
        finally:
            db.close()

    def __len__(self):
        return self._count

    @property
    def ranked_expirations(self) -> int:
        return len(self._completed)

    @property
    def annual_ids(self) -> set[str]:
        return {row["id"] for row in self._annual.values()}

    @property
    def annual_rows(self) -> list[dict[str, Any]]:
        return sorted(self._annual.values(), key=lambda row: _rank(row, self.target))

    @property
    def expirations(self) -> list[date]:
        with self._connect() as db:
            return [date.fromisoformat(row[0]) for row in db.execute("SELECT DISTINCT expiry FROM spreads ORDER BY expiry")]

    def best_by_year(self, *, max_distance=None, column_filters=None, year=None) -> list[dict[str, Any]]:
        if max_distance is None and not column_filters and year is None:
            return self.annual_rows
        where, args = self._where(max_distance=max_distance, column_filters=column_filters, year=year)
        target = self.effective_target(column_filters)
        order = _CANONICAL_ORDER.replace("distance", self._distance_expression(column_filters))
        year_clause = " AND " if where else " WHERE "
        result = []
        with self._connect() as db:
            for row_year in sorted({expiry.year for expiry in self._completed}):
                if year is not None and row_year != year:
                    continue
                row = db.execute("SELECT * FROM spreads" + where
                    + year_clause + "expiry>=? AND expiry<? ORDER BY " + order + " LIMIT 1",
                    args + [f"{row_year:04d}-01-01", f"{row_year + 1:04d}-01-01"]).fetchone()
                if row is not None:
                    result.append(self._decode(row))
        return sorted(result, key=lambda row: _rank(row, target))

    @contextmanager
    def snapshot(self):
        """Keep a deferred CSV's rows and annual markers in the same revision."""
        with self._lock:
            yield self

    def prune_before(self, cutoff: date) -> int:
        """Remove ineligible expirations from every retained-result access path."""
        if type(cutoff) is not date:
            raise ValueError("Invalid minimum expiration date.")
        with self._lock:
            if self._minimum_expiry is not None and cutoff <= self._minimum_expiry:
                return 0
            completed = {expiry: size for expiry, size in self._completed.items()
                         if expiry >= cutoff}
            annual = dict(self._annual)
            with self._connect() as db:
                removed = db.execute("DELETE FROM spreads WHERE expiry<?", [cutoff.isoformat()]).rowcount
                if removed:
                    annual = {}
                    for year in sorted({expiry.year for expiry in completed}):
                        row = db.execute(
                            "SELECT * FROM spreads WHERE expiry>=? AND expiry<? ORDER BY "
                            + _CANONICAL_ORDER + " LIMIT 1",
                            [f"{year:04d}-01-01", f"{year + 1:04d}-01-01"],
                        ).fetchone()
                        if row is not None:
                            annual[year] = self._decode(row)
            self._count -= removed
            self._completed = completed
            self._annual = annual
            self._minimum_expiry = cutoff
            self._choices_cache = None
            self._fill_values_cache.clear()
            return removed

    def add_expiration(self, expiry: date, rows: list[dict[str, Any]], calculator: Callable,
                       progress: Callable[[int], None] | None = None) -> bool:
        """Commit a whole expiration atomically; never refetch or reprice old ones."""
        with self._lock:
            if self._minimum_expiry is not None and expiry < self._minimum_expiry:
                return False
            if self._completed.get(expiry) == len(rows):
                return False
            annual = dict(self._annual)
            batch = []
            checked = 0
            with self._connect() as db:
                if expiry in self._completed:
                    raise ValueError("An already ranked expiration changed; start a fresh scan.")

                def flush():
                    db.executemany("INSERT INTO spreads VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)", batch)
                    batch.clear()

                def retain(row):
                    old = annual.get(row["year"])
                    if old is None or _rank(row, self.target) < _rank(old, self.target):
                        annual[row["year"]] = row
                    batch.append((
                        row["id"], row["expiry"].isoformat(), row["call_put"], row["grade"],
                        min(abs(row["breakeven"] - self.target), abs(row["lower_breakeven"] - self.target)) if self.target is not None else 0,
                        row["cost"], row["reward_risk"],
                        row["breakeven"], row["max_profit"], row["width"],
                        row["buy_strike"], row["sell_strike"], row["buy_last"], row["sell_last"],
                        row["buy_osi"], row["sell_osi"],
                        json.dumps([row.get(key) for key in _DETAILS] + [_stored_extras(row)], separators=(",", ":"), allow_nan=False),
                    ))
                    if len(batch) >= 512:
                        flush()

                def update(value):
                    nonlocal checked
                    checked = value
                    if progress is not None:
                        progress(value)

                calculator(symbol=self.symbol, spot_last=self.spot, option_rows=rows,
                           target_breakeven=self.target, max_cost=self.max_cost,
                           pricing_mode=self.mode, min_reward_risk=self.min_reward_risk,
                           max_per_expiration=None, fee_per_spread=self.fee_per_spread,
                           candidate_sink=retain, progress=update if progress is not None else None)
                flush()
                if progress is not None:
                    progress(checked)
                added = db.total_changes
            # Publish metadata only after successful transaction commit.
            self._count += added
            self._annual = annual
            self._completed[expiry] = len(rows)
            self._choices_cache = None
            self._fill_values_cache.clear()
            return True

    # ==============================
    # WHOLE-SCAN FILTERS AND PAGES
    # ==============================
    def effective_target(self, column_filters=None) -> float | None:
        """Resolve a display-only target without mutating the retained scan."""
        breakeven = column_filters.get("breakeven") if isinstance(column_filters, dict) else None
        if not isinstance(breakeven, dict) or "target" not in breakeven:
            return self.target
        value = breakeven["target"]
        if value is None or value == "":
            return None
        try:
            target = float(value)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError("Invalid breakeven target.") from exc
        if isinstance(value, bool) or not math.isfinite(target) or target <= 0:
            raise ValueError("Invalid breakeven target.")
        return target

    def _distance_expression(self, column_filters=None) -> str:
        target = self.effective_target(column_filters)
        if target == self.target:
            return "distance"
        # Only a validated finite float is interpolated into the SQL expression.
        return "0.0" if target is None else f"min(abs(breakeven - {target!r}), abs(json_extract(details, '$[12].lower_breakeven') - {target!r}))"

    def _strike_distance_expression(self) -> str:
        try:
            spot = float(self.spot)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError("Invalid fixed scan spot for strike distance.") from exc
        if isinstance(self.spot, bool) or not math.isfinite(spot) or spot <= 0:
            raise ValueError("Invalid fixed scan spot for strike distance.")
        return (f"100.0 * max(abs(buy - {spot!r}), abs(sell - {spot!r}), "
                f"abs(json_extract(details, '$[12].put_buy_strike') - {spot!r}), "
                f"abs(json_extract(details, '$[12].put_sell_strike') - {spot!r})) / {spot!r}")

    def _where(self, expiry="ALL", side="CALL + PUT", max_distance=None, column_filters=None,
               year=None):
        clauses, args = [], []
        target = self.effective_target(column_filters)
        if year is not None:
            if type(year) is not int or not 1 <= year <= 9998:
                raise ValueError("Invalid result year.")
            clauses.extend(("expiry>=?", "expiry<?"))
            args.extend((f"{year:04d}-01-01", f"{year + 1:04d}-01-01"))
        if expiry != "ALL":
            if not isinstance(expiry, date):
                raise ValueError("Invalid expiration filter.")
            clauses.append("expiry=?")
            args.append(expiry.isoformat())
        if side not in {"CALL + PUT", "RIC", "ALL"}:
            raise ValueError("Invalid option type filter.")
        if side not in {"CALL + PUT", "ALL"}:
            clauses.append("side=?")
            args.append(side)
        if max_distance is not None:
            if not math.isfinite(max_distance) or max_distance < 0:
                raise ValueError("Invalid breakeven distance filter.")
            if target is not None:
                clauses.append(self._distance_expression(column_filters) + "<=?")
                args.append(max_distance + 1e-8)
        if column_filters:
            if not isinstance(column_filters, dict):
                raise ValueError("Invalid column filters.")
            for field, selected in column_filters.items():
                if field == "fill_scale":
                    if (not isinstance(selected, dict) or set(selected) != {"gt"}
                            or isinstance(selected["gt"], bool)
                            or not isinstance(selected["gt"], (int, float))
                            or not math.isfinite(selected["gt"]) or not 0 <= selected["gt"] <= 100):
                        raise ValueError("Invalid fill estimate threshold (0–100%, strictly greater than).")
                    clauses.append(f"{_DISPLAY_FILL_EST_SQL}>?")
                    args.append(float(selected["gt"]))
                elif field in _NUMERIC_FILTERS:
                    allowed = ({"target", "percent", "min", "max"} if field == "breakeven"
                               else {"min", "max"})
                    if not isinstance(selected, dict) or set(selected) - allowed:
                        raise ValueError("Invalid numeric column filter.")
                    # Original desktop opt-in uses percent; the mobile scanner
                    # still relies on its legacy target-only ranking and MIN/MAX.
                    if field == "breakeven" and "percent" in selected:
                        if "min" in selected or "max" in selected:
                            raise ValueError("Cannot mix breakeven percent with legacy bounds.")
                        percent = selected["percent"]
                        try:
                            percent = float(percent)
                        except (TypeError, ValueError, OverflowError) as exc:
                            raise ValueError("Invalid breakeven tolerance.") from exc
                        if (isinstance(selected.get("percent"), bool) or
                                not math.isfinite(percent) or not 0 <= percent <= 100):
                            raise ValueError("Invalid breakeven tolerance (0–100%).")
                        if target is not None:
                            tolerance = target * percent / 100.0
                            clauses.append(self._distance_expression(column_filters) + "<=?")
                            args.append(tolerance + 1e-8)
                        continue
                    bounds = {}
                    for limit in ("min", "max"):
                        value = selected.get(limit)
                        if value is None or value == "":
                            continue
                        if field == "strike_distance_pct" and (isinstance(value, bool) or
                                                               not isinstance(value, (int, float))):
                            raise ValueError("Invalid strike distance column filter.")
                        try:
                            value = float(value)
                        except (TypeError, ValueError, OverflowError) as exc:
                            raise ValueError("Invalid numeric column filter.") from exc
                        if not math.isfinite(value):
                            raise ValueError("Invalid numeric column filter.")
                        bounds[limit] = value
                    if "min" in bounds and "max" in bounds and bounds["min"] > bounds["max"]:
                        clauses.append("1=0")
                    expression = (self._strike_distance_expression() if field == "strike_distance_pct"
                                  else _NUMERIC_FILTERS[field])
                    if "min" in bounds:
                        clauses.append(f"{expression}>=?")
                        args.append(bounds["min"] - 1e-8)
                    if "max" in bounds:
                        clauses.append(f"{expression}<=?")
                        args.append(bounds["max"] + 1e-8)
                elif field == "ticker" or field in _CHOICE_FILTERS:
                    if not isinstance(selected, list) or len(selected) > 1000 or any(
                        not isinstance(item, str) or len(item) > 64 for item in selected
                    ):
                        raise ValueError("Invalid column choices.")
                    if not selected:
                        clauses.append("1=0")
                    elif field == "ticker":
                        if self.symbol not in selected:
                            clauses.append("1=0")
                    else:
                        clauses.append(f"{_CHOICE_FILTERS[field]} IN (" + ",".join("?" for _ in selected) + ")")
                        args.extend(selected)
                else:
                    raise ValueError("Unknown column filter.")
        return (" WHERE " + " AND ".join(clauses) if clauses else ""), args

    def count(self, *, expiry="ALL", side="CALL + PUT", max_distance=None, column_filters=None,
              year=None) -> int:
        if expiry == "ALL" and side == "CALL + PUT" and max_distance is None and not column_filters and year is None:
            return len(self)
        where, args = self._where(expiry, side, max_distance, column_filters, year)
        with self._connect() as db:
            return db.execute("SELECT count(*) FROM spreads" + where, args).fetchone()[0]

    def counts_by_year(self, *, max_distance=None, column_filters=None) -> dict[int, int]:
        """Count every matching pair per calendar year for compact year selection."""
        where, args = self._where(max_distance=max_distance, column_filters=column_filters)
        with self._connect() as db:
            return {int(year): count for year, count in db.execute(
                "SELECT substr(expiry, 1, 4), count(*) FROM spreads" + where
                + " GROUP BY substr(expiry, 1, 4) ORDER BY substr(expiry, 1, 4)", args
            )}

    def column_filter_choices(self) -> dict[str, list[str]]:
        """Return distinct choices from every stored spread, not just a visible page."""
        if self._choices_cache is None:
            with self._connect() as db:
                self._choices_cache = {
                    "ticker": [self.symbol],
                    "side": [row[0] for row in db.execute("SELECT DISTINCT side FROM spreads ORDER BY side")],
                    "expiry": [row[0] for row in db.execute("SELECT DISTINCT expiry FROM spreads ORDER BY expiry")],
                    "basis": [row[0] for row in db.execute(
                        "SELECT DISTINCT json_extract(details, '$[5]') FROM spreads ORDER BY 1") if row[0] is not None],
                }
        return self._choices_cache

    def fill_est_values(self, *, column_filters=None, max_distance=None, year=None) -> list[int]:
        """Display-rounded values across all other active filters, never just a page."""
        if column_filters is not None and not isinstance(column_filters, dict):
            raise ValueError("Invalid column filters.")
        self._where(max_distance=max_distance, column_filters=column_filters, year=year)
        filters = {key: value for key, value in (column_filters or {}).items() if key != "fill_scale"}
        where, args = self._where(max_distance=max_distance, column_filters=filters, year=year)
        cache_key = (where, tuple(args))
        with self._lock:
            cached = self._fill_values_cache.get(cache_key)
            if cached is None:
                known = (" AND " if where else " WHERE ") + _DISPLAY_FILL_EST_SQL + " IS NOT NULL"
                with self._connect() as db:
                    cached = [row[0] for row in db.execute(
                        f"SELECT DISTINCT {_DISPLAY_FILL_EST_SQL} AS estimate FROM spreads"
                        + where + known + " ORDER BY estimate LIMIT 91", args)]
                self._fill_values_cache[cache_key] = cached
                while len(self._fill_values_cache) > 8:
                    self._fill_values_cache.pop(next(iter(self._fill_values_cache)))
            return list(cached)

    def _order(self, sort_by, direction, column_filters=None):
        if sort_by not in _SORTS or direction not in {"ASC", "DESC"}:
            raise ValueError("Invalid qualified-spread sorting controls.")
        distance = self._distance_expression(column_filters)
        terms = []
        for column, reverse in _SORTS[sort_by]:
            if column == "distance":
                column = distance
            if column == "fill_est":
                column = _FILL_EST_SQL
                terms.append(f"({column} IS NULL) ASC")
            if column == "strike_distance_pct":
                column = self._strike_distance_expression()
            if column in {"buy_last", "sell_last",
                          "json_extract(details, '$[12].put_buy_last')",
                          "json_extract(details, '$[12].put_sell_last')"}:
                terms.append(f"({column} IS NULL) {direction}")
            terms.append(f"{column} {'DESC' if reverse != (direction == 'DESC') else 'ASC'}")
        # Match the existing stable identity tie-break, including DESC ties.
        return ", ".join(terms + ["id ASC"])

    def _ensure_index(self, sort_by, direction, column_filters=None):
        order = self._order(sort_by, direction, column_filters)
        if (self.effective_target(column_filters) != self.target
                and any(column == "distance" for column, _ in _SORTS[sort_by])):
            return  # Display targets share the retained rows without per-target indexes.
        if sort_by == "TARGET DISTANCE" and direction == "ASC":
            return  # Covered by the permanent distance index; do not duplicate it.
        key = (sort_by, direction)
        if key not in self._indexes or self._analyzed_count != self._count:
            with self._lock, self._connect() as db:
                if key in self._indexes and self._analyzed_count == self._count:
                    return
                if key not in self._indexes:
                    name = f"sort_{list(_SORTS).index(sort_by)}_{direction}"
                    db.execute(f"CREATE INDEX IF NOT EXISTS {name} ON spreads ({order})")
                    self._indexes[key] = name
                    while len(self._indexes) > 3:
                        old = next(iter(self._indexes))
                        db.execute(f"DROP INDEX {self._indexes.pop(old)}")
                # Keep broad expiry filters from choosing a full-result sort.
                db.execute("ANALYZE")
                self._analyzed_count = self._count

    def _decode(self, row):
        (identity, expiry, side, grade, _, cost, ratio, breakeven, profit, width,
         buy, sell, buy_last, sell_last, buy_osi, sell_osi, details) = row
        expiry = date.fromisoformat(expiry)
        values = json.loads(details)
        return {
            **values[12],
            "id": identity, "symbol": self.symbol, "spot_last": self.spot,
            "expiry": expiry, "year": expiry.year, "call_put": side,
            "buy_strike": buy, "sell_strike": sell, "buy_osi": buy_osi, "sell_osi": sell_osi,
            "buy_last": buy_last, "sell_last": sell_last, "pricing_mode": self.mode,
            **dict(zip(_DETAILS, values[:12])), "grade": grade, "cost": cost,
            "width": width, "max_profit": profit, "max_loss": cost,
            "breakeven": breakeven, "reward_risk": ratio,
        }

    def page(self, *, expiry="ALL", side="CALL + PUT", sort_by="FILL + TARGET",
             direction="ASC", offset=0, limit=200, max_distance=None,
             column_filters=None, year=None) -> list[dict[str, Any]]:
        if type(offset) is not int or offset < 0 or type(limit) is not int or not 1 <= limit <= 1000:
            raise ValueError("Invalid spread page.")
        self._ensure_index(sort_by, direction, column_filters)
        where, args = self._where(expiry, side, max_distance, column_filters, year)
        # Locate page IDs through the index before reading their detail payloads.
        sql = ("SELECT * FROM spreads WHERE rowid IN (SELECT rowid FROM spreads" + where
               + " ORDER BY " + self._order(sort_by, direction, column_filters) + " LIMIT ? OFFSET ?) ORDER BY "
               + self._order(sort_by, direction, column_filters))
        with self._connect() as db:
            return [self._decode(row) for row in db.execute(sql, args + [limit, offset])]

    def get_many(self, identities: Iterable[str]) -> dict[str, dict[str, Any]]:
        ids = sorted({item for item in identities if isinstance(item, str)})
        found = {}
        with self._connect() as db:
            for offset in range(0, len(ids), 400):
                part = ids[offset:offset + 400]
                sql = "SELECT * FROM spreads WHERE id IN (" + ",".join("?" for _ in part) + ")"
                for values in db.execute(sql, part):
                    row = self._decode(values)
                    found[row["id"]] = row
        return dict(sorted(found.items(), key=lambda item: _rank(item[1], self.target)))

    def iter_rows(self, *, expiry="ALL", side="CALL + PUT", sort_by="FILL + TARGET",
                  direction="ASC", max_distance=None, column_filters=None, year=None):
        """Stream the entire filtered universe, never just the displayed page."""
        self._ensure_index(sort_by, direction, column_filters)
        where, args = self._where(expiry, side, max_distance, column_filters, year)
        yield from self._iterate(where, args, self._order(sort_by, direction, column_filters))

    def iter_ranked(self):
        yield from self._iterate("", [], _CANONICAL_ORDER)

    def _iterate(self, where, args, order):
        with self._connect() as db:
            cursor = db.execute("SELECT * FROM spreads" + where + " ORDER BY " + order, args)
            while batch := cursor.fetchmany(256):
                for row in batch:
                    yield self._decode(row)



