def _money(value: Any) -> str:
    try:
        return f"${float(value):,.2f}"
    except (TypeError, ValueError):
        return "—"


_DEFAULT_ACCOUNT_SUFFIX = "5474"


def _account_label(account: dict[str, Any]) -> str:
    name = str(account.get("accountDesc") or account.get("accountName") or "E*TRADE")
    ident = str(account.get("accountId") or account.get("accountIdKey") or "")
    return f"{name} // x{ident[-4:]}" if ident else name


def _account_matches_default(account: dict[str, Any]) -> bool:
    """Prefer Raj's x5474 account without overriding later manual selections."""
    for key in ("accountId", "accountDesc", "accountName", "accountIdKey"):
        raw = str(account.get(key) or "")
        digits = "".join(ch for ch in raw if ch.isdigit())
        if digits.endswith(_DEFAULT_ACCOUNT_SUFFIX):
            return True
    return False


def _default_account_index(accounts: list[dict[str, Any]]) -> int:
    return next(
        (index for index, account in enumerate(accounts) if _account_matches_default(account)),
        0,
    )


def _leg_quote_markup(label: str, value: Any) -> str:
    return (
        '<div class="ob-leg-quote">'
        '<div class="ob-leg-quote-label">' + html.escape(str(label)) + "</div>"
        '<div class="ob-leg-quote-value">' + html.escape(_money(value)) + "</div>"
        "</div>"
    )


def _date_label(expiry: date) -> str:
    return expiry.strftime("%b-%d-%y")


def _default_expiry(expirations: list[date]) -> date:
    today = date.today()
    return next((d for d in expirations if (d - today).days >= 14), expirations[0])


def _closest(strikes: list[float], spot: float, offset: int = 0) -> float:
    base = min(range(len(strikes)), key=lambda i: abs(strikes[i] - spot))
    return float(strikes[max(0, min(len(strikes) - 1, base + offset))])


def _strategy_defaults(strategy: str, symbol: str) -> None:
    signature = f"{symbol}:{strategy}"
    if st.session_state.get("_ob_strategy") == signature:
        return
    defaults = {
        "Call/Put": [("BUY_OPEN", "CALL")],
        "Call Vertical": [("BUY_OPEN", "CALL"), ("SELL_OPEN", "CALL")],
        "Put Vertical": [("BUY_OPEN", "PUT"), ("SELL_OPEN", "PUT")],
        "Custom Spread": [("BUY_OPEN", "CALL"), ("SELL_OPEN", "CALL")],
    }[strategy]
    st.session_state["ob_leg_count"] = len(defaults)
    for i, (action, call_put) in enumerate(defaults):
        st.session_state[f"ob_{i}_action"] = action
        st.session_state[f"ob_{i}_type"] = call_put
    st.session_state["_ob_strategy"] = signature
    st.session_state.pop("_ob_price_seed", None)


def _add_leg() -> None:
    count = int(st.session_state.get("ob_leg_count", 1) or 1)
    if count >= 4:
        return
    st.session_state["option_book_strategy"] = "Custom Spread"
    st.session_state["ob_leg_count"] = count + 1
    st.session_state[f"ob_{count}_action"] = "BUY_OPEN"
    st.session_state[f"ob_{count}_type"] = "CALL"
    symbol = str(st.session_state.get("ob_symbol_value", "SPY") or "SPY").upper()
    st.session_state["_ob_strategy"] = f"{symbol}:Custom Spread"
    st.session_state.pop("_ob_price_seed", None)


def _remove_leg(index: int) -> None:
    count = int(st.session_state.get("ob_leg_count", 1) or 1)
    if count <= 1:
        return
    fields = ("action", "qty", "expiry", "type", "strike")
    for i in range(index, count - 1):
        for field in fields:
            src, dst = f"ob_{i + 1}_{field}", f"ob_{i}_{field}"
            if src in st.session_state:
                st.session_state[dst] = st.session_state[src]
            else:
                st.session_state.pop(dst, None)
    for field in fields:
        st.session_state.pop(f"ob_{count - 1}_{field}", None)
    st.session_state["ob_leg_count"] = count - 1
    st.session_state["option_book_strategy"] = "Custom Spread"
    symbol = str(st.session_state.get("ob_symbol_value", "SPY") or "SPY").upper()
    st.session_state["_ob_strategy"] = f"{symbol}:Custom Spread"
    st.session_state.pop("_ob_price_seed", None)


def _expirations(client, symbol: str, touch_session) -> list[date]:
    payload = client.get_option_expirations(symbol)
    touch_session()
    out = []
    for year, month, day in option_expiration_dates(payload):
        try:
            out.append(date(year, month, day))
        except ValueError:
            pass
    return sorted(set(out))


def _chain(client, symbol: str, expiry: date, touch_session) -> list[dict[str, Any]]:
    payload = client.get_option_chain(
        symbol, expiry.year, expiry.month, expiry.day,
        no_of_strikes=None, chain_type="CALLPUT",
    )
    touch_session()
    return extract_option_rows(payload, expiry)


def _save(ticket: dict[str, Any]) -> None:
    rows = list(st.session_state.get("option_book_saved_tickets") or [])
    rows.insert(0, ticket)
    st.session_state["option_book_saved_tickets"] = rows[:25]


