def _extract_close(raw: pd.DataFrame, ticker: str, single: bool) -> pd.Series:
    if raw is None or raw.empty:
        return pd.Series(dtype=float)
    try:
        if isinstance(raw.columns, pd.MultiIndex):
            if ticker in raw.columns.get_level_values(0):
                close = raw[ticker]["Close"]
            elif ticker in raw.columns.get_level_values(1):
                close = raw["Close"][ticker]
            else:
                return pd.Series(dtype=float)
        elif single:
            close = raw["Close"]
        else:
            return pd.Series(dtype=float)
        result = pd.to_numeric(close, errors="coerce").dropna()
        result = result[result > 0].sort_index()
        result.index = pd.DatetimeIndex(result.index).tz_localize(None).normalize()
        result = result[~result.index.duplicated(keep="last")]
        return result.astype(float)
    except (KeyError, TypeError, ValueError, AttributeError):
        return pd.Series(dtype=float)


@st.cache_data(ttl=3600, show_spinner=False)
def _historical_prices(tickers: tuple[str, ...]) -> tuple[pd.DataFrame, tuple[str, ...]]:
    """Fetch the maximum daily history for each selected ticker, not a fixed 5y slice."""
    if not tickers:
        return pd.DataFrame(), ()
    raw = yf.download(
        tickers=list(tickers),
        period="max",
        interval="1d",
        group_by="ticker",
        auto_adjust=True,
        progress=False,
        threads=True,
        timeout=20,
    )
    closes: dict[str, pd.Series] = {}
    missing: list[str] = []
    for ticker in tickers:
        series = _extract_close(raw, ticker, len(tickers) == 1)
        if len(series) < 2:
            # Partial failures in Yahoo's multi-ticker response are common.
            # Attempt a targeted fallback without losing the healthy symbols.
            try:
                single = yf.Ticker(ticker).history(
                    period="max", interval="1d", auto_adjust=True, timeout=15
                )
                series = _extract_close(single, ticker, True)
            except Exception:
                series = pd.Series(dtype=float)
        if len(series) >= 2:
            closes[ticker] = series
        else:
            missing.append(ticker)
    if not closes:
        return pd.DataFrame(), tuple(missing)
    return pd.DataFrame(closes).sort_index(), tuple(missing)


