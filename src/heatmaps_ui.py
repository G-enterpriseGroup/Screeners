def _symbol(value: Any) -> str:
    ticker = str(value or "").strip().upper()
    for prefix in ("NYSEARCA:", "NASDAQ:", "NYSE:", "AMEX:", "ARCA:"):
        if ticker.startswith(prefix):
            ticker = ticker[len(prefix):]
            break
    ticker = ticker.replace(".", "-")
    return ticker if _SYMBOL_RE.fullmatch(ticker) else ""


def _clean_state(raw: Any) -> dict[str, Any]:
    if not isinstance(raw, dict):
        raw = {}
    raw_tickers = raw.get("tickers", list(DEFAULT_TICKERS))
    if not isinstance(raw_tickers, list):
        raw_tickers = list(DEFAULT_TICKERS)
    tickers: list[str] = []
    for value in raw_tickers:
        ticker = _symbol(value)
        if ticker and ticker not in tickers:
            tickers.append(ticker)
        if len(tickers) >= MAX_TICKERS:
            break
    try:
        revision = max(0, int(raw.get("revision") or 0))
    except (ValueError, TypeError):
        revision = 0
    focus = _symbol(raw.get("focus"))
    view = str(raw.get("view") or VIEWS[0])
    try:
        focus_year = int(raw.get("focus_year") or pd.Timestamp.now().year)
    except (ValueError, TypeError):
        focus_year = pd.Timestamp.now().year
    return {
        "revision": revision,
        "saved_at": float(raw.get("saved_at") or 0.0),
        "tickers": tickers,
        "focus": focus if focus in tickers else (tickers[0] if tickers else ""),
        "focus_year": min(2100, max(1990, focus_year)),
        "view": view if view in VIEWS else VIEWS[0],
    }


def _storage_token(vault_key: str) -> str:
    return hashlib.sha256(str(vault_key or "default").encode()).hexdigest()[:24]


def _load_state(vault_key: str) -> tuple[dict[str, Any], bool]:
    token = _storage_token(vault_key)
    session_key = "_heatmaps_state_" + token
    hydrated_key = "_heatmaps_hydrated_" + token
    current = _clean_state(st.session_state.get(session_key))
    if not st.session_state.get(hydrated_key, False):
        with st.container(key="heatmaps_memory_reader", gap=None):
            browser = _heatmaps_memory(
                storage_key="raj-terminal-heatmaps-v1:" + token,
                server_state=current,
                mode="read",
                hydrated=False,
                key="raj_heatmaps_reader_" + token,
                default=None,
            )
        if isinstance(browser, dict) and browser.get("source") in {"browser", "empty"}:
            if isinstance(browser.get("state"), dict):
                current = _clean_state(browser["state"])
            st.session_state[hydrated_key] = True
            st.session_state[session_key] = current
            st.rerun(scope="fragment")
        return current, False
    st.session_state[session_key] = current
    return current, True


def _save_state(vault_key: str, previous: dict[str, Any], candidate: dict[str, Any]) -> dict[str, Any]:
    token = _storage_token(vault_key)
    cleaned = _clean_state(candidate)
    before = _clean_state(previous)
    if any(cleaned[k] != before[k] for k in ("tickers", "focus", "view", "focus_year")):
        cleaned["revision"] = before["revision"] + 1
        cleaned["saved_at"] = time.time()
    st.session_state["_heatmaps_state_" + token] = cleaned
    return cleaned


def _write_browser(vault_key: str, state: dict[str, Any]) -> None:
    token = _storage_token(vault_key)
    with st.container(key="heatmaps_memory_writer", gap=None):
        _heatmaps_memory(
            storage_key="raj-terminal-heatmaps-v1:" + token,
            server_state=state,
            mode="write",
            hydrated=True,
            key="raj_heatmaps_writer_" + token,
            default=None,
        )


