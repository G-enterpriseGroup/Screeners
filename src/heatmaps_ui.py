def _shade(value: float | None, scale: float) -> tuple[str, str]:
    if value is None or not math.isfinite(value):
        return "#181818", "#78818c"
    ratio = min(abs(value) / max(scale, 0.01), 1.0)
    neutral = (35, 35, 35)
    endpoint = (226, 65, 83) if value < 0 else (35, 204, 155)
    mix = ratio ** 0.60
    rgb = tuple(round(a + (b - a) * mix) for a, b in zip(neutral, endpoint))
    color = "#111111" if ratio > 0.70 else "#f6f7f8"
    return "#%02x%02x%02x" % rgb, color


def _heatmap_markup(title: str, columns: list[str], rows: list[tuple[str, list[float | None]]],
                    subtitle: str = "") -> str:
    values = [
        abs(float(v)) for _, row in rows for v in row
        if v is not None and math.isfinite(float(v))
    ]
    scale = max(3.0, float(np.percentile(values, 85))) if values else 10.0
    out = ['<div class="hm-section">' + html.escape(title) + '</div>']
    if subtitle:
        out.append('<div class="hm-notes">' + html.escape(subtitle) + '</div>')
    out.append('<div class="hm-scroll"><table class="hm-grid"><thead><tr><th>SYMBOL / YEAR</th>')
    out.extend("<th>" + html.escape(str(col)) + "</th>" for col in columns)
    out.append("</tr></thead><tbody>")
    for label, data in rows:
        out.append("<tr><td title='" + html.escape(label, quote=True) + "'>" + html.escape(label) + "</td>")
        for col, value in zip(columns, data):
            bg, fg = _shade(value, scale)
            valstr = f"{value:+.1f}%" if value is not None and math.isfinite(value) else "—"
            tip = html.escape(f"{label} / {col}: {valstr}", quote=True)
            out.append(
                f'<td title="{tip}" style="background:{bg};color:{fg}">'
                + html.escape(valstr) + "</td>"
            )
        out.append("</tr>")
    out.append('</tbody></table></div><div class="hm-legend"><span>LOSS</span>'
               '<span class="hm-gradient"></span><span>GAIN</span>'
               '<span>// relative color intensity; blank = unavailable</span></div>')
    return "".join(out)


def _overview(prices: pd.DataFrame, tickers: list[str]) -> tuple[list[str], list[tuple[str, list[float | None]]]]:
    periods = ["1D", "1W", "1M", "3M", "6M", "YTD", "1Y", "3Y", "5Y", "MAX"]
    rows: list[tuple[str, list[float | None]]] = []
    for symbol in tickers:
        if symbol not in prices:
            continue
        row = [_period_return(prices[symbol], period) for period in periods]
        rows.append((symbol, row))
    return periods, rows


def _annual(prices: pd.DataFrame, tickers: list[str]) -> tuple[list[str], list[tuple[str, list[float | None]]]]:
    returns = {
        symbol: _calendar_returns(prices[symbol], "year")
        for symbol in tickers if symbol in prices
    }
    years = sorted({year for data in returns.values() for year in data}, reverse=True)
    return list(returns), [
        (str(year), [returns[symbol].get(year) for symbol in returns]) for year in years
    ]


def _monthly(prices: pd.DataFrame, ticker: str) -> tuple[list[str], list[tuple[str, list[float | None]]]]:
    periods = _calendar_returns(prices[ticker], "month")
    years = sorted({key[0] for key in periods}, reverse=True)
    cols = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]
    return cols, [
        (str(year), [periods.get((year, month)) for month in range(1, 13)])
        for year in years
    ]


def _sector_month(prices: pd.DataFrame, tickers: list[str], year: int) -> tuple[list[str], list[tuple[str, list[float | None]]]]:
    cols = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]
    rows = []
    for symbol in tickers:
        if symbol not in prices:
            continue
        perf = _calendar_returns(prices[symbol], "month")
        rows.append((symbol, [perf.get((year, month)) for month in range(1, 13)]))
    return cols, rows


def _export_csv(columns: list[str], rows: list[tuple[str, list[float | None]]]) -> bytes:
    return pd.DataFrame(
        [data for _, data in rows], index=[label for label, _ in rows], columns=columns
    ).rename_axis("TICKER_OR_YEAR").to_csv(float_format="%.5f").encode("utf-8")


