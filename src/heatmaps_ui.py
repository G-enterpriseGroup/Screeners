# RETURN CALCULATIONS
# ==============================
def _daily_returns(prices: pd.Series) -> pd.Series:
    prices = prices.dropna()
    if len(prices) < 2:
        return pd.Series(dtype=float)
    returns = prices.pct_change(fill_method=None)
    returns.iloc[0] = 0.0
    return returns


def _period_return(prices: pd.Series, period: str) -> float:
    prices = prices.dropna()
    if len(prices) < 2:
        return float("nan")
    end = prices.index[-1]
    if period == "1D":
        base = prices.iloc[-2]
    elif period == "MAX":
        base = prices.iloc[0]
    else:
        if period == "1W":
            start = end - timedelta(days=7)
        elif period == "1M":
            start = end - pd.DateOffset(months=1)
        elif period == "3M":
            start = end - pd.DateOffset(months=3)
        elif period == "6M":
            start = end - pd.DateOffset(months=6)
        elif period == "1Y":
            start = end - pd.DateOffset(years=1)
        elif period == "3Y":
            start = end - pd.DateOffset(years=3)
        elif period == "5Y":
            start = end - pd.DateOffset(years=5)
        elif period == "YTD":
            start = pd.Timestamp(year=end.year, month=1, day=1)
        else:
            return float("nan")
        eligible = prices.loc[prices.index < start]
        if eligible.empty:
            # This ticker launched after the requested horizon. The actual
            # available return is shown, with explicit first-date coverage.
            base = prices.iloc[0]
        else:
            base = eligible.iloc[-1]
    return float((prices.iloc[-1] / base - 1.0) * 100.0)


def _calendar_returns(prices: pd.Series, frequency: str) -> dict[Any, float]:
    """Compound daily adjusted-close returns inside each period.

    First observed trading day's return is zero, so the first (possibly
    partial) month/year begins at the fund's first available closing price.
    """
    daily = _daily_returns(prices)
    if daily.empty:
        return {}
    if frequency == "year":
        keys = daily.index.year
    elif frequency == "month":
        keys = zip(daily.index.year, daily.index.month)
        keys = list(keys)
    else:
        raise ValueError("frequency must be year or month")
    totals = (1.0 + daily).groupby(keys).prod()
    return {key: float((factor - 1.0) * 100.0) for key, factor in totals.items()}


